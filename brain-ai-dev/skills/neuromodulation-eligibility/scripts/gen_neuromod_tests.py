# ============================================================================
# 6. TestDelayedRewardAssociation (~6 tests)
# ============================================================================

@pytest.mark.slow
class TestDelayedRewardAssociation:
    """End-to-end learning tests on a toy delayed reward task.

    A stimulus is presented, then after a configurable delay of N steps
    with no input, a reward arrives. The model must learn the stimulus-reward
    association. These tests validate that eligibility traces bridge the
    temporal credit assignment gap.
    """

    @staticmethod
    def _build_toy_model(use_eligibility: bool = True, delay: int = 5):
        """Build a tiny model for delayed reward toy task.

        Returns (model, trace_mod, updater, gate) if use_eligibility,
        else (model, None, None, None).
        """
        torch.manual_seed(DEFAULT_SEED)
        input_dim = 8
        hidden_dim = 32
        output_dim = 2

        model = nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, output_dim),
        )

        if not use_eligibility:
            return model, None, None, None

        trace_mod = EligibilityTraceModule(
            n_pre=hidden_dim, n_post=output_dim,
            tau_e=float(delay * 4),
            trace_type="accumulating",
        )
        updater = ThreeFactorUpdate(ThreeFactorConfig(lr=0.05))
        gate = NeuromodulatoryGate(NeuromodConfig())
        return model, trace_mod, updater, gate

    @staticmethod
    def _run_training(
        model, trace_mod, updater, gate,
        num_episodes: int = 200,
        delay: int = 5,
        use_eligibility: bool = True,
    ) -> Tuple[List[float], List[float]]:
        """Run training and return (losses, accuracies).

        When use_eligibility=True, uses gradient-aligned eligibility:
        the gradient of log-policy is used as the eligibility trace,
        then decayed over the delay period. The reward modulates the
        trace into a weight update (REINFORCE-style three-factor rule).
        """
        torch.manual_seed(DEFAULT_SEED)
        input_dim = 8
        hidden_dim = 32

        losses = []
        correct_count = 0
        total_count = 0
        accuracy_per_epoch = []

        if not use_eligibility:
            optimizer = torch.optim.SGD(model.parameters(), lr=0.01)

        for ep in range(num_episodes):
            # Generate stimulus: class 0 or 1
            label = torch.randint(0, 2, (1,)).item()
            stimulus = torch.zeros(input_dim)
            stimulus[label * 4:(label + 1) * 4] = 1.0

            if use_eligibility:
                # Forward pass with grad to compute gradient-aligned eligibility
                hidden = torch.relu(model[0](stimulus.unsqueeze(0)))
                logits = model[2](hidden)

                # Compute log-prob of taken action (policy gradient proxy)
                probs = torch.softmax(logits, dim=-1)
                pred = logits.argmax(dim=-1).item()
                log_prob = torch.log(probs[0, pred] + 1e-8)

                is_correct = pred == label
                if is_correct:
                    correct_count += 1
                total_count += 1
                reward = 1.0 if is_correct else -1.0

                # Compute gradient as eligibility (gradient-aligned trace)
                model.zero_grad()
                log_prob.backward()
                grad_w = model[2].weight.grad.clone().detach()

                # Simulate delay: exponential decay of eligibility
                decay = trace_mod.decay_e
                decayed_grad = grad_w * (decay ** delay)

                # Three-factor update: delta_w = lr * reward * decayed_eligibility
                with torch.no_grad():
                    delta_w = 0.02 * reward * decayed_grad
                    model[2].weight.data += delta_w

                loss_val = -reward * log_prob.item()
            else:
                # Standard backprop with direct loss (no delayed credit)
                hidden = torch.relu(model[0](stimulus.unsqueeze(0)))
                logits = model[2](hidden)
                pred = logits.argmax(dim=-1).item()

                is_correct = pred == label
                if is_correct:
                    correct_count += 1
                total_count += 1

                target = torch.tensor([label])
                loss = F.cross_entropy(logits, target)
                optimizer.zero_grad()
                loss.backward()
                optimizer.step()
                loss_val = loss.item()

            losses.append(loss_val)

            if (ep + 1) % 20 == 0:
                acc = correct_count / total_count
                accuracy_per_epoch.append(acc)
                correct_count = 0
                total_count = 0

        return losses, accuracy_per_epoch

    def test_with_eligibility_learns(self):
        """With eligibility traces active, the model learns the delayed
        stimulus-reward association."""
        model, trace_mod, updater, gate = self._build_toy_model(
            use_eligibility=True, delay=5
        )
        losses, accs = self._run_training(
            model, trace_mod, updater, gate,
            num_episodes=200, delay=5, use_eligibility=True,
        )
        # Check that later accuracy is better than early
        if len(accs) >= 4:
            early = sum(accs[:2]) / 2
            late = sum(accs[-2:]) / 2
            assert late > early, (
                f"With eligibility, late accuracy ({late:.2f}) should exceed "
                f"early accuracy ({early:.2f})"
            )

