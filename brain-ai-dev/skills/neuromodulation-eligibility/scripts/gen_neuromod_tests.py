    class NeuromodulatoryGate(nn.Module):
        """Stub NeuromodulatoryGate for CI before module exists."""

        def __init__(self, config: Optional[NeuromodConfig] = None):
            super().__init__()
            if config is None:
                config = NeuromodConfig()
            self.config = config

            # DA parameters
            self.w_reward = nn.Parameter(torch.tensor(1.0))
            self.alpha_baseline = 0.01
            self.register_buffer("reward_baseline", torch.tensor(0.0))

            # ACh parameters
            self.w_novelty = nn.Parameter(torch.tensor(1.0))
            self.ach_bias = nn.Parameter(torch.tensor(0.0))

            # NE parameters
            self.w_urgency = nn.Parameter(torch.tensor(1.0))
            self.ne_bias = nn.Parameter(torch.tensor(0.0))

            # 5-HT parameters
            self.w_patience = nn.Parameter(torch.tensor(1.0))
            self.sht_bias = nn.Parameter(torch.tensor(0.0))

            # Combination
            if config.combination_fn == "weighted_sum":
                self.combination_weights = nn.Parameter(
                    torch.tensor([0.4, 0.3, 0.2, 0.1])
                )
            elif config.combination_fn == "gated_product":
                self.gate_weight = nn.Parameter(torch.tensor(0.7))
            elif config.combination_fn == "mlp":
                self.combine_mlp = nn.Sequential(
                    nn.Linear(4, config.modulator_hidden_dim),
                    nn.ReLU(),
                    nn.Linear(config.modulator_hidden_dim, 1),
                    nn.Tanh(),
                )

        def forward(
            self,
            signals: Dict[str, Tensor],
            state: Optional[Dict] = None,
        ) -> Tuple[Dict[str, Tensor], Tensor]:
            with torch.cuda.amp.autocast(enabled=False):
                # Determine batch size from any provided signal
                B = 1
                for v in signals.values():
                    if v is not None and isinstance(v, Tensor) and v.dim() > 0:
                        B = v.shape[0]
                        break
                ref_device = next(
                    (v.device for v in signals.values()
                     if isinstance(v, Tensor)), torch.device("cpu")
                )

                # DA
                reward = signals.get("reward")
                if reward is not None:
                    reward = reward.float()
                    if reward.dim() == 0:
                        reward = reward.unsqueeze(0)
                    rpe = reward - self.reward_baseline
                    da = torch.tanh(self.w_reward * rpe)
                else:
                    da = torch.zeros(B, device=ref_device)

                # ACh
                novelty = signals.get("novelty")
                if novelty is not None:
                    novelty = novelty.float()
                    if novelty.dim() == 0:
                        novelty = novelty.unsqueeze(0)
                    raw_ach = self.w_novelty * novelty + self.ach_bias
                    ach = torch.sigmoid(raw_ach)
                else:
                    ach = torch.full((B,), 0.5, device=ref_device)

                # NE
                urgency = signals.get("urgency")
                if urgency is not None:
                    urgency = urgency.float()
                    if urgency.dim() == 0:
                        urgency = urgency.unsqueeze(0)
                    raw_ne = self.w_urgency * urgency + self.ne_bias
                    ne = torch.sigmoid(raw_ne)
                else:
                    ne = torch.full((B,), 0.5, device=ref_device)

                # 5-HT
                patience = signals.get("patience")
                if patience is not None:
                    patience = patience.float()
                    if patience.dim() == 0:
                        patience = patience.unsqueeze(0)
                    raw_sht = self.w_patience * patience + self.sht_bias
                    sht = torch.sigmoid(raw_sht)
                else:
                    sht = torch.full((B,), 0.5, device=ref_device)

                # Ensure all have same batch dim
                max_B = max(da.shape[0], ach.shape[0], ne.shape[0], sht.shape[0])
                if da.shape[0] < max_B:
                    da = da.expand(max_B)
                if ach.shape[0] < max_B:
                    ach = ach.expand(max_B)
                if ne.shape[0] < max_B:
                    ne = ne.expand(max_B)
                if sht.shape[0] < max_B:
                    sht = sht.expand(max_B)

                # Combine
                if self.config.combination_fn == "weighted_sum":
                    mods = torch.stack([da, ach, ne, sht], dim=-1)  # (B, 4)
                    raw_gp = (mods * self.combination_weights).sum(dim=-1)
                    global_plasticity = torch.tanh(raw_gp)
                elif self.config.combination_fn == "gated_product":
                    gate = self.gate_weight * ach + (1 - self.gate_weight) * 0.5
                    global_plasticity = da * gate
                elif self.config.combination_fn == "mlp":
                    mods = torch.stack([da, ach, ne, sht], dim=-1)  # (B, 4)
                    global_plasticity = self.combine_mlp(mods).squeeze(-1)
                else:
                    global_plasticity = da

                modulators = {"DA": da, "ACh": ach, "NE": ne, "5HT": sht}
            return modulators, global_plasticity

        def update_baseline(self, reward: Tensor) -> None:
            with torch.no_grad():
                mean_r = reward.detach().mean()
                self.reward_baseline.mul_(1 - self.alpha_baseline).add_(
                    self.alpha_baseline * mean_r
                )

        def reset_state(self) -> None:
            self.reward_baseline.zero_()

        def state_dict_custom(self) -> Dict[str, Any]:
            return {
                "reward_baseline": self.reward_baseline.clone(),
                "params": {k: v.clone() for k, v in self.named_parameters()},
            }


