try:
    from brain_ai.meta.three_factor_update import ThreeFactorUpdate
except ImportError:

    class ThreeFactorUpdate:
        """Stub ThreeFactorUpdate for CI before module exists."""

        def __init__(self, config: Optional[ThreeFactorConfig] = None):
            if config is None:
                config = ThreeFactorConfig()
            self.config = config
            self.step_count = 0
            self._eligible_layers: Dict[str, Dict[str, Any]] = {}
            self._clamp_hits = 0

        def register_layer(
            self,
            name: str,
            param: nn.Parameter,
            lr: Optional[float] = None,
        ) -> None:
            self._eligible_layers[name] = {
                "param": param,
                "lr": lr if lr is not None else self.config.lr,
                "trace": torch.zeros_like(param.data),
            }

        def is_eligible(self, name: str) -> bool:
            return name in self._eligible_layers

        def compute_update(
            self,
            eligibility: Tensor,
            mod_signal: Tensor,
            lr: Optional[float] = None,
        ) -> Tensor:
            if lr is None:
                lr = self.config.lr
            with torch.no_grad():
                mod = mod_signal.detach()
                e = eligibility.detach().float()
                while mod.dim() < e.dim():
                    mod = mod.unsqueeze(-1)
                delta_w = lr * mod * e
                delta_w = delta_w.mean(dim=0) if delta_w.dim() > e.dim() - 1 else delta_w
            return delta_w

        def apply_update(
            self,
            weights: Tensor,
            eligibility: Tensor,
            mod_signal: Tensor,
            lr: Optional[float] = None,
            clamp: Optional[Tuple[float, float]] = None,
            max_delta: Optional[float] = None,
        ) -> Tuple[Tensor, Tensor]:
            if lr is None:
                lr = self.config.lr
            if clamp is None:
                clamp = self.config.weight_clamp

            self.step_count += 1

            if self.config.update_frequency > 1:
                if self.step_count % self.config.update_frequency != 0:
                    return weights, torch.zeros_like(weights)

            with torch.no_grad():
                mod = mod_signal.detach().float()
                e = eligibility.detach().float()
                while mod.dim() < e.dim():
                    mod = mod.unsqueeze(-1)

                delta_w = lr * mod * e
                if delta_w.dim() > weights.dim():
                    delta_w = delta_w.mean(dim=0)

                if max_delta is not None:
                    pre_clamp = (delta_w.abs() > max_delta).sum().item()
                    self._clamp_hits += int(pre_clamp)
                    delta_w = torch.clamp(delta_w, -max_delta, max_delta)

                w_new = weights + delta_w
                w_new = torch.clamp(w_new, clamp[0], clamp[1])

            return w_new, delta_w

        @property
        def clamp_hits(self) -> int:
            return self._clamp_hits

        def reset(self) -> None:
            self.step_count = 0
            self._clamp_hits = 0


