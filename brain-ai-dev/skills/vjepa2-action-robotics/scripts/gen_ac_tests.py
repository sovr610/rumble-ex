    def test_T49_batched_equals_sequential(self):
        """T49: Batched rollout identical to sequential rollout."""
        N, horizon, repr_dim = 4, 3, 16
        wm = LinearSyntheticWorldModel(repr_dim=repr_dim, alpha=0.1)
        sequences = torch.randn(N, horizon, 7)
        current = torch.zeros(repr_dim)
        state = torch.zeros(7)

        # Batched
        final_batched = batched_rollout(wm, current, sequences, state)

        # Sequential
        final_seq = []
        for n in range(N):
            r = current.unsqueeze(0).clone()
            s = state.unsqueeze(0).clone()
            for t in range(horizon):
                a = sequences[n:n+1, t, :]
                r = wm.predict_next(r, a, s)
            final_seq.append(r.squeeze(0))
        final_seq = torch.stack(final_seq)

        assert torch.allclose(final_batched, final_seq, atol=1e-5)

    def test_T50_horizon_1_rollout(self):
        """T50: Rollout with horizon=1 makes one predict_next call."""
        call_count = [0]

