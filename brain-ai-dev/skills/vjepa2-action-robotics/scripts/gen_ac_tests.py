        torch.manual_seed(42)

        goal = torch.tensor([0.5, -0.3, 0.2, 0.0, 0.0, 0.0, 0.3])
        _, diag = planner.plan(torch.zeros(7), goal, torch.zeros(7), return_diagnostics=True)

        costs = diag['cost_history']
        # Allow small upward blips (stochastic), but final must be < initial
        assert costs[-1] < costs[0]

