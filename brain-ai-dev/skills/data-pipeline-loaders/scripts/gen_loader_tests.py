def main():
    parser = argparse.ArgumentParser(description="Generate pytest test cases for data pipeline")
    parser.add_argument("-o", "--output-dir", type=str, default=None,
                        help="Directory to write test file to (default: stdout)")
    parser.add_argument("--run", action="store_true",
                        help="Run the generated tests with pytest after writing")
    parser.add_argument("--filename", type=str, default="test_data_pipeline.py",
                        help="Output filename (default: test_data_pipeline.py)")
    args = parser.parse_args()

    content = generate_test_file()

    # Count tests
    test_count = content.count("\ndef test_")
    print(f"Generated {test_count} test functions", file=sys.stderr)

    if args.output_dir:
        os.makedirs(args.output_dir, exist_ok=True)
        output_path = os.path.join(args.output_dir, args.filename)
        with open(output_path, "w") as f:
            f.write(content)
        print(f"Wrote test file to {output_path}", file=sys.stderr)

        if args.run:
            import subprocess
            result = subprocess.run(
                [sys.executable, "-m", "pytest", output_path, "-v", "--tb=short"],
                cwd=os.path.dirname(os.path.abspath(__file__))
            )
            sys.exit(result.returncode)
    else:
        print(content)


if __name__ == "__main__":
    main()
