class AblationRunnerStub:
    """Minimal AblationRunner stub."""

    @staticmethod
    def derive_ablation_id(overrides: dict) -> str:
        canonical = json.dumps(overrides, sort_keys=True, separators=(",", ":"))
        return hashlib.sha256(canonical.encode()).hexdigest()[:8]

    @classmethod
    def generate_matrix(cls, spec: dict) -> List[dict]:
        """Generate all combinations from toggles dict (full factorial)."""
        import itertools

        toggles = spec.get("toggles", {})
        if not toggles:
            return []
        keys = sorted(toggles.keys())
        values = [toggles[k] for k in keys]
        combos = []
        for combo in itertools.product(*values):
            overrides = dict(zip(keys, combo))
            combos.append(
                {
                    "overrides": overrides,
                    "ablation_id": cls.derive_ablation_id(overrides),
                    "status": "pending",
                    "metrics": {},
                    "duration": None,
                }
            )
        return combos

    @classmethod
    def generate_pairwise(cls, spec: dict) -> List[dict]:
        """Return pairwise-reduced matrix (typically much smaller)."""
        full = cls.generate_matrix(spec)
        # Naive pairwise: return the first ceil(sqrt(N)) combos as approximation
        import math
        n = max(1, math.ceil(math.sqrt(len(full))))
        return full[:n]

    @classmethod
    def execute(
        cls,
        matrix: List[dict],
        run_fn,
        *,
        parallel: bool = False,
        dry_run: bool = False,
    ) -> dict:
        results = []
        for run_spec in matrix:
            if dry_run:
                run_spec["status"] = "dry_run"
                run_spec["duration"] = 0.0
                results.append(run_spec)
                continue
            try:
                t0 = time.time()
                metrics = run_fn(run_spec["overrides"])
                run_spec["status"] = "completed"
                run_spec["metrics"] = metrics
                run_spec["duration"] = time.time() - t0
            except Exception as exc:
                run_spec["status"] = "failed"
                run_spec["error"] = str(exc)
                run_spec["duration"] = time.time() - t0
            results.append(run_spec)
        return {"runs": results, "total": len(results)}

    @staticmethod
    def write_csv(results: dict, path: Path) -> Path:
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        runs = results["runs"]
        if not runs:
            return path
        fieldnames = list(runs[0].keys())
        with path.open("w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(runs)
        return path

    @staticmethod
    def validate_spec(spec: dict) -> List[str]:
        errors = []
        if "toggles" not in spec:
            errors.append("spec missing 'toggles' key")
        if not isinstance(spec.get("toggles", {}), dict):
            errors.append("'toggles' must be a dict")
        return errors

    @staticmethod
    def apply_constraints(matrix: List[dict], constraints: List[dict]) -> List[dict]:
        """Filter combos that violate constraints (if-then rules)."""
        filtered = []
        for run in matrix:
            ok = True
            for c in constraints:
                cond_key, cond_val = list(c["if"].items())[0]
                then_key, then_val = list(c["then"].items())[0]
                if run["overrides"].get(cond_key) == cond_val:
                    if run["overrides"].get(then_key) != then_val:
                        ok = False
                        break
            if ok:
                filtered.append(run)
        return filtered


