    def log_scalar(self, tag: str, value: float, step: int) -> None:
        self._scalars.append((tag, value, step))
        with self._jsonl_path.open("a") as f:
            f.write(json.dumps({"tag": tag, "value": value, "step": step}) + "\\n")

