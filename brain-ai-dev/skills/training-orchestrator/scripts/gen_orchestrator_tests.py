class PipelineOrchestratorStub:
    """Minimal PipelineOrchestrator stub."""

    def __init__(self, config: TrainingConfigStub, run_dir: Path):
        self.config = config
        self.run_dir = Path(run_dir)
        self._phase_results: List[PhaseResult] = []
        self._boundary_paths: Dict[int, Path] = {}
        self._error: Optional[Exception] = None

    def run_phase(
        self,
        phase: int,
        *,
        model=None,
        steps: int = 3,
        resume_from: Optional[Path] = None,
    ) -> PhaseResult:
        runner = PhaseRunnerStub(self.config, phase)
        try:
            metrics = runner.run(model=model, steps=steps)
            result = PhaseResult(phase, "completed", metrics)
            # Write a fake boundary artifact
            ckpt_mgr = CheckpointManagerStub(self.run_dir, phase)
            boundary = ckpt_mgr.save_boundary(
                {"dummy": True},
                compatibility={"workspace_dim": 4096, "phase": phase},
            )
            self._boundary_paths[phase] = boundary
        except Exception as exc:
            result = PhaseResult(phase, "failed", {"error": str(exc)})
            self._error = exc
        self._phase_results.append(result)
        return result

    def run_pipeline(
        self,
        phases: Optional[List[int]] = None,
        *,
        start_phase: int = 1,
        steps_per_phase: int = 3,
        validate_boundaries: bool = True,
    ) -> dict:
        phases = phases or self.config.phases
        phases = [p for p in phases if p >= start_phase]
        for phase in phases:
            if validate_boundaries and phase > 1:
                prev = phase - 1
                boundary = self._boundary_paths.get(prev)
                if boundary is None or not boundary.exists():
                    return {
                        "status": "failed",
                        "completed_phases": [r.phase for r in self._phase_results],
                        "error": f"Missing boundary for phase {prev}",
                    }
            result = self.run_phase(phase, steps=steps_per_phase)
            if result.status == "failed":
                return {
                    "status": "failed",
                    "completed_phases": [r.phase for r in self._phase_results if r.status == "completed"],
                    "error": result.metrics.get("error"),
                }
        return {
            "status": "completed",
            "completed_phases": [r.phase for r in self._phase_results],
        }

    def generate_report(self, path: Optional[Path] = None) -> dict:
        report = {
            "phases": [
                {"phase": r.phase, "status": r.status, "metrics": r.metrics}
                for r in self._phase_results
            ],
            "overall_status": (
                "completed"
                if all(r.status == "completed" for r in self._phase_results)
                else "failed"
            ),
        }
        if path:
            Path(path).parent.mkdir(parents=True, exist_ok=True)
            Path(path).write_text(json.dumps(report, indent=2))
        return report

    @staticmethod
    def build_cli_parser() -> argparse.ArgumentParser:
        p = argparse.ArgumentParser()
        p.add_argument("--mode", default="dev", choices=["dev", "production"])
        p.add_argument("--start-phase", type=int, default=1)
        p.add_argument("--phases", nargs="+", type=int, default=list(range(1, 8)))
        p.add_argument("--run-dir", default="runs/")
        p.add_argument("--use-amp", action="store_true")
        return p


