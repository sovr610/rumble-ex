@dataclass
class AlignmentConfig:
    """Configuration for multi-modal alignment.

    Controls projection heads, contrastive loss, uniformity regularization,
    centering, gap regularization, and curriculum alignment.

    Attributes
    ----------
    alignment_dim:
        Dimension of the shared alignment embedding space.  All projection
        heads output vectors of this dimensionality.
    encoder_dim:
        Default encoder output dimension.  Can be overridden per-modality
        via ``modality_dims``.
    modality_dims:
        Optional mapping from modality name to its encoder output dimension.
        Modalities not listed use ``encoder_dim``.
    temperature:
        Temperature for contrastive loss computation.  Lower values produce
        sharper contrastive gradients.
    learnable_temperature:
        Whether temperature is a learnable nn.Parameter (CLIP-style).
    temperature_min:
        Minimum allowed temperature (clamp lower bound).
    temperature_max:
        Maximum allowed temperature (clamp upper bound).
    loss_type:
        Contrastive loss variant: ``"infonce"``, ``"siglip"``, or
        ``"combined"`` (average of both).
    projector_type:
        Projection head architecture: ``"linear"``, ``"mlp_1"`` (one hidden
        layer), or ``"mlp_2"`` (two hidden layers).
    projector_hidden_expansion:
        Expansion factor for MLP projector hidden dimension relative to
        ``max(encoder_dim, alignment_dim)``.
    projector_dropout:
        Dropout rate inside projection heads.
    pooling_type:
        Token pooling strategy before projection: ``"mean"``, ``"cls"``,
        or ``"attention"``.
    use_uniformity_loss:
        Add uniformity regularization to prevent representation collapse.
    uniformity_weight:
        Weight for the uniformity loss term.
    uniformity_temperature:
        Temperature parameter ``t`` in the uniformity loss kernel.
    use_centering:
        Subtract running modality centroids to reduce modality gap.
    centering_momentum:
        EMA momentum for centroid tracking (higher = slower update).
    gap_reg_weight:
        Weight for the modality gap regularization term.
    hard_negative_mining:
        Enable hard negative selection within the contrastive loss.
    curriculum_phases:
        Number of curriculum difficulty phases (0 = disabled).
    """

    # Dimensions
    alignment_dim: int = 512
    encoder_dim: int = 512
    modality_dims: Dict[str, int] = field(default_factory=dict)

    # Temperature
    temperature: float = 0.07
    learnable_temperature: bool = True
    temperature_min: float = 0.001
    temperature_max: float = 1.0

    # Loss
    loss_type: str = "infonce"

    # Projector
    projector_type: str = "mlp_1"
    projector_hidden_expansion: float = 2.0
    projector_dropout: float = 0.1

    # Pooling
    pooling_type: str = "mean"

    # Uniformity regularization
    use_uniformity_loss: bool = True
    uniformity_weight: float = 0.1
    uniformity_temperature: float = 2.0

    # Centering
    use_centering: bool = True
    centering_momentum: float = 0.9

    # Gap regularization
    gap_reg_weight: float = 0.01

    # Hard negatives
    hard_negative_mining: bool = False

    # Curriculum
    curriculum_phases: int = 0

    def __post_init__(self) -> None:
        if self.alignment_dim <= 0:
            raise ValueError(
                f"AlignmentConfig.alignment_dim must be > 0, "
                f"got {self.alignment_dim}"
            )
        if self.encoder_dim <= 0:
            raise ValueError(
                f"AlignmentConfig.encoder_dim must be > 0, "
                f"got {self.encoder_dim}"
            )
        if self.temperature <= 0.0:
            raise ValueError(
                f"AlignmentConfig.temperature must be > 0, "
                f"got {self.temperature}"
            )
        if self.temperature_min <= 0.0:
            raise ValueError(
                f"AlignmentConfig.temperature_min must be > 0, "
                f"got {self.temperature_min}"
            )
        if self.temperature_max <= self.temperature_min:
            raise ValueError(
                f"AlignmentConfig.temperature_max ({self.temperature_max}) must be > "
                f"temperature_min ({self.temperature_min})"
            )
        if self.loss_type not in _VALID_LOSS_TYPES:
            raise ValueError(
                f"AlignmentConfig.loss_type must be one of {_VALID_LOSS_TYPES}, "
                f"got '{self.loss_type}'"
            )
        if self.projector_type not in _VALID_PROJECTOR_TYPES:
            raise ValueError(
                f"AlignmentConfig.projector_type must be one of {_VALID_PROJECTOR_TYPES}, "
                f"got '{self.projector_type}'"
            )
        if self.projector_hidden_expansion <= 0.0:
            raise ValueError(
                f"AlignmentConfig.projector_hidden_expansion must be > 0, "
                f"got {self.projector_hidden_expansion}"
            )
        if not (0.0 <= self.projector_dropout < 1.0):
            raise ValueError(
                f"AlignmentConfig.projector_dropout must be in [0, 1), "
                f"got {self.projector_dropout}"
            )
        if self.pooling_type not in _VALID_POOLING_TYPES:
            raise ValueError(
                f"AlignmentConfig.pooling_type must be one of {_VALID_POOLING_TYPES}, "
                f"got '{self.pooling_type}'"
            )
        if self.uniformity_weight < 0.0:
            raise ValueError(
                f"AlignmentConfig.uniformity_weight must be >= 0, "
                f"got {self.uniformity_weight}"
            )
        if self.uniformity_temperature <= 0.0:
            raise ValueError(
                f"AlignmentConfig.uniformity_temperature must be > 0, "
                f"got {self.uniformity_temperature}"
            )
        if not (0.0 <= self.centering_momentum < 1.0):
            raise ValueError(
                f"AlignmentConfig.centering_momentum must be in [0, 1), "
                f"got {self.centering_momentum}"
            )
        if self.gap_reg_weight < 0.0:
            raise ValueError(
                f"AlignmentConfig.gap_reg_weight must be >= 0, "
                f"got {self.gap_reg_weight}"
            )
        if self.curriculum_phases < 0:
            raise ValueError(
                f"AlignmentConfig.curriculum_phases must be >= 0, "
                f"got {self.curriculum_phases}"
            )
        for modality, dim in self.modality_dims.items():
            if dim <= 0:
                raise ValueError(
                    f"AlignmentConfig.modality_dims['{modality}'] must be > 0, "
                    f"got {dim}"
                )

    # -- derived properties ---------------------------------------------------

    @property
    def projector_hidden_dim(self) -> int:
        """Hidden dimension for MLP projectors."""
        base = max(self.encoder_dim, self.alignment_dim)
        return int(base * self.projector_hidden_expansion)

    @property
    def init_log_temperature(self) -> float:
        """Initial value for the log-temperature parameter."""
        return math.log(1.0 / self.temperature)

    def get_encoder_dim(self, modality: str) -> int:
        """Return encoder dim for a modality, falling back to encoder_dim."""
        return self.modality_dims.get(modality, self.encoder_dim)

    @property
    def estimated_projector_params(self) -> int:
        """Rough parameter count for a single projection head."""
        d_in = self.encoder_dim
        d_out = self.alignment_dim
        d_h = self.projector_hidden_dim

        if self.projector_type == "linear":
            return d_in * d_out + d_out
        elif self.projector_type == "mlp_1":
            return (d_in * d_h + d_h) + (d_h * d_out + d_out) + d_h  # +LN
        elif self.projector_type == "mlp_2":
            return (
                (d_in * d_h + d_h) + d_h
                + (d_h * d_h + d_h) + d_h
                + (d_h * d_out + d_out)
            )
        return 0

    def summary(self) -> str:
        """Human-readable configuration summary."""
        lines = [
            "AlignmentConfig Summary",
            "=" * 55,
            f"  alignment_dim:            {self.alignment_dim}",
            f"  encoder_dim:              {self.encoder_dim}",
            f"  modality_dims:            {self.modality_dims or '(default)'}",
            "",
            f"  temperature:              {self.temperature}",
            f"  learnable_temperature:    {self.learnable_temperature}",
            f"  temperature_range:        [{self.temperature_min}, {self.temperature_max}]",
            "",
            f"  loss_type:                {self.loss_type}",
            f"  projector_type:           {self.projector_type}",
            f"  projector_hidden_dim:     {self.projector_hidden_dim}",
            f"  projector_dropout:        {self.projector_dropout}",
            f"  pooling_type:             {self.pooling_type}",
            "",
            f"  use_uniformity_loss:      {self.use_uniformity_loss}",
            f"  uniformity_weight:        {self.uniformity_weight}",
            f"  use_centering:            {self.use_centering}",
            f"  centering_momentum:       {self.centering_momentum}",
            f"  gap_reg_weight:           {self.gap_reg_weight}",
            "",
            f"  hard_negative_mining:     {self.hard_negative_mining}",
            f"  curriculum_phases:        {self.curriculum_phases}",
            "",
            f"  estimated params/projector: {self.estimated_projector_params:,}",
        ]
        return "\n".join(lines)


