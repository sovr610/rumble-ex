def alignment_config_from_dict(d: Dict[str, Any]) -> AlignmentConfig:
    """Deserialize an AlignmentConfig from a dict.

    Filters to known fields so extra keys are silently ignored.
    """
    known = {f.name for f in fields(AlignmentConfig)}
    filtered = {k: v for k, v in d.items() if k in known}
    return AlignmentConfig(**filtered)


def alignment_config_to_json(config: AlignmentConfig, indent: int = 2) -> str:
    """Serialize AlignmentConfig to a JSON string."""
    return json.dumps(alignment_config_to_dict(config), indent=indent)


def alignment_config_from_json(s: str) -> AlignmentConfig:
    """Deserialize AlignmentConfig from a JSON string."""
    return alignment_config_from_dict(json.loads(s))


