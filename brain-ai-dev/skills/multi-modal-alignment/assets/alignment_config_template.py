if __name__ == "__main__":
    import sys

    _pass = 0
    _fail = 0
    _errors: list = []

    def _check(name: str, condition: bool, detail: str = "") -> None:
        global _pass, _fail
        if condition:
            _pass += 1
            print(f"  [PASS] {name}")
        else:
            _fail += 1
            msg = f"  [FAIL] {name}"
            if detail:
                msg += f" -- {detail}"
            print(msg)
            _errors.append(name)

    def _check_raises(name: str, exc_type: type, fn, *args, **kwargs) -> None:
        global _pass, _fail
        try:
            fn(*args, **kwargs)
            _fail += 1
            print(f"  [FAIL] {name} -- expected {exc_type.__name__}, got no error")
            _errors.append(name)
        except exc_type:
            _pass += 1
            print(f"  [PASS] {name}")
        except Exception as e:
            _fail += 1
            print(
                f"  [FAIL] {name} -- expected {exc_type.__name__}, "
                f"got {type(e).__name__}: {e}"
            )
            _errors.append(name)

    # -----------------------------------------------------------------------
