# ---------------------------------------------------------------------------
# Test counting helper
# ---------------------------------------------------------------------------

def _count_test_methods(source: str) -> int:
    """Count lines beginning with 'def test_' (after stripping whitespace)."""
    return sum(
        1 for line in source.splitlines()
        if line.strip().startswith("def test_")
    )


# ---------------------------------------------------------------------------
# Main assembly
# ---------------------------------------------------------------------------

def generate() -> str:
    """Assemble and return the full generated test source."""
    sections: List[str] = [
        _build_header(),
        _build_imports(),
        _build_fixtures(),
        _build_class_inner_loop_engine(),
        _build_class_maml(),
        _build_class_fomaml(),
        _build_class_reptile(),
        _build_class_maml_plus_plus(),
        _build_class_episode_sampler(),
        _build_class_meta_metrics(),
        _build_class_meta_checkpoint(),
        _build_class_meta_config(),
        _build_footer(),
    ]
    return "\n".join(sections)


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Generate tests/test_meta_learning.py with ~82 pytest test cases "
            "for the Meta-Learning Suite (brain_ai/meta/)."
        ),
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("tests") / "test_meta_learning.py",
        help="Destination path for the generated test file.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print generated source to stdout instead of writing to disk.",
    )
    parser.add_argument(
        "--verbose", "-v",
        action="store_true",
        help="Print a generation summary to stderr.",
    )
    return parser.parse_args()


def main() -> None:
    args = _parse_args()
    source = generate()
    n_tests = _count_test_methods(source)
    n_lines = source.count("\n")

    if args.dry_run:
        print(source)
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(source, encoding="utf-8")
        print(f"Generated {args.output}", file=sys.stderr)
        print(f"  {n_tests} test methods, {n_lines} lines", file=sys.stderr)
        print(
            "  Run with: python -m pytest tests/test_meta_learning.py -v",
            file=sys.stderr,
        )

    if args.verbose:
        print(
            f"[gen_meta_tests] {n_tests} test methods, {n_lines} lines -> {args.output}",
            file=sys.stderr,
        )


if __name__ == "__main__":
    main()
