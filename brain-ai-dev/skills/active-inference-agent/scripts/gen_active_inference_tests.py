        # ======================================================================
        # 1. TestLatentEncoder
        # ======================================================================


        class TestLatentEncoder:
            """Tests for the _BuiltinEncoder (latent encoder q(s|o))."""

            def test_output_shape(self, toy_encoder, device):
                """Encoder produces (B, state_dim) mu and log_var."""
                obs = torch.randn(B, OBS_DIM, device=device)
                mu, log_var = toy_encoder(obs)
                assert mu.shape == (B, STATE_DIM), f"mu shape {mu.shape}"
                assert log_var.shape == (B, STATE_DIM), f"log_var shape {log_var.shape}"

            def test_reparameterization(self, toy_encoder, device):
                """Sampling via reparameterization produces valid output."""
                obs = torch.randn(B, OBS_DIM, device=device)
                (mu, log_var), sample = toy_encoder.sample(obs)
                assert sample.shape == (B, STATE_DIM)
                # Sample should differ from mu due to noise
                assert not torch.allclose(sample, mu, atol=1e-7), (
                    "Sample should differ from mu (reparameterization noise)"
                )

            def test_deterministic_mu(self, toy_encoder, device):
                """Same input produces same mu and log_var."""
                torch.manual_seed(SEED)
                obs = torch.randn(B, OBS_DIM, device=device)
                mu1, lv1 = toy_encoder(obs)
                mu2, lv2 = toy_encoder(obs)
                assert torch.allclose(mu1, mu2, atol=1e-6)
                assert torch.allclose(lv1, lv2, atol=1e-6)

            def test_with_context(self, tiny_config, device):
                """Encoder accepts optional context tensor."""
                gc = tiny_config.generative
                encoder = _BuiltinEncoder(
                    obs_dim=gc.obs_dim,
                    state_dim=gc.state_dim,
                    hidden_dim=gc.hidden_dim,
                    num_layers=2,
                    ctx_dim=16,
                    ctx_mode="concat",
                )
                obs = torch.randn(B, gc.obs_dim, device=device)
                ctx = torch.randn(B, 16, device=device)
                mu, log_var = encoder(obs, ctx)
                assert mu.shape == (B, STATE_DIM)

            def test_without_context(self, toy_encoder, device):
                """Encoder works correctly when ctx is None."""
                obs = torch.randn(B, OBS_DIM, device=device)
                mu, log_var = toy_encoder(obs, ctx=None)
                assert mu.shape == (B, STATE_DIM)

            def test_kl_nonneg(self, toy_encoder, device):
                """KL divergence of encoder posterior vs N(0,I) is non-negative."""
                obs = torch.randn(B, OBS_DIM, device=device)
                mu, log_var = toy_encoder(obs)
                # KL(N(mu, diag(exp(lv))) || N(0, I))
                kl = 0.5 * (torch.exp(log_var) + mu.pow(2) - 1.0 - log_var).sum(dim=-1)
                assert (kl >= -1e-5).all(), f"KL has negative values: {kl.min().item()}"

