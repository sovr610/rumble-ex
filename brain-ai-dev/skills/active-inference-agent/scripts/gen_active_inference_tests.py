def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Generate comprehensive pytest test file for "
            "the Active Inference Agent."
        ),
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help=(
            "Output path for the generated test file. "
            "Defaults to tests/test_active_inference.py relative to "
            "this script's parent skill directory."
        ),
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the generated file to stdout instead of writing.",
    )
    args = parser.parse_args()

    content = build_test_file()

    if args.dry_run:
        print(content)
        return

    if args.output:
        output_path = Path(args.output)
    else:
        skill_dir = Path(__file__).resolve().parent.parent
        output_path = skill_dir / "tests" / "test_active_inference.py"

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")
    print(f"Generated test file: {output_path}")
    print(f"  Size: {len(content)} bytes, {content.count(chr(10))} lines")

    # Count test methods
    test_count = content.count("    def test_")
    class_count = content.count("class Test")
    print(f"  Classes: {class_count}, Test methods: {test_count}")


if __name__ == "__main__":
    main()
