def _indent(text: str, level: int = 1) -> str:
    """Indent every line of *text* by *level* * 4 spaces."""
    prefix = "    " * level
    return textwrap.indent(textwrap.dedent(text), prefix)


def _section_comment(title: str) -> str:
    """Return a prominent section separator comment."""
    bar = "# " + "=" * 70
    return f"\n\n{bar}\n# {title}\n{bar}\n"


