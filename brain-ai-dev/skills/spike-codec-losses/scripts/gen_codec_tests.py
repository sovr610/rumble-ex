def main() -> None:
    args = parse_args()

    content = build_test_file()

    # Verify syntax of generated content
    if not verify_syntax(content):
        print(
            "ERROR: Generated file has syntax errors. Aborting.",
            file=sys.stderr,
        )
        sys.exit(1)

    if args.dry_run:
        print(content)
        classes, cases = count_tests(content)
        print(
            f"\n# Dry run: {classes} test classes, "
            f"{cases} test cases",
            file=sys.stderr,
        )
        return

    output_path = (
        Path(args.output) if args.output else _default_output_path()
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)

    output_path.write_text(content, encoding="utf-8")

    print_summary(output_path, content)

    # Self-test: verify the written file
    written = output_path.read_text(encoding="utf-8")
    assert len(written) == len(content), (
        "Written content length mismatch"
    )
    assert verify_syntax(written), (
        "Written file fails syntax check"
    )

    classes, cases = count_tests(content)
    print(f"Written: {output_path}")
    print(
        f"Summary: {classes} test classes, "
        f"{cases} test cases generated"
    )
    print(
        f"File: {len(content):,} chars, "
        f"{content.count(chr(10)):,} lines"
    )


