def count_tests(content: str) -> Tuple[int, int]:
    """Count test classes and test cases in generated content."""
    classes = 0
    cases = 0
    for line in content.splitlines():
        stripped = line.strip()
        if stripped.startswith("class Test"):
            classes += 1
        if stripped.startswith("def test_"):
            cases += 1
    return classes, cases


