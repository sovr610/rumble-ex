        has_spiked = (cumsum >= 1.0)
        t_first = has_spiked.float().argmax(dim=1)
        ever_spiked = (cumsum[:, -1, :] > 0)
        t_first = torch.where(ever_spiked, t_first, torch.full_like(t_first, T))
