    class ProbSpikesLoss(LossTerm):
        def __init__(self, temperature=1.0, eps=1e-7, mode="softmax"):
            super().__init__()
            self.temperature = temperature
            self.eps = eps
            self.mode = mode

        def forward(self, spikes, membrane, targets, **kwargs):
            counts = spikes.float().sum(dim=1)
            if self.mode == "softmax":
                scaled = counts / self.temperature
                log_probs = F.log_softmax(scaled, dim=-1)
                loss = F.nll_loss(log_probs, targets)
            elif self.mode == "normalize":
                total = counts.sum(dim=-1, keepdim=True)
                probs = counts / (total + self.eps)
                probs = probs.clamp(min=self.eps)
                log_probs = probs.log()
                loss = F.nll_loss(log_probs, targets)
            else:
                loss = torch.tensor(0.0, device=spikes.device)
            with torch.no_grad():
                diag = {
                    "mean_count": counts.mean().item(),
                    "max_count": counts.max().item(),
                    "accuracy": (
                        (counts.argmax(dim=-1) == targets).float().mean().item()
                    ),
                }
            return loss, diag

    class SpikeRateRegularization(LossTerm):
        def __init__(
            self,
            target_rate=0.1,
            min_rate=0.01,
            max_rate=0.3,
            rate_type="l2",
            use_range_penalty=True,
        ):
            super().__init__()
            self.target_rate = target_rate
            self.min_rate = min_rate
            self.max_rate = max_rate
            self.rate_type = rate_type
            self.use_range_penalty = use_range_penalty

        def forward(self, spikes, membrane, targets, **kwargs):
            rates = spikes.float().mean(dim=1)
            if self.rate_type == "l2":
                target_loss = ((rates - self.target_rate) ** 2).mean()
            elif self.rate_type == "l1":
                target_loss = (rates - self.target_rate).abs().mean()
            else:
                target_loss = torch.tensor(0.0, device=spikes.device)
            loss = target_loss
            if self.use_range_penalty:
                below = F.relu(self.min_rate - rates)
                above = F.relu(rates - self.max_rate)
                range_loss = (below + above).mean()
                loss = loss + range_loss
            with torch.no_grad():
                diag = {
                    "mean_rate": rates.mean().item(),
                    "max_rate": rates.max().item(),
                    "min_rate": rates.min().item(),
                }
            return loss, diag

    class TemporalConsistencyLoss(LossTerm):
        def __init__(self, window_size=5, penalty_type="l2"):
            super().__init__()
            self.window_size = window_size
            self.penalty_type = penalty_type

        def forward(self, spikes, membrane, targets, **kwargs):
            B, T, N = spikes.shape
            if self.penalty_type in ("l1", "l2"):
                rates = spikes.float()
                diffs = rates[:, 1:, :] - rates[:, :-1, :]
                if self.penalty_type == "l1":
                    loss = diffs.abs().mean()
                else:
                    loss = (diffs ** 2).mean()
            elif self.penalty_type == "variance":
                if T < self.window_size * 2:
                    zero = torch.tensor(0.0, device=spikes.device)
                    return zero, {"skipped": 1.0}
                n_windows = T // self.window_size
                trimmed = spikes[:, :n_windows * self.window_size, :].float()
                windowed = trimmed.view(B, n_windows, self.window_size, N)
                window_means = windowed.mean(dim=2)
                loss = window_means.var(dim=1).mean()
            else:
                loss = torch.tensor(0.0, device=spikes.device)
            with torch.no_grad():
                rates_f = spikes.float()
                rate_diffs = rates_f[:, 1:, :] - rates_f[:, :-1, :]
                diag = {
                    "mean_temporal_variance": rate_diffs.var().item(),
                }
            return loss, diag

    class ISIRegularization(LossTerm):
        def __init__(
            self,
            refractory_window=5,
            kernel_type="exponential",
            penalty_weight=1.0,
        ):
            super().__init__()
            self.refractory_window = refractory_window
            self.kernel_type = kernel_type
            self.penalty_weight = penalty_weight
            k = torch.arange(
                1, refractory_window + 1, dtype=torch.float32,
            )
            if kernel_type == "exponential":
                tau = refractory_window / 3.0
                kernel = torch.exp(-k / tau)
            elif kernel_type == "rectangular":
                kernel = torch.ones_like(k)
            else:
                kernel = torch.ones_like(k)
            self.register_buffer(
                "kernel", kernel.flip(0).unsqueeze(0).unsqueeze(0),
            )

        def forward(self, spikes, membrane, targets, **kwargs):
            B, T, N = spikes.shape
            s = spikes.float().permute(0, 2, 1).reshape(B * N, 1, T)
            kernel_fp32 = self.kernel
            padded = F.pad(s, (self.refractory_window, 0))
            refractory_signal = F.conv1d(padded, kernel_fp32)
            penalty = (s * refractory_signal).mean()
            loss = self.penalty_weight * penalty
            with torch.no_grad():
                diag = {"mean_refractory_penalty": penalty.item()}
            return loss, diag

    class MembraneRegularization(LossTerm):
        def __init__(self, max_membrane=1.5):
            super().__init__()
            self.max_membrane = max_membrane

        def forward(self, spikes, membrane, targets, **kwargs):
            if membrane is None:
                zero = torch.tensor(0.0, device=spikes.device)
                return zero, {"skipped": 1.0}
            excess = F.relu(membrane.float().abs() - self.max_membrane)
            loss = (excess ** 2).mean()
            with torch.no_grad():
                diag = {
                    "mean_membrane": membrane.float().mean().item(),
                    "max_membrane": membrane.float().abs().max().item(),
                }
            return loss, diag

    class SNNLossComposer(nn.Module):
        def __init__(self, terms: dict):
            super().__init__()
            self.terms = nn.ModuleDict(
                {k: v[0] for k, v in terms.items()},
            )
            self.weights = {k: v[1] for k, v in terms.items()}

        def forward(self, spikes, membrane, targets, **kwargs):
            total = torch.tensor(
                0.0, device=spikes.device, dtype=torch.float32,
            )
            components = {}
            diagnostics = {}
            for name, term in self.terms.items():
                w = self.weights[name]
                if w == 0.0:
                    continue
                raw_loss, diag = term(spikes, membrane, targets, **kwargs)
                weighted = w * raw_loss
                total = total + weighted
                components[f"loss/{name}_raw"] = raw_loss.item()
                components[f"loss/{name}_weighted"] = weighted.item()
                diagnostics.update(
                    {f"diag/{name}/{k}": v for k, v in diag.items()},
                )
            components["loss/total"] = total.item()
            return total, {**components, **diagnostics}


