class WorkingMemory(nn.Module):
    """Working Memory module with automatic backend selection.

    Integrates a recurrent backend (CfC, LTC, or GRU) with a capacity-limited
    ring buffer and ignition-gated memory updates.

    Auto backend selection at init:
        If mode == 'auto': try CfC -> LTC -> GRU.
        If mode == 'cfc' and ncps unavailable: fall back to GRU with warning.
        If mode == 'ltc' and ncps unavailable: fall back to GRU with warning.
        If mode == 'gru': always use GRU.

    Forward pass:
        1. If input is (B, K, D): attention-pool to (B, D) via SlotPooler.
        2. Run through the recurrent backend.
        3. If ignition gain is provided: interpolate hidden state and
           write to buffer with gain weighting.
        4. Return (wm_out, next_state).

    Args:
        config: WMConfig or None (uses defaults).
        **kwargs: Forwarded to WMConfig if config is None.
    """

    def __init__(self, config: Optional[WMConfig] = None, **kwargs):
        super().__init__()

        self.config = config or WMConfig(**kwargs)

        # -- resolve backend mode ----------------------------------------
        resolved_mode = self._resolve_mode(self.config.mode)
        self._backend_type = resolved_mode

        # -- create backend -----------------------------------------------
        if resolved_mode == "cfc":
            self.backend = CfCBackend(
                input_dim=self.config.input_dim,
                hidden_dim=self.config.hidden_dim,
                output_dim=self.config.output_dim,
                num_units=self.config.num_units,
                sparsity=self.config.sparsity,
                dropout=self.config.dropout,
            )
        elif resolved_mode == "ltc":
            self.backend = LTCBackend(
                input_dim=self.config.input_dim,
                hidden_dim=self.config.hidden_dim,
                output_dim=self.config.output_dim,
                num_units=self.config.num_units,
                sparsity=self.config.sparsity,
                dropout=self.config.dropout,
            )
        else:  # gru
            self.backend = GRUBackend(
                input_dim=self.config.input_dim,
                hidden_dim=self.config.hidden_dim,
                output_dim=self.config.output_dim,
                num_layers=self.config.num_layers,
                dropout=self.config.dropout,
                use_dt=self.config.use_dt,
                dt_input_mode=self.config.dt_input_mode,
            )

        # -- slot pooler (for (B, K, D) input) ----------------------------
        num_pool_heads = max(1, min(8, self.config.input_dim // 64))
        self.slot_pooler = SlotPooler(
            dim=self.config.input_dim,
            num_heads=num_pool_heads,
            dropout=self.config.dropout,
        )

        # -- memory buffer -------------------------------------------------
        self.memory_buffer = MemoryBuffer(
            capacity=self.config.buffer_capacity,
            dim=self.config.output_dim,
        )

        # -- dropout for output -------------------------------------------
        self.output_dropout = nn.Dropout(self.config.dropout)

        logger.info(
            "WorkingMemory initialized: backend=%s, input_dim=%d, "
            "hidden_dim=%d, output_dim=%d, buffer_capacity=%d",
            self._backend_type,
            self.config.input_dim,
            self.config.hidden_dim,
            self.config.output_dim,
            self.config.buffer_capacity,
        )

    # -- backend resolution ------------------------------------------------

    @staticmethod
    def _resolve_mode(mode: str) -> str:
        """Resolve 'auto' mode and validate.

        Auto selection order: CfC -> LTC -> GRU.

        Returns:
            Resolved mode string: 'cfc', 'ltc', or 'gru'.
        """
        if mode == "auto":
            if NCPS_AVAILABLE:
                return "cfc"
            else:
                logger.info(
                    "WorkingMemory: ncps not available; auto-selecting GRU backend."
                )
                return "gru"
        elif mode == "cfc":
            if not NCPS_AVAILABLE:
                logger.warning(
                    "WorkingMemory: CfC requested but ncps not available; "
                    "falling back to GRU."
                )
                return "gru"
            return "cfc"
        elif mode == "ltc":
            if not NCPS_AVAILABLE:
                logger.warning(
                    "WorkingMemory: LTC requested but ncps not available; "
                    "falling back to GRU."
                )
                return "gru"
            return "ltc"
        elif mode == "gru":
            return "gru"
        else:
            raise ValueError(
                f"Unknown working memory mode '{mode}'. "
                f"Choose from: 'cfc', 'ltc', 'gru', 'auto'."
            )

    # -- properties --------------------------------------------------------

    @property
    def backend_type(self) -> str:
        """Return the resolved backend type: 'cfc', 'ltc', or 'gru'."""
        return self._backend_type

    # -- state management --------------------------------------------------

    def reset_state(
        self,
        batch_size: int,
        device: torch.device,
        dtype: torch.dtype = torch.float32,
    ) -> WMState:
        """Create a fresh initial state for the given batch.

        Args:
            batch_size: Number of sequences in the batch.
            device: Target device.
            dtype: Target dtype (default fp32).

        Returns:
            Freshly initialized WMState with zero hidden and empty buffer.
        """
        # Hidden state for GRU backend
        if self._backend_type == "gru":
            hidden = torch.zeros(
                self.config.num_layers,
                batch_size,
                self.config.hidden_dim,
                device=device,
                dtype=dtype,
            )
        else:
            # CfC / LTC: None lets the backend initialize its own state
            # We store a zero tensor as a sentinel that we convert to None
            # during forward.  This keeps WMState fields as Tensors for
            # serialization consistency.
            hidden = torch.zeros(1, device=device, dtype=dtype)

        buffer = torch.zeros(
            batch_size,
            self.config.buffer_capacity,
            self.config.output_dim,
            device=device,
            dtype=dtype,
        )

        # Also reset the internal MemoryBuffer module
        self.memory_buffer.reset(batch_size, device, dtype)

        return WMState(
            hidden=hidden,
            buffer=buffer,
            buffer_ptr=0,
            buffer_count=0,
            step_count=0,
        )

    def detach_state(self, state: WMState) -> WMState:
        """Detach all tensors in a WMState (for truncated BPTT).

        Values are preserved but gradient history is discarded.

        Args:
            state: State to detach.

        Returns:
            New WMState with all tensors detached.
        """
        return state.detach()

    def get_state_norms(self, state: WMState) -> Dict[str, float]:
        """Return L2 norms of all state tensors for monitoring.

        Args:
            state: WMState to inspect.

        Returns:
            Dictionary mapping name -> L2 norm (float).
        """
        norms: Dict[str, float] = {}

        # Hidden norms
        norms.update(_hidden_norms(state.hidden, "hidden"))

        # Buffer norm
        norms["buffer"] = state.buffer.float().norm().item()

        # Summary statistics
        norms["buffer_count"] = float(state.buffer_count)
        norms["step_count"] = float(state.step_count)

        return norms

    def get_summary(self, state: WMState) -> Tensor:
        """Return mean of valid buffer entries from a WMState.

        Args:
            state: WMState containing buffer data.

        Returns:
            (B, D) mean vector.  Zeros if buffer is empty.
        """
        if state.buffer_count == 0:
            B = state.buffer.shape[0]
            D = state.buffer.shape[2]
            return torch.zeros(
                B, D,
                device=state.buffer.device,
                dtype=state.buffer.dtype,
            )

        count = min(state.buffer_count, self.config.buffer_capacity)

        if count < self.config.buffer_capacity:
            # Not yet wrapped — valid entries at 0..count-1
            valid = state.buffer[:, :count, :]
        else:
            # Full ring buffer — reorder from oldest to newest
            ptr = state.buffer_ptr
            indices = [(ptr + i) % self.config.buffer_capacity
                       for i in range(self.config.buffer_capacity)]
            valid = state.buffer[:, indices, :]

        return valid.mean(dim=1)  # (B, D)

    # -- forward -----------------------------------------------------------

    def forward(
        self,
        slots: Tensor,
        state: Optional[WMState] = None,
        dt: Optional[Tensor] = None,
        gain: Optional[Tensor] = None,
    ) -> Tuple[Tensor, WMState]:
        """Process input through working memory.

        Args:
            slots: Input tensor.
                (B, D) — single workspace vector per batch element.
                (B, K, D) — K slots per batch element (attention-pooled).
            state: Current WMState, or None (will auto-reset).
            dt: Optional delta-time tensor (B,) or (B, 1).
                Passed as timespans to CfC/LTC, or integrated into GRU
                via the configured dt_input_mode.
            gain: Optional ignition gain (B,) or (B, 1).
                Modulates the memory update:
                  next_hidden = gain * new_hidden + (1-gain) * state.hidden
                  buffer write is weighted by gain.
                If None, full update (gain=1).

        Returns:
            wm_out: (B, output_dim) working memory output.
            next_state: Updated WMState.
        """
        # -- determine batch size and device -------------------------------
        if slots.dim() == 2:
            B, D = slots.shape
            x = slots
        elif slots.dim() == 3:
            B, K, D = slots.shape
            # Attention-pool to (B, D)
            x = self.slot_pooler(slots)
        else:
            raise ValueError(
                f"Expected slots of shape (B, D) or (B, K, D), "
                f"got {slots.shape}"
            )

        device = x.device
        dtype = x.dtype

        # -- auto-reset state if needed ------------------------------------
        if state is None:
            state = self.reset_state(B, device, dtype)

        # -- prepare hidden state for backend -----------------------------
        if self._backend_type == "gru":
            backend_hidden = state.hidden
            # Ensure batch size compatibility
            if backend_hidden.shape[1] != B:
                backend_hidden = torch.zeros(
                    self.config.num_layers, B, self.config.hidden_dim,
                    device=device, dtype=dtype,
                )
        else:
            # CfC / LTC: use None if sentinel
            if state.hidden.numel() == 1:
                backend_hidden = None
            else:
                backend_hidden = state.hidden

        # -- backend forward -----------------------------------------------
        wm_out, new_hidden = self.backend(x, backend_hidden, dt=dt)

        # -- ignition-gated update -----------------------------------------
        if gain is not None:
            if gain.dim() == 1:
                gain_expanded = gain.unsqueeze(-1)  # (B, 1)
            else:
                gain_expanded = gain

            # Interpolate hidden state
            if self._backend_type == "gru":
                # GRU hidden: (num_layers, B, hidden_dim)
                gain_h = gain_expanded.unsqueeze(0)  # (1, B, 1)
                new_hidden = gain_h * new_hidden + (1.0 - gain_h) * state.hidden
            else:
                # CfC/LTC: only interpolate if old hidden is not sentinel
                if state.hidden.numel() > 1 and new_hidden is not None:
                    if isinstance(new_hidden, Tensor):
                        # Determine how to reshape gain for the hidden shape
                        if new_hidden.dim() == 2:
                            # (B, hidden_dim)
                            new_hidden = gain_expanded * new_hidden + (1.0 - gain_expanded) * state.hidden
                        else:
                            new_hidden = gain_expanded.view(B, *([1] * (new_hidden.dim() - 1))) * new_hidden + \
                                         (1.0 - gain_expanded.view(B, *([1] * (new_hidden.dim() - 1)))) * state.hidden

            # Buffer write with gain weighting
            write_gain = gain_expanded  # (B, 1)
        else:
            write_gain = None

        # -- apply output dropout -----------------------------------------
        wm_out = self.output_dropout(wm_out)

        # -- write to buffer -----------------------------------------------
        # Update internal MemoryBuffer (for retrieve/summary convenience)
        self.memory_buffer._buffer = state.buffer.clone()
        self.memory_buffer._ptr = state.buffer_ptr
        self.memory_buffer._count = state.buffer_count
        self.memory_buffer._batch_size = B
        self.memory_buffer.write(wm_out.detach(), gain=write_gain)

        # -- build next state ----------------------------------------------
        # Use the updated MemoryBuffer state
        new_buffer = self.memory_buffer._buffer
        new_ptr = self.memory_buffer._ptr
        new_count = self.memory_buffer._count

        # For CfC/LTC, ensure hidden is stored as Tensor
        if new_hidden is None:
            stored_hidden = torch.zeros(1, device=device, dtype=dtype)
        elif isinstance(new_hidden, Tensor):
            stored_hidden = new_hidden
        else:
            # Tuple/list hidden — store as-is (WMState.hidden is typed as
            # Tensor but in practice we allow Any for CfC/LTC)
            stored_hidden = new_hidden  # type: ignore[assignment]

        next_state = WMState(
            hidden=stored_hidden,
            buffer=new_buffer,
            buffer_ptr=new_ptr,
            buffer_count=new_count,
            step_count=state.step_count + 1,
        )

        return wm_out, next_state


