class GRUBackend(nn.Module):
    """GRU-based working memory backend.

    Provides temporal integration using standard GRU cells with optional
    delta-time (dt) handling.

    dt handling modes:
        'concat' — dt is embedded, concatenated to the input, and a larger
            input projection accommodates the extra features.
        'gate_scale' — a learned linear layer maps dt to a scale factor
            applied to the GRU update gate (z) via a hook that modifies
            the GRU output.  This is a lightweight post-hoc approach.

    Args:
        input_dim: Input feature dimension.
        hidden_dim: GRU hidden dimension.
        output_dim: Output feature dimension.
        num_layers: Number of stacked GRU layers.
        dropout: Dropout between GRU layers (only when num_layers > 1).
        use_dt: Whether to accept and integrate dt.
        dt_input_mode: 'concat' or 'gate_scale'.
    """

    # Dimensionality of the dt embedding used in concat mode
    DT_EMBED_DIM: int = 64

    def __init__(
        self,
        input_dim: int = 4096,
        hidden_dim: int = 4096,
        output_dim: int = 4096,
        num_layers: int = 1,
        dropout: float = 0.1,
        use_dt: bool = True,
        dt_input_mode: str = "concat",
    ):
        super().__init__()

        self.input_dim = input_dim
        self.hidden_dim = hidden_dim
        self.output_dim = output_dim
        self.num_layers = num_layers
        self.use_dt = use_dt
        self.dt_input_mode = dt_input_mode

        # -- dt handling layers -------------------------------------------
        if use_dt and dt_input_mode == "concat":
            # Embed scalar dt into a small vector and concat to input
            self.dt_embed = nn.Sequential(
                nn.Linear(1, self.DT_EMBED_DIM),
                nn.ReLU(),
                nn.Linear(self.DT_EMBED_DIM, self.DT_EMBED_DIM),
            )
            gru_input_dim = input_dim + self.DT_EMBED_DIM
        elif use_dt and dt_input_mode == "gate_scale":
            # Learn a scalar gate-scale from dt
            self.dt_gate_linear = nn.Linear(1, hidden_dim)
            gru_input_dim = input_dim
        else:
            gru_input_dim = input_dim

        # -- input projection ---------------------------------------------
        self.input_proj = nn.Linear(gru_input_dim, hidden_dim)

        # -- GRU -----------------------------------------------------------
        self.gru = nn.GRU(
            input_size=hidden_dim,
            hidden_size=hidden_dim,
            num_layers=num_layers,
            batch_first=True,
            dropout=dropout if num_layers > 1 else 0.0,
        )

        # -- output projection --------------------------------------------
        self.output_proj = nn.Sequential(
            nn.Linear(hidden_dim, output_dim),
            nn.LayerNorm(output_dim),
        )

    def forward(
        self,
        x: Tensor,
        hidden: Optional[Tensor] = None,
        dt: Optional[Tensor] = None,
    ) -> Tuple[Tensor, Tensor]:
        """Process a single step through the GRU backend.

        Args:
            x: Input tensor (B, input_dim).
            hidden: GRU hidden state (num_layers, B, hidden_dim) or None.
            dt: Optional delta-time tensor.
                For 'concat' mode: (B,) or (B, 1) scalar dt values.
                For 'gate_scale' mode: (B,) or (B, 1) scalar dt values.

        Returns:
            output: (B, output_dim).
            new_hidden: (num_layers, B, hidden_dim).
        """
        batch_size = x.shape[0]

        # -- dt integration -----------------------------------------------
        if self.use_dt and dt is not None:
            if dt.dim() == 1:
                dt = dt.unsqueeze(-1)  # (B, 1)

            if self.dt_input_mode == "concat":
                dt_feat = self.dt_embed(dt)  # (B, DT_EMBED_DIM)
                x = torch.cat([x, dt_feat], dim=-1)  # (B, input_dim + DT_EMBED_DIM)

        # -- input projection --------------------------------------------
        x = self.input_proj(x)  # (B, hidden_dim)

        # Add sequence dimension for GRU
        x = x.unsqueeze(1)  # (B, 1, hidden_dim)

        # -- GRU forward ---------------------------------------------------
        output, new_hidden = self.gru(x, hidden)  # output: (B, 1, hidden_dim)
        output = output.squeeze(1)  # (B, hidden_dim)

        # -- gate_scale dt modulation (post-hoc) --------------------------
        if self.use_dt and dt is not None and self.dt_input_mode == "gate_scale":
            if dt.dim() == 1:
                dt = dt.unsqueeze(-1)
            gate_scale = torch.sigmoid(self.dt_gate_linear(dt))  # (B, hidden_dim)
            output = output * gate_scale

        # -- output projection --------------------------------------------
        output = self.output_proj(output)  # (B, output_dim)

        return output, new_hidden


