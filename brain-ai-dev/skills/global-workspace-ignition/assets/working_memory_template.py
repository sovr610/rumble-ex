def create_working_memory(
    config: Optional[WMConfig] = None,
    **kwargs,
) -> WorkingMemory:
    """Create a WorkingMemory instance with automatic backend selection.

    If `mode` is 'auto' (default when no config provided), the factory
    tries CfC first, then LTC, then GRU.

    Args:
        config: Pre-built WMConfig.  If None, one is constructed from kwargs.
        **kwargs: Forwarded to WMConfig constructor if config is None.

    Returns:
        Configured WorkingMemory module.

    Examples:
        >>> wm = create_working_memory()  # auto mode, default dims
        >>> wm = create_working_memory(mode='gru', input_dim=512)
        >>> cfg = WMConfig(mode='cfc', num_units=64)
        >>> wm = create_working_memory(config=cfg)
    """
    if config is None:
        # Set auto mode as default if not specified
        if "mode" not in kwargs:
            kwargs["mode"] = "auto"
        config = WMConfig(**kwargs)

    return WorkingMemory(config=config)


