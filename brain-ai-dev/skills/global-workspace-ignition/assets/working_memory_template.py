    class TestMemoryBuffer(unittest.TestCase):
        """Tests for MemoryBuffer ring buffer."""

        def _make_buffer(self, capacity=7, dim=64, batch_size=2):
            buf = MemoryBuffer(capacity=capacity, dim=dim)
            buf.reset(batch_size, device=torch.device("cpu"), dtype=torch.float32)
            return buf

        def test_write_and_read(self):
            """Write entries and read them back."""
            buf = self._make_buffer(capacity=7, dim=64, batch_size=2)
            entry = torch.randn(2, 64)
            buf.write(entry)
            result = buf.read_all()
            self.assertEqual(result.shape, (2, 1, 64))
            torch.testing.assert_close(result[:, 0, :], entry)

        def test_read_empty(self):
            """Reading from empty buffer returns (B, 0, D)."""
            buf = self._make_buffer()
            result = buf.read_all()
            self.assertEqual(result.shape[1], 0)

        def test_summary(self):
            """Summary returns mean of valid entries."""
            buf = self._make_buffer(capacity=7, dim=64, batch_size=2)
            e1 = torch.ones(2, 64) * 2.0
            e2 = torch.ones(2, 64) * 4.0
            buf.write(e1)
            buf.write(e2)
            summary = buf.summary()
            self.assertEqual(summary.shape, (2, 64))
            # Mean of 2 and 4 = 3
            torch.testing.assert_close(
                summary, torch.ones(2, 64) * 3.0, atol=1e-5, rtol=1e-5
            )

        def test_summary_empty(self):
            """Summary of empty buffer returns zeros."""
            buf = self._make_buffer()
            summary = buf.summary()
            self.assertEqual(summary.shape, (2, 64))
            self.assertTrue(torch.all(summary == 0.0))

        def test_retrieve(self):
            """Attention-weighted retrieval returns (B, D)."""
            buf = self._make_buffer(capacity=7, dim=64, batch_size=2)
            buf.write(torch.randn(2, 64))
            buf.write(torch.randn(2, 64))
            query = torch.randn(2, 64)
            retrieved = buf.retrieve(query)
            self.assertEqual(retrieved.shape, (2, 64))

        def test_retrieve_empty(self):
            """Retrieval from empty buffer returns query."""
            buf = self._make_buffer()
            query = torch.randn(2, 64)
            retrieved = buf.retrieve(query)
            torch.testing.assert_close(retrieved, query)

        def test_ring_buffer_wrapping(self):
            """Writing more than capacity wraps correctly."""
            capacity = 3
            buf = self._make_buffer(capacity=capacity, dim=8, batch_size=1)

            entries = []
            for i in range(5):  # Write 5 entries into capacity-3 buffer
                e = torch.ones(1, 8) * float(i)
                entries.append(e)
                buf.write(e)

            self.assertEqual(buf.get_count(), capacity)

            # After 5 writes into capacity 3:
            # ptr wraps: 0,1,2,0,1 -> ptr is now at 2
            # buffer contains entries[2], entries[3], entries[4] at indices 2,0,1
            # read_all should return them in chronological order: entries[2], entries[3], entries[4]
            result = buf.read_all()
            self.assertEqual(result.shape, (1, capacity, 8))

            # Verify the values are the last 3 entries written (values 2, 3, 4)
            expected_vals = [2.0, 3.0, 4.0]
            for i, val in enumerate(expected_vals):
                torch.testing.assert_close(
                    result[0, i, 0],
                    torch.tensor(val),
                    atol=1e-6, rtol=1e-6,
                )

        def test_write_with_gain(self):
            """Gain-weighted write scales the entry."""
            buf = self._make_buffer(capacity=3, dim=8, batch_size=2)
            entry = torch.ones(2, 8) * 10.0
            gain = torch.tensor([0.5, 0.0]).unsqueeze(-1)  # (B, 1)
            buf.write(entry, gain=gain)

            result = buf.read_all()
            # Batch 0: 10 * 0.5 = 5.0
            self.assertAlmostEqual(result[0, 0, 0].item(), 5.0, places=4)
            # Batch 1: 10 * 0.0 = 0.0
            self.assertAlmostEqual(result[1, 0, 0].item(), 0.0, places=4)

    class TestWorkingMemory(unittest.TestCase):
        """Tests for the main WorkingMemory module."""

        def _make_wm(self, dim=64, mode="gru", **kwargs):
            cfg = WMConfig(
                input_dim=dim, hidden_dim=dim, output_dim=dim,
                mode=mode, num_layers=1, buffer_capacity=5,
                num_units=32, **kwargs,
            )
            return WorkingMemory(config=cfg)

        def test_forward_2d_input(self):
            """WorkingMemory forward with (B, D) input."""
            B, D = 4, 64
            wm = self._make_wm(D)
            x = torch.randn(B, D)
            state = wm.reset_state(B, torch.device("cpu"))
            out, next_state = wm(x, state)
            self.assertEqual(out.shape, (B, D))
            self.assertIsInstance(next_state, WMState)
            self.assertEqual(next_state.step_count, 1)

        def test_forward_3d_slot_input(self):
            """WorkingMemory forward with (B, K, D) slot input."""
            B, K, D = 4, 3, 64
            wm = self._make_wm(D)
            slots = torch.randn(B, K, D)
            state = wm.reset_state(B, torch.device("cpu"))
            out, next_state = wm(slots, state)
            self.assertEqual(out.shape, (B, D))

        def test_reset_state_shapes(self):
            """reset_state creates correct shape/device/dtype."""
            B, D = 4, 64
            wm = self._make_wm(D)
            state = wm.reset_state(B, torch.device("cpu"), dtype=torch.float32)

            # GRU hidden: (num_layers, B, hidden_dim)
            self.assertEqual(state.hidden.shape, (1, B, D))
            self.assertEqual(state.hidden.dtype, torch.float32)

            # Buffer: (B, capacity, output_dim)
            self.assertEqual(state.buffer.shape, (B, 5, D))
            self.assertEqual(state.buffer.dtype, torch.float32)

            self.assertEqual(state.buffer_ptr, 0)
            self.assertEqual(state.buffer_count, 0)
            self.assertEqual(state.step_count, 0)

        def test_detach_state(self):
            """detach_state preserves values, removes grad tracking."""
            B, D = 4, 64
            wm = self._make_wm(D)
            x = torch.randn(B, D)
            state = wm.reset_state(B, torch.device("cpu"))
            out, next_state = wm(x, state)

            detached = wm.detach_state(next_state)
            if isinstance(detached.hidden, Tensor):
                self.assertFalse(detached.hidden.requires_grad)
            self.assertFalse(detached.buffer.requires_grad)
            # Values unchanged
            if isinstance(detached.hidden, Tensor) and isinstance(next_state.hidden, Tensor):
                torch.testing.assert_close(detached.hidden.data, next_state.hidden.data)

        def test_state_persistence(self):
            """Sequential forward calls produce different outputs."""
            B, D = 2, 64
            wm = self._make_wm(D)
            state = wm.reset_state(B, torch.device("cpu"))

            x1 = torch.randn(B, D)
            x2 = torch.randn(B, D)

            out1, state = wm(x1, state)
            out2, state = wm(x2, state)

            # Different inputs + accumulated state -> different outputs
            self.assertFalse(torch.allclose(out1, out2, atol=1e-6))
            self.assertEqual(state.step_count, 2)

        def test_reset_restores_baseline(self):
            """Resetting state after forward steps restores baseline behavior."""
            B, D = 2, 64
            wm = self._make_wm(D)

            torch.manual_seed(42)
            state0 = wm.reset_state(B, torch.device("cpu"))
            x = torch.randn(B, D)
            out_baseline, _ = wm(x, state0)

            # Run some forward steps
            state = wm.reset_state(B, torch.device("cpu"))
            for _ in range(5):
                _, state = wm(torch.randn(B, D), state)

            # Reset and rerun
            torch.manual_seed(42)
            state_reset = wm.reset_state(B, torch.device("cpu"))
            x = torch.randn(B, D)
            out_after_reset, _ = wm(x, state_reset)

            torch.testing.assert_close(out_baseline, out_after_reset, atol=1e-5, rtol=1e-5)

        def test_gain_zero_preserves_state(self):
            """gain=0 should keep hidden state unchanged (GRU backend)."""
            B, D = 2, 64
            wm = self._make_wm(D)
            state = wm.reset_state(B, torch.device("cpu"))

            x = torch.randn(B, D)
            gain = torch.zeros(B)  # No update
            _, next_state = wm(x, state, gain=gain)

            # Hidden should be unchanged from initial (zeros)
            torch.testing.assert_close(
                next_state.hidden,
                state.hidden,
                atol=1e-6, rtol=1e-6,
            )

        def test_gain_one_full_update(self):
            """gain=1 should commit full update (same as no gain)."""
            B, D = 2, 64
            wm = self._make_wm(D)
            state = wm.reset_state(B, torch.device("cpu"))
            x = torch.randn(B, D)

            # With gain=1
            gain = torch.ones(B)
            out_gain, state_gain = wm(x, state, gain=gain)

            # Without gain (should be identical)
            state2 = wm.reset_state(B, torch.device("cpu"))
            out_no_gain, state_no_gain = wm(x, state2, gain=None)

            torch.testing.assert_close(out_gain, out_no_gain, atol=1e-5, rtol=1e-5)

        def test_get_state_norms(self):
            """get_state_norms returns a dict with float values."""
            B, D = 2, 64
            wm = self._make_wm(D)
            state = wm.reset_state(B, torch.device("cpu"))
