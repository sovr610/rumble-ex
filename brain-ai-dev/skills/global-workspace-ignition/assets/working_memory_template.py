class SlotPooler(nn.Module):
    """Attention-based pooling of (B, K, D) slots to (B, D).

    Uses a single learnable query vector and cross-attention to produce a
    fixed-size summary of variable-length slot inputs.

    The operation is:
        query = self.query_embed (1, 1, D) expanded to (B, 1, D)
        attn_out = cross_attention(query, keys=slots, values=slots)
        output = attn_out.squeeze(1)  -> (B, D)

    This preserves information from all slots via attention weights while
    producing a deterministic-size output for the recurrent backend.

    Args:
        dim: Feature dimension of the slots and query.
        num_heads: Number of attention heads for cross-attention.
        dropout: Attention dropout probability.
    """

    def __init__(self, dim: int, num_heads: int = 8, dropout: float = 0.1):
        super().__init__()

        self.dim = dim
        self.num_heads = num_heads

        # Learnable query vector
        self.query_embed = nn.Parameter(torch.randn(1, 1, dim) * 0.02)

        # Cross-attention: query attends to slots
        self.cross_attn = nn.MultiheadAttention(
            embed_dim=dim,
            num_heads=num_heads,
            dropout=dropout,
            batch_first=True,
        )

        self.norm = nn.LayerNorm(dim)

    def forward(self, slots: Tensor) -> Tensor:
        """Pool slots to a single vector via cross-attention.

        Args:
            slots: (B, K, D) input slots.

        Returns:
            pooled: (B, D) summary vector.
        """
        B = slots.shape[0]

        # Expand query to batch
        query = self.query_embed.expand(B, -1, -1)  # (B, 1, D)

        # Cross-attention
        attn_out, _ = self.cross_attn(query, slots, slots)  # (B, 1, D)

        # Squeeze and normalize
        pooled = attn_out.squeeze(1)  # (B, D)
        pooled = self.norm(pooled)

        return pooled


