def _detach_hidden(h: Any) -> Any:
    """Recursively detach a hidden state that may be a Tensor, tuple, or list."""
    if isinstance(h, Tensor):
        return h.detach()
    elif isinstance(h, tuple):
        return tuple(_detach_hidden(x) for x in h)
    elif isinstance(h, list):
        return [_detach_hidden(x) for x in h]
    return h


def _clone_hidden(h: Any) -> Any:
    """Recursively clone a hidden state."""
    if isinstance(h, Tensor):
        return h.clone()
    elif isinstance(h, tuple):
        return tuple(_clone_hidden(x) for x in h)
    elif isinstance(h, list):
        return [_clone_hidden(x) for x in h]
    return h


def _hidden_norms(h: Any, prefix: str = "hidden") -> Dict[str, float]:
    """Return L2 norms of all tensors in a hidden state."""
    norms: Dict[str, float] = {}
    if isinstance(h, Tensor):
        norms[prefix] = h.float().norm().item()
    elif isinstance(h, (tuple, list)):
        for i, x in enumerate(h):
            norms.update(_hidden_norms(x, f"{prefix}_{i}"))
    return norms


