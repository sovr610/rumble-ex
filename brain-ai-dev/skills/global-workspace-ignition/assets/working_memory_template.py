class MemoryBuffer(nn.Module):
    """Fixed-capacity ring buffer for working memory storage.

    Stores up to `capacity` entries of dimension `dim` per batch element.
    Uses a pre-allocated tensor and a circular write pointer for O(1) writes
    (no torch.cat per step, which would cause quadratic memory growth).

    Ignition-gated writing:
        When `gain` is provided to `write()`, the entry is scaled by the
        gain factor before storage.  This allows the global workspace ignition
        signal to modulate how strongly new content is committed to memory.

    Thread safety:
        Not thread-safe.  The buffer_ptr and buffer_count are plain Python
        ints.  For distributed training, wrap in DDP as usual (the buffer
        tensor is a parameter-free registered buffer).

    Args:
        capacity: Maximum number of entries in the ring buffer.
        dim: Feature dimension of each entry.
    """

    def __init__(self, capacity: int = 7, dim: int = 4096):
        super().__init__()

        self.capacity = capacity
        self.dim = dim

        # Pre-allocated buffer — registered as a non-persistent buffer
        # (not saved in state_dict by default, but we override below)
        self.register_buffer(
            "_buffer",
            torch.zeros(1, capacity, dim),
            persistent=False,
        )
        self._ptr: int = 0
        self._count: int = 0
        self._batch_size: int = 1

    # -- public API --------------------------------------------------------

    def reset(
        self,
        batch_size: int,
        device: torch.device,
        dtype: torch.dtype = torch.float32,
    ) -> None:
        """Reset the buffer to zeros with the given batch size.

        Args:
            batch_size: Number of independent sequences in the batch.
            device: Target device.
            dtype: Target dtype (default fp32).
        """
        self._buffer = torch.zeros(
            batch_size, self.capacity, self.dim,
            device=device, dtype=dtype,
        )
        self._ptr = 0
        self._count = 0
        self._batch_size = batch_size

    def write(self, entry: Tensor, gain: Optional[Tensor] = None) -> None:
        """Write one entry to the ring buffer.

        Args:
            entry: (B, D) tensor to write.
            gain: Optional (B, 1) or (B,) ignition gain factor.
                The entry is scaled by gain before writing.
                gain=0 effectively skips the write (writes zeros).
                gain=1 writes the full entry.
        """
        if gain is not None:
            if gain.dim() == 1:
                gain = gain.unsqueeze(-1)  # (B, 1)
            entry = entry * gain

        # Write at current pointer position
        self._buffer[:, self._ptr, :] = entry

        # Advance pointer (circular)
        self._ptr = (self._ptr + 1) % self.capacity
        self._count = min(self._count + 1, self.capacity)

    def read_all(self) -> Tensor:
        """Read all valid entries from the buffer.

        Returns:
            (B, valid_count, D) tensor of stored entries.
            If buffer is empty, returns (B, 0, D).
        """
        if self._count == 0:
            return self._buffer[:, :0, :]  # (B, 0, D)

        if self._count < self.capacity:
            # Buffer not yet full — entries are at indices 0..count-1
            return self._buffer[:, :self._count, :]
        else:
            # Buffer full — read in order from oldest to newest
            # Oldest entry is at self._ptr (it was just overwritten last time
            # the buffer wrapped).  We reorder for chronological reading.
            indices = [(self._ptr + i) % self.capacity for i in range(self.capacity)]
            return self._buffer[:, indices, :]

    def summary(self) -> Tensor:
        """Return mean of all valid buffer entries.

        Returns:
            (B, D) mean vector.  If buffer is empty, returns zeros.
        """
        if self._count == 0:
            return torch.zeros(
                self._batch_size, self.dim,
                device=self._buffer.device,
                dtype=self._buffer.dtype,
            )
        valid = self.read_all()  # (B, valid_count, D)
        return valid.mean(dim=1)  # (B, D)

    def retrieve(self, query: Tensor) -> Tensor:
        """Attention-weighted retrieval from the buffer.

        Computes dot-product attention between the query and all valid
        buffer entries, then returns the attention-weighted sum.

        Args:
            query: (B, D) query vector.

        Returns:
            (B, D) retrieved content.  Returns the query itself if the
            buffer is empty.
        """
        if self._count == 0:
            return query

        valid = self.read_all()  # (B, valid_count, D)

        # Dot-product attention scores
        scores = torch.bmm(valid, query.unsqueeze(-1))  # (B, valid_count, 1)
        scores = scores.squeeze(-1)  # (B, valid_count)

        # Scale by sqrt(dim) for stable softmax
        scores = scores / math.sqrt(self.dim)

        weights = F.softmax(scores, dim=-1)  # (B, valid_count)

        # Weighted sum
        retrieved = torch.bmm(weights.unsqueeze(1), valid)  # (B, 1, D)
        return retrieved.squeeze(1)  # (B, D)

    def get_buffer_tensor(self) -> Tensor:
        """Return the raw internal buffer tensor (B, capacity, D)."""
        return self._buffer

    def get_ptr(self) -> int:
        """Return current write pointer."""
        return self._ptr

    def get_count(self) -> int:
        """Return number of valid entries."""
        return self._count

    # -- state persistence -------------------------------------------------

    def get_state(self) -> Dict[str, Any]:
        """Export buffer state for WMState integration."""
        return {
            "buffer": self._buffer.clone(),
            "ptr": self._ptr,
            "count": self._count,
            "batch_size": self._batch_size,
        }

    def set_state(self, state: Dict[str, Any]) -> None:
        """Import buffer state."""
        self._buffer = state["buffer"]
        self._ptr = state["ptr"]
        self._count = state["count"]
        self._batch_size = state["batch_size"]


