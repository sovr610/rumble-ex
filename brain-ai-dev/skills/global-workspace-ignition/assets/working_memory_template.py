class CfCBackend(nn.Module):
    """CfC (Closed-form Continuous-time) backend using the ncps library.

    Provides efficient closed-form continuous-time dynamics for working memory.
    Delta-time is passed directly as the `timespans` argument to CfC.

    Architecture:
        input_proj  (input_dim -> ncp_input_dim)
        CfC         (ncp_input_dim -> ncp_output_size, via AutoNCP wiring)
        hidden_proj (ncp_output_size -> hidden_dim)
        output_proj (hidden_dim -> output_dim)

    Args:
        input_dim: Input feature dimension.
        hidden_dim: Intermediate hidden dimension.
        output_dim: Output feature dimension.
        num_units: Number of NCP units in the AutoNCP wiring.
        sparsity: Connection sparsity in the wiring.
        dropout: Dropout in projection layers.
    """

    def __init__(
        self,
        input_dim: int = 4096,
        hidden_dim: int = 4096,
        output_dim: int = 4096,
        num_units: int = 128,
        sparsity: float = 0.5,
        dropout: float = 0.1,
    ):
        super().__init__()

        if not NCPS_AVAILABLE:
            raise ImportError(
                "ncps package required for CfCBackend. "
                "Install with: pip install ncps"
            )

        self.input_dim = input_dim
        self.hidden_dim = hidden_dim
        self.output_dim = output_dim

        # -- NCP wiring ---------------------------------------------------
        # AutoNCP requires output_size < num_units - 2
        ncp_output_size = min(hidden_dim, num_units - 4)
        if ncp_output_size < 1:
            ncp_output_size = max(1, num_units // 2)
        effective_units = max(num_units, ncp_output_size + 4)
        self.ncp_output_size = ncp_output_size

        wiring = AutoNCP(
            units=effective_units,
            output_size=ncp_output_size,
            sparsity_level=sparsity,
        )

        # -- input projection (reduce dim for NCP efficiency) -------------
        # NCP processes at a smaller internal dimension; we project down first
        ncp_input_dim = min(input_dim, num_units * 2)
        self.input_proj = nn.Sequential(
            nn.Linear(input_dim, ncp_input_dim),
            nn.LayerNorm(ncp_input_dim),
            nn.Dropout(dropout),
        )

        # -- CfC network --------------------------------------------------
        self.cfc = CfC(
            input_size=ncp_input_dim,
            units=wiring,
            return_sequences=False,
            batch_first=True,
        )

        # -- output projection --------------------------------------------
        self.hidden_proj = nn.Linear(ncp_output_size, hidden_dim)
        self.output_proj = nn.Sequential(
            nn.Linear(hidden_dim, output_dim),
            nn.LayerNorm(output_dim),
        )

    def forward(
        self,
        x: Tensor,
        hidden: Optional[Tensor] = None,
        dt: Optional[Tensor] = None,
    ) -> Tuple[Tensor, Tensor]:
        """Process a single step through the CfC backend.

        Args:
            x: Input tensor (B, input_dim).
            hidden: CfC hidden state or None.
            dt: Optional delta-time (B,) or (B, 1).  Passed as `timespans`
                to the CfC network (expanded to sequence length 1).

        Returns:
            output: (B, output_dim).
            new_hidden: CfC hidden state.
        """
        # Project input
        x = self.input_proj(x)  # (B, ncp_input_dim)

        # Add sequence dimension
        x = x.unsqueeze(1)  # (B, 1, ncp_input_dim)

        # Prepare timespans
        timespans = None
        if dt is not None:
            if dt.dim() == 1:
                dt = dt.unsqueeze(-1)  # (B, 1)
            # CfC expects timespans with shape matching the sequence: (B, seq_len, 1)
            timespans = dt.unsqueeze(1)  # (B, 1, 1)

        # CfC forward
        output, new_hidden = self.cfc(x, hx=hidden, timespans=timespans)
        # output: (B, ncp_output_size) when return_sequences=False

        # Project to output
        output = self.hidden_proj(output)  # (B, hidden_dim)
        output = self.output_proj(output)  # (B, output_dim)

        return output, new_hidden


