    def clone(self) -> "WMState":
        """Deep clone — safe for checkpointing."""
        cloned_hidden = _clone_hidden(self.hidden)
        return WMState(
            hidden=cloned_hidden,
            buffer=self.buffer.clone(),
            buffer_ptr=self.buffer_ptr,
            buffer_count=self.buffer_count,
            step_count=self.step_count,
        )


