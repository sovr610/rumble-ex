# 2. RoundsConfig -- Iterative stabilization of competition
# ---------------------------------------------------------------------------

@dataclass
class RoundsConfig:
    """Configuration for iterative competition rounds.

    The workspace runs multiple rounds of competition until either:
    (a) the winner set stabilizes (cosine similarity of consecutive
    selections exceeds ``stability_threshold``), or (b) ``max_rounds``
    is reached.

    Key relationships
    -----------------
    * ``max_rounds`` bounds compute cost per forward pass.
    * ``consecutive_stable_rounds`` requires multiple successive stable
      iterations before early termination.
    * ``broadcast_feedback_strength`` controls how much broadcast output
      feeds back into the next competition round.
    """

    # Round limits
    max_rounds: int = 4                        # Maximum competition rounds

    # Stability criteria
    stability_threshold: float = 0.9           # Cosine similarity for stability
    embedding_stability_threshold: float = 0.95  # Embedding-level stability
    consecutive_stable_rounds: int = 2         # Required consecutive stable rounds

    # Feedback from broadcast back into competition
    broadcast_feedback_strength: float = 0.5   # Feedback mixing coefficient

    def __post_init__(self) -> None:
        if not (1 <= self.max_rounds <= 10):
            raise ValueError(
                f"RoundsConfig.max_rounds must be in [1, 10], "
                f"got {self.max_rounds}"
            )
        if not (0.0 <= self.stability_threshold <= 1.0):
            raise ValueError(
                f"RoundsConfig.stability_threshold must be in [0, 1], "
                f"got {self.stability_threshold}"
            )
        if not (0.0 <= self.embedding_stability_threshold <= 1.0):
            raise ValueError(
                f"RoundsConfig.embedding_stability_threshold must be in [0, 1], "
                f"got {self.embedding_stability_threshold}"
            )
        if self.consecutive_stable_rounds < 1:
            raise ValueError(
                f"RoundsConfig.consecutive_stable_rounds must be >= 1, "
                f"got {self.consecutive_stable_rounds}"
            )
        if self.consecutive_stable_rounds > self.max_rounds:
            raise ValueError(
                f"RoundsConfig.consecutive_stable_rounds ({self.consecutive_stable_rounds}) "
                f"must be <= max_rounds ({self.max_rounds})"
            )
        if not (0.0 <= self.broadcast_feedback_strength <= 1.0):
            raise ValueError(
                f"RoundsConfig.broadcast_feedback_strength must be in [0, 1], "
                f"got {self.broadcast_feedback_strength}"
            )


