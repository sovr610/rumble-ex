def workspace_config_to_dict(config: WorkspaceConfig) -> Dict[str, Any]:
    """Serialize a WorkspaceConfig to a nested dict (JSON-safe).

    Uses ``dataclasses.asdict`` internally, which recursively converts all
    sub-dataclasses.  The result contains only JSON-compatible types.

    Parameters
    ----------
    config : WorkspaceConfig
        The configuration to serialize.

    Returns
    -------
    dict
        Nested dictionary suitable for ``json.dumps()``.
    """
    return asdict(config)


def workspace_config_from_dict(d: Dict[str, Any]) -> WorkspaceConfig:
    """Deserialize a WorkspaceConfig from a nested dict.

    Handles both:
    * New-style nested dicts (with ``competition``, ``rounds``, etc. keys).
    * Legacy flat dicts (via ``upgrade_workspace_config``).

    Parameters
    ----------
    d : dict
        Configuration dictionary.

    Returns
    -------
    WorkspaceConfig
        Reconstructed configuration.
    """
    # Detect legacy format: if there is no "competition" key but there IS
    # a "capacity_limit" or "selection_rounds" key at the top level, treat
    # as legacy.
    if "competition" not in d and (
        "capacity_limit" in d or "selection_rounds" in d or "memory_mode" in d
    ):
        return upgrade_workspace_config(d)

    # New-style nested format
    comp = CompetitionConfig(**d["competition"]) if "competition" in d else CompetitionConfig()
    rounds = RoundsConfig(**d["rounds"]) if "rounds" in d else RoundsConfig()
    ignition = IgnitionConfig(**d["ignition"]) if "ignition" in d else IgnitionConfig()
    broadcast = BroadcastConfig(**d["broadcast"]) if "broadcast" in d else BroadcastConfig()
    wm = WMConfig(**d["wm"]) if "wm" in d else WMConfig()

    top_keys = {"workspace_dim", "dropout"}
    top_kwargs = {k: d[k] for k in top_keys if k in d}

    return WorkspaceConfig(
        competition=comp,
        rounds=rounds,
        ignition=ignition,
        broadcast=broadcast,
        wm=wm,
        **top_kwargs,
    )


def workspace_config_to_json(config: WorkspaceConfig, indent: int = 2) -> str:
    """Serialize WorkspaceConfig to a JSON string."""
    return json.dumps(workspace_config_to_dict(config), indent=indent)


def workspace_config_from_json(s: str) -> WorkspaceConfig:
    """Deserialize WorkspaceConfig from a JSON string."""
    return workspace_config_from_dict(json.loads(s))


# -- Per-config to_dict / from_dict helpers -----------------------------------

def _subconfig_to_dict(config: Any) -> Dict[str, Any]:
    """Serialize any sub-config dataclass to a dict."""
    return asdict(config)


def _subconfig_from_dict(d: Dict[str, Any], cls: type) -> Any:
    """Deserialize a sub-config dataclass from a dict.

    Filters to known fields so extra keys are silently ignored.
    """
    known_fields = {f.name for f in fields(cls)}
    filtered = {k: v for k, v in d.items() if k in known_fields}
    return cls(**filtered)


