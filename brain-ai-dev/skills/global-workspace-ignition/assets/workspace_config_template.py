# 1. CompetitionConfig -- Multi-head attention competition for workspace access
# ---------------------------------------------------------------------------

@dataclass
class CompetitionConfig:
    """Configuration for workspace access competition.

    Multiple modality representations compete for a limited number of
    "slots" in the global workspace.  Competition is scored by a weighted
    combination of content relevance, salience, novelty, and task demand.

    Key relationships
    -----------------
    * ``capacity_limit`` follows Miller's Law (7 +/- 2 items).
    * ``num_heads`` controls multi-head attention in the competition scorer.
    * Weight fields (w_content, w_salience, w_novelty, w_task) are combined
      linearly to produce a single competition score per candidate.
    * Tie-breaking uses modality-level and token-level epsilon offsets
      (``eps_tie_modality``, ``eps_tie_token``).
    """

    # Capacity
    capacity_limit: int = 7                    # K workspace slots (Miller's Law)
    num_heads: int = 16                        # Multi-head attention heads

    # Competition temperature (softmax sharpness)
    competition_temperature: float = 0.5       # Lower = sharper competition

    # Scoring weights (combined linearly)
    w_content: float = 1.0                     # Content relevance weight
    w_salience: float = 0.5                    # Bottom-up salience weight
    w_novelty: float = 0.3                     # Novelty / surprise weight
    w_task: float = 0.0                        # Top-down task demand weight

    # Tie-breaking epsilons (for deterministic winner ordering)
    eps_tie_modality: float = 1e-6             # Per-modality tie offset
    eps_tie_token: float = 1e-8                # Per-token tie offset

    # Slot mixer (post-competition mixing of winners)
    use_slot_mixer: bool = True                # Enable MLP mixer over slots
    slot_mixer_expansion: float = 2.0          # FFN expansion factor

    def __post_init__(self) -> None:
        if self.capacity_limit <= 0:
            raise ValueError(
                f"CompetitionConfig.capacity_limit must be > 0, "
                f"got {self.capacity_limit}"
            )
        if self.num_heads <= 0:
            raise ValueError(
                f"CompetitionConfig.num_heads must be > 0, "
                f"got {self.num_heads}"
            )
        if self.competition_temperature <= 0.0:
            raise ValueError(
                f"CompetitionConfig.competition_temperature must be > 0, "
                f"got {self.competition_temperature}"
            )
        for wname in ("w_content", "w_salience", "w_novelty", "w_task"):
            val = getattr(self, wname)
            if val < 0.0:
                raise ValueError(
                    f"CompetitionConfig.{wname} must be >= 0, got {val}"
                )
        if self.eps_tie_modality < 0.0:
            raise ValueError(
                f"CompetitionConfig.eps_tie_modality must be >= 0, "
                f"got {self.eps_tie_modality}"
            )
        if self.eps_tie_token < 0.0:
            raise ValueError(
                f"CompetitionConfig.eps_tie_token must be >= 0, "
                f"got {self.eps_tie_token}"
            )
        if self.slot_mixer_expansion <= 0.0:
            raise ValueError(
                f"CompetitionConfig.slot_mixer_expansion must be > 0, "
                f"got {self.slot_mixer_expansion}"
            )

    # -- derived properties ---------------------------------------------------

    @property
    def total_weight(self) -> float:
        """Sum of all scoring weights (for normalization checks)."""
        return self.w_content + self.w_salience + self.w_novelty + self.w_task

    @property
    def active_weights(self) -> Dict[str, float]:
        """Return dict of scoring weights that are > 0."""
        mapping = {
            "content": self.w_content,
            "salience": self.w_salience,
            "novelty": self.w_novelty,
            "task": self.w_task,
        }
        return {k: v for k, v in mapping.items() if v > 0.0}


