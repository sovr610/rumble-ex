# 5. WMConfig -- Working Memory (Liquid NN / CfC)
# ---------------------------------------------------------------------------

#: Valid working memory modes.
_VALID_WM_MODES = ("cfc", "ltc", "gru", "lstm")

#: Valid dt input modes for liquid networks.
_VALID_DT_INPUT_MODES = ("concat", "gate", "add")


@dataclass
class WMConfig:
    """Configuration for the working memory module.

    The working memory is implemented as a Liquid Neural Network (CfC or
    LTC) that maintains temporal context across timesteps.  Fallback to
    GRU/LSTM is supported when ncps is unavailable.

    Key relationships
    -----------------
    * ``input_dim``, ``hidden_dim``, ``output_dim`` default to the
      workspace dimension.  The ``WorkspaceConfig.__post_init__``
      synchronises them from ``workspace_dim``.
    * ``mode`` selects the backend: cfc (Closed-form Continuous-time) or
      ltc (Liquid Time-Constant) from ncps, with gru/lstm fallbacks.
    * ``buffer_capacity`` matches ``CompetitionConfig.capacity_limit``
      for the number of items tracked in working memory.
    """

    # Dimensions (synced from workspace_dim by WorkspaceConfig)
    input_dim: int = 4096
    hidden_dim: int = 4096
    output_dim: int = 4096

    # Backend
    mode: str = "cfc"                          # cfc | ltc | gru | lstm
    num_units: int = 128                       # Liquid network units
    sparsity: float = 0.5                      # Wiring sparsity (liquid nets)
    num_layers: int = 1                        # Stacked layers

    # Buffer
    buffer_capacity: int = 7                   # Items in working memory

    # Time-varying dynamics
    use_dt: bool = True                        # Use elapsed-time input
    dt_input_mode: str = "concat"              # How dt is fed: concat | gate | add

    # Regularization
    dropout: float = 0.1                       # Recurrent dropout

    def __post_init__(self) -> None:
        if self.input_dim <= 0:
            raise ValueError(
                f"WMConfig.input_dim must be > 0, got {self.input_dim}"
            )
        if self.hidden_dim <= 0:
            raise ValueError(
                f"WMConfig.hidden_dim must be > 0, got {self.hidden_dim}"
            )
        if self.output_dim <= 0:
            raise ValueError(
                f"WMConfig.output_dim must be > 0, got {self.output_dim}"
            )
        if self.mode not in _VALID_WM_MODES:
            raise ValueError(
                f"WMConfig.mode must be one of {_VALID_WM_MODES}, "
                f"got '{self.mode}'"
            )
        if self.num_units <= 0:
            raise ValueError(
                f"WMConfig.num_units must be > 0, got {self.num_units}"
            )
        if not (0.0 <= self.sparsity < 1.0):
            raise ValueError(
                f"WMConfig.sparsity must be in [0, 1), got {self.sparsity}"
            )
        if self.num_layers < 1:
            raise ValueError(
                f"WMConfig.num_layers must be >= 1, got {self.num_layers}"
            )
        if self.buffer_capacity <= 0:
            raise ValueError(
                f"WMConfig.buffer_capacity must be > 0, "
                f"got {self.buffer_capacity}"
            )
        if self.dt_input_mode not in _VALID_DT_INPUT_MODES:
            raise ValueError(
                f"WMConfig.dt_input_mode must be one of {_VALID_DT_INPUT_MODES}, "
                f"got '{self.dt_input_mode}'"
            )
        if not (0.0 <= self.dropout < 1.0):
            raise ValueError(
                f"WMConfig.dropout must be in [0, 1), got {self.dropout}"
            )

    # -- derived properties ---------------------------------------------------

    @property
    def effective_input_dim(self) -> int:
        """Input dimension accounting for dt concatenation."""
        if self.use_dt and self.dt_input_mode == "concat":
            return self.input_dim + 1
        return self.input_dim

    @property
    def estimated_params(self) -> int:
        """Rough parameter count estimate for the working memory module."""
        if self.mode in ("cfc", "ltc"):
            # Liquid networks: input projection + recurrent + output
            inp = self.effective_input_dim * self.num_units
            rec = self.num_units * self.num_units
            out = self.num_units * self.output_dim
            return self.num_layers * (inp + rec + out)
        elif self.mode == "lstm":
            # LSTM: 4 gates * (input + hidden) * hidden per layer
            return self.num_layers * 4 * (self.input_dim + self.hidden_dim) * self.hidden_dim
        else:
            # GRU: 3 gates
            return self.num_layers * 3 * (self.input_dim + self.hidden_dim) * self.hidden_dim


