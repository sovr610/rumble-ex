# Mapping from old flat WorkspaceConfig field names to new nested locations.
_LEGACY_FIELD_MAP: Dict[str, str] = {
    # Competition
    "capacity_limit":           "competition.capacity_limit",
    "num_heads":                "competition.num_heads",

    # Rounds
    "selection_rounds":         "rounds.max_rounds",

    # Ignition
    "ignition_threshold":       "ignition.ignition_threshold",

    # Broadcast
    "broadcast_iterations":     "broadcast.broadcast_iterations",
    "broadcast_decay":          "broadcast.broadcast_decay",
    "use_selection_broadcast":  "_use_selection_broadcast",
    "use_confidence_gating":    "_use_confidence_gating",

    # Working memory
    "memory_hidden_dim":        "wm.hidden_dim",
    "memory_mode":              "wm.mode",
    "memory_num_layers":        "wm.num_layers",

    # Cross-modal (mapped to competition heads)
    "cross_modal_heads":        "competition.num_heads",
    "cross_modal_layers":       "_cross_modal_layers",

    # Top-level
    "workspace_dim":            "_workspace_dim",
}


def upgrade_workspace_config(legacy: Dict[str, Any]) -> WorkspaceConfig:
    """Convert an old flat WorkspaceConfig dict to the new nested structure.

    This handles checkpoint loading and YAML migration.  Unknown keys are
    silently ignored (with a warning printed to stderr).

    Parameters
    ----------
    legacy : dict
        Flat dictionary with old WorkspaceConfig fields.  Typically obtained
        from ``dataclasses.asdict(old_workspace_config)`` or from a
        checkpoint's ``config["workspace"]`` entry.

    Returns
    -------
    WorkspaceConfig
        New nested configuration.

    Field mapping
    -------------
    Old field                  -> New location
    -------------------------  ---------------------------------
    workspace_dim              -> workspace_dim (top-level)
    capacity_limit             -> competition.capacity_limit
    num_heads                  -> competition.num_heads
    selection_rounds           -> rounds.max_rounds
    ignition_threshold         -> ignition.ignition_threshold
    broadcast_iterations       -> broadcast.broadcast_iterations
    broadcast_decay            -> broadcast.broadcast_decay
    use_selection_broadcast    -> (always True, ignored)
    use_confidence_gating      -> (always True, ignored)
    memory_hidden_dim          -> wm.hidden_dim
    memory_mode                -> wm.mode
    memory_num_layers          -> wm.num_layers
    cross_modal_heads          -> competition.num_heads
    cross_modal_layers         -> (derived, ignored)
    """
    import sys

    comp_kwargs: Dict[str, Any] = {}
    rounds_kwargs: Dict[str, Any] = {}
    ignition_kwargs: Dict[str, Any] = {}
    broadcast_kwargs: Dict[str, Any] = {}
    wm_kwargs: Dict[str, Any] = {}
    top_kwargs: Dict[str, Any] = {}
    unmapped: list[str] = []

    for key, value in legacy.items():
        target = _LEGACY_FIELD_MAP.get(key)
        if target is None:
            unmapped.append(key)
            continue

        if target.startswith("competition."):
            field_name = target[len("competition."):]
            comp_kwargs[field_name] = value
        elif target.startswith("rounds."):
            field_name = target[len("rounds."):]
            rounds_kwargs[field_name] = value
        elif target.startswith("ignition."):
            field_name = target[len("ignition."):]
            ignition_kwargs[field_name] = value
        elif target.startswith("broadcast."):
            field_name = target[len("broadcast."):]
            broadcast_kwargs[field_name] = value
        elif target.startswith("wm."):
            field_name = target[len("wm."):]
            wm_kwargs[field_name] = value
        elif target == "_workspace_dim":
            top_kwargs["workspace_dim"] = value
        elif target in ("_use_selection_broadcast", "_use_confidence_gating",
                        "_cross_modal_layers"):
            # These legacy flags are always True in the new architecture
            # or are derived; silently ignore.
            pass

    # Handle num_heads appearing from both num_heads and cross_modal_heads:
    # The last one written wins (cross_modal_heads overwrites num_heads
    # in _LEGACY_FIELD_MAP since both map to competition.num_heads).
    # We want num_heads to take priority if both exist.
    if "num_heads" in legacy and "cross_modal_heads" in legacy:
        comp_kwargs["num_heads"] = legacy["num_heads"]

    if unmapped:
        print(
            f"[upgrade_workspace_config] Warning: unmapped legacy fields "
            f"ignored: {unmapped}",
            file=sys.stderr,
        )

    return WorkspaceConfig(
        competition=CompetitionConfig(**comp_kwargs) if comp_kwargs else CompetitionConfig(),
        rounds=RoundsConfig(**rounds_kwargs) if rounds_kwargs else RoundsConfig(),
        ignition=IgnitionConfig(**ignition_kwargs) if ignition_kwargs else IgnitionConfig(),
        broadcast=BroadcastConfig(**broadcast_kwargs) if broadcast_kwargs else BroadcastConfig(),
        wm=WMConfig(**wm_kwargs) if wm_kwargs else WMConfig(),
        **top_kwargs,
    )


