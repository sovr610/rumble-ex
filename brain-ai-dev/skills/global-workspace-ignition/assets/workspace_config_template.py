@dataclass
class BroadcastConfig:
    """Configuration for the workspace broadcast mechanism.

    After ignition, winning workspace content is broadcast to all
    specialist modules (temporal, decision, symbolic, etc.) via
    per-module adapters.  Optionally, feedback flows back from modules
    into the workspace.

    Key relationships
    -----------------
    * ``broadcast_iterations`` controls how many refinement cycles are
      run (each cycle: broadcast -> feedback -> re-broadcast).
    * ``broadcast_decay`` attenuates the broadcast signal across iterations.
    * ``default_adapters`` lists the module names that receive broadcast.
    * ``feedback_gate_dim`` controls the gating MLP for feedback; None
      defaults to workspace_dim.
    """

    # Broadcast refinement
    broadcast_iterations: int = 2              # Number of broadcast cycles
    broadcast_decay: float = 0.9               # Temporal decay per iteration

    # Feedback from specialist modules
    use_feedback: bool = True                  # Enable bidirectional broadcast
    feedback_gate_dim: Optional[int] = None    # Gate MLP dim (None = workspace_dim)

    # Adapter configuration
    adapter_dropout: float = 0.1               # Dropout in broadcast adapters
    default_adapters: List[str] = field(
        default_factory=lambda: ["temporal", "pooled", "decision"]
    )

    # Symbolic adapter specifics
    symbolic_num_predicates: int = 16          # Number of symbolic predicates
    symbolic_pred_dim: int = 256               # Predicate embedding dimension

    # Decision adapter specifics
    decision_dim: int = 512                    # Decision output dimension

    def __post_init__(self) -> None:
        if self.broadcast_iterations < 1:
            raise ValueError(
                f"BroadcastConfig.broadcast_iterations must be >= 1, "
                f"got {self.broadcast_iterations}"
            )
        if not (0.0 < self.broadcast_decay <= 1.0):
            raise ValueError(
                f"BroadcastConfig.broadcast_decay must be in (0, 1], "
                f"got {self.broadcast_decay}"
            )
        if self.feedback_gate_dim is not None and self.feedback_gate_dim <= 0:
            raise ValueError(
                f"BroadcastConfig.feedback_gate_dim must be > 0 or None, "
                f"got {self.feedback_gate_dim}"
            )
        if not (0.0 <= self.adapter_dropout < 1.0):
            raise ValueError(
                f"BroadcastConfig.adapter_dropout must be in [0, 1), "
                f"got {self.adapter_dropout}"
            )
        if not isinstance(self.default_adapters, list):
            raise TypeError(
                f"BroadcastConfig.default_adapters must be a list, "
                f"got {type(self.default_adapters).__name__}"
            )
        if len(self.default_adapters) == 0:
            raise ValueError(
                "BroadcastConfig.default_adapters must contain at least "
                "one adapter name"
            )
        if self.symbolic_num_predicates <= 0:
            raise ValueError(
                f"BroadcastConfig.symbolic_num_predicates must be > 0, "
                f"got {self.symbolic_num_predicates}"
            )
        if self.symbolic_pred_dim <= 0:
            raise ValueError(
                f"BroadcastConfig.symbolic_pred_dim must be > 0, "
                f"got {self.symbolic_pred_dim}"
            )
        if self.decision_dim <= 0:
            raise ValueError(
                f"BroadcastConfig.decision_dim must be > 0, "
                f"got {self.decision_dim}"
            )


