# 3. IgnitionConfig -- Threshold-gated global ignition
# ---------------------------------------------------------------------------

@dataclass
class IgnitionConfig:
    """Configuration for global workspace ignition dynamics.

    Ignition is the threshold event that determines whether workspace
    content reaches "conscious" global access.  A composite ignition
    score is computed as a weighted sum of stability, confidence, margin
    (winner - runner-up), and cross-modal coherence.

    Key relationships
    -----------------
    * ``ignition_threshold`` is the primary gate: scores below this
      produce attenuated (weak) broadcast instead of full broadcast.
    * ``w_stability + w_confidence + w_margin + w_coherence`` are the
      component weights for the ignition score.
    * ``use_learned_ignition`` replaces the hand-crafted score with a
      small MLP trained end-to-end.
    * ``slot_dropout`` and ``winner_decay`` promote diversity.
    * ``cooldown_steps`` / ``cooldown_boost`` implement a cooldown
      mechanism for recently-active winners.
    """

    # Primary ignition threshold
    ignition_threshold: float = 0.3            # Threshold for full ignition

    # Ignition score component weights
    w_stability: float = 0.3                   # Competition stability weight
    w_confidence: float = 0.3                  # Winner confidence weight
    w_margin: float = 0.2                      # Winner-runner-up margin weight
    w_coherence: float = 0.2                   # Cross-modal coherence weight

    # Sub-threshold behavior
    weak_gain: float = 0.3                     # Gain for sub-threshold broadcast
    gate_temperature: float = 0.1              # Sigmoid temperature for gate

    # Learned ignition (optional MLP replacement)
    use_learned_ignition: bool = False          # Replace heuristic with MLP
    learned_ignition_hidden: int = 128          # MLP hidden dimension

    # Diversity and fairness
    slot_dropout: float = 0.1                  # Dropout on winning slots (training)
    winner_decay: float = 0.1                  # Decay for recently-won modalities

    # Cooldown mechanism
    cooldown_steps: int = 0                    # Steps before winner can re-enter
    cooldown_boost: float = 0.5                # Boost for cooled-down candidates

    def __post_init__(self) -> None:
        if not (0.0 <= self.ignition_threshold <= 1.0):
            raise ValueError(
                f"IgnitionConfig.ignition_threshold must be in [0, 1], "
                f"got {self.ignition_threshold}"
            )
        for wname in ("w_stability", "w_confidence", "w_margin", "w_coherence"):
            val = getattr(self, wname)
            if val < 0.0:
                raise ValueError(
                    f"IgnitionConfig.{wname} must be >= 0, got {val}"
                )
        if not (0.0 <= self.weak_gain <= 1.0):
            raise ValueError(
                f"IgnitionConfig.weak_gain must be in [0, 1], "
                f"got {self.weak_gain}"
            )
        if self.gate_temperature <= 0.0:
            raise ValueError(
                f"IgnitionConfig.gate_temperature must be > 0, "
                f"got {self.gate_temperature}"
            )
        if self.learned_ignition_hidden <= 0:
            raise ValueError(
                f"IgnitionConfig.learned_ignition_hidden must be > 0, "
                f"got {self.learned_ignition_hidden}"
            )
        if not (0.0 <= self.slot_dropout < 1.0):
            raise ValueError(
                f"IgnitionConfig.slot_dropout must be in [0, 1), "
                f"got {self.slot_dropout}"
            )
        if self.winner_decay < 0.0:
            raise ValueError(
                f"IgnitionConfig.winner_decay must be >= 0, "
                f"got {self.winner_decay}"
            )
        if self.cooldown_steps < 0:
            raise ValueError(
                f"IgnitionConfig.cooldown_steps must be >= 0, "
                f"got {self.cooldown_steps}"
            )
        if self.cooldown_boost < 0.0:
            raise ValueError(
                f"IgnitionConfig.cooldown_boost must be >= 0, "
                f"got {self.cooldown_boost}"
            )

    # -- derived properties ---------------------------------------------------

    @property
    def ignition_weight_sum(self) -> float:
        """Sum of ignition score component weights."""
        return (
            self.w_stability
            + self.w_confidence
            + self.w_margin
            + self.w_coherence
        )


