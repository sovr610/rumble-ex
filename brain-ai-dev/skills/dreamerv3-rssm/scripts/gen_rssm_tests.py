class TestUnimixCategorical:

    @pytest.mark.parametrize("unimix", [0.001, 0.01, 0.05, 0.1])
    def test_probs_sum_to_one(self, unimix):
        logits = torch.randn(8, 32, 32)
        probs = unimix_probs(logits, unimix)
        sums = probs.sum(-1)
        assert torch.allclose(sums, torch.ones_like(sums), atol=1e-5)

    @pytest.mark.parametrize("unimix", [0.001, 0.01, 0.05])
    def test_no_zero_probs(self, unimix):
        logits = torch.zeros(4, 32, 32)
        logits[:, :, 0] = 1e6  # push all mass to class 0
        probs = unimix_probs(logits, unimix)
        assert probs.min().item() > 0

    def test_minimum_probability_at_least_unimix_floor(self):
        unimix = 0.01
        num_classes = 32
        logits = torch.zeros(4, 32, num_classes)
        logits[:, :, 0] = 1000.0
        probs = unimix_probs(logits, unimix)
        expected_min = unimix / num_classes
        assert probs.min().item() >= expected_min - 1e-7

    def test_uniform_logits_equal_probs(self):
        logits = torch.zeros(4, 8, 8)
        probs = unimix_probs(logits, unimix=0.0)  # no unimix → pure softmax
        expected = torch.full_like(probs, 1.0 / 8)
        assert torch.allclose(probs, expected, atol=1e-5)

    @pytest.mark.parametrize("shape", [(4, 8, 8), (1, 32, 32), (16, 4, 16)])
    def test_probs_shape(self, shape):
        logits = torch.randn(*shape)
        probs = unimix_probs(logits)
        assert probs.shape == torch.Size(shape)


