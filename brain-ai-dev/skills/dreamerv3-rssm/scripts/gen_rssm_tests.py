class TestSymlogSymexp:

    def test_symlog_zero(self):
        assert symlog(torch.tensor(0.0)).item() == pytest.approx(0.0, abs=1e-7)

    def test_symexp_zero(self):
        assert symexp(torch.tensor(0.0)).item() == pytest.approx(0.0, abs=1e-7)

    def test_symlog_positive(self):
        assert symlog(torch.tensor(1.0)).item() == pytest.approx(math.log(2.0), abs=1e-5)

    def test_symlog_antisymmetric(self):
        x = torch.tensor([0.5, 1.0, 10.0, 100.0])
        assert torch.allclose(symlog(-x), -symlog(x), atol=1e-6)

    def test_symexp_antisymmetric(self):
        x = torch.tensor([0.5, 1.0, 5.0, 10.0])
        assert torch.allclose(symexp(-x), -symexp(x), atol=1e-6)

    @pytest.mark.parametrize("val", [-1e6, -100.0, -1.0, -0.1, 0.0, 0.1, 1.0, 100.0, 1e6])
    def test_symexp_is_inverse_of_symlog(self, val):
        x = torch.tensor(val)
        recovered = symexp(symlog(x))
        if abs(val) > 1:
            assert abs(recovered.item() - val) / (abs(val) + 1e-8) < 1e-5
        else:
            assert abs(recovered.item() - val) < 1e-6

    def test_symlog_near_identity_for_small_x(self):
        x = torch.tensor([0.001, 0.01, 0.1])
        ratio = symlog(x) / x
        assert torch.allclose(ratio, torch.ones_like(ratio), atol=0.1)


