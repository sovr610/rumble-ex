# ====================================================================
# Test Class: Determinism
# ====================================================================

@pytest.mark.skipif(not HAS_BRAIN_AI, reason="brain_ai not importable")
class TestDeterminism:
    """Same input + same seed produces identical output in eval mode."""

    def test_text_deterministic(self):
        enc = _build_text_encoder(WORKSPACE_DIM, "cpu")
        ids, mask = make_text_input(2, "cpu", seq_len=15)

        torch.manual_seed(42)
        with torch.no_grad():
            out1 = enc(ids, attention_mask=mask)

        torch.manual_seed(42)
        with torch.no_grad():
            out2 = enc(ids, attention_mask=mask)

        assert torch.equal(out1, out2), "text encoder is non-deterministic"

    def test_audio_deterministic(self):
        enc = _build_audio_encoder(WORKSPACE_DIM, "cpu")
        wav = torch.randn(2, 16000)

        with torch.no_grad():
            out1 = enc(wav)
            out2 = enc(wav)

        assert torch.allclose(out1, out2, atol=1e-5), (
            "audio encoder is non-deterministic"
        )

    def test_vision_deterministic(self):
        enc = _build_vision_encoder(WORKSPACE_DIM, "cpu")
        img = torch.randn(2, 3, 28, 28)

        torch.manual_seed(42)
        with torch.no_grad():
            out1 = enc(img)

        torch.manual_seed(42)
