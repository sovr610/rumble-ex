# ---------------------------------------------------------------------------
# Assembly
# ---------------------------------------------------------------------------

def _assemble(workspace_dim: int) -> str:
    """Join all template fragments into the final generated test file."""
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    parts = [
        _HEADER.format(timestamp=timestamp, workspace_dim=workspace_dim),
        _ENCODER_OUTPUT_DEF,
        _FIXTURES,
        _TEST_SHAPE_CONTRACT,
        _TEST_DTYPE_DEVICE,
        _TEST_VARIABLE_LENGTH,
        _TEST_CROSS_MODAL,
        _TEST_MISSING_DEPS,
        _TEST_DETERMINISM,
        _TEST_SALIENCE_SPIKE,
        _TEST_MASK_INVARIANTS,
    ]

    return "\n".join(parts)


# ---------------------------------------------------------------------------
# Verification
# ---------------------------------------------------------------------------

def _verify(code: str) -> bool:
    """Check generated code with ast.parse to ensure syntax validity.

    Returns True on success, prints diagnostic and returns False on failure.
    """
    try:
        ast.parse(code, filename="<generated test_encoder_contracts.py>")
        return True
    except SyntaxError as exc:
        # Show the offending region for easier debugging
        lines = code.splitlines()
        lineno = exc.lineno or 0
        start = max(0, lineno - 5)
        end = min(len(lines), lineno + 5)
        context = "\n".join(
            (">>> " if i + 1 == lineno else "    ")
            + f"{i + 1:4d} | {lines[i]}"
            for i in range(start, end)
        )
        print(
            f"ERROR: Generated code has a syntax error at line {lineno}:\n"
            f"  {exc.msg}\n\n{context}\n",
            file=sys.stderr,
        )
        return False


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Generate encoder contract validation tests. "
            "Output goes to stdout by default."
        ),
    )
    parser.add_argument(
        "--workspace-dim",
        type=int,
        default=512,
        help="Workspace embedding dimension (default: 512).",
    )
    parser.add_argument(
        "--output", "-o",
        type=str,
        default=None,
        help="Write to this file instead of stdout.",
    )
    args = parser.parse_args()

    code = _assemble(args.workspace_dim)

    if not _verify(code):
        return 1

    if args.output:
        with open(args.output, "w", encoding="utf-8") as fh:
            fh.write(code)
        print(f"Wrote {len(code)} bytes to {args.output}", file=sys.stderr)
    else:
        sys.stdout.write(code)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
