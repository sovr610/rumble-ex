def _make_neuron(name: str, size: int = 16, surrogate: str = "atan", **kwargs):
    """
    Create a neuron of the given type with appropriate constructor args.

    RecurrentLIFNeuron and AdvancedLIFNeuron require an explicit size;
    LIFNeuron and AdaptiveLIFNeuron are size-agnostic (they take input
    as current rather than applying a linear projection internally).
    """
    if name == "lif":
        return LIFNeuron(surrogate=surrogate, **kwargs)
    elif name == "adaptive_lif":
        return AdaptiveLIFNeuron(surrogate=surrogate, **kwargs)
    elif name == "recurrent_lif":
        return RecurrentLIFNeuron(size=size, surrogate=surrogate, **kwargs)
    elif name == "advanced_lif":
        return AdvancedLIFNeuron(size=size, surrogate=surrogate, **kwargs)
    else:
        raise ValueError(f"Unknown neuron name: {{name}}")


def _reset_neuron(neuron) -> None:
    """Reset neuron state using whichever API is available."""
    if hasattr(neuron, "reset_state"):
        # Explicit-state API: reset_state returns a fresh state object.
        # The caller is responsible for passing it back; implicit self.mem
        # is irrelevant in this path.
        pass
    elif hasattr(neuron, "reset_mem"):
        neuron.reset_mem()


def _forward_timesteps(
    neuron,
    x_seq: torch.Tensor,
    T: Optional[int] = None,
    state=None,
) -> Tuple[torch.Tensor, list]:
    """
    Run the neuron for T timesteps, returning stacked spikes and membrane values.

    x_seq shape: (B, T, features) for neurons that accept shaped input, or
                 (B, features) for a single-step neuron (replicated T times).

    Handles both legacy (implicit self.mem) and explicit-state APIs.

    Returns:
        spikes  : (B, T, features)
        mems    : list of T tensors, each (B, features)
    """
    if T is None:
        T = x_seq.shape[1] if x_seq.dim() == 3 else DEFAULT_T

    spikes_list: list = []
    mems_list: list = []

    for t in range(T):
        # Slice the time dimension if provided, else reuse x_seq for each step
        if x_seq.dim() == 3:
            x_t = x_seq[:, t, :]
        else:
            x_t = x_seq

        if EXPLICIT_STATE and hasattr(neuron, "reset_state") and state is None:
            # First call: initialize state from the layer if supported
            result = neuron(x_t, state=None)
        elif EXPLICIT_STATE and hasattr(neuron, "forward") and state is not None:
            try:
                result = neuron(x_t, state=state)
            except TypeError:
                result = neuron(x_t)
        else:
            result = neuron(x_t)

        if isinstance(result, (tuple, list)):
            spk, mem_or_state = result[0], result[1]
            # For explicit-state API mem_or_state may be a SpikingState
            if EXPLICIT_STATE and hasattr(mem_or_state, "v"):
                state = mem_or_state
                mem = mem_or_state.v
            else:
                mem = mem_or_state
        else:
            spk = result
            mem = torch.zeros_like(spk)

        spikes_list.append(spk)
        mems_list.append(mem)

    spikes = torch.stack(spikes_list, dim=1)   # (B, T, features)
    return spikes, mems_list


