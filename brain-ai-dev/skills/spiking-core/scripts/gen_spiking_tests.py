        if hasattr(neuron, "prev_spk") and neuron.prev_spk is not None:
            neuron.prev_spk = neuron.prev_spk.detach()

        # --- Chunk 2 ---
        spikes2_list = []
        for _ in range(T - chunk):
            h = W_proj_2(x)
            out = neuron(h)
            spk = out[0] if isinstance(out, (tuple, list)) else out
            spikes2_list.append(spk)

