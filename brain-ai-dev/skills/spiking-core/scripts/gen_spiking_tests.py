class TinySpikingNet(nn.Module):
    """
    Minimal network: Linear -> LIF -> Linear -> LIF.
    Provides W_in (first linear) with easily testable gradients.
    """

    def __init__(
        self,
        in_features: int = 8,
        hidden: int = 4,
        out_features: int = 2,
        surrogate: str = "atan",
        beta: float = 0.9,
    ):
        super().__init__()
        self.W_in = nn.Linear(in_features, hidden)
        self.lif1 = LIFNeuron(beta=beta, surrogate=surrogate)
        self.W_out = nn.Linear(hidden, out_features)
        self.lif2 = LIFNeuron(beta=beta, surrogate=surrogate)

    def reset(self):
        self.lif1.reset_mem()
        self.lif2.reset_mem()

    def forward_T(self, x_seq: torch.Tensor) -> torch.Tensor:
        """
        x_seq: (B, T, in_features)
        Returns: spikes (B, T, out_features)
        """
        T = x_seq.shape[1]
        out_list = []
        for t in range(T):
            h = self.W_in(x_seq[:, t, :])
            h, _ = self.lif1(h)
            o = self.W_out(h)
            o, _ = self.lif2(o)
            out_list.append(o)
        return torch.stack(out_list, dim=1)
