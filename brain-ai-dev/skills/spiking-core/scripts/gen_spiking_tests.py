# ===========================================================================
# Category 3: State Reset and Carry
# ===========================================================================

class TestStateResetCarry:
    """
    Verify the three fundamental state-management properties:
      - Reset determinism: same input + reset -> identical output
      - Carry changes output: carried state -> different output vs reset
      - Detach preserves values but cuts gradient flow

    Specification: testing-matrix.md sections 3a, 3b, 3d.
    """

    @pytest.mark.parametrize("neuron_name", NEURON_NAMES)
    def test_reset_determinism(self, neuron_name: str):
        """
        Two independent reset+forward runs with the same input must produce
        bitwise-identical spike outputs on CPU.
        """
        torch.manual_seed(10)
        T = {timesteps}
        B = {batch_size}
        size = 16

        neuron = _make_neuron(neuron_name, size=size, surrogate="atan")
        x = torch.randn(B, size)

        # Run 1
        _reset_neuron(neuron)
        spikes1, _ = _forward_timesteps(neuron, x, T=T)

        # Run 2
        _reset_neuron(neuron)
        spikes2, _ = _forward_timesteps(neuron, x, T=T)

        assert torch.equal(spikes1, spikes2), (
            f"Reset+forward not deterministic for {{neuron_name}}. "
            f"Max diff: {{(spikes1 - spikes2).abs().max().item():.6f}}"
        )

    @pytest.mark.parametrize("neuron_name", NEURON_NAMES)
    def test_carry_changes_output(self, neuron_name: str):
        """
        Carried state must change the forward output compared to a fresh reset.

        Procedure:
          y1 = forward(reset, x)
          y2 = forward(carry from y1, x)   <- different from y1
          y3 = forward(reset, x)           <- equal to y1
        """
        torch.manual_seed(11)
        T = {timesteps}
        B = {batch_size}
        size = 16

        neuron = _make_neuron(neuron_name, size=size, surrogate="atan")
        x = torch.randn(B, size) * 1.5   # Non-trivial input to ensure firing

        # Run 1: fresh reset
        _reset_neuron(neuron)
        spikes1, _ = _forward_timesteps(neuron, x, T=T)

        # Run 2: carry state (no reset between runs)
        spikes2, _ = _forward_timesteps(neuron, x, T=T)

        # Run 3: reset again
        _reset_neuron(neuron)
        spikes3, _ = _forward_timesteps(neuron, x, T=T)

        # y1 == y3 (reset recovers identical output)
