def _class_finite_difference(timesteps: int, batch_size: int) -> str:
    return f'''\
# ===========================================================================
# Category 1c: Finite Difference Spot-Check
# ===========================================================================

class TestFiniteDifference:
    """
    Compare autograd gradients against a numeric finite-difference
    approximation.

    IMPORTANT: The Heaviside forward pass has zero true derivative almost
    everywhere.  Finite difference estimates the Heaviside gradient, while
    autograd computes the surrogate gradient.  These agree only at operating
    points where the surrogate closely approximates the forward response.
    This test is valid ONLY with the ATan surrogate (the smoothest of the
    three) and a relative tolerance of 5%.

    Specification: testing-matrix.md section 1c.
    """

    def test_finite_difference_lif(self):
        """
        For 5 randomly selected entries of W_in, the relative error between
        autograd gradient and finite-difference approximation must be < 5%.

        Network: in=4, hidden=2, out=1, T=3 (tiny to keep FD tractable).
        """
        torch.manual_seed(7)
        EPS = 1e-4
        TOLS = 0.05   # 5% relative tolerance as per spec
        T = 3
        B = 2
        IN = 4

        # ---- helper: run the network and return scalar loss ----
        def compute_loss(net, x_seq):
            net.reset()
            spikes = net.forward_T(x_seq)
            return spikes.sum()

        net = TinySpikingNet(in_features=IN, hidden=2, out_features=1, surrogate="atan")
        torch.manual_seed(7)
        x_seq = torch.randn(B, T, IN)

        # Autograd gradient
        net.reset()
        loss = compute_loss(net, x_seq)
        loss.backward()
        autograd_grad = net.W_in.weight.grad.clone()

        # Finite-difference approximation for 5 randomly selected scalar entries
        torch.manual_seed(7)
        H_out, H_in = net.W_in.weight.shape
        indices = [
            (torch.randint(H_out, (1,)).item(), torch.randint(H_in, (1,)).item())
            for _ in range(5)
        ]

        for (i, j) in indices:
            original_val = net.W_in.weight.data[i, j].item()

            # f(w + eps)
            with torch.no_grad():
                net.W_in.weight.data[i, j] = original_val + EPS
            f_plus = compute_loss(net, x_seq).item()

            # f(w - eps)
            with torch.no_grad():
                net.W_in.weight.data[i, j] = original_val - EPS
            f_minus = compute_loss(net, x_seq).item()

            # Restore
            with torch.no_grad():
                net.W_in.weight.data[i, j] = original_val

            g_numeric = (f_plus - f_minus) / (2.0 * EPS)
            g_autograd = autograd_grad[i, j].item()

            rel_err = abs(g_numeric - g_autograd) / (abs(g_autograd) + 1e-8)

            assert rel_err < TOLS, (
                f"FD mismatch at W_in[{{i}},{{j}}]: "
                f"numeric={{g_numeric:.6f}}, autograd={{g_autograd:.6f}}, "
                f"rel_err={{rel_err:.4f}} (threshold={{TOLS}})"
            )
'''


