# TestTauGradients
# ===========================================================================

@pytest.mark.tau
class TestTauGradients:
    """
    Verify gradient flow through tau_raw in learnable mode, and absence
    of gradients in fixed mode.
    """

    def test_gradient_exists_learnable(self):
        """
        tau_raw.grad must not be None after backward() in learnable mode.

        Gradient path: loss -> spikes -> membrane v -> beta -> tau_raw.
        The soft surrogate spike ensures differentiability through the threshold.
        """
        torch.manual_seed(5)
        B = {batch_size}
        T = {timesteps}
        N = 16

        tau_module = _make_tau(n=N, learnable=True)
        tau_module.train()

        v = torch.zeros(B, N)
        x = torch.randn(B, N)
        spikes_list = []

        for _ in range(T):
            beta = tau_module.beta   # (N,) -- in grad graph
            v_new = beta.unsqueeze(0) * v + x
            spk = torch.sigmoid(10.0 * (v_new - 1.0))   # soft surrogate
            v = v_new * (1.0 - spk.detach())
            spikes_list.append(spk)

        loss = torch.stack(spikes_list).sum()
        loss.backward()

        assert tau_module.tau_raw.grad is not None, (
            "tau_raw.grad is None in learnable mode -- "
            "gradient did not flow through beta = exp(-dt/tau)"
        )

    def test_no_gradient_fixed(self):
        """
        tau_raw must have no gradient in fixed (non-learnable) mode.

        In fixed mode, tau_raw is a buffer, not a Parameter, so it is
        excluded from the autograd graph.

        Note: x requires_grad=True provides a leaf so backward() does not
        raise even when the only pathway is through fixed buffers.
        """
        torch.manual_seed(6)
        B = {batch_size}
        T = min({timesteps}, 5)
        N = 16

        tau_module = _make_tau(n=N, learnable=False)
        v = torch.zeros(B, N)
        # requires_grad on x ensures loss.grad_fn exists
        x = torch.randn(B, N, requires_grad=True)
        spikes_list = []

        for _ in range(T):
            beta = tau_module.beta
            v_new = beta.unsqueeze(0) * v + x
            spk = torch.sigmoid(10.0 * (v_new - 1.0))
            v = v_new * (1.0 - spk.detach())
            spikes_list.append(spk)

        loss = torch.stack(spikes_list).sum()
        if loss.grad_fn is not None:
            loss.backward()

        tau_raw = tau_module.tau_raw
        assert not tau_raw.requires_grad, (
            "tau_raw.requires_grad=True in fixed mode -- it should be a buffer"
        )
        assert tau_raw.grad is None, (
            "tau_raw.grad is not None in fixed mode -- gradient leaked to buffer"
        )

    def test_gradient_magnitude(self):
        """
        tau_raw gradient must not be vanishing: abs().mean() > 1e-8.

        The gradient of exp(-dt/tau) w.r.t. tau_raw is:
          d(beta)/d(tau_raw) = (dt/tau^2) * exp(-dt/tau) * sigmoid(tau_raw)
        This is bounded and nonzero for tau in [tau_min, tau_max].
        """
        torch.manual_seed(7)
        B = {batch_size}
        T = {timesteps}
        N = 32

        tau_module = _make_tau(n=N, learnable=True, tau_min=1.0, tau_max=100.0)
        v = torch.zeros(B, N)
        x = torch.randn(B, N) * 0.5

        for _ in range(T):
            beta = tau_module.beta
            v_new = beta.unsqueeze(0) * v + x
            spk = torch.sigmoid(10.0 * (v_new - 1.0))
            v = v_new * (1.0 - spk.detach())

        loss = v.sum()
        loss.backward()

        if tau_module.tau_raw.grad is None:
            pytest.skip("tau_raw.grad is None -- gradient flow test skipped")

        grad_mag = tau_module.tau_raw.grad.abs().mean().item()
        assert grad_mag > 1e-8, (
            f"tau_raw gradient vanishing: abs_mean={{grad_mag:.2e}}"
        )
