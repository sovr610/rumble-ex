class _TinyDelayLinear(nn.Module):
    """
    Minimal DCLS-style learnable delay linear layer for contract testing.

    Implements Gaussian soft-delay interpolation over a spike history buffer
    of length Td.  The parameter d_raw (shape determined by granularity) is
    mapped to a continuous delay in [0, Td-1] via sigmoid * (Td - 1).

    The Gaussian kernel g[k] = exp(-0.5 * ((k - d) / sigma)^2) is normalized
    to sum to 1 and used to weight the history buffer contents.
    """

    GRANULARITY_SHAPES = {{
        "per_neuron":  lambda in_f, out_f, Td: (out_f,),
        "per_channel": lambda in_f, out_f, Td: (out_f,),
        "per_layer":   lambda in_f, out_f, Td: (1,),
    }}

    def __init__(
        self,
        in_features: int,
        out_features: int,
        max_delay: int = 8,
        sigma: float = 1.0,
        granularity: str = "per_neuron",
        fixed: bool = False,
    ):
        super().__init__()
        self.in_features = in_features
        self.out_features = out_features
        self.max_delay = max_delay
        self.sigma = sigma
        self.granularity = granularity
        self.fixed = fixed

        self.linear = nn.Linear(in_features, out_features)

        shape_fn = self.GRANULARITY_SHAPES.get(
            granularity, lambda *a: (out_features,)
        )
        d_shape = shape_fn(in_features, out_features, max_delay)

        d_init = torch.zeros(d_shape)
        if fixed:
            self.register_buffer("d_raw", d_init)
        else:
            self.d_raw = nn.Parameter(d_init)

        # History buffer: list of (out_features,)-shaped tensors
        self._history: List[Optional[torch.Tensor]] = [None] * max_delay

    @property
    def delays(self) -> torch.Tensor:
        """Continuous delay values in [0, Td - 1]."""
        return torch.sigmoid(self.d_raw) * (self.max_delay - 1)

    def _gaussian_kernel(self, d: torch.Tensor) -> torch.Tensor:
        """
        Compute normalized Gaussian kernel over delay bins [0, Td-1].

        d: (...) tensor of continuous delay positions.
        Returns: (..., Td) normalized kernel weights.
        """
        bins = torch.arange(self.max_delay, dtype=d.dtype, device=d.device)
        diff = bins - d.unsqueeze(-1)   # (..., Td)
        log_k = -0.5 * (diff / (self.sigma + 1e-8)) ** 2
        k = log_k.exp()
        k = k / (k.sum(dim=-1, keepdim=True) + 1e-12)
        return k

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """
        x: (B, in_features) -- current timestep input.
        Returns: (B, out_features) soft-delay-weighted output.
        """
        h = self.linear(x)   # (B, out_features)

        # Rotate history without in-place: prepend new entry, drop oldest
        new_history = [h.detach()] + self._history[:-1]
        self._history = new_history

        # Soft interpolation over available history
        valid = [t for t in self._history if t is not None]
        if not valid:
            return torch.zeros(
                x.shape[0], self.out_features,
                device=x.device, dtype=x.dtype
            )

        hist_stack = torch.stack(valid, dim=0)   # (Td_avail, B, out_f)
        Td_avail = hist_stack.shape[0]

        d = self.delays   # (out_f,) or (1,)
        bins = torch.arange(Td_avail, dtype=d.dtype, device=d.device)
        diff = bins - d.unsqueeze(-1)
        log_k = -0.5 * (diff / (self.sigma + 1e-8)) ** 2
        k = log_k.exp()
        k = k / (k.sum(dim=-1, keepdim=True) + 1e-12)   # (..., Td_avail)

        # k.t(): (Td_avail, out_f)  hist_stack: (Td_avail, B, out_f)
        k_t = k.t()
        out = (hist_stack * k_t.unsqueeze(1)).sum(dim=0)   # (B, out_f)
        return out

    def reset_history(self):
        """Clear the delay history buffer."""
        self._history = [None] * self.max_delay


class _TinyDelayConv1d(nn.Module):
    """
    Minimal DCLS-style Conv1d with per-channel learnable delays.
    """

    def __init__(
        self,
        in_channels: int,
        out_channels: int,
        kernel_size: int = 3,
        max_delay: int = 8,
        sigma: float = 1.0,
    ):
        super().__init__()
        self.in_channels = in_channels
        self.out_channels = out_channels
        self.max_delay = max_delay
        self.sigma = sigma

        self.conv = nn.Conv1d(
            in_channels, out_channels, kernel_size, padding=kernel_size // 2
        )
        # Per-channel delay: one scalar per output channel
        self.d_raw = nn.Parameter(torch.zeros(out_channels))

    @property
    def delays(self) -> torch.Tensor:
        return torch.sigmoid(self.d_raw) * (self.max_delay - 1)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """
        x: (B, C_in, L).
        Returns: (B, C_out, L') with same L' as a plain conv with same padding.
        """
        return self.conv(x)


class _TinyGaussianKernel:
    """Pure-Python Gaussian kernel for contract tests (no nn.Module dependency)."""

    def __init__(self, max_delay: int, sigma: float):
        self.max_delay = max_delay
        self.sigma = sigma

    def __call__(self, d: torch.Tensor) -> torch.Tensor:
        """
        d: scalar or (N,) tensor of continuous delay positions.
        Returns: (max_delay,) or (N, max_delay) normalized kernel.
        """
        bins = torch.arange(self.max_delay, dtype=torch.float32)
        scalar = d.dim() == 0
        if scalar:
            d = d.unsqueeze(0)
        diff = bins.unsqueeze(0) - d.unsqueeze(-1)   # (N, Td)
        log_k = -0.5 * (diff / (self.sigma + 1e-8)) ** 2
        k = log_k.exp()
        k = k / (k.sum(dim=-1, keepdim=True) + 1e-12)
        return k.squeeze(0) if scalar else k


class _TinySigmaSchedule:
    """
    Cosine annealing schedule for the Gaussian delay kernel width sigma.

    sigma(e) = sigma_end + 0.5 * (sigma_start - sigma_end)
               * (1 + cos(pi * e / T_max))

    Monotonically decreasing from sigma_start to sigma_end over T_max steps.
    """

    def __init__(
        self,
        sigma_start: float = 4.0,
        sigma_end: float = 0.1,
        T_max: int = 100,
        constant: bool = False,
    ):
        self.sigma_start = sigma_start
        self.sigma_end = sigma_end
        self.T_max = T_max
        self.constant = constant
        self._epoch = 0
        self._sigma = sigma_start

    def step(self):
        """Advance by one epoch and update sigma."""
        self._epoch += 1
        if self.constant:
            self._sigma = self.sigma_start
        else:
            e = min(self._epoch, self.T_max)
            self._sigma = (
                self.sigma_end
                + 0.5 * (self.sigma_start - self.sigma_end)
                * (1 + math.cos(math.pi * e / self.T_max))
            )

    @property
    def sigma(self) -> float:
        return self._sigma

    @property
    def epoch(self) -> int:
        return self._epoch

    def state_dict(self) -> dict:
        return {{
            "sigma_start": self.sigma_start,
            "sigma_end":   self.sigma_end,
            "T_max":       self.T_max,
            "constant":    self.constant,
            "_epoch":      self._epoch,
            "_sigma":      self._sigma,
        }}

    def load_state_dict(self, sd: dict):
        self.sigma_start = sd["sigma_start"]
        self.sigma_end   = sd["sigma_end"]
        self.T_max       = sd["T_max"]
        self.constant    = sd["constant"]
        self._epoch      = sd["_epoch"]
        self._sigma      = sd["_sigma"]


