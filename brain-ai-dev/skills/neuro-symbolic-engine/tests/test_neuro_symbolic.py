    def compose_formula(
        bundle: OperatorBundle,
        ast_node: FormulaNode,
        truth_cache: Dict[str, Tensor],
    ) -> Tensor:
        op = ast_node.op.upper()
        if op == "ATOM":
            return truth_cache[ast_node.atom_key]
        if op == "NOT":
            child_val = compose_formula(bundle, ast_node.children[0], truth_cache)
            return bundle.not_op(child_val)
        if op == "AND":
            result = compose_formula(bundle, ast_node.children[0], truth_cache)
            for child in ast_node.children[1:]:
                result = bundle.and_op(result, compose_formula(bundle, child, truth_cache))
            return result
        if op == "OR":
            result = compose_formula(bundle, ast_node.children[0], truth_cache)
            for child in ast_node.children[1:]:
                result = bundle.or_op(result, compose_formula(bundle, child, truth_cache))
            return result
        if op == "IMPLIES":
            ante = compose_formula(bundle, ast_node.children[0], truth_cache)
            cons = compose_formula(bundle, ast_node.children[1], truth_cache)
            return bundle.implies_op(ante, cons)
        if op == "FORALL":
            body = compose_formula(bundle, ast_node.children[0], truth_cache)
            if body.dim() == 1:
                body = body.unsqueeze(0)
            return bundle.forall(body)
        if op == "EXISTS":
            body = compose_formula(bundle, ast_node.children[0], truth_cache)
            if body.dim() == 1:
                body = body.unsqueeze(0)
            return bundle.exists(body)
        raise ValueError(f"Unknown operator: {op}")


