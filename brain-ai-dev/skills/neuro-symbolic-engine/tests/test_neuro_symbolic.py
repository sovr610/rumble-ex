class TestConstraintViolationReduction:
    """Constraint violation reduction gate: synthetic violation rate decreases.

    Simulates a synthetic scenario with a small reasoner and verifies that
    training reduces rule violations while query accuracy stays stable.
    """

    @pytest.fixture
    def synthetic_setup(self):
        """Create a synthetic training scenario."""
        torch.manual_seed(42)
        B, K, D_ws = 16, 7, 128
        reasoner = StubSymbolicReasoner(
            entity_dim=64, hidden_dim=128, workspace_dim=D_ws,
            num_rules=5, bundle_name="stable_product",
        )
        slots = torch.randn(B, K, D_ws)
        mask = torch.ones(B, K, dtype=torch.bool)
        optimizer = torch.optim.Adam(reasoner.parameters(), lr=2e-3)
        return reasoner, slots, mask, optimizer

    def test_synthetic_violation_decreases(self, synthetic_setup):
        """Violation rate decreases after training."""
        reasoner, slots, mask, optimizer = synthetic_setup
        # Measure initial violation
        with torch.no_grad():
            out0 = reasoner(slots, mask)
            initial_violation = out0["violation_stats"]["mean_violation"].item()
        # Train
        for _ in range(30):
            optimizer.zero_grad()
            out = reasoner(slots, mask)
            out["constraint_loss"].backward()
            optimizer.step()
        # Measure final violation
        with torch.no_grad():
            outf = reasoner(slots, mask)
            final_violation = outf["violation_stats"]["mean_violation"].item()
        assert final_violation < initial_violation, (
            f"Violation did not decrease: initial={initial_violation:.4f}, "
            f"final={final_violation:.4f}"
        )

    def test_query_accuracy_stable(self, synthetic_setup):
        """Truth values remain in valid range throughout training."""
        reasoner, slots, mask, optimizer = synthetic_setup
        for step in range(20):
            optimizer.zero_grad()
            out = reasoner(slots, mask)
            truth = out["truth"]
            assert truth.min().item() >= -0.01, (
                f"Truth below 0 at step {step}: {truth.min().item():.4f}"
            )
            assert truth.max().item() <= 1.01, (
                f"Truth above 1 at step {step}: {truth.max().item():.4f}"
            )
            out["constraint_loss"].backward()
            optimizer.step()

    def test_top_violated_rules_logged(self, synthetic_setup):
        """Top violated rules are correctly identified in logs."""
        reasoner, slots, mask, _ = synthetic_setup
        out = reasoner(slots, mask, return_logs=True)
        logs = out["logs"]
        assert logs is not None
        top_k = logs["top_k_violated_rules"]
        assert "indices" in top_k
        assert "values" in top_k
        # Values should be non-negative (violations in [0, 1])
        assert top_k["values"].min().item() >= -1e-6

    def test_before_after_comparison(self, synthetic_setup):
        """Explicit before/after comparison of constraint loss."""
        reasoner, slots, mask, optimizer = synthetic_setup
        with torch.no_grad():
            before = reasoner(slots, mask)["constraint_loss"].item()
        for _ in range(40):
            optimizer.zero_grad()
            out = reasoner(slots, mask)
            out["constraint_loss"].backward()
            optimizer.step()
        with torch.no_grad():
            after = reasoner(slots, mask)["constraint_loss"].item()
        improvement = before - after
        assert improvement > 0, (
            f"No improvement: before={before:.6f}, after={after:.6f}"
        )

    def test_predicate_grounding_improves(self, synthetic_setup):
        """Predicate truth values move toward target during training."""
        reasoner, slots, mask, optimizer = synthetic_setup
        # Measure initial predicate spread
        with torch.no_grad():
            entities, emask = reasoner.extractor(slots, mask)
            p0 = reasoner.predicates.run_predicate("P", entities, emask)
            q0 = reasoner.predicates.run_predicate("Q", entities, emask)
        # The rule is FORALL x: P(x) -> Q(x), so training should push
        # Q(x) higher where P(x) is high.
        # Train
        for _ in range(30):
            optimizer.zero_grad()
            out = reasoner(slots, mask)
            out["constraint_loss"].backward()
            optimizer.step()
        # Re-check after training
        with torch.no_grad():
            entities_after, _ = reasoner.extractor(slots, mask)
            pf = reasoner.predicates.run_predicate("P", entities_after, emask)
            qf = reasoner.predicates.run_predicate("Q", entities_after, emask)
        # Check that implication satisfaction improves
        b = reasoner.bundle
        impl_before = b.implies_op(p0, q0).mean().item()
        impl_after = b.implies_op(pf, qf).mean().item()
        assert impl_after >= impl_before - 0.05, (
            f"Implication satisfaction did not improve: "
            f"before={impl_before:.4f}, after={impl_after:.4f}"
        )

    def test_loss_balance(self, synthetic_setup):
        """Constraint loss can be balanced with a task loss without NaN."""
        reasoner, slots, mask, optimizer = synthetic_setup
        for step in range(10):
            optimizer.zero_grad()
            out = reasoner(slots, mask)
            # Simulated task loss
            task_loss = torch.tensor(1.0, requires_grad=True)
            total = task_loss + 0.1 * out["constraint_loss"]
            assert not torch.isnan(total), f"NaN total loss at step {step}"
            total.backward()
            optimizer.step()



