@pytest.mark.parametrize("bundle_name", ALL_BUNDLES)
class TestFuzzyOperatorIdentities:
    """Algebraic identities that every t-norm / t-conorm family must satisfy."""

    def _get_bundle(self, bundle_name: str) -> OperatorBundle:
        return get_operator_bundle(OperatorConfig(bundle=bundle_name))

    def _atol(self, bundle_name: str) -> float:
        return _atol_for(bundle_name)

    # -- AND identities --------------------------------------------------

    def test_and_right_identity(self, bundle_name):
        """AND(x, 1) = x for all x in [0,1]."""
        b = self._get_bundle(bundle_name)
        x = torch.linspace(0, 1, 50)
        result = b.and_op(x, torch.ones_like(x))
        assert torch.allclose(result, x, atol=self._atol(bundle_name)), (
            f"AND(x,1) != x for {bundle_name}, max_diff="
            f"{(result - x).abs().max().item():.2e}"
        )

    def test_and_annihilator(self, bundle_name):
        """AND(x, 0) = 0 for all x (exact for pure, approximate for stable)."""
        b = self._get_bundle(bundle_name)
        x = torch.linspace(0, 1, 50)
        result = b.and_op(x, torch.zeros_like(x))
        if bundle_name == "stable_product":
            # Stable product: AND(x, 0) = eps * clamp(x, min=eps), not exact 0
            assert result.max().item() < 0.01, (
                f"stable_product AND(x,0) too large: max={result.max().item():.4e}"
            )
        else:
            assert torch.allclose(result, torch.zeros_like(x), atol=ATOL_EXACT), (
                f"AND(x,0) != 0 for {bundle_name}"
            )

    # -- OR identities ---------------------------------------------------

    def test_or_identity(self, bundle_name):
        """OR(x, 0) = x for all x in [0,1]."""
        b = self._get_bundle(bundle_name)
        x = torch.linspace(0, 1, 50)
