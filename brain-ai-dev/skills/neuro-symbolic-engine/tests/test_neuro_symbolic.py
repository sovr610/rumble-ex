class StubRuleNetwork(nn.Module):
    """Simplified rule network with attention over rules."""
    def __init__(self, max_rules: int = 16, workspace_dim: int = 128,
                 rule_embed_dim: int = 64, use_attention: bool = True,
                 violation_agg: str = "mean"):
        super().__init__()
        self.max_rules = max_rules
        self.use_attention = use_attention
        self.violation_agg = violation_agg
        self.rule_embeddings = nn.Parameter(torch.randn(max_rules, rule_embed_dim))
        nn.init.orthogonal_(self.rule_embeddings)
        if use_attention:
            attn_in = workspace_dim + rule_embed_dim + rule_embed_dim
            self.attn_proj = nn.Linear(attn_in, rule_embed_dim)
            self.attn_score = nn.Linear(rule_embed_dim, 1)

    def compute_attention(self, ws: Tensor, query: Optional[Tensor], R: int) -> Tensor:
        B = ws.shape[0]
        if query is None:
            query = torch.zeros(B, self.rule_embeddings.shape[-1], device=ws.device)
        r_emb = self.rule_embeddings[:R].unsqueeze(0).expand(B, -1, -1)
        ws_exp = ws.unsqueeze(1).expand(-1, R, -1)
        q_exp = query.unsqueeze(1).expand(-1, R, -1)
        h = torch.cat([ws_exp, q_exp, r_emb], dim=-1)
        scores = self.attn_score(torch.tanh(self.attn_proj(h))).squeeze(-1)
        return F.softmax(scores, dim=-1)

    def forward(self, truth_values: Tensor, workspace_summary: Tensor,
                query_embedding: Optional[Tensor] = None,
                polarity: Optional[List[bool]] = None,
                return_logs: bool = False):
        B, R = truth_values.shape
        if self.use_attention:
            alpha = self.compute_attention(workspace_summary, query_embedding, R)
        else:
            alpha = torch.ones(B, R, device=truth_values.device) / R
        if polarity is not None:
            pol = torch.tensor(polarity[:R], dtype=torch.float32, device=truth_values.device)
            violations = pol * (1.0 - truth_values) + (1.0 - pol) * truth_values
        else:
            violations = 1.0 - truth_values
        if self.use_attention:
            constraint_loss = (alpha * violations).sum(dim=-1).mean()
        else:
            if self.violation_agg == "mean":
                constraint_loss = violations.mean()
            elif self.violation_agg == "soft_min":
                tau = 0.1
                constraint_loss = (tau * torch.logsumexp(violations / tau, dim=-1)).mean()
            elif self.violation_agg == "p_mean":
                p = 2.0
                constraint_loss = (violations.pow(p).mean(dim=-1)).pow(1.0 / p).mean()
            else:
                constraint_loss = violations.mean()
        logs = None
        if return_logs:
            k = min(5, R)
            top_vals, top_idx = torch.topk(violations, k=k, dim=-1)
            logs = {
                "rule_attention_weights": alpha.detach(),
                "per_rule_truth_values": truth_values.detach(),
                "top_k_violated_rules": {"indices": top_idx.detach(), "values": top_vals.detach()},
            }
        return {
            "truth_values": truth_values,
            "constraint_loss": constraint_loss,
            "attention_weights": alpha,
            "logs": logs,
        }


class StubSymbolicReasoner(nn.Module):
    """Minimal symbolic reasoner wiring operators + grounding + rules."""
    def __init__(self, entity_dim: int = 64, hidden_dim: int = 128,
                 workspace_dim: int = 128, num_rules: int = 5,
                 bundle_name: str = "stable_product", mode: str = "loss"):
        super().__init__()
        self.mode = mode  # "loss" or "feature"
        self.entity_dim = entity_dim
        self.bundle = get_operator_bundle(OperatorConfig(bundle=bundle_name))
        self.extractor = StubSlotIdentityExtractor(workspace_dim, entity_dim)
        self.predicates = StubPredicateRegistry(entity_dim, hidden_dim)
        self.predicates.register_predicate("P")
        self.predicates.register_predicate("Q")
        self.relation_registry = StubRelationRegistry(entity_dim, hidden_dim)
        self.relation_registry.register_relation("R")
        self.rule_network = StubRuleNetwork(
            max_rules=num_rules, workspace_dim=workspace_dim,
            rule_embed_dim=64, use_attention=True,
        )

    def forward(self, slots: Tensor, slot_mask: Tensor,
                query: Optional[Tensor] = None, return_logs: bool = False):
        entities, emask = self.extractor(slots, slot_mask)
        B, N, _ = entities.shape
        p_truth = self.predicates.run_predicate("P", entities, emask)
        q_truth = self.predicates.run_predicate("Q", entities, emask)
        # Simple rule truths: FORALL x: P(x) -> Q(x)
        impl = self.bundle.implies_op(p_truth, q_truth)
        forall_val = self.bundle.forall(impl)
        # Stack rule truths (repeat for num_rules)
        R = self.rule_network.max_rules
        rule_truths = forall_val.unsqueeze(-1).expand(-1, R)
        ws_summary = slots.mean(dim=1)
        out = self.rule_network(rule_truths, ws_summary,
                                query_embedding=query, return_logs=return_logs)
        result = {
            "truth": forall_val,
            "constraint_loss": out["constraint_loss"],
            "violation_stats": {"mean_violation": (1.0 - rule_truths).mean()},
        }
        if return_logs:
            result["logs"] = out["logs"]
        else:
            result["logs"] = None
        return result


