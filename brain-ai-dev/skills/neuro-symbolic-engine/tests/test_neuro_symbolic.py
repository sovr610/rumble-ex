        """Stable product AND has non-zero gradients near 0 and near 1."""
        # Near zero
        x0 = torch.tensor([0.0], requires_grad=True)
        y0 = torch.tensor([0.5], requires_grad=True)
        result0 = stable_product_and(x0, y0)
        result0.backward()
        assert y0.grad is not None and y0.grad.abs().item() > 1e-8, (
            "grad(y) is zero at x=0 boundary"
        )

        # Near one
        x1 = torch.tensor([0.5], requires_grad=True)
        y1 = torch.tensor([1.0], requires_grad=True)
        result1 = stable_product_and(x1, y1)
        result1.backward()
