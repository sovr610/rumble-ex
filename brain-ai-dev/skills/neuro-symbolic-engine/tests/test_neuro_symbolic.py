        """Product OR has non-zero gradients at interior values."""
        x = torch.tensor([0.5], requires_grad=True)
        y = torch.tensor([0.6], requires_grad=True)
        result = product_or(x, y)
        result.backward()
        assert x.grad is not None and x.grad.abs().item() > 1e-8, "grad(x) is zero"
        assert y.grad is not None and y.grad.abs().item() > 1e-8, "grad(y) is zero"

