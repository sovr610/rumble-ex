            torch.manual_seed(42)
            inputs = [torch.randn(1, 32) for _ in range(8)]
            batched = torch.cat(inputs, dim=0)
            with torch.no_grad():
                individual = torch.cat([simple_model(x) for x in inputs])
                batch_out = simple_model(batched)
