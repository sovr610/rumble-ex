def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate 100+ pytest test cases for export modules"
    )
    parser.add_argument(
        "-o", "--output",
        default=None,
        help="Output file path. Defaults to test_export_generated.py in the same directory.",
    )
    parser.add_argument(
        "--stdout", action="store_true",
        help="Print to stdout instead of writing to file.",
    )
    args = parser.parse_args()

    content = generate_full_test_file()

    if args.stdout:
        print(content)
        return

    if args.output is None:
        script_dir = os.path.dirname(os.path.abspath(__file__))
        output_path = os.path.join(script_dir, "test_export_generated.py")
    else:
        output_path = args.output

    with open(output_path, "w") as f:
        f.write(content)

    # Count tests
    test_count = content.count("def test_")
    print(f"Generated {test_count} test cases -> {output_path}")


if __name__ == "__main__":
    main()
