            cold = time.perf_counter() - t0
            # Warm inferences
            for _ in range(10):
                with torch.no_grad():
                    simple_model(x)
            t0 = time.perf_counter()
            with torch.no_grad():
                simple_model(x)
            warm = time.perf_counter() - t0
