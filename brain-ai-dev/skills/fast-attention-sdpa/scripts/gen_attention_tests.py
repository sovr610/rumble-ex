# ---------------------------------------------------------------------------


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(
        description="Generate pytest test cases for fast-attention-sdpa skill."
    )
    parser.add_argument(
        "--output", "-o", default=_DEFAULT_OUTPUT,
        help=f"Output file path (default: {_DEFAULT_OUTPUT})"
    )
    parser.add_argument(
        "--count", action="store_true",
        help="Print estimated test count and exit."
    )
    args = parser.parse_args(argv)

    content = generate_test_file()

    if args.count:
        count = content.count("\ndef test_")
        print(f"Estimated test functions: {count}")
        return

    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as fh:
        fh.write(content)

    # Count generated tests
    test_count = content.count("\ndef test_")
    print(f"Generated {test_count} test functions -> {args.output}")


if __name__ == "__main__":
    main()
