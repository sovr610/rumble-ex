def make_qkv(batch=2, heads=4, seq=16, head_dim=64, dtype=torch.float32, device="cpu"):
    q = torch.randn(batch, heads, seq, head_dim, dtype=dtype, device=device)
    k = torch.randn(batch, heads, seq, head_dim, dtype=dtype, device=device)
    v = torch.randn(batch, heads, seq, head_dim, dtype=dtype, device=device)
    return q, k, v

def manual_attention(q, k, v):
    """Reference implementation for correctness checks."""
    scale = 1.0 / math.sqrt(q.shape[-1])
    w = torch.softmax((q @ k.transpose(-2, -1)) * scale, dim=-1)
    return w @ v


