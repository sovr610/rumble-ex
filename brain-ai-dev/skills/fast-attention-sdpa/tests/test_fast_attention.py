def test_sdpa_attention_causal_numerical():
    """is_causal=True Math backend is causal (future positions zeroed)."""
    reset_log_state()
    bc = BackendConfig(policy='math', log=False)
    torch.manual_seed(7)
    q, k, v = make_qkv(batch=1, heads=1, seq=4, head_dim=32)
    out = sdpa_attention(q, k, v, is_causal=True, training=False, backend_cfg=bc)
    # Manual causal
    scale = 1.0 / math.sqrt(32)
    scores = (q @ k.transpose(-2, -1)) * scale
    causal_mask = torch.tril(torch.ones(4, 4)).bool()
    scores = scores.masked_fill(~causal_mask, float('-inf'))
    w = torch.softmax(scores, dim=-1)
    expected = w @ v
    assert torch.allclose(out, expected, **TOLERANCES[torch.float32])

