    def test_2_11_beta_threshold_quadratic_side(self):
        """For diff just below beta, loss should use quadratic formula."""
        pred   = torch.zeros(1, 1, 1)
        diff   = 0.9  # Just below beta=1.0
        target = torch.full((1, 1, 1), diff)
        expected_quad = 0.5 * diff ** 2 / 1.0
        expected_lin  = diff - 0.5 * 1.0
        actual = self._loss(pred, target, beta=1.0).item()
        assert abs(actual - expected_quad) < 1e-5, (
            f"Should use quadratic: expected {expected_quad:.4f}, got {actual:.4f}"
        )

    def test_2_12_beta_threshold_linear_side(self):
        """For diff just above beta, loss should use linear formula."""
        pred   = torch.zeros(1, 1, 1)
        diff   = 1.1  # Just above beta=1.0
        target = torch.full((1, 1, 1), diff)
        expected_lin = diff - 0.5 * 1.0
        actual = self._loss(pred, target, beta=1.0).item()
        assert abs(actual - expected_lin) < 1e-5

