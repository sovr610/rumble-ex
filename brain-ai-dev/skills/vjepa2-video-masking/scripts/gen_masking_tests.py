class TestMaskGeneratorCoverage:

    GRIDS = [(8, 14, 14), (4, 14, 14), (8, 16, 16)]

    @pytest.mark.parametrize("grid", GRIDS)
    @pytest.mark.parametrize("seed", [0, 42, 99])
    def test_no_gaps(self, grid, seed):
        mg = MaskGenerator(spatial_scale=(0.15, 0.15), temporal_scale=(1.0, 1.0),
                           aspect_ratio=(0.75, 1.5), npred=4, grid_size=grid)
        enc, pred = mg(4, seed=seed)
        for e, p in zip(enc, pred):
            assert (e | p).all().item(), "Gap detected: some tokens uncovered"

    @pytest.mark.parametrize("grid", GRIDS)
    @pytest.mark.parametrize("seed", [0, 42, 99])
    def test_no_overlaps(self, grid, seed):
        mg = MaskGenerator(spatial_scale=(0.15, 0.15), temporal_scale=(1.0, 1.0),
                           aspect_ratio=(0.75, 1.5), npred=4, grid_size=grid)
        enc, pred = mg(4, seed=seed)
        for e, p in zip(enc, pred):
            assert not (e & p).any().item(), "Overlap: enc and pred share a token"

    @pytest.mark.parametrize("grid", GRIDS)
    def test_exact_complement(self, grid):
        mg = MaskGenerator(npred=4, grid_size=grid)
        enc, pred = mg(2, seed=7)
        for e, p in zip(enc, pred):
            assert torch.equal(e, ~p), "enc is not exact complement of pred"

    @pytest.mark.parametrize("grid", GRIDS)
    def test_sum_equals_N(self, grid):
        N  = grid[0] * grid[1] * grid[2]
        mg = MaskGenerator(npred=4, grid_size=grid)
        enc, pred = mg(4, seed=1)
        for e, p in zip(enc, pred):
            assert e.long().sum() + p.long().sum() == N

    def test_large_blocks_cover_majority(self, grid_8_14_14):
        mg = make_large_mask_generator(grid_size=grid_8_14_14, npred=2)
        enc, pred = mg(8, seed=0)
        mean_pred = sum(p.float().mean().item() for p in pred) / 8
        assert mean_pred >= 0.5, f"Large blocks only covered {mean_pred:.2%} on average"

    def test_small_blocks_non_trivial(self, grid_8_14_14):
        mg = make_small_mask_generator(grid_size=grid_8_14_14, npred=8)
        enc, pred = mg(4, seed=0)
        for p in pred:
            assert p.any().item(), "Small block pred mask is all False"

    def test_npred_zero_enc_all_true(self):
        mg = MaskGenerator(npred=0, grid_size=(4, 4, 4))
        enc, pred = mg(2, seed=0)
        for e in enc:
            assert e.all().item()
        for p in pred:
            assert not p.any().item()

    def test_coverage_with_temporal_half(self):
        grid = (8, 7, 7)
        mg = MaskGenerator(
            spatial_scale=(0.15, 0.15),
            temporal_scale=(0.5, 0.5),
            aspect_ratio=(1.0, 1.0),
            npred=1,
            grid_size=grid,
        )
        enc, pred = mg(4, seed=0)
        for e, p in zip(enc, pred):
            assert (e | p).all(), "No gaps despite temporal_scale=0.5"
            assert not (e & p).any(), "No overlaps"


