class TestMaxContextFramesRatio:

    def test_ratio_1_no_cap(self):
        """ratio=1.0 means no temporal cap."""
        T, H, W = 8, 7, 7
        mg = MaskGenerator(npred=0, grid_size=(T, H, W),
                           max_context_frames_ratio=1.0)
        enc, _ = mg(4, seed=0)
        N = T * H * W
        for e in enc:
            assert e.long().sum().item() == N, "npred=0 should leave all tokens visible"

    def test_ratio_half_limits_frames(self):
        T, H, W = 8, 7, 7
        mg = MaskGenerator(npred=0, grid_size=(T, H, W),
                           max_context_frames_ratio=0.5)
        enc, _ = mg(1, seed=0)
        enc3d = enc[0].view(T, H, W)
        visible_frames = enc3d.any(dim=(1, 2)).nonzero(as_tuple=False)
        if visible_frames.numel() > 0:
            last = visible_frames[-1, 0].item()
            assert last < T, f"Expected frame capped, last visible={last}, T={T}"

    def test_ratio_quarter_limits_frames(self):
        T, H, W = 8, 7, 7
        mg = MaskGenerator(npred=0, grid_size=(T, H, W),
                           max_context_frames_ratio=0.25)
        enc, _ = mg(1, seed=0)
        enc3d = enc[0].view(T, H, W)
        # Frames beyond first 25% should be invisible
        beyond = enc3d[round(T * 0.25):, :, :]
        assert not beyond.any(), "Frames beyond ratio should be masked"

    def test_invalid_ratio_zero(self):
        with pytest.raises(ValueError):
            MaskGenerator(grid_size=(4, 4, 4), max_context_frames_ratio=0.0)

    def test_invalid_ratio_negative(self):
        with pytest.raises(ValueError):
            MaskGenerator(grid_size=(4, 4, 4), max_context_frames_ratio=-0.5)

    def test_invalid_ratio_above_1(self):
        with pytest.raises(ValueError):
            MaskGenerator(grid_size=(4, 4, 4), max_context_frames_ratio=1.5)


