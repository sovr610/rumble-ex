class TestMaskCollatorSeed:

    def test_counter_increments(self):
        mg  = MaskGenerator(npred=2, grid_size=(4, 7, 7))
        col = MaskCollator(mg)
        with col._itr_counter.get_lock():
            col._itr_counter.value = -1

        step0 = col._step()
        step1 = col._step()
        assert step0 == 0
        assert step1 == 1

    def test_different_calls_different_masks(self):
        mg  = MaskGenerator(npred=4, grid_size=(8, 14, 14))
        col = MaskCollator(mg)
        with col._itr_counter.get_lock():
            col._itr_counter.value = -1

        r1 = col([make_item(16)] * 2)
        r2 = col([make_item(16)] * 2)
        _, e1, _ = r1[0]
        _, e2, _ = r2[0]
        assert any(not torch.equal(a, b) for a, b in zip(e1, e2))

    def test_same_step_same_masks(self):
        mg  = MaskGenerator(npred=4, grid_size=(8, 14, 14))
        col = MaskCollator(mg)

        with col._itr_counter.get_lock():
            col._itr_counter.value = 41  # next = 42

        r_a = col([make_item(16)] * 2)

        with col._itr_counter.get_lock():
            col._itr_counter.value = 41  # reset

        r_b = col([make_item(16)] * 2)
        _, ea, _ = r_a[0]
        _, eb, _ = r_b[0]
        assert all(torch.equal(a, b) for a, b in zip(ea, eb))


