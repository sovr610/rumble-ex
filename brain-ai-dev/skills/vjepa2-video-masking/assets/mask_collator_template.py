"""
mask_collator_template.py
=========================
MaskCollator: DataLoader collate_fn that groups batch items by FPC (frames per
clip) and generates spatiotemporal masks per group.

References:
    - references/mask-collation.md
    - SKILL.md § MaskCollator, § Mask Collator Details

Done-when Gate 3 (Collator Grouping):
    MaskCollator correctly groups mixed-FPC batches.
    Each group has a consistent token sequence length.
    Returns [(collated_batch, masks_enc, masks_pred)] per FPC group.
"""

from __future__ import annotations

import random
from collections import defaultdict
from multiprocessing import Value
from typing import Any, Dict, List, Optional, Tuple

import torch
from torch import Tensor
from torch.utils.data.dataloader import default_collate

from mask_generator_template import MaskGenerator


# ---------------------------------------------------------------------------
# Type aliases
# ---------------------------------------------------------------------------

# One element returned by the collator per FPC group.
# (collated_batch, list-of-enc-masks, list-of-pred-masks)
CollatorGroup = Tuple[Any, List[Tensor], List[Tensor]]


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _group_by_fpc(
    batch: List[Any],
    fpc_key: str = "fpc",
) -> Dict[int, List[Any]]:
    """
    Partition batch items into groups keyed by frames-per-clip.

    Items are expected to be dicts with a `fpc_key` field.  If they do not,
    the collator falls back to treating all items as a single FPC group
    (single-FPC mode, FPC value taken from the first item).

    Preserves insertion order within each group.
    """
    groups: Dict[int, List[Any]] = defaultdict(list)
    for item in batch:
        if isinstance(item, dict) and fpc_key in item:
            fpc = int(item[fpc_key])
        elif isinstance(item, (list, tuple)) and len(item) >= 1:
            # Assume first element is the video tensor; derive FPC from T dim
            try:
                fpc = int(item[0].shape[-4])  # [..., T, H, W, C] or [C, T, H, W]
            except (AttributeError, IndexError):
                fpc = -1
        else:
            fpc = -1
        groups[fpc].append(item)
    return dict(groups)


# ---------------------------------------------------------------------------
# MaskCollator
# ---------------------------------------------------------------------------

class MaskCollator:
    """
    Custom DataLoader collate_fn for V-JEPA 2.

    Groups batch items by their FPC value, runs default_collate within each
    group, and attaches spatiotemporal masks generated by the appropriate
    MaskGenerator.

    Args:
        mask_generators:            Dict mapping FPC -> MaskGenerator, or a
                                    single MaskGenerator used for all FPCs.
        max_context_frames_ratio:   Passed to each MaskGenerator.
        max_keep:                   Passed to each MaskGenerator.
        fpc_key:                    Dict key used to read FPC from each item.

    Returns (per __call__):
        List[Tuple[collated_batch, List[Tensor], List[Tensor]]]
        One tuple per FPC group in the batch.
    """

    def __init__(
        self,
        mask_generators:            Any,   # MaskGenerator or Dict[int, MaskGenerator]
        max_context_frames_ratio:   float = 1.0,
        max_keep:                   Optional[int] = None,
        fpc_key:                    str = "fpc",
    ) -> None:
        # Normalise to dict form
        if isinstance(mask_generators, MaskGenerator):
            self._mg_dict:  Optional[Dict[int, MaskGenerator]] = None
            self._mg_default: MaskGenerator = mask_generators
        elif isinstance(mask_generators, dict):
            self._mg_dict    = mask_generators
            self._mg_default = None
        else:
            raise TypeError(
                "mask_generators must be a MaskGenerator or Dict[int, MaskGenerator], "
                f"got {type(mask_generators)}."
            )

        self.max_context_frames_ratio = max_context_frames_ratio
        self.max_keep                 = max_keep
        self.fpc_key                  = fpc_key

        # Shared integer counter for seed stepping across DataLoader workers.
        # Must be created BEFORE the DataLoader (before fork) so that the
        # underlying ctypes integer is shared across all workers.
        self._itr_counter: Value = Value("i", -1)

    # ------------------------------------------------------------------
    # Seed management
    # ------------------------------------------------------------------

    def _step(self) -> int:
        """
        Atomically increment and return the shared counter.

        This is safe to call from multiple DataLoader workers because
        multiprocessing.Value uses a reentrant lock.
        """
        with self._itr_counter.get_lock():
            self._itr_counter.value += 1
            return self._itr_counter.value

    def _get_mask_generator(self, fpc: int) -> MaskGenerator:
        """Return the MaskGenerator for the given FPC, or the default one."""
        if self._mg_dict is not None:
            if fpc in self._mg_dict:
                return self._mg_dict[fpc]
            # Fallback: use an arbitrary available generator
            return next(iter(self._mg_dict.values()))
        return self._mg_default

    # ------------------------------------------------------------------
    # Core collation logic
    # ------------------------------------------------------------------

    def __call__(self, batch: List[Any]) -> List[CollatorGroup]:
        """
        Collate a batch of dataset items into FPC groups with masks.

        Args:
            batch: List of items from the Dataset.__getitem__.

        Returns:
            List of (collated_batch, masks_enc, masks_pred) tuples, one per
            distinct FPC value found in the batch.
        """
        seed = self._step()

        groups = _group_by_fpc(batch, self.fpc_key)
        results: List[CollatorGroup] = []

        for fpc, items in groups.items():
            # Standard PyTorch collation within the FPC group
            collated = default_collate(items)
            B        = len(items)

            mg = self._get_mask_generator(fpc)
            masks_enc, masks_pred = mg(B, seed=seed)

            results.append((collated, masks_enc, masks_pred))

        return results

    def __repr__(self) -> str:
        if self._mg_dict is not None:
            mg_info = f"generators={list(self._mg_dict.keys())}"
        else:
            mg_info = f"generator={self._mg_default}"
        return (
            f"MaskCollator({mg_info}, "
            f"max_context_frames_ratio={self.max_context_frames_ratio}, "
            f"max_keep={self.max_keep})"
        )


# ---------------------------------------------------------------------------
# Convenience: build a MaskCollator from a VideoConfig + MaskConfig
# ---------------------------------------------------------------------------

def build_collator(
    grid_size:                Tuple[int, int, int] = (8, 14, 14),
    npred_small:              int = 8,
    npred_large:              int = 2,
    spatial_scale_small:      Tuple[float, float] = (0.15, 0.15),
    spatial_scale_large:      Tuple[float, float] = (0.70, 0.70),
    temporal_scale:           Tuple[float, float] = (1.0, 1.0),
    aspect_ratio:             Tuple[float, float] = (0.75, 1.5),
    max_context_frames_ratio: float = 1.0,
    max_keep:                 Optional[int] = None,
) -> Tuple["MaskCollator", MaskGenerator, MaskGenerator]:
    """
    Build a MaskCollator pre-configured with small + large generators.

    Returns:
        (collator, small_generator, large_generator)
    """
    mg_small = MaskGenerator(
        spatial_scale=spatial_scale_small,
        temporal_scale=temporal_scale,
        aspect_ratio=aspect_ratio,
        npred=npred_small,
        grid_size=grid_size,
        max_context_frames_ratio=max_context_frames_ratio,
        max_keep=max_keep,
    )
    mg_large = MaskGenerator(
        spatial_scale=spatial_scale_large,
        temporal_scale=temporal_scale,
        aspect_ratio=aspect_ratio,
        npred=npred_large,
        grid_size=grid_size,
        max_context_frames_ratio=max_context_frames_ratio,
        max_keep=max_keep,
    )
    # Use small generator as default for single-FPC batches
    collator = MaskCollator(mg_small, max_context_frames_ratio, max_keep)
    return collator, mg_small, mg_large


