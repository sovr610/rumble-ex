if __name__ == "__main__":
    import sys

    PASSED = 0
    FAILED = 0

    def check(name: str, condition: bool, msg: str = "") -> None:
        global PASSED, FAILED
        if condition:
            print(f"  PASS  {name}")
            PASSED += 1
        else:
            print(f"  FAIL  {name}  {msg}")
            FAILED += 1

    # Helper: make a fake batch item as a dict
    def make_item(fpc: int, T: int = None, H: int = 14, W: int = 14,
                  D: int = 1024) -> Dict[str, Any]:
        T = T or fpc // 2  # tubelet=2 convention
        return {
            "fpc":    fpc,
            "frames": torch.randn(fpc, H * 16, W * 16, 3),  # raw pixels
            "label":  torch.tensor(0),
        }

    GRID = (8, 14, 14)
    N    = 8 * 14 * 14  # 1568

    mg = MaskGenerator(
        spatial_scale=(0.15, 0.15),
        temporal_scale=(1.0, 1.0),
        aspect_ratio=(0.75, 1.5),
        npred=4,
        grid_size=GRID,
    )
    collator = MaskCollator(mg)

    # -------------------------------------------------------------------
    # Single-FPC batch
    # -------------------------------------------------------------------
    print("=" * 60)
    print("MaskCollator -- single-FPC batch")
    print("=" * 60)

    batch_single = [make_item(16) for _ in range(4)]
    result = collator(batch_single)

    check("Single-FPC: returns a list", isinstance(result, list))
    check("Single-FPC: exactly 1 group", len(result) == 1,
          f"got {len(result)} groups")

    collated_s, enc_s, pred_s = result[0]
    check("Single-FPC: collated batch is a dict", isinstance(collated_s, dict))
    check("Single-FPC: masks_enc is a list", isinstance(enc_s, list))
    check("Single-FPC: masks_pred is a list", isinstance(pred_s, list))
    check("Single-FPC: len(masks_enc) == 4", len(enc_s) == 4,
          f"got {len(enc_s)}")
    check("Single-FPC: mask shape == [N]",
          enc_s[0].shape == (N,), f"got {enc_s[0].shape}")
    check("Single-FPC: mask dtype bool",
          enc_s[0].dtype == torch.bool)

    # Coverage
    for i in range(4):
        check(f"Single-FPC[{i}] no gaps",
              (enc_s[i] | pred_s[i]).all().item())
        check(f"Single-FPC[{i}] no overlaps",
              not (enc_s[i] & pred_s[i]).any().item())

    # -------------------------------------------------------------------
    # Multi-FPC batch
    # -------------------------------------------------------------------
    print()
    print("=" * 60)
    print("MaskCollator -- multi-FPC batch")
    print("=" * 60)

    # 2 items FPC=16, 2 items FPC=8 -> 2 groups
    mg16 = MaskGenerator(
        spatial_scale=(0.15, 0.15), temporal_scale=(1.0, 1.0),
        aspect_ratio=(0.75, 1.5), npred=4, grid_size=(8, 14, 14),
    )
    mg8 = MaskGenerator(
        spatial_scale=(0.15, 0.15), temporal_scale=(1.0, 1.0),
        aspect_ratio=(0.75, 1.5), npred=4, grid_size=(4, 14, 14),
    )
    mg_dict = {16: mg16, 8: mg8}
    collator_multi = MaskCollator(mg_dict)

    batch_multi = [make_item(16), make_item(16), make_item(8), make_item(8)]
    result_multi = collator_multi(batch_multi)

    check("Multi-FPC: returns 2 groups",
          len(result_multi) == 2,
          f"got {len(result_multi)} groups")

    # Map groups by their mask length
    groups_by_n: Dict[int, Any] = {}
    for col, enc, pred in result_multi:
        n = enc[0].numel()
        groups_by_n[n] = (col, enc, pred)

    N16 = 8 * 14 * 14   # 1568
    N8  = 4 * 14 * 14   # 784

    check("Multi-FPC: group FPC=16 has N=1568 tokens",
          N16 in groups_by_n, f"groups found: {list(groups_by_n.keys())}")
    check("Multi-FPC: group FPC=8 has N=784 tokens",
          N8 in groups_by_n, f"groups found: {list(groups_by_n.keys())}")

    if N16 in groups_by_n:
        _, enc16, pred16 = groups_by_n[N16]
        check("Multi-FPC: FPC=16 group has 2 items", len(enc16) == 2,
              f"got {len(enc16)}")
        for i in range(len(enc16)):
            check(f"Multi-FPC FPC=16[{i}] no gaps",
                  (enc16[i] | pred16[i]).all().item())
            check(f"Multi-FPC FPC=16[{i}] no overlaps",
                  not (enc16[i] & pred16[i]).any().item())

    if N8 in groups_by_n:
        _, enc8, pred8 = groups_by_n[N8]
        check("Multi-FPC: FPC=8 group has 2 items", len(enc8) == 2,
              f"got {len(enc8)}")

    # -------------------------------------------------------------------
    # Seed determinism (counter increments)
    # -------------------------------------------------------------------
    print()
    print("=" * 60)
    print("MaskCollator -- counter / seed determinism")
    print("=" * 60)

    coll_det = MaskCollator(mg)
    # Reset counter manually for test
    with coll_det._itr_counter.get_lock():
        coll_det._itr_counter.value = -1

    r1 = coll_det([make_item(16) for _ in range(2)])
    r2 = coll_det([make_item(16) for _ in range(2)])

    # Seeds 0 and 1 should produce different masks
    _, enc1_list, _ = r1[0]
    _, enc2_list, _ = r2[0]
    seeds_differ = any(not torch.equal(e1, e2)
                       for e1, e2 in zip(enc1_list, enc2_list))
    check("Sequential calls use different seeds -> different masks",
          seeds_differ)

    # Same call with same seed should be identical
    coll_rep = MaskCollator(mg)
    with coll_rep._itr_counter.get_lock():
        coll_rep._itr_counter.value = 41  # next step = 42

    r_a = coll_rep([make_item(16) for _ in range(2)])

    with coll_rep._itr_counter.get_lock():
        coll_rep._itr_counter.value = 41  # reset to 41 again

    r_b = coll_rep([make_item(16) for _ in range(2)])

    _, enc_a_list, _ = r_a[0]
    _, enc_b_list, _ = r_b[0]
    same = all(torch.equal(a, b) for a, b in zip(enc_a_list, enc_b_list))
    check("Same counter value -> identical masks", same)

    print()
    print("=" * 60)
    print(f"Results: {PASSED} passed, {FAILED} failed")
    print("=" * 60)

    sys.exit(0 if FAILED == 0 else 1)
