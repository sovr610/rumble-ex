# 3. ReflexConfig -- Reflex Memory (AHTM acceleration)
# ---------------------------------------------------------------------------

@dataclass
class ReflexConfig:
    """Reflex Memory configuration for Accelerated HTM.

    Uses Locality-Sensitive Hashing for O(1) pattern lookup, with automatic
    promotion of frequently-matched patterns and demotion of stale ones.

    Key relationships
    -----------------
    * ``num_tables`` and ``bits_per_hash`` control LSH resolution:
      each table has ``2**bits_per_hash`` buckets.
    * ``max_per_bucket`` caps collision chains.
    * ``promotion_threshold`` controls how many observations before a
      pattern becomes a reflex shortcut.
    """

    # Enable flag
    enabled: bool = True

    # Capacity
    max_observations: int = 50_000
    max_promoted: int = 10_000

    # Promotion / demotion
    promotion_threshold: int = 5
    min_confidence: float = 0.8
    demotion_threshold: float = 0.7
    demotion_window: int = 20

    # LSH
    similarity_threshold: float = 0.9
    num_tables: int = 8
    bits_per_hash: int = 12
    max_candidates: int = 32
    max_per_bucket: int = 64

    # Decay
    decay_rate: float = 0.99
    decay_interval: int = 1000

    def __post_init__(self) -> None:
        assert self.promotion_threshold >= 1, (
            f"promotion_threshold must be >= 1, got {self.promotion_threshold}"
        )
        assert 0 < self.min_confidence <= 1, (
            f"min_confidence must be in (0, 1], got {self.min_confidence}"
        )
        assert 0 < self.demotion_threshold <= 1, (
            f"demotion_threshold must be in (0, 1], got {self.demotion_threshold}"
        )
        assert self.demotion_window >= 1, (
            f"demotion_window must be >= 1, got {self.demotion_window}"
        )
        assert 0 < self.similarity_threshold <= 1, (
            f"similarity_threshold must be in (0, 1], got {self.similarity_threshold}"
        )
        assert self.num_tables >= 1, (
            f"num_tables must be >= 1, got {self.num_tables}"
        )
        assert self.bits_per_hash >= 1, (
            f"bits_per_hash must be >= 1, got {self.bits_per_hash}"
        )
        assert self.max_candidates >= 1
        assert self.max_per_bucket >= 1
        assert self.max_observations >= 0
        assert self.max_promoted >= 0
        assert 0 < self.decay_rate <= 1
        assert self.decay_interval >= 1

    # -- derived properties ---------------------------------------------------

    @property
    def total_buckets(self) -> int:
        """Total buckets across all LSH tables."""
        return self.num_tables * (2 ** self.bits_per_hash)

    @property
    def estimated_lsh_memory_bytes(self) -> int:
        """Rough memory estimate for LSH index (pointer per bucket + entries)."""
        # Each bucket: pointer (8B) + max_per_bucket entries * 16B (hash + pointer)
        bucket_overhead = 8 + self.max_per_bucket * 16
        return self.total_buckets * bucket_overhead


