"""
HTM Configuration -- Nested configuration for Spatial Pooler, Temporal Memory,
Reflex Memory, and Fallback Predictors.

Template for: brain_ai/config.py (extend existing HTMConfig section)
Generated by: brain-ai-dev/skills/htm-spatial-temporal-reflex

Restructures flat HTMConfig into nested SPConfig + TMConfig + ReflexConfig +
FallbackConfig with validation, presets, and backward-compatible upgrade path.

Integration notes
-----------------
Replace the existing HTMConfig block (lines ~124-155) in brain_ai/config.py
with SPConfig, TMConfig, ReflexConfig, FallbackConfig, and the new HTMConfig
aggregator.  All top-level BrainAIConfig references (e.g. config.htm.column_count)
continue to work through delegating @property accessors on HTMConfig.

Legacy checkpoints and YAML configs are supported via ``upgrade_htm_config()``.
"""

