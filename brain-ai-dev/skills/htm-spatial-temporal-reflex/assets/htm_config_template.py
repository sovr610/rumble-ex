# 2. TMConfig -- Temporal Memory
# ---------------------------------------------------------------------------

@dataclass
class TMConfig:
    """Temporal Memory configuration.

    Manages cells-per-column, segment/synapse limits, permanence rules, and
    memory-compaction thresholds.

    Key relationships
    -----------------
    * ``column_count`` must match ``SPConfig.column_count``.
    * ``total_cells = column_count * cells_per_column``.
    * ``min_threshold <= activation_threshold`` is enforced.
    """

    # Geometry
    column_count: int = 2048
    cells_per_column: int = 32

    # Activation
    activation_threshold: int = 13
    min_threshold: int = 10
    max_new_synapses: int = 20

    # Synapse / segment limits
    max_synapses_per_segment: int = 255
    max_segments_per_cell: int = 128
    max_total_segments: int = 100_000
    max_total_synapses: int = 2_000_000

    # Permanence learning
    initial_permanence: float = 0.21
    connected_threshold: float = 0.5
    perm_inc: float = 0.1
    perm_dec: float = 0.1
    predicted_dec: float = 0.05
    prune_threshold: float = 0.01

    # Compaction
    compaction_threshold: float = 0.3

    def __post_init__(self) -> None:
        assert self.column_count > 0, (
            f"column_count must be positive, got {self.column_count}"
        )
        assert self.cells_per_column > 0, (
            f"cells_per_column must be positive, got {self.cells_per_column}"
        )
        assert self.activation_threshold > 0, (
            f"activation_threshold must be positive, got {self.activation_threshold}"
        )
        assert self.min_threshold > 0, (
            f"min_threshold must be positive, got {self.min_threshold}"
        )
        assert self.min_threshold <= self.activation_threshold, (
            f"min_threshold ({self.min_threshold}) must be <= "
            f"activation_threshold ({self.activation_threshold})"
        )
        assert self.max_new_synapses > 0, (
            f"max_new_synapses must be positive, got {self.max_new_synapses}"
        )
        assert self.max_synapses_per_segment > 0
        assert self.max_segments_per_cell > 0
        assert self.max_total_segments > 0
        assert self.max_total_synapses > 0
        assert 0 < self.connected_threshold <= 1
        assert 0 < self.initial_permanence <= 1
        assert self.perm_inc >= 0
        assert self.perm_dec >= 0
        assert self.predicted_dec >= 0
        assert self.prune_threshold >= 0
        assert 0 < self.compaction_threshold < 1, (
            f"compaction_threshold must be in (0, 1), got {self.compaction_threshold}"
        )

    # -- derived properties ---------------------------------------------------

    @property
    def total_cells(self) -> int:
        """Total number of TM cells."""
        return self.column_count * self.cells_per_column

    @property
    def estimated_segment_memory_bytes(self) -> int:
        """Rough memory for segment metadata (64 bytes per segment estimate)."""
        return self.max_total_segments * 64

    @property
    def estimated_synapse_memory_bytes(self) -> int:
        """Rough memory for synapse data (12 bytes per synapse estimate)."""
        return self.max_total_synapses * 12


