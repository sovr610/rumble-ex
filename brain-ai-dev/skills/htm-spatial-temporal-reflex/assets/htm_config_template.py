@dataclass
class HTMConfig:
    """Unified HTM configuration aggregating all sub-configs.

    This replaces the previous flat HTMConfig while maintaining backward
    compatibility through delegating @property accessors.

    Sub-configs
    -----------
    * ``sp``      -- Spatial Pooler (SPConfig)
    * ``tm``      -- Temporal Memory (TMConfig)
    * ``reflex``  -- Reflex Memory / AHTM acceleration (ReflexConfig)
    * ``fallback``-- Fallback neural predictor (FallbackConfig)

    Top-level flags
    ---------------
    * ``use_htm``      -- run the full HTM pipeline (SP + TM)
    * ``use_reflex``   -- enable Reflex Memory acceleration
    * ``use_fallback`` -- keep fallback predictor available

    Backward compatibility
    ----------------------
    Legacy flat-field access (e.g. ``config.htm.column_count``) is supported
    through @property accessors that delegate to the nested sub-configs.
    Use ``upgrade_htm_config()`` to convert old checkpoint dicts.
    """

    # Sub-configs
    sp: SPConfig = field(default_factory=SPConfig)
    tm: TMConfig = field(default_factory=TMConfig)
    reflex: ReflexConfig = field(default_factory=ReflexConfig)
    fallback: FallbackConfig = field(default_factory=FallbackConfig)

    # Top-level flags
    use_htm: bool = True
    use_reflex: bool = True
    use_fallback: bool = True

    def __post_init__(self) -> None:
        # Synchronise column_count between SP and TM
        if self.tm.column_count != self.sp.column_count:
            self.tm.column_count = self.sp.column_count

        # Propagate reflex.enabled from use_reflex
        if not self.use_reflex:
            self.reflex.enabled = False

    # -- backward-compatible property accessors --------------------------------
    # These allow existing code that reads ``htm_config.column_count`` etc. to
    # continue working without modification.

    @property
    def input_size(self) -> int:
        """SP input dimension (encoder output)."""
        return self.sp.input_size

    @property
    def column_count(self) -> int:
        """Number of mini-columns (delegates to SP)."""
        return self.sp.column_count

    @property
    def cells_per_column(self) -> int:
        """Cells per mini-column (delegates to TM)."""
        return self.tm.cells_per_column

    @property
    def sparsity(self) -> float:
        """Target SP sparsity."""
        return self.sp.sparsity

    @property
    def permanence_inc(self) -> float:
        """Permanence increment (SP value; TM may differ)."""
        return self.sp.perm_inc

    @property
    def permanence_dec(self) -> float:
        """Permanence decrement (SP value; TM may differ)."""
        return self.sp.perm_dec

    @property
    def activation_threshold(self) -> int:
        """TM activation threshold."""
        return self.tm.activation_threshold

    @property
    def lstm_hidden_dim(self) -> int:
        """Fallback hidden size (legacy name)."""
        return self.fallback.hidden_size

    @property
    def lstm_num_layers(self) -> int:
        """Fallback num layers (legacy name)."""
        return self.fallback.num_layers

    @property
    def use_reflex_memory(self) -> bool:
        """Legacy accessor for reflex enable flag."""
        return self.use_reflex and self.reflex.enabled

    @property
    def reflex_num_tables(self) -> int:
        """LSH table count (legacy accessor)."""
        return self.reflex.num_tables

    @property
    def reflex_bits_per_hash(self) -> int:
        """LSH bits per hash (legacy accessor)."""
        return self.reflex.bits_per_hash

    @property
    def reflex_promotion_threshold(self) -> int:
        """Promotion threshold (legacy accessor)."""
        return self.reflex.promotion_threshold

    @property
    def reflex_capacity(self) -> int:
        """Reflex observation capacity (legacy accessor)."""
        return self.reflex.max_observations

    # -- derived properties ---------------------------------------------------

    @property
    def num_active_columns(self) -> int:
        """Target number of active columns per step."""
        return self.sp.num_active_columns

    @property
    def total_cells(self) -> int:
        """Total TM cells."""
        return self.tm.total_cells

    @property
    def estimated_total_params(self) -> int:
        """Very rough parameter estimate for the entire HTM subsystem."""
        sp_params = self.sp.column_count * self.sp.potential_pool_size  # permanences
        tm_params = self.tm.max_total_synapses  # synapse permanences
        fallback_params = self.fallback.estimated_params
        return sp_params + tm_params + fallback_params

    def summary(self) -> str:
        """Human-readable configuration summary."""
        lines = [
            "HTMConfig Summary",
            "=" * 50,
            f"  use_htm:      {self.use_htm}",
            f"  use_reflex:   {self.use_reflex}",
            f"  use_fallback: {self.use_fallback}",
            "",
            "  Spatial Pooler:",
            f"    input_size:          {self.sp.input_size}",
            f"    column_count:        {self.sp.column_count}",
            f"    sparsity:            {self.sp.sparsity}",
            f"    num_active_columns:  {self.sp.num_active_columns}",
            f"    potential_pool_size:  {self.sp.potential_pool_size}",
            f"    binarization_mode:   {self.sp.binarization_mode}",
            f"    inhibition_mode:     {self.sp.inhibition_mode}",
            "",
            "  Temporal Memory:",
            f"    column_count:        {self.tm.column_count}",
            f"    cells_per_column:    {self.tm.cells_per_column}",
            f"    total_cells:         {self.tm.total_cells}",
            f"    activation_thresh:   {self.tm.activation_threshold}",
            f"    max_total_segments:  {self.tm.max_total_segments}",
            f"    max_total_synapses:  {self.tm.max_total_synapses}",
            "",
            "  Reflex Memory:",
            f"    enabled:             {self.reflex.enabled}",
            f"    max_observations:    {self.reflex.max_observations}",
            f"    max_promoted:        {self.reflex.max_promoted}",
            f"    num_tables:          {self.reflex.num_tables}",
            f"    bits_per_hash:       {self.reflex.bits_per_hash}",
            f"    total_buckets:       {self.reflex.total_buckets}",
            "",
            "  Fallback Predictor:",
            f"    backend:             {self.fallback.backend}",
            f"    hidden_size:         {self.fallback.hidden_size}",
            f"    num_layers:          {self.fallback.num_layers}",
            f"    estimated_params:    {self.fallback.estimated_params:,}",
            "",
            f"  Estimated total params: {self.estimated_total_params:,}",
        ]
        return "\n".join(lines)


