# Mapping from old flat HTMConfig field names to new nested locations.
_LEGACY_FIELD_MAP: Dict[str, str] = {
    # Spatial Pooler
    "column_count":          "sp.column_count",
    "sparsity":              "sp.sparsity",
    "permanence_inc":        "sp.perm_inc",
    "permanence_dec":        "sp.perm_dec",
    "permanence_connected":  "sp.perm_threshold",
    "initial_permanence":    "sp.initial_permanence",

    # Temporal Memory (also receives some SP-level fields)
    "cells_per_column":      "tm.cells_per_column",
    "activation_threshold":  "tm.activation_threshold",
    "min_threshold":         "tm.min_threshold",
    "max_new_synapse_count": "tm.max_new_synapses",

    # Fallback
    "use_fallback":          "_use_fallback",
    "lstm_hidden_dim":       "fallback.hidden_size",
    "lstm_num_layers":       "fallback.num_layers",

    # Reflex
    "use_reflex_memory":     "_use_reflex",
    "reflex_num_tables":     "reflex.num_tables",
    "reflex_bits_per_hash":  "reflex.bits_per_hash",
    "reflex_promotion_threshold": "reflex.promotion_threshold",
    "reflex_capacity":       "reflex.max_observations",
}


def upgrade_htm_config(legacy: Dict[str, Any]) -> HTMConfig:
    """Convert an old flat HTMConfig dict to the new nested structure.

    This handles checkpoint loading and YAML migration.  Unknown keys are
    silently ignored (with a warning printed to stderr if available).

    Parameters
    ----------
    legacy : dict
        Flat dictionary with old HTMConfig fields.  Typically obtained from
        ``dataclasses.asdict(old_htm_config)`` or from a checkpoint's
        ``config["htm"]`` entry.

    Returns
    -------
    HTMConfig
        New nested configuration.

    Field mapping
    -------------
    Old field                  -> New location
    -------------------------  ---------------------------------
    column_count               -> sp.column_count, tm.column_count
    cells_per_column           -> tm.cells_per_column
    sparsity                   -> sp.sparsity
    permanence_inc             -> sp.perm_inc, tm.perm_inc
    permanence_dec             -> sp.perm_dec, tm.perm_dec
    permanence_connected       -> sp.perm_threshold, tm.connected_threshold
    activation_threshold       -> tm.activation_threshold
    min_threshold              -> tm.min_threshold
    max_new_synapse_count      -> tm.max_new_synapses
    initial_permanence         -> sp.initial_permanence, tm.initial_permanence
    use_fallback               -> use_fallback
    lstm_hidden_dim            -> fallback.hidden_size
    lstm_num_layers            -> fallback.num_layers
    use_reflex_memory          -> use_reflex, reflex.enabled
    reflex_num_tables          -> reflex.num_tables
    reflex_bits_per_hash       -> reflex.bits_per_hash
    reflex_promotion_threshold -> reflex.promotion_threshold
    reflex_capacity            -> reflex.max_observations
    """
    import sys

    sp_kwargs: Dict[str, Any] = {}
    tm_kwargs: Dict[str, Any] = {}
    reflex_kwargs: Dict[str, Any] = {}
    fallback_kwargs: Dict[str, Any] = {}
    top_kwargs: Dict[str, Any] = {}
    unmapped: list[str] = []

    for key, value in legacy.items():
        target = _LEGACY_FIELD_MAP.get(key)
        if target is None:
            unmapped.append(key)
            continue

        if target.startswith("sp."):
            field_name = target[3:]
            sp_kwargs[field_name] = value
        elif target.startswith("tm."):
            field_name = target[3:]
            tm_kwargs[field_name] = value
        elif target.startswith("reflex."):
            field_name = target[7:]
            reflex_kwargs[field_name] = value
        elif target.startswith("fallback."):
            field_name = target[9:]
            fallback_kwargs[field_name] = value
        elif target == "_use_fallback":
            top_kwargs["use_fallback"] = value
        elif target == "_use_reflex":
            top_kwargs["use_reflex"] = bool(value)
            reflex_kwargs["enabled"] = bool(value)

    # Fields that map to BOTH SP and TM
    if "column_count" in legacy:
        tm_kwargs.setdefault("column_count", legacy["column_count"])
    if "permanence_inc" in legacy:
        tm_kwargs.setdefault("perm_inc", legacy["permanence_inc"])
    if "permanence_dec" in legacy:
        tm_kwargs.setdefault("perm_dec", legacy["permanence_dec"])
    if "permanence_connected" in legacy:
        tm_kwargs.setdefault("connected_threshold", legacy["permanence_connected"])
    if "initial_permanence" in legacy:
        sp_kwargs.setdefault("initial_permanence", legacy["initial_permanence"])
        tm_kwargs.setdefault("initial_permanence", legacy["initial_permanence"])

    if unmapped:
        print(
            f"[upgrade_htm_config] Warning: unmapped legacy fields ignored: "
            f"{unmapped}",
            file=sys.stderr,
        )

    return HTMConfig(
        sp=SPConfig(**sp_kwargs) if sp_kwargs else SPConfig(),
        tm=TMConfig(**tm_kwargs) if tm_kwargs else TMConfig(),
        reflex=ReflexConfig(**reflex_kwargs) if reflex_kwargs else ReflexConfig(),
        fallback=FallbackConfig(**fallback_kwargs) if fallback_kwargs else FallbackConfig(),
        **top_kwargs,
    )


