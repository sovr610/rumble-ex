def htm_config_to_dict(config: HTMConfig) -> Dict[str, Any]:
    """Serialize an HTMConfig to a nested dict (JSON-safe).

    Uses ``dataclasses.asdict`` internally, which recursively converts all
    sub-dataclasses.  The result contains only JSON-compatible types (no
    Tensor values, no custom objects).

    Parameters
    ----------
    config : HTMConfig
        The configuration to serialize.

    Returns
    -------
    dict
        Nested dictionary suitable for ``json.dumps()``.
    """
    return asdict(config)


def htm_config_from_dict(d: Dict[str, Any]) -> HTMConfig:
    """Deserialize an HTMConfig from a nested dict.

    Handles both:
    * New-style nested dicts (with ``sp``, ``tm``, ``reflex``, ``fallback`` keys).
    * Legacy flat dicts (via ``upgrade_htm_config``).

    Parameters
    ----------
    d : dict
        Configuration dictionary.

    Returns
    -------
    HTMConfig
        Reconstructed configuration.
    """
    # Detect legacy format: if there is no "sp" key but there IS a
    # "column_count" key at the top level, treat as legacy.
    if "sp" not in d and "column_count" in d:
        return upgrade_htm_config(d)

    # New-style nested format
    sp = SPConfig(**d["sp"]) if "sp" in d else SPConfig()
    tm = TMConfig(**d["tm"]) if "tm" in d else TMConfig()
    reflex = ReflexConfig(**d["reflex"]) if "reflex" in d else ReflexConfig()

    fb_data = d.get("fallback", {})
    fallback = FallbackConfig(**fb_data) if fb_data else FallbackConfig()

    top_keys = {"use_htm", "use_reflex", "use_fallback"}
    top_kwargs = {k: d[k] for k in top_keys if k in d}

    return HTMConfig(
        sp=sp,
        tm=tm,
        reflex=reflex,
        fallback=fallback,
        **top_kwargs,
    )


def htm_config_to_json(config: HTMConfig, indent: int = 2) -> str:
    """Serialize HTMConfig to a JSON string."""
    return json.dumps(htm_config_to_dict(config), indent=indent)


def htm_config_from_json(s: str) -> HTMConfig:
    """Deserialize HTMConfig from a JSON string."""
    return htm_config_from_dict(json.loads(s))


