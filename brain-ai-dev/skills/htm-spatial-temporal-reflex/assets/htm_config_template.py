@dataclass
class FallbackConfig:
    """Fallback neural predictor configuration.

    Used when htm.core is unavailable or for hybrid prediction (ensemble).
    Supports LSTM, GRU, and Transformer backends.

    Key relationships
    -----------------
    * ``hidden_size`` should match the workspace dimension for seamless
      integration (default 2048).
    * ``num_heads`` and ``max_seq_len`` only apply to the transformer backend.
    * ``anomaly_mode`` selects how the anomaly score is computed from the
      fallback predictor output.
    """

    # Backend selection
    backend: str = "lstm"                    # lstm | gru | transformer

    # Architecture
    hidden_size: int = 2048
    num_layers: int = 2
    dropout: float = 0.1

    # Transformer-specific
    num_heads: int = 8
    max_seq_len: int = 100
    feedforward_dim: Optional[int] = None    # defaults to 4 * hidden_size

    # Anomaly detection
    anomaly_mode: str = "overlap"            # overlap | learned | mse
    anomaly_window: int = 1000

    def __post_init__(self) -> None:
        assert self.backend in ("lstm", "gru", "transformer"), (
            f"Invalid backend: {self.backend}"
        )
        assert self.hidden_size > 0, (
            f"hidden_size must be positive, got {self.hidden_size}"
        )
        assert self.num_layers >= 1, (
            f"num_layers must be >= 1, got {self.num_layers}"
        )
        assert 0 <= self.dropout < 1, (
            f"dropout must be in [0, 1), got {self.dropout}"
        )
        assert self.anomaly_mode in ("overlap", "learned", "mse"), (
            f"Invalid anomaly_mode: {self.anomaly_mode}"
        )
        assert self.anomaly_window > 0, (
            f"anomaly_window must be positive, got {self.anomaly_window}"
        )
        if self.backend == "transformer":
            assert self.num_heads > 0
            assert self.hidden_size % self.num_heads == 0, (
                f"hidden_size ({self.hidden_size}) must be divisible by "
                f"num_heads ({self.num_heads})"
            )
            assert self.max_seq_len > 0
        if self.feedforward_dim is None:
            self.feedforward_dim = 4 * self.hidden_size

    # -- derived properties ---------------------------------------------------

    @property
    def estimated_params(self) -> int:
        """Rough parameter count for the fallback network."""
        if self.backend in ("lstm", "gru"):
            # LSTM/GRU: ~4*H*H per gate per layer (LSTM has 4 gates, GRU has 3)
            gates = 4 if self.backend == "lstm" else 3
            return self.num_layers * gates * self.hidden_size * self.hidden_size
        else:
            # Transformer: attention + FFN per layer
            attn = 4 * self.hidden_size * self.hidden_size  # Q, K, V, O
            ffn = 2 * self.hidden_size * (self.feedforward_dim or 4 * self.hidden_size)
            return self.num_layers * (attn + ffn)


