# 1. SPConfig -- Spatial Pooler
# ---------------------------------------------------------------------------

@dataclass
class SPConfig:
    """Spatial Pooler configuration.

    Controls input binarization, potential pool wiring, permanence learning,
    boosting / homeostatic regulation, and inhibition.

    Key relationships
    -----------------
    * ``input_size`` must match the encoder output dimension (default 4096).
    * ``column_count`` is shared with ``TMConfig.column_count``; the
      aggregator ``HTMConfig.__post_init__`` synchronises them automatically.
    * ``num_active_columns`` is derived: ``max(1, int(column_count * sparsity))``.
    """

    # Geometry
    input_size: int = 4096
    column_count: int = 2048
    potential_pool_size: int = 256

    # Sparsity
    sparsity: float = 0.02

    # Permanence learning
    perm_inc: float = 0.1
    perm_dec: float = 0.05
    perm_threshold: float = 0.5
    initial_permanence: float = 0.21

    # Overlap & boosting
    min_overlap: int = 1
    boost_strength: float = 3.0
    duty_cycle_period: int = 1000

    # Binarization of continuous encoder output
    binarization_mode: str = "topk"          # passthrough | topk | threshold | learned_gate
    binarization_topk: int = 200
    binarization_threshold: float = 0.5

    # Inhibition
    inhibition_mode: str = "global"          # global | local
    local_radius: int = 64

    def __post_init__(self) -> None:
        assert self.input_size > 0, (
            f"input_size must be positive, got {self.input_size}"
        )
        assert self.column_count > 0, (
            f"column_count must be positive, got {self.column_count}"
        )
        assert 0 < self.sparsity < 1, (
            f"sparsity must be in (0, 1), got {self.sparsity}"
        )
        assert self.potential_pool_size <= self.input_size, (
            f"potential_pool_size ({self.potential_pool_size}) must be "
            f"<= input_size ({self.input_size})"
        )
        assert self.binarization_mode in (
            "passthrough", "topk", "threshold", "learned_gate",
        ), f"Invalid binarization_mode: {self.binarization_mode}"
        assert self.inhibition_mode in ("global", "local"), (
            f"Invalid inhibition_mode: {self.inhibition_mode}"
        )
        assert self.perm_inc >= 0, f"perm_inc must be >= 0, got {self.perm_inc}"
        assert self.perm_dec >= 0, f"perm_dec must be >= 0, got {self.perm_dec}"
        assert 0 < self.perm_threshold <= 1, (
            f"perm_threshold must be in (0, 1], got {self.perm_threshold}"
        )
        assert 0 < self.initial_permanence <= 1, (
            f"initial_permanence must be in (0, 1], got {self.initial_permanence}"
        )
        assert self.boost_strength >= 0, (
            f"boost_strength must be >= 0, got {self.boost_strength}"
        )
        assert self.duty_cycle_period > 0, (
            f"duty_cycle_period must be positive, got {self.duty_cycle_period}"
        )
        if self.binarization_mode == "topk":
            assert self.binarization_topk > 0, (
                f"binarization_topk must be positive, got {self.binarization_topk}"
            )
        if self.inhibition_mode == "local":
            assert self.local_radius > 0, (
                f"local_radius must be positive, got {self.local_radius}"
            )

    # -- derived properties ---------------------------------------------------

    @property
    def num_active_columns(self) -> int:
        """Number of active columns per time step (target)."""
        return max(1, int(self.column_count * self.sparsity))

    @property
    def potential_pool_fraction(self) -> float:
        """Fraction of input bits each column *can* connect to."""
        return self.potential_pool_size / self.input_size if self.input_size else 0.0

    @property
    def estimated_permanence_memory_bytes(self) -> int:
        """Rough memory estimate for the permanence matrix (float32)."""
        return self.column_count * self.potential_pool_size * 4


