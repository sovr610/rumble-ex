class SpatialPooler(nn.Module):
    """HTM Spatial Pooler with deterministic tie-breaking and AMP safety.

    Converts (B, N_inputs) float inputs into (B, K) int SDR column indices
    where K = int(column_count * sparsity).

    All mutable state tensors are registered as buffers (no ``nn.Parameter``)
    so that:
      - They move with ``.to(device)`` / ``.half()`` automatically.
      - They are included in ``state_dict`` for checkpointing.
      - No gradient graph is constructed.

    Learning is purely Hebbian (``torch.no_grad()``).  Overlap and count
    arithmetic is performed in ``int32`` or ``float32`` regardless of the
    module's autocast dtype.

    Args:
        config: ``SPConfig`` instance with all hyper-parameters.
    """

    def __init__(self, config: Optional[SPConfig] = None) -> None:
        super().__init__()
        self.config = config or SPConfig()
        cfg = self.config

        # Derived constants
        self.K: int = int(cfg.column_count * cfg.sparsity)
        assert self.K >= 1, "K (active column count) must be >= 1"

        # -- Binarizer --
        self.binarizer = InputBinarizer(cfg)

        # -- Potential pool: (N_columns, P) int32 --
        # Each column can only form synapses to a random subset of inputs.
        self.register_buffer("potential_idx", self._init_potential_pools())

        # -- Permanences: (N_columns, P) float32 --
        self.register_buffer("perm", self._init_permanences())

        # -- Boosting state --
        self.register_buffer("boost", torch.ones(cfg.column_count, dtype=torch.float32))
        self.register_buffer(
            "active_duty_cycle",
            torch.zeros(cfg.column_count, dtype=torch.float32),
        )
        self.register_buffer(
            "overlap_duty_cycle",
            torch.zeros(cfg.column_count, dtype=torch.float32),
        )
        self.register_buffer(
            "step_count", torch.tensor(0, dtype=torch.long)
        )

    # -----------------------------------------------------------------
    # Initialisation helpers
    # -----------------------------------------------------------------

    def _init_potential_pools(self) -> Tensor:
        """Create random potential synapse pools.

        For each of the ``N_columns`` columns, uniformly sample ``P`` distinct
        indices from ``[0, N_inputs)`` without replacement.

        Returns:
            (N_columns, P) int32 tensor.
        """
        cfg = self.config
        pools = torch.zeros(
            cfg.column_count, cfg.potential_pool_size, dtype=torch.int32
        )
        for c in range(cfg.column_count):
            perm = torch.randperm(cfg.input_size)[: cfg.potential_pool_size]
            pools[c] = perm.int()
        return pools

    def _init_permanences(self) -> Tensor:
        """Initialise permanence values.

        Values are drawn from ``N(initial_permanence, 0.05)`` and clamped
        to ``[0, 1]``.

        Returns:
            (N_columns, P) float32 tensor.
        """
        cfg = self.config
        perm = torch.empty(
            cfg.column_count, cfg.potential_pool_size, dtype=torch.float32
        )
        perm.normal_(mean=cfg.initial_permanence, std=0.05)
        perm.clamp_(0.0, 1.0)
        return perm

    # -----------------------------------------------------------------
    # Core SP stages
    # -----------------------------------------------------------------

    def compute_overlap(self, input_bits: Tensor) -> Tensor:
        """Compute overlap between input and each column's connected synapses.

        Args:
            input_bits: (B, N_inputs) bool tensor.

        Returns:
            (B, N_columns) int32 tensor of overlap counts.

        Note:
            The computation gathers input bits corresponding to each column's
            potential pool and then masks by connected synapses (permanence
            >= threshold).  All arithmetic is performed in int32 for
            mixed-precision safety.
        """
        # potential_idx: (N_col, P) int32
        # Expand for batch gather: (B, N_col, P)
        idx = self.potential_idx.long()  # int64 for indexing
        pool_inputs = input_bits[:, idx]  # (B, N_col, P)

        # Connected mask: (N_col, P) bool
        connected = self.perm >= self.config.perm_threshold

        # Overlap: count of (connected AND active) per column
        # Cast to int32 for accumulation precision under AMP.
        # Note: .sum() on int32 may return int64 in PyTorch; we force int32.
        overlap = (pool_inputs & connected.unsqueeze(0)).to(torch.int32).sum(dim=-1).to(torch.int32)
        return overlap  # (B, N_col)

    def inhibit(self, boosted_overlap: Tensor) -> Tensor:
        """Select winner columns via global inhibition with deterministic tie-breaking.

        Ties are broken by a small column-id-based offset so that the output is
        identical across runs with the same input (no non-determinism from
        unstable sorts).

        Args:
            boosted_overlap: (B, N_col) float tensor.

        Returns:
            (B, K) int64 tensor of winning column indices sorted ascending.
        """
        N_col = self.config.column_count
        col_ids = torch.arange(N_col, device=boosted_overlap.device, dtype=torch.float32)

        # Deterministic tie-breaking:
        # Multiply overlap by N_col and subtract column id so that equal
        # overlaps are resolved by column index (lower id wins, because
        # topk selects highest values and (overlap*N - small_id) > (overlap*N - big_id)).
        # The offset is small enough (< N_col) that it cannot change the
        # ordering of overlaps that differ by >= 1.
        tiebroken = boosted_overlap * N_col - col_ids.unsqueeze(0)

        _, top_indices = tiebroken.topk(self.K, dim=-1, sorted=False)
        # Sort the indices for consistent ordering within each sample.
        top_indices, _ = top_indices.sort(dim=-1)
        return top_indices  # (B, K) int64

    def local_inhibit(self, boosted_overlap: Tensor) -> Tensor:
        """Select winner columns via local (neighbourhood) inhibition.

        Each column competes only with columns within ``local_radius`` on
        either side.  The number of local winners is proportional to the
        neighbourhood size times sparsity.

        Args:
            boosted_overlap: (B, N_col) float tensor.

        Returns:
            (B, K_local) int64 tensor of winning column indices.  The actual
            number of winners may vary per sample; we pad to a fixed K
            by taking the global top-K from the local winners.
        """
        cfg = self.config
        N_col = cfg.column_count
        B = boosted_overlap.shape[0]
        radius = cfg.local_radius
        local_k = max(1, int((2 * radius + 1) * cfg.sparsity))

        # We slide a window across columns and mark local winners.
        is_winner = torch.zeros(B, N_col, device=boosted_overlap.device, dtype=torch.bool)

        for center in range(N_col):
            lo = max(0, center - radius)
            hi = min(N_col, center + radius + 1)
            neighbourhood = boosted_overlap[:, lo:hi]  # (B, window)

            # Tie-breaking offset within the window
            window_size = hi - lo
            offset_in_window = center - lo
            col_offsets = torch.arange(
                window_size, device=boosted_overlap.device, dtype=torch.float32
            )
            tiebroken = neighbourhood * window_size + col_offsets.unsqueeze(0)

            # Top local_k in the window
            _, local_top = tiebroken.topk(min(local_k, window_size), dim=-1, sorted=False)
            # Check if the center column is among local winners
            # local_top contains indices within [lo, hi), we need offset_in_window
            center_won = (local_top == offset_in_window).any(dim=-1)  # (B,)
            is_winner[:, center] = center_won

        # Collect winner indices; pad/truncate to exactly K per sample
        # using the boosted_overlap to rank among winners.
        winner_overlap = boosted_overlap.clone()
        winner_overlap[~is_winner] = -1.0  # suppress non-winners

        # Deterministic tie-breaking for final selection
        col_ids = torch.arange(N_col, device=boosted_overlap.device, dtype=torch.float32)
        tiebroken = winner_overlap * N_col + col_ids.unsqueeze(0)
        _, top_indices = tiebroken.topk(self.K, dim=-1, sorted=False)
        top_indices, _ = top_indices.sort(dim=-1)
        return top_indices  # (B, K)

    # -----------------------------------------------------------------
    # Learning (loop-based reference implementation)
    # -----------------------------------------------------------------

    def learn_loop(self, active_columns: Tensor, input_bits: Tensor) -> None:
        """Update permanences for active columns -- loop-based reference.

        For each active column in each batch sample:
          - Increase permanence for potential synapses whose input is active.
          - Decrease permanence for potential synapses whose input is inactive.
        Permanences are clamped to [0, 1].

        This implementation uses explicit Python loops and is provided as a
        reference.  For GPU-efficient training use :meth:`learn` (vectorised).

        The semantics match the vectorised version: permanence deltas are
        accumulated from the original permanence values (not compounded
        across batch samples), then applied once.

        Args:
            active_columns: (B, K) int64 -- winning column indices.
            input_bits: (B, N_inputs) bool.
        """
        cfg = self.config
        N_col = cfg.column_count
        P = cfg.potential_pool_size

        with torch.no_grad():
            perm_fp32 = self.perm.float()  # (N_col, P) fp32

            # Accumulate: for each column, mean input-active fraction over
            # batch samples that activated it.
            active_input_sum = torch.zeros(N_col, P, dtype=torch.float32,
                                           device=perm_fp32.device)
            col_active_count = torch.zeros(N_col, dtype=torch.float32,
                                           device=perm_fp32.device)

            B = active_columns.shape[0]
            for b in range(B):
                cols = active_columns[b]  # (K,)
                for c in cols:
                    c_idx = c.item()
                    pool_active = input_bits[b, self.potential_idx[c_idx].long()].float()
                    active_input_sum[c_idx] += pool_active
                    col_active_count[c_idx] += 1.0

            # Compute mean fraction and delta (same formula as vectorised)
            update_mask = col_active_count > 0
            count_safe = col_active_count.clamp(min=1.0)
            mean_active_frac = active_input_sum / count_safe.unsqueeze(-1)
            delta = (cfg.perm_inc + cfg.perm_dec) * mean_active_frac - cfg.perm_dec
            delta = delta * update_mask.unsqueeze(-1).float()

            perm_fp32 += delta
            perm_fp32.clamp_(0.0, 1.0)
            self.perm.copy_(perm_fp32)

    # -----------------------------------------------------------------
    # Learning (vectorised -- preferred for GPU)
    # -----------------------------------------------------------------

    def learn(self, active_columns: Tensor, input_bits: Tensor) -> None:
        """Update permanences for active columns -- vectorised GPU implementation.

        Uses advanced indexing and ``scatter_add`` / masked operations to
        avoid Python loops over the batch and column dimensions.

        The permanence update rule is identical to :meth:`learn_loop`:
          - ``perm[c, p] += perm_inc``  if input_bits[b, potential_idx[c, p]] is True
          - ``perm[c, p] -= perm_dec``  if input_bits[b, potential_idx[c, p]] is False
        averaged across batch samples where column ``c`` was active.

        Args:
            active_columns: (B, K) int64 -- winning column indices.
            input_bits: (B, N_inputs) bool.
        """
        cfg = self.config
        B = active_columns.shape[0]
        N_col = cfg.column_count
        P = cfg.potential_pool_size

        with torch.no_grad():
            perm_fp32 = self.perm.float()  # (N_col, P) fp32

            # Build a mask of which columns were active (across batch).
            # col_active_count[c] = number of batch samples where c was active.
            col_active_count = torch.zeros(
                N_col, device=perm_fp32.device, dtype=torch.float32
            )
            flat_cols = active_columns.reshape(-1).long()  # (B * K,)
            ones = torch.ones(flat_cols.shape[0], device=perm_fp32.device, dtype=torch.float32)
            col_active_count.scatter_add_(0, flat_cols, ones)

            # For each column that was active at least once, compute the
            # mean input activity across batch samples that activated it.
            # active_input_sum[c, p] = sum over batch of input_bits[b, potential_idx[c, p]]
            #   for those b where column c was active.

            # Gather pool inputs for all batch items: (B, N_col, P) bool
            idx_long = self.potential_idx.long()  # (N_col, P)
            pool_inputs_all = input_bits[:, idx_long]  # (B, N_col, P) bool

            # Mask: (B, N_col) bool -- True where (b, c) is an active pair.
            active_mask = torch.zeros(
                B, N_col, device=perm_fp32.device, dtype=torch.bool
            )
            batch_idx = (
                torch.arange(B, device=perm_fp32.device)
                .unsqueeze(1)
                .expand_as(active_columns)
            )  # (B, K)
            active_mask[batch_idx, active_columns.long()] = True  # (B, N_col)

            # Sum of pool_inputs over active batch entries: (N_col, P)
            # active_mask: (B, N_col, 1), pool_inputs_all: (B, N_col, P)
            masked_inputs = pool_inputs_all.float() * active_mask.unsqueeze(-1).float()
            active_input_sum = masked_inputs.sum(dim=0)  # (N_col, P) float

            # Which columns to update (active at least once)
            update_mask = col_active_count > 0  # (N_col,) bool

            # Per-column normalisation factor
            count_safe = col_active_count.clamp(min=1.0)  # avoid div-by-zero

            # Mean fraction of batch samples (that activated this column)
            # where the synapse's input was active.
            mean_active_frac = active_input_sum / count_safe.unsqueeze(-1)  # (N_col, P)

            # Permanence delta:
            #   For active inputs:   +perm_inc * mean_active_frac
            #   For inactive inputs: -perm_dec * (1 - mean_active_frac)
            # Combined: perm_inc * frac - perm_dec * (1 - frac)
            #         = (perm_inc + perm_dec) * frac - perm_dec
            delta = (cfg.perm_inc + cfg.perm_dec) * mean_active_frac - cfg.perm_dec
            # (N_col, P)

            # Only apply to columns that were active
            delta = delta * update_mask.unsqueeze(-1).float()

            perm_fp32 += delta
            perm_fp32.clamp_(0.0, 1.0)
            self.perm.copy_(perm_fp32)

    # -----------------------------------------------------------------
    # Boosting
    # -----------------------------------------------------------------

    def _update_duty_cycles(self, active_columns: Tensor) -> None:
        """Update overlap and active duty cycles via exponential moving average.

        Args:
            active_columns: (B, K) int64 -- winning column indices.
        """
        cfg = self.config
        B = active_columns.shape[0]
        alpha = 1.0 / cfg.duty_cycle_period

        # Per-column activity frequency in this batch
        is_active = torch.zeros(
            cfg.column_count, device=self.perm.device, dtype=torch.float32
        )
        flat_cols = active_columns.reshape(-1).long()
        ones = torch.ones(
            flat_cols.shape[0], device=self.perm.device, dtype=torch.float32
        )
        is_active.scatter_add_(0, flat_cols, ones)
        is_active = is_active / max(B, 1)  # mean across batch

        # EMA update
        self.active_duty_cycle.mul_(1.0 - alpha).add_(alpha * is_active)

    def _update_boosting(self) -> None:
        """Recompute boost factors from current duty cycles.

        Columns whose active_duty_cycle is below the target sparsity get
        an exponentially increasing boost.
        """
        cfg = self.config
        self.boost.copy_(
            torch.exp(
                -cfg.boost_strength * (self.active_duty_cycle - cfg.sparsity)
            )
        )

    # -----------------------------------------------------------------
    # Forward pass
    # -----------------------------------------------------------------

    def forward(self, x: Tensor, learn: bool = True) -> Tensor:
        """Run the full Spatial Pooler pipeline.

        Pipeline stages:
          1. **Binarize** -- convert float inputs to binary.
          2. **Overlap** -- count connected active synapses per column.
          3. **Stimulus threshold** -- zero out columns below ``min_overlap``.
          4. **Boost** -- multiply overlap by per-column boost factor.
          5. **Inhibition** -- select top-K winners (global or local).
          6. **Learn** -- Hebbian permanence update (if ``learn=True``).
          7. **Boost update** -- adjust duty cycles and boost factors.

        Args:
            x: (B, N_inputs) float tensor of input features.
            learn: If True, update permanences and boosting state.

        Returns:
            (B, K) int64 tensor of active column indices (SDR in index form)
            where K = int(column_count * sparsity).
        """
        # Ensure 2-D
        if x.dim() == 1:
            x = x.unsqueeze(0)

        # 1. Binarize
        input_bits: Tensor = self.binarizer(x)  # (B, N_inputs) bool

        # 2. Overlap -- always in int32/fp32
        overlap: Tensor = self.compute_overlap(input_bits)  # (B, N_col) int32

        # 3. Stimulus threshold
        overlap_f = overlap.float()
        overlap_f[overlap_f < self.config.min_overlap] = 0.0

        # 4. Boost
        boosted: Tensor = overlap_f * self.boost.unsqueeze(0)  # (B, N_col)

        # 5. Inhibition
        if self.config.inhibition_mode == "local":
            active_columns: Tensor = self.local_inhibit(boosted)
        else:
            active_columns = self.inhibit(boosted)  # (B, K) int64

        # 6 & 7. Learn + boost update
        if learn:
            with torch.no_grad():
                self.learn(active_columns, input_bits)
                self._update_duty_cycles(active_columns)
                self._update_boosting()
                self.step_count += 1

        return active_columns

    # -----------------------------------------------------------------
    # Diagnostics
    # -----------------------------------------------------------------

    def get_stats(self) -> Dict[str, Union[float, int, Dict[str, float]]]:
        """Return diagnostic statistics about the Spatial Pooler state.

        Returns:
            Dictionary with keys:
              - ``mean_permanence``: Mean permanence across all synapses.
              - ``std_permanence``: Std of permanences.
              - ``connected_synapse_count``: Total connected synapses.
              - ``connected_frac``: Fraction of synapses that are connected.
              - ``duty_cycle_mean``: Mean active duty cycle.
              - ``duty_cycle_std``: Std of active duty cycles.
              - ``duty_cycle_min``: Min active duty cycle.
              - ``duty_cycle_max``: Max active duty cycle.
              - ``boost_mean``: Mean boost factor.
              - ``boost_std``: Std of boost factors.
              - ``boost_min``: Min boost factor.
              - ``boost_max``: Max boost factor.
              - ``step_count``: Number of forward steps executed.
        """
        perm = self.perm.float()
        connected = (perm >= self.config.perm_threshold).sum().item()
        total_synapses = perm.numel()

        dc = self.active_duty_cycle
        b = self.boost

        return {
            "mean_permanence": perm.mean().item(),
            "std_permanence": perm.std().item(),
            "connected_synapse_count": int(connected),
            "connected_frac": connected / max(total_synapses, 1),
            "duty_cycle_mean": dc.mean().item(),
            "duty_cycle_std": dc.std().item(),
            "duty_cycle_min": dc.min().item(),
            "duty_cycle_max": dc.max().item(),
            "boost_mean": b.mean().item(),
            "boost_std": b.std().item(),
            "boost_min": b.min().item(),
            "boost_max": b.max().item(),
            "step_count": self.step_count.item(),
        }

    # -----------------------------------------------------------------
    # Reset
    # -----------------------------------------------------------------

    def reset(self) -> None:
        """Reset all learned state to initial values.

        Re-initialises permanences, clears duty cycles, resets boost factors
        and step counter.  Potential pools are NOT changed (topology is fixed).
        """
        self.perm.copy_(self._init_permanences().to(self.perm.device))
        self.boost.fill_(1.0)
        self.active_duty_cycle.zero_()
        self.overlap_duty_cycle.zero_()
        self.step_count.zero_()

    # -----------------------------------------------------------------
    # Repr
    # -----------------------------------------------------------------

    def extra_repr(self) -> str:
        cfg = self.config
        return (
            f"input_size={cfg.input_size}, column_count={cfg.column_count}, "
            f"K={self.K}, P={cfg.potential_pool_size}, sparsity={cfg.sparsity}, "
            f"inhibition={cfg.inhibition_mode}, binarization={cfg.binarization_mode}"
        )


