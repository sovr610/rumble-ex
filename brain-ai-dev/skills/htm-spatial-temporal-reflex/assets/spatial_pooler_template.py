class InputBinarizer(nn.Module):
    """Convert dense float inputs to binary sparse inputs.

    Supports four modes controlled by ``SPConfig.binarization_mode``:

    * ``"passthrough"`` -- assume inputs are already binary (no-op).
    * ``"topk"`` -- keep the top-k values as 1, the rest as 0.
    * ``"threshold"`` -- values > threshold become 1.
    * ``"learned_gate"`` -- a learned linear layer followed by a sigmoid;
      values > 0.5 become 1 during inference (straight-through in training
      is NOT used here since the SP does not require gradients).

    All outputs are boolean tensors cast to the input dtype for downstream
    arithmetic.
    """

    def __init__(self, config: SPConfig) -> None:
        super().__init__()
        self.mode: str = config.binarization_mode
        self.topk: int = config.binarization_topk
        self.threshold: float = config.binarization_threshold

        if self.mode == "learned_gate":
            # A small linear projection whose sigmoid is thresholded at 0.5.
            self.gate_linear = nn.Linear(config.input_size, config.input_size)
            # Initialise bias so that sigmoid(bias) ~ 0.5 -> bias ~ 0
            nn.init.zeros_(self.gate_linear.bias)
            nn.init.xavier_uniform_(self.gate_linear.weight)

    def forward(self, x: Tensor) -> Tensor:
        """Binarize input tensor.

        Args:
            x: (B, N_inputs) float tensor.

        Returns:
            (B, N_inputs) bool tensor (True where the input bit is active).
        """
        if self.mode == "passthrough":
            return x.bool()

        if self.mode == "topk":
            # Top-k values are active; rest are off.
            _, topk_idx = x.topk(self.topk, dim=-1)
            out = torch.zeros_like(x, dtype=torch.bool)
            out.scatter_(1, topk_idx, True)
            return out

        if self.mode == "threshold":
            return x > self.threshold

        if self.mode == "learned_gate":
            # No gradient needed for SP, but the gate itself is differentiable
            # in case it is used within a larger differentiable graph.
            gate_logits = self.gate_linear(x.float())
            return torch.sigmoid(gate_logits) > 0.5

        raise ValueError(f"Unknown binarization mode: {self.mode}")

    def extra_repr(self) -> str:
        parts = [f"mode={self.mode!r}"]
        if self.mode == "topk":
            parts.append(f"topk={self.topk}")
        if self.mode == "threshold":
            parts.append(f"threshold={self.threshold}")
        return ", ".join(parts)


