def indices_to_dense(indices: Tensor, size: int) -> Tensor:
    """Convert SDR index form to dense binary tensor.

    Args:
        indices: (B, K) int -- active column indices per sample.
        size: Total number of columns (N_columns).

    Returns:
        (B, size) float32 binary tensor with 1.0 at active positions.
    """
    B = indices.shape[0]
    dense = torch.zeros(B, size, device=indices.device, dtype=torch.float32)
    dense.scatter_(1, indices.long(), 1.0)
    return dense


def dense_to_indices(dense: Tensor, k: int) -> Tensor:
    """Convert dense binary tensor to SDR index form (top-k active bits).

    Args:
        dense: (B, N) float or bool tensor.
        k: Number of active columns to extract.

    Returns:
        (B, k) int64 -- indices of the k largest values.
    """
    _, topk_idx = dense.topk(k, dim=-1, sorted=True)
    return topk_idx


def _dense_overlap(a: Tensor, b: Tensor, n_columns: int) -> Tensor:
    """Compute overlap (number of shared active bits) between two SDRs in index form.

    Args:
        a: (B, K) int -- first SDR.
        b: (B, K) int -- second SDR.
        n_columns: Total column count (used for dense conversion).

    Returns:
        (B,) int -- overlap count per sample.
    """
    da = indices_to_dense(a, n_columns)
    db = indices_to_dense(b, n_columns)
    return (da * db).sum(dim=-1).int()


def sdr_sparsity(indices: Tensor, n_columns: int) -> Tensor:
    """Compute actual sparsity (fraction active) per sample.

    Args:
        indices: (B, K) int.
        n_columns: Total column count.

    Returns:
        (B,) float.
    """
    return torch.tensor(
        indices.shape[1] / n_columns,
        device=indices.device,
        dtype=torch.float32,
    ).expand(indices.shape[0])


