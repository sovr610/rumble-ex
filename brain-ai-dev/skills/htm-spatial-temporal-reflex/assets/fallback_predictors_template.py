class GRUPredictor(FallbackPredictor):
    """GRU-based fallback sequence predictor.

    Lighter-weight alternative to LSTM with only a single hidden state
    tensor (no cell state).

    Args:
        config: :class:`FallbackConfig` with ``backend="gru"``.
    """

    def __init__(self, config: FallbackConfig) -> None:
        super().__init__(config)
        self.gru = nn.GRU(
            input_size=config.input_size,
            hidden_size=config.hidden_size,
            num_layers=config.num_layers,
            batch_first=True,
            dropout=config.dropout if config.num_layers > 1 else 0.0,
        )
        self._h: Optional[Tensor] = None

    def reset(self, batch_size: int, device: torch.device) -> None:
        """Reset GRU hidden state.

        Args:
            batch_size: Batch size for the new sequence.
            device: Device for state tensors.
        """
        self._h = torch.zeros(
            self.config.num_layers, batch_size, self.config.hidden_size,
            device=device,
        )
        self._prev_sdr = None
        self._anomaly_history.clear()

    def _ensure_state(self, x: Tensor) -> None:
        """Auto-initialize GRU state if not yet reset."""
        B = x.shape[0]
        device = x.device
        if self._h is None:
            self.reset(B, device)
        elif self._h.shape[1] != B:
            self.reset(B, device)

    def _forward_step(self, x: Tensor) -> Tensor:
        """Run one GRU timestep.

        Args:
            x: (B, input_size) float input.

        Returns:
            (B, hidden_size) GRU output.
        """
        out, self._h = self.gru(x.unsqueeze(1), self._h)
        return out.squeeze(1)  # (B, hidden_size)


