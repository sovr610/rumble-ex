class TransformerPredictor(FallbackPredictor):
    """Transformer-based fallback sequence predictor.

    Maintains an internal sequence buffer and applies causal self-attention.
    Each call to :meth:`_forward_step` appends the input to the buffer
    and runs the full transformer over the buffered history up to
    ``max_seq_len`` tokens.

    Args:
        config: :class:`FallbackConfig` with ``backend="transformer"``.
    """

    def __init__(self, config: FallbackConfig) -> None:
        super().__init__(config)

        # Input projection: input_size -> hidden_size
        self.input_proj = nn.Linear(config.input_size, config.hidden_size)

        # Sinusoidal positional encoding
        self.pos_encoding = PositionalEncoding(
            d_model=config.hidden_size,
            max_len=config.max_seq_len,
            dropout=config.dropout,
        )

        # Transformer encoder with causal masking
        encoder_layer = nn.TransformerEncoderLayer(
            d_model=config.hidden_size,
            nhead=config.num_heads,
            dim_feedforward=config.hidden_size * 4,
            dropout=config.dropout,
            batch_first=True,
        )
        self.transformer = nn.TransformerEncoder(
            encoder_layer, config.num_layers
        )

        # Buffer state
        self._buffer: Optional[Tensor] = None
        self._buffer_len: int = 0

    def reset(self, batch_size: int, device: torch.device) -> None:
        """Reset transformer buffer for a new sequence.

        Args:
            batch_size: Batch size for the new sequence.
            device: Device for state tensors.
        """
        self._buffer = torch.zeros(
            batch_size,
            self.config.max_seq_len,
            self.config.hidden_size,
            device=device,
        )
        self._buffer_len = 0
        self._prev_sdr = None
        self._anomaly_history.clear()

    def _ensure_state(self, x: Tensor) -> None:
        """Auto-initialize buffer if not yet reset."""
        B = x.shape[0]
        device = x.device
        if self._buffer is None:
            self.reset(B, device)
        elif self._buffer.shape[0] != B:
            self.reset(B, device)

    def _forward_step(self, x: Tensor) -> Tensor:
        """Run one transformer step with causal masking.

        Projects the input, appends to the internal buffer, runs the
        transformer over the buffer with a causal mask, and returns the
        last position's representation.

        Args:
            x: (B, input_size) float input.

        Returns:
            (B, hidden_size) output from the last buffer position.
        """
        # Project input to hidden dimension
        proj = self.input_proj(x)  # (B, hidden_size)

        # Append to buffer (shift left when full)
        if self._buffer_len < self.config.max_seq_len:
            self._buffer[:, self._buffer_len] = proj
            self._buffer_len += 1
        else:
            # Shift buffer left and insert at the end
            self._buffer[:, :-1] = self._buffer[:, 1:].clone()
            self._buffer[:, -1] = proj

        # Slice active portion of buffer
        seq_len = min(self._buffer_len, self.config.max_seq_len)
        buf = self._buffer[:, :seq_len]  # (B, seq_len, hidden)

        # Add positional encoding
        buf = self.pos_encoding(buf)

        # Causal mask: prevent attending to future positions
        mask = nn.Transformer.generate_square_subsequent_mask(
            seq_len, device=x.device
        )
        out = self.transformer(buf, mask=mask)  # (B, seq_len, hidden)

        return out[:, -1]  # (B, hidden_size) -- last position


