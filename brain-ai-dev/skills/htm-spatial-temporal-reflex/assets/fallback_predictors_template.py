class TemporalPredictor(nn.Module):
    """Unified temporal prediction interface.

    Auto-selects HTM or a fallback neural-network predictor based on
    availability and configuration.  All backends expose the same
    ``reset`` / ``step`` / ``predict`` API returning :class:`SequenceOutput`.

    Backend selection priority for ``"auto"``:
        1. ``htm`` (htm.core library, if available)
        2. ``accelerated_htm`` (AHTM with ReflexMemory, if available)
        3. ``lstm`` (always available)

    Args:
        backend: One of ``"auto"``, ``"htm"``, ``"accelerated_htm"``,
            ``"lstm"``, ``"gru"``, ``"transformer"``.
        input_size: Input feature dimension.
        hidden_size: Hidden state size (for neural backends).
        num_columns: SDR output width (N).
        num_active: Active bits per SDR (K).
        **kwargs: Additional keyword arguments forwarded to the backend
            constructor (e.g. ``num_layers``, ``num_heads``).
    """

    def __init__(
        self,
        backend: str = "auto",
        input_size: int = 4096,
        hidden_size: int = 2048,
        num_columns: int = 2048,
        num_active: int = 41,
        **kwargs,
    ) -> None:
        super().__init__()
        self.requested_backend = backend
        self.active_backend: str = ""

        # Track config for introspection
        self._input_size = input_size
        self._hidden_size = hidden_size
        self._num_columns = num_columns
        self._num_active = num_active

        if backend == "auto":
            self._predictor = self._auto_select(
                input_size, hidden_size, num_columns, num_active, **kwargs
            )
        elif backend in ("htm", "accelerated_htm"):
            self._predictor = self._create_htm_backend(
                backend, input_size, num_columns, num_active, **kwargs
            )
        elif backend in ("lstm", "gru", "transformer"):
            cfg = FallbackConfig(
                backend=backend,
                input_size=input_size,
                hidden_size=hidden_size,
                num_columns=num_columns,
                num_active=num_active,
                **kwargs,
            )
            self._predictor = create_fallback_predictor(cfg)
            self.active_backend = backend
        else:
            raise ValueError(
                f"Unknown backend: '{backend}'. Expected one of: "
                f"auto, htm, accelerated_htm, lstm, gru, transformer"
            )

    def _auto_select(
        self,
        input_size: int,
        hidden_size: int,
        num_columns: int,
        num_active: int,
        **kwargs,
    ) -> nn.Module:
        """Try backends in priority order: htm -> accelerated_htm -> lstm."""
        # Try HTM
        try:
            predictor = self._create_htm_backend(
                "htm", input_size, num_columns, num_active, **kwargs
            )
            return predictor
        except Exception:
            pass

        # Try accelerated HTM
        try:
            predictor = self._create_htm_backend(
                "accelerated_htm", input_size, num_columns, num_active, **kwargs
            )
            return predictor
        except Exception:
            pass

        # Fall back to LSTM
        cfg = FallbackConfig(
            backend="lstm",
            input_size=input_size,
            hidden_size=hidden_size,
            num_columns=num_columns,
            num_active=num_active,
        )
        self.active_backend = "lstm"
        return create_fallback_predictor(cfg)

    def _create_htm_backend(
        self,
        backend: str,
        input_size: int,
        num_columns: int,
        num_active: int,
        **kwargs,
    ) -> nn.Module:
        """Create an HTM-based backend.

        This imports from brain_ai.temporal.htm and wraps it to return
        SequenceOutput.

        Raises:
            ImportError: If HTM modules are not available.
        """
        if backend == "htm":
            from brain_ai.temporal.htm import HTMLayer, HTMConfig
            htm_config = HTMConfig(
                input_size=input_size,
                column_count=num_columns,
                sparsity=num_active / num_columns,
                **{k: v for k, v in kwargs.items()
                   if k in HTMConfig.__dataclass_fields__},
            )
            predictor = _HTMSequenceOutputWrapper(
                HTMLayer(htm_config), num_active=num_active
            )
            self.active_backend = "htm"
            return predictor

        elif backend == "accelerated_htm":
            from brain_ai.temporal.htm import create_accelerated_htm
            ahtm = create_accelerated_htm(
                input_size=input_size,
                column_count=num_columns,
                sparsity=num_active / num_columns,
                **{k: v for k, v in kwargs.items()
                   if k not in ("hidden_size",)},
            )
            predictor = _HTMSequenceOutputWrapper(
                ahtm, num_active=num_active
            )
            self.active_backend = "accelerated_htm"
            return predictor

        raise ValueError(f"Unknown HTM backend: {backend}")

    def reset(self, batch_size: int = 1, device: Optional[torch.device] = None) -> None:
        """Reset state for a new sequence.

        Args:
            batch_size: Number of sequences in the batch.
            device: Target device.
        """
        if device is None:
            # Infer device from model parameters or default to CPU
            params = list(self.parameters())
            if params:
                device = params[0].device
            else:
                device = torch.device("cpu")

        if isinstance(self._predictor, FallbackPredictor):
            self._predictor.reset(batch_size, device)
        elif hasattr(self._predictor, "reset"):
            self._predictor.reset(batch_size, device)

    def step(self, x: Tensor, learn: bool = True) -> SequenceOutput:
        """Process one timestep.

        Args:
            x: (B, D) float or (B, K) int input.
            learn: Whether to learn from this step.

        Returns:
            :class:`SequenceOutput`.
        """
        if isinstance(self._predictor, FallbackPredictor):
            return self._predictor.step(x, learn=learn)
        elif isinstance(self._predictor, _HTMSequenceOutputWrapper):
            return self._predictor.step(x, learn=learn)
        else:
            # Generic fallback for unknown wrapper types
            result = self._predictor(x, learn=learn)
            return result

    def predict(
        self, x_seq: Tensor, learn: bool = True
    ) -> List[SequenceOutput]:
        """Process a full sequence.

        Args:
            x_seq: (B, T, D) input sequence.
            learn: Whether to learn.

        Returns:
            List of T :class:`SequenceOutput`.
        """
        if isinstance(self._predictor, FallbackPredictor):
            return self._predictor.predict(x_seq, learn=learn)
        else:
            T = x_seq.shape[1]
            results = []
            for t in range(T):
                out = self.step(x_seq[:, t], learn=learn)
                results.append(out)
            return results

    def forward(self, x: Tensor, learn: bool = True) -> SequenceOutput:
        """Forward pass -- dispatches to step or predict.

        Args:
            x: (B, D) or (B, T, D) input.
            learn: Training flag.

        Returns:
            :class:`SequenceOutput`.
        """
        if x.dim() == 3:
            results = self.predict(x, learn=learn)
            return results[-1]
        return self.step(x, learn=learn)


