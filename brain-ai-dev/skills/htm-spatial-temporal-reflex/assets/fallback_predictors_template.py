# HTM Wrapper (adapts old dict-return HTM to SequenceOutput)
# ---------------------------------------------------------------------------

class _HTMSequenceOutputWrapper(nn.Module):
    """Wraps an HTM module to return SequenceOutput instead of dicts.

    This adapter translates the legacy ``Dict[str, Tensor]`` return
    format from ``HTMLayer`` / ``AcceleratedHTM`` into the standardized
    :class:`SequenceOutput` contract.

    Args:
        htm_module: An ``HTMLayer`` or ``AcceleratedHTM`` instance.
        num_active: K for output SDR width.
    """

    def __init__(self, htm_module: nn.Module, num_active: int = 41) -> None:
        super().__init__()
        self.htm = htm_module
        self.num_active = num_active

    def reset(self, batch_size: int = 1, device: Optional[torch.device] = None) -> None:
        """Reset the wrapped HTM module."""
        if hasattr(self.htm, "reset"):
            self.htm.reset()

    def step(self, x: Tensor, learn: bool = True) -> SequenceOutput:
        """Process one step through HTM and return SequenceOutput.

        Args:
            x: (B, D) or (D,) input.
            learn: Whether to learn.

        Returns:
            :class:`SequenceOutput`.
        """
        result = self.htm(x, learn=learn)

        # Extract SDRs from dict results
        if "features" in result:
            features = result["features"]
            sdr = dense_to_indices(features > 0, self.num_active)
        elif "active_cells" in result:
            sdr = dense_to_indices(
                result["active_cells"] > 0, self.num_active
            )
        else:
            B = x.shape[0] if x.dim() == 2 else 1
            sdr = torch.full(
                (B, self.num_active), -1, dtype=torch.long, device=x.device
            )

        if "predictive_cells" in result:
            pred_sdr = dense_to_indices(
                result["predictive_cells"] > 0, self.num_active
            )
        else:
            pred_sdr = torch.full_like(sdr, -1)

        # Ensure 2D
        if sdr.dim() == 1:
            sdr = sdr.unsqueeze(0)
        if pred_sdr.dim() == 1:
            pred_sdr = pred_sdr.unsqueeze(0)

        anomaly = result.get("anomaly", torch.tensor(1.0, device=x.device))
        if anomaly.dim() == 0:
            anomaly = anomaly.unsqueeze(0)

        aux = {
            k: v for k, v in result.items()
            if k not in ("features", "active_cells", "predictive_cells", "anomaly")
        }

        return SequenceOutput(
            sdr=sdr,
            pred_sdr=pred_sdr,
            anomaly_score=anomaly,
            aux=aux,
        )

    def forward(self, x: Tensor, learn: bool = True) -> SequenceOutput:
        """Forward pass."""
        return self.step(x, learn=learn)


