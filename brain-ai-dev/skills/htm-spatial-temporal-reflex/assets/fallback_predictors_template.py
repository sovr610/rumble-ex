    def indices_to_dense(indices: Tensor, N: int) -> Tensor:
        """Convert index-form SDR to dense boolean vector.

        Args:
            indices: (B, K) int64 active bit positions.  -1 = padding.
            N: Total number of columns.

        Returns:
            (B, N) bool tensor with True at active positions.
        """
        B, K = indices.shape
        dense = torch.zeros(B, N, dtype=torch.bool, device=indices.device)
        valid = indices >= 0
        safe_idx = indices.clamp(min=0)
        dense.scatter_(1, safe_idx, valid)
        return dense

    def dense_to_indices(dense: Tensor, K: int) -> Tensor:
        """Convert dense SDR to index form by selecting top-K positions.

        Args:
            dense: (B, N) bool or float tensor.
            K: Number of active indices to extract per row.

        Returns:
            (B, K) int64 tensor.  Rows with fewer than K active bits are
            right-padded with -1.
        """
        B, N = dense.shape
        device = dense.device
        actual_k = min(K, N)
        _, top_idx = torch.topk(dense.float(), actual_k, dim=1, sorted=True)
        top_idx = top_idx.long()

        if dense.dtype == torch.bool:
            gathered = torch.gather(dense.long(), 1, top_idx)
            top_idx[gathered == 0] = -1

        if actual_k < K:
            pad = torch.full(
                (B, K - actual_k), -1, dtype=torch.long, device=device
            )
            top_idx = torch.cat([top_idx, pad], dim=1)
        return top_idx

    def sdr_overlap(a: Tensor, b: Tensor) -> Tensor:
        """Count shared active indices between two index-form SDRs.

        Args:
            a: (B, K_a) int64 active indices.
            b: (B, K_b) int64 active indices.

        Returns:
            (B,) int64 -- number of matching indices per row.
        """
        match = (a.unsqueeze(2) == b.unsqueeze(1))
        a_valid = (a >= 0).unsqueeze(2)
        b_valid = (b >= 0).unsqueeze(1)
        match = match & a_valid & b_valid
        return match.any(dim=2).sum(dim=1).long()


