class FallbackPredictor(nn.Module, abc.ABC):
    """Base class for all fallback neural-network sequence predictors.

    Subclasses must implement :meth:`reset` and :meth:`_forward_step`.
    The base class provides the common SDR-conversion, anomaly, and
    SequenceOutput packaging logic.

    Args:
        config: A :class:`FallbackConfig` instance.
    """

    def __init__(self, config: FallbackConfig) -> None:
        super().__init__()
        self.config = config

        # Output projection: hidden_size -> num_columns logits
        self.output_proj = nn.Linear(config.hidden_size, config.num_columns)

        # Optional learned anomaly head
        if config.anomaly_mode == "learned":
            self.anomaly_head = nn.Sequential(
                nn.Linear(config.hidden_size, config.hidden_size // 4),
                nn.ReLU(),
                nn.Linear(config.hidden_size // 4, 1),
                nn.Sigmoid(),
            )

        # Anomaly likelihood tracker (rolling window)
        self._anomaly_history: deque = deque(maxlen=config.anomaly_window)

        # Previous-step SDR for anomaly comparison
        self._prev_sdr: Optional[Tensor] = None

    @abc.abstractmethod
    def reset(self, batch_size: int, device: torch.device) -> None:
        """Reset hidden state for a new sequence.

        Must be called before processing the first step of a new sequence.

        Args:
            batch_size: Number of independent sequences in the batch.
            device: Target device for state tensors.
        """

    @abc.abstractmethod
    def _forward_step(self, x: Tensor) -> Tensor:
        """Process one timestep and return hidden representation.

        Args:
            x: (B, input_size) float input for this timestep.

        Returns:
            (B, hidden_size) hidden state tensor.
        """

    def _ensure_state(self, x: Tensor) -> None:
        """Auto-initialize hidden state if not yet reset."""
        # Subclasses can override for more specific checks.
        pass

    # ----- Input conversion -----

    def _to_dense_input(self, x: Tensor) -> Tensor:
        """Convert SDR index input to dense float if needed.

        If *x* is an integer tensor with last dimension == num_active, it
        is interpreted as SDR index input and converted to a dense
        (B, input_size) float representation.

        Args:
            x: (B, D) float or (B, K) int input.

        Returns:
            (B, input_size) float tensor suitable for the network.
        """
        if x.dtype in (torch.int32, torch.int64):
            if x.shape[-1] == self.config.num_active:
                # SDR indices -> dense float
                dense = indices_to_dense(x, self.config.num_columns).float()
                # If input_size != num_columns, project via zero-padding
                if self.config.input_size != self.config.num_columns:
                    B = dense.shape[0]
                    if self.config.input_size > self.config.num_columns:
                        pad = torch.zeros(
                            B,
                            self.config.input_size - self.config.num_columns,
                            device=dense.device,
                        )
                        dense = torch.cat([dense, pad], dim=1)
                    else:
                        dense = dense[:, : self.config.input_size]
                return dense
        return x

    # ----- SDR extraction -----

    def _logits_to_sdr(self, logits: Tensor) -> Tensor:
        """Convert output logits to SDR by selecting top-K columns.

        Args:
            logits: (B, num_columns) float logits.

        Returns:
            (B, K) int64 sorted SDR indices.
        """
        K = self.config.num_active
        topk_vals, topk_idx = logits.topk(K, dim=-1)
        return topk_idx.sort(dim=-1).values  # sorted for determinism

    def _input_to_sdr(self, x: Tensor) -> Tensor:
        """Extract the current SDR from the (possibly dense) input.

        Args:
            x: Original input before dense conversion.

        Returns:
            (B, K) int64 SDR indices.
        """
        K = self.config.num_active
        N = self.config.num_columns

        if x.dtype in (torch.int32, torch.int64) and x.shape[-1] == K:
            return x.long()

        # Dense float input: threshold and convert
        if x.shape[-1] >= N:
            # Use the first num_columns elements
            dense_cols = x[:, :N]
        else:
            # Pad to num_columns
            B = x.shape[0]
            pad = torch.zeros(B, N - x.shape[-1], device=x.device)
            dense_cols = torch.cat([x, pad], dim=1)

        return dense_to_indices(dense_cols > 0, K)

    # ----- Anomaly computation -----

    def _compute_anomaly(
        self,
        actual_sdr: Tensor,
        pred_sdr: Tensor,
        hidden: Optional[Tensor] = None,
        actual_dense: Optional[Tensor] = None,
        pred_logits: Optional[Tensor] = None,
    ) -> Tensor:
        """Compute anomaly score using the configured method.

        Args:
            actual_sdr: (B, K) int64 -- current step's SDR.
            pred_sdr: (B, K) int64 -- predicted SDR (from previous step).
            hidden: (B, hidden_size) -- hidden state for learned anomaly.
            actual_dense: (B, D) float -- dense input for MSE anomaly.
            pred_logits: (B, N) float -- predicted logits for MSE anomaly.

        Returns:
            (B,) float anomaly scores clamped to [0, 1].
        """
        mode = self.config.anomaly_mode

        if mode == "overlap":
            overlap = sdr_overlap(actual_sdr, pred_sdr)  # (B,) int
            # Count valid (non-padding) entries in actual
            valid_count = (actual_sdr >= 0).sum(dim=-1).float().clamp(min=1.0)
            anomaly = 1.0 - overlap.float() / valid_count
            return anomaly.clamp(0.0, 1.0)

        elif mode == "learned":
            if hidden is None:
                # Fall back to overlap if no hidden state
                overlap = sdr_overlap(actual_sdr, pred_sdr)
                valid_count = (actual_sdr >= 0).sum(dim=-1).float().clamp(min=1.0)
                anomaly = 1.0 - overlap.float() / valid_count
                return anomaly.clamp(0.0, 1.0)
            return self.anomaly_head(hidden).squeeze(-1).clamp(0.0, 1.0)

        elif mode == "mse":
            if pred_logits is not None and actual_dense is not None:
                N = self.config.num_columns
                pred_cols = pred_logits[:, :N]
                actual_cols = actual_dense[:, :N] if actual_dense.shape[-1] >= N else actual_dense
                if actual_cols.shape[-1] < N:
                    pad = torch.zeros(
                        actual_cols.shape[0], N - actual_cols.shape[-1],
                        device=actual_cols.device,
                    )
                    actual_cols = torch.cat([actual_cols, pad], dim=1)
                mse = F.mse_loss(pred_cols, actual_cols, reduction="none").mean(dim=-1)
                return torch.sigmoid(mse).clamp(0.0, 1.0)
            # Fall back to overlap
            overlap = sdr_overlap(actual_sdr, pred_sdr)
            valid_count = (actual_sdr >= 0).sum(dim=-1).float().clamp(min=1.0)
            anomaly = 1.0 - overlap.float() / valid_count
            return anomaly.clamp(0.0, 1.0)

        else:
            # Default to overlap
            overlap = sdr_overlap(actual_sdr, pred_sdr)
            valid_count = (actual_sdr >= 0).sum(dim=-1).float().clamp(min=1.0)
            anomaly = 1.0 - overlap.float() / valid_count
            return anomaly.clamp(0.0, 1.0)

    def _compute_anomaly_likelihood(self, raw_anomaly: Tensor) -> Tensor:
        """Compute rolling anomaly likelihood (per-batch mean).

        Smooths the raw anomaly via a rolling Gaussian estimator, identical
        in spirit to HTM's anomaly likelihood computation.

        Args:
            raw_anomaly: (B,) float raw anomaly scores.

        Returns:
            (B,) float anomaly likelihood in [0, 1].
        """
        mean_val = raw_anomaly.mean().item()
        self._anomaly_history.append(mean_val)

        if len(self._anomaly_history) < 10:
            return raw_anomaly

        hist = list(self._anomaly_history)
        mu = sum(hist) / len(hist)
        var = sum((x - mu) ** 2 for x in hist) / len(hist)
        std = max(var ** 0.5, 1e-6)

        z = (mean_val - mu) / std
        likelihood = 1.0 / (1.0 + math.exp(-1.7 * z))
        likelihood = max(0.0, min(1.0, likelihood))

        return torch.full_like(raw_anomaly, likelihood)

    # ----- Main interface -----

    def step(self, x: Tensor, learn: bool = True) -> SequenceOutput:
        """Process one timestep and return a SequenceOutput.

        Args:
            x: Input for this step.  Can be:
                - (B, input_size) float -- dense feature vector.
                - (B, K) int -- SDR index input (converted to dense internally).
            learn: Whether this is a training step.  When False, hidden
                state gradients are detached to prevent backprop through
                time beyond this step.

        Returns:
            :class:`SequenceOutput` with sdr, pred_sdr, anomaly_score, aux.
        """
        # Preserve original for SDR extraction
        x_orig = x

        # Convert integer SDR indices to dense float
        x_dense = self._to_dense_input(x)

        # Auto-init state if needed
        self._ensure_state(x_dense)

        # Forward through the network
        hidden = self._forward_step(x_dense)  # (B, hidden_size)

        # Compute output logits and predicted SDR
        logits = self.output_proj(hidden)     # (B, num_columns)
        pred_sdr = self._logits_to_sdr(logits)  # (B, K)

        # Extract current input SDR
        current_sdr = self._input_to_sdr(x_orig)  # (B, K)

        # Anomaly: compare current actual vs what was predicted last step
        if self._prev_sdr is not None:
            prev_pred = self._prev_sdr
            # Align batch sizes (handle reset or batch change)
            if prev_pred.shape[0] != current_sdr.shape[0]:
                anomaly = torch.ones(
                    current_sdr.shape[0], device=current_sdr.device
                )
            else:
                anomaly = self._compute_anomaly(
                    actual_sdr=current_sdr,
                    pred_sdr=prev_pred,
                    hidden=hidden,
                    actual_dense=x_dense,
                    pred_logits=logits,
                )
        else:
            # First step: maximum anomaly (no prediction available)
            anomaly = torch.ones(current_sdr.shape[0], device=current_sdr.device)

        # Store predicted SDR for next step's anomaly computation
        self._prev_sdr = pred_sdr.detach().clone()

        # Build aux dict
        anomaly_likelihood = self._compute_anomaly_likelihood(anomaly)
        aux: Dict[str, Tensor] = {
            "logits": logits,
            "hidden": hidden,
            "anomaly_likelihood": anomaly_likelihood,
        }

        return SequenceOutput(
            sdr=current_sdr,
            pred_sdr=pred_sdr,
            anomaly_score=anomaly,
            aux=aux,
        )

    def predict(
        self,
        x_seq: Tensor,
        learn: bool = True,
    ) -> List[SequenceOutput]:
        """Process a full sequence and return per-step SequenceOutputs.

        Args:
            x_seq: (B, T, D) float or (B, T, K) int input sequence.
            learn: Whether this is a training pass.

        Returns:
            List of T :class:`SequenceOutput` instances.
        """
        T = x_seq.shape[1]
        results: List[SequenceOutput] = []
        for t in range(T):
            out = self.step(x_seq[:, t], learn=learn)
            results.append(out)
        return results

    def forward(
        self,
        x: Tensor,
        learn: bool = True,
    ) -> SequenceOutput:
        """Alias for :meth:`step` when input is (B, D).

        If input is (B, T, D), delegates to :meth:`predict` and returns
        the last step's output.

        Args:
            x: (B, D) or (B, T, D) input.
            learn: Training flag.

        Returns:
            :class:`SequenceOutput` for the (last) timestep.
        """
        if x.dim() == 3:
            results = self.predict(x, learn=learn)
            return results[-1]
        return self.step(x, learn=learn)


