@dataclass
class FallbackConfig:
    """Configuration for fallback neural-network sequence predictors.

    Attributes:
        backend: Which predictor architecture to use.
            One of ``"lstm"``, ``"gru"``, ``"transformer"``.
        input_size: Dimension of the input feature vector (or N_columns
            when receiving SDR index input that gets converted to dense).
        hidden_size: Size of the recurrent hidden state.
        num_layers: Number of stacked RNN layers or transformer encoder
            layers.
        num_columns: SDR output width (N).  The output projection maps
            hidden_size -> num_columns logits, then top-K selection
            produces the predicted SDR.
        num_active: Number of active columns per output SDR (K).  Must
            be <= num_columns.
        dropout: Dropout probability applied between layers.
        num_heads: Number of attention heads (transformer only).
        max_seq_len: Maximum sequence length for positional encoding and
            the internal buffer (transformer only).
        anomaly_mode: Method for computing anomaly.
            ``"overlap"`` -- SDR overlap-based (same as HTM, default).
            ``"learned"`` -- learned anomaly head on hidden state.
            ``"mse"`` -- mean squared error between predicted and actual.
        anomaly_window: Window size for rolling anomaly likelihood
            smoothing.
    """

    backend: str = "lstm"
    input_size: int = 4096
    hidden_size: int = 2048
    num_layers: int = 2
    num_columns: int = 2048
    num_active: int = 41
    dropout: float = 0.1
    # Transformer-specific
    num_heads: int = 8
    max_seq_len: int = 100
    # Anomaly
    anomaly_mode: str = "overlap"
    anomaly_window: int = 1000

    def __post_init__(self) -> None:
        valid_backends = {"lstm", "gru", "transformer"}
        if self.backend not in valid_backends:
            raise ValueError(
                f"backend must be one of {valid_backends}, got '{self.backend}'"
            )
        if self.num_active > self.num_columns:
            raise ValueError(
                f"num_active ({self.num_active}) must be <= "
                f"num_columns ({self.num_columns})"
            )
        if self.num_active < 1:
            raise ValueError(
                f"num_active must be >= 1, got {self.num_active}"
            )
        if self.hidden_size < 1:
            raise ValueError(
                f"hidden_size must be >= 1, got {self.hidden_size}"
            )
        valid_anomaly_modes = {"overlap", "learned", "mse"}
        if self.anomaly_mode not in valid_anomaly_modes:
            raise ValueError(
                f"anomaly_mode must be one of {valid_anomaly_modes}, "
                f"got '{self.anomaly_mode}'"
            )


