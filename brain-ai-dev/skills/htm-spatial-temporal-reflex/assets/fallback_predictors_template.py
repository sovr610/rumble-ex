class PositionalEncoding(nn.Module):
    """Standard sinusoidal positional encoding.

    Adds position-dependent signals to input embeddings so the transformer
    can distinguish token order.

    Args:
        d_model: Embedding dimension.
        max_len: Maximum sequence length to pre-compute encodings for.
        dropout: Dropout applied after adding positional encoding.
    """

    def __init__(
        self,
        d_model: int,
        max_len: int = 5000,
        dropout: float = 0.1,
    ) -> None:
        super().__init__()
        self.dropout = nn.Dropout(p=dropout)

        pe = torch.zeros(max_len, d_model)
        position = torch.arange(0, max_len, dtype=torch.float32).unsqueeze(1)
        div_term = torch.exp(
            torch.arange(0, d_model, 2, dtype=torch.float32)
            * (-math.log(10000.0) / d_model)
        )
        pe[:, 0::2] = torch.sin(position * div_term)
        pe[:, 1::2] = torch.cos(position * div_term[: d_model // 2 + d_model % 2])
        pe = pe.unsqueeze(0)  # (1, max_len, d_model)
        self.register_buffer("pe", pe)

    def forward(self, x: Tensor) -> Tensor:
        """Add positional encoding to input.

        Args:
            x: (B, T, D) input tensor.

        Returns:
            (B, T, D) with positional encoding added.
        """
        x = x + self.pe[:, : x.shape[1]]
        return self.dropout(x)


