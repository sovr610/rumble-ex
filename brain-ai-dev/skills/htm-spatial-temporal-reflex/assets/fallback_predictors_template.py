def create_fallback_predictor(config: FallbackConfig) -> FallbackPredictor:
    """Create a fallback predictor instance from config.

    Args:
        config: :class:`FallbackConfig` specifying the backend and
            hyperparameters.

    Returns:
        An instance of :class:`LSTMPredictor`, :class:`GRUPredictor`,
        or :class:`TransformerPredictor`.

    Raises:
        ValueError: If ``config.backend`` is not recognized.
    """
    if config.backend == "lstm":
        return LSTMPredictor(config)
    elif config.backend == "gru":
        return GRUPredictor(config)
    elif config.backend == "transformer":
        return TransformerPredictor(config)
    else:
        raise ValueError(
            f"Unknown backend: '{config.backend}'. "
            f"Expected one of: lstm, gru, transformer"
        )


