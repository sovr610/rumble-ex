def from_sparse_tensor_list(
    sparse_tensors: list,
    K: int,
) -> Tensor:
    """Convert a list of legacy SparseTensor objects to batched index form.

    Each SparseTensor.sparse gives (K_i,) indices for one sample.
    Output is padded to uniform K.

    Args:
        sparse_tensors: List of B SparseTensor instances.
        K: Target active-bit width.

    Returns:
        (B, K) int64 tensor.
    """
    B = len(sparse_tensors)
    device = (
        sparse_tensors[0].device
        if B > 0 and hasattr(sparse_tensors[0], "device")
        else torch.device("cpu")
    )
    out = torch.full((B, K), -1, dtype=torch.long, device=device)
    for i, st in enumerate(sparse_tensors):
        row_indices = st.sparse
        n = min(len(row_indices), K)
        if n > 0:
            out[i, :n] = row_indices[:n].long().to(device)
    return out


def to_sparse_tensor_list(
    indices: Tensor,
    N: int,
) -> list:
    """Convert batched index-form SDR back to a list of SparseTensor objects.

    Requires brain_ai.temporal.htm.SparseTensor to be importable.

    Args:
        indices: (B, K) int64.
        N: Total columns (SparseTensor.size).

    Returns:
        List of B SparseTensor objects.
    """
    # Lazy import to avoid circular dependency
    from brain_ai.temporal.htm import SparseTensor

    B, K = indices.shape
    device = indices.device
    result = []
    for i in range(B):
        st = SparseTensor(size=N, device=device)
        valid = indices[i][indices[i] >= 0]
        if valid.numel() > 0:
            st.sparse = valid
        result.append(st)
    return result


