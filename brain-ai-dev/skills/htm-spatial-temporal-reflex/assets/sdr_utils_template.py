def random_sdr(
    batch_size: int,
    K: int,
    N: int,
    device: Optional[torch.device] = None,
    generator: Optional[torch.Generator] = None,
) -> Tensor:
    """Generate random SDR indices with exactly K unique active bits per row.

    Args:
        batch_size: Number of SDRs (B).
        K: Active bits per SDR.
        N: Total number of columns.
        device: Target device.
        generator: Optional torch RNG for reproducibility.

    Returns:
        (B, K) int64 tensor, each row containing K unique indices in [0, N).
    """
    if K > N:
        raise ValueError(f"K ({K}) must be <= N ({N})")
    if K == 0:
        return empty_sdr(batch_size, K, device=device)

    # For each batch item, sample K unique indices from [0, N)
    # Use multinomial with uniform weights for vectorized unique sampling
    weights = torch.ones(batch_size, N, dtype=torch.float32, device=device)
    indices = torch.multinomial(
        weights, K, replacement=False, generator=generator
    )  # (B, K)
    return indices.long()


def empty_sdr(
    batch_size: int,
    K: int,
    device: Optional[torch.device] = None,
) -> Tensor:
    """Create an empty SDR (all padding).

    Args:
        batch_size: Number of SDRs (B).
        K: Width of the index dimension.
        device: Target device.

    Returns:
        (B, K) int64 tensor filled with -1 (no active bits).
    """
    return torch.full((batch_size, K), -1, dtype=torch.long, device=device)


def constant_sdr(
    indices_list: List[List[int]],
    K: int,
    device: Optional[torch.device] = None,
) -> Tensor:
    """Create an SDR batch from explicit index lists (for testing/constants).

    Each inner list is padded or truncated to exactly K.

    Args:
        indices_list: List of B lists, each containing column indices.
        K: Target active-bit width.
        device: Target device.

    Returns:
        (B, K) int64 tensor.
    """
    B = len(indices_list)
    out = torch.full((B, K), -1, dtype=torch.long, device=device)
    for i, row in enumerate(indices_list):
        n = min(len(row), K)
        out[i, :n] = torch.tensor(row[:n], dtype=torch.long, device=device)
    return out


