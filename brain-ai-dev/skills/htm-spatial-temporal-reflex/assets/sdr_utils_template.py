def sdr_overlap(a: Tensor, b: Tensor) -> Tensor:
    """Count shared active indices between two index-form SDRs.

    Uses the vectorized expand-and-compare approach which is efficient
    for small K (typical HTM K in 40-400 range).

    Args:
        a: (B, K_a) int64 active indices.
        b: (B, K_b) int64 active indices.

    Returns:
        (B,) int64 tensor -- number of matching indices per row.
        Padding entries (-1) never count as overlap.
    """
    # (B, K_a, 1) == (B, 1, K_b) -> (B, K_a, K_b) bool
    match = (a.unsqueeze(2) == b.unsqueeze(1))
    # Exclude -1 == -1 matches (padding collision)
    a_valid = (a >= 0).unsqueeze(2)   # (B, K_a, 1)
    b_valid = (b >= 0).unsqueeze(1)   # (B, 1, K_b)
    match = match & a_valid & b_valid
    return match.any(dim=2).sum(dim=1).long()  # (B,)


def sdr_union_size(a: Tensor, b: Tensor) -> Tensor:
    """Compute |A union B| for index-form SDRs.

    |A u B| = |A| + |B| - |A n B|

    Args:
        a: (B, K_a) int64.
        b: (B, K_b) int64.

    Returns:
        (B,) int64.
    """
    a_size = (a >= 0).sum(dim=1).long()  # (B,)
    b_size = (b >= 0).sum(dim=1).long()  # (B,)
    overlap = sdr_overlap(a, b)
    return a_size + b_size - overlap


def sdr_jaccard(a: Tensor, b: Tensor) -> Tensor:
    """Jaccard similarity: |A n B| / |A u B|.

    Args:
        a: (B, K_a) int64.
        b: (B, K_b) int64.

    Returns:
        (B,) float32 in [0.0, 1.0].  Returns 0 when both SDRs are empty.
    """
    overlap = sdr_overlap(a, b).float()
    union = sdr_union_size(a, b).float().clamp(min=1.0)
    return overlap / union


def sdr_hamming(a_dense: Tensor, b_dense: Tensor) -> Tensor:
    """Hamming distance between dense SDR vectors.

    Args:
        a_dense: (B, N) bool tensor.
        b_dense: (B, N) bool tensor.

    Returns:
        (B,) int64 -- number of bit positions that differ.
    """
    return (a_dense ^ b_dense).sum(dim=1).long()


def sdr_overlap_score(a: Tensor, b: Tensor) -> Tensor:
    """Normalized overlap score: overlap / min(|A|, |B|).

    This measures how well the smaller SDR is contained in the larger.

    Args:
        a: (B, K_a) int64.
        b: (B, K_b) int64.

    Returns:
        (B,) float32 in [0.0, 1.0].  Returns 0 when either SDR is empty.
    """
    overlap = sdr_overlap(a, b).float()
    a_size = (a >= 0).sum(dim=1).float()
    b_size = (b >= 0).sum(dim=1).float()
    min_size = torch.min(a_size, b_size).clamp(min=1.0)
    return overlap / min_size


