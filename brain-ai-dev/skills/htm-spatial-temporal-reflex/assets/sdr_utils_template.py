def sdr_cat(sdrs: List[Tensor], dim: int = 0) -> Tensor:
    """Concatenate SDR batches along the batch dimension.

    All input tensors must have the same K (column) dimension.

    Args:
        sdrs: List of (B_i, K) int64 tensors.
        dim: Concatenation dimension.  Default 0 (batch dim).

    Returns:
        (sum(B_i), K) int64 tensor.

    Raises:
        ValueError: If K dimensions do not match (when dim=0).
    """
    if dim == 0 and len(sdrs) > 1:
        Ks = {s.shape[1] for s in sdrs}
        if len(Ks) > 1:
            raise ValueError(
                f"Cannot concatenate SDRs with different K values: {Ks}. "
                f"Use sdr_pad first to align widths."
            )
    return torch.cat(sdrs, dim=dim)


def sdr_pad(
    indices: Tensor,
    target_K: int,
    pad_value: int = -1,
) -> Tensor:
    """Pad (or truncate) SDR to a target K width.

    Args:
        indices: (B, K_orig) int64.
        target_K: Desired output width.
        pad_value: Value for padding positions (default -1).

    Returns:
        (B, target_K) int64 tensor.
    """
    B, K_orig = indices.shape
    device = indices.device

    if K_orig == target_K:
        return indices
    elif K_orig > target_K:
        return indices[:, :target_K].contiguous()
    else:
        pad = torch.full(
            (B, target_K - K_orig), pad_value, dtype=torch.long, device=device
        )
        return torch.cat([indices, pad], dim=1)


def sdr_unique_columns(indices: Tensor) -> Tuple[Tensor, Tensor]:
    """Extract unique column indices per batch item.

    Useful for finding the set of predicted columns from a union of
    cell-level predictions.

    Args:
        indices: (B, K) int64 active indices (may contain duplicates
                 and -1 padding).

    Returns:
        Tuple of:
            unique_indices: (B, max_unique) int64, padded with -1.
            counts: (B,) int64 -- number of unique valid indices per row.
    """
    B, K = indices.shape
    device = indices.device

    # Sort each row; duplicates and -1s cluster together
    sorted_idx = indices.sort(dim=1).values  # (B, K)

    # Mark first occurrence: different from predecessor
    first_occ = torch.ones(B, K, dtype=torch.bool, device=device)
    first_occ[:, 1:] = sorted_idx[:, 1:] != sorted_idx[:, :-1]

    # Exclude -1 entries
    valid = sorted_idx >= 0
    keep = first_occ & valid  # (B, K)

    # Count unique per row
    counts = keep.sum(dim=1).long()  # (B,)
    max_unique = int(counts.max().item()) if B > 0 else 0

    if max_unique == 0:
        return empty_sdr(B, 1, device=device), counts

    # Gather unique values into dense output
    # Use masked_fill to push non-kept values to the end
    large_val = torch.iinfo(torch.long).max
    keys = sorted_idx.clone()
    keys[~keep] = large_val
    keys = keys.sort(dim=1).values  # unique first, large_val at end

    unique_indices = keys[:, :max_unique].clone()
    unique_indices[unique_indices == large_val] = -1

    return unique_indices, counts


def sdr_subsample(
    indices: Tensor,
    target_K: int,
    generator: Optional[torch.Generator] = None,
) -> Tensor:
    """Randomly subsample active bits to reduce K.

    If the SDR already has <= target_K valid (non-padding) entries,
    it is returned padded to target_K with no subsampling.

    Args:
        indices: (B, K) int64.
        target_K: Desired number of active bits.
        generator: Optional torch RNG.

    Returns:
        (B, target_K) int64, each row with up to target_K valid indices.
    """
    B, K = indices.shape
    device = indices.device

    if target_K >= K:
        return sdr_pad(indices, target_K)

    # For each row, permute columns and take the first target_K
    # We permute only valid positions
    valid = (indices >= 0).float()  # (B, K)
    # Random keys for valid positions, large for padding
    noise = torch.rand(B, K, device=device, generator=generator)
    noise = noise * valid + (1.0 - valid) * 2.0  # padding gets key > 1
    _, perm = noise.sort(dim=1)  # (B, K)
    shuffled = torch.gather(indices, 1, perm)  # (B, K)

    result = shuffled[:, :target_K].clone()
    # Ensure any -1 that crept into first target_K positions stays -1
    return result


