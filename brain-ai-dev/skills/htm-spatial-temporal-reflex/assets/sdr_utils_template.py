def validate_sdr(indices: Tensor, N: int, K: Optional[int] = None) -> None:
    """Assert SDR invariants.

    Checks:
        1. All valid indices are in [0, N).
        2. No duplicate indices within any row (excluding -1 padding).
        3. If K is provided, tensor width matches K.
        4. Tensor is 2-D (B, K) and dtype is integer.

    Args:
        indices: (B, K) int tensor.
        N: Total number of columns.
        K: Expected active-bit width (optional).

    Raises:
        ValueError: If any invariant is violated.
    """
    if indices.ndim != 2:
        raise ValueError(
            f"SDR must be 2-D (B, K), got {indices.ndim}-D shape {indices.shape}"
        )

    if not indices.dtype.is_floating_point and indices.dtype not in (
        torch.int32, torch.int64, torch.int16, torch.int8,
    ):
        raise ValueError(
            f"SDR indices must be integer dtype, got {indices.dtype}"
        )

    B, K_actual = indices.shape

    if K is not None and K_actual != K:
        raise ValueError(
            f"Expected K={K}, got tensor width {K_actual}"
        )

    # Check range of valid (non-padding) entries
    valid = indices >= 0
    valid_vals = indices[valid]
    if valid_vals.numel() > 0:
        if valid_vals.min().item() < 0:
            raise ValueError("SDR contains negative indices other than -1 padding")
        if valid_vals.max().item() >= N:
            raise ValueError(
                f"SDR index {valid_vals.max().item()} out of range [0, {N})"
            )

    # Check for duplicates within rows
    for i in range(B):
        row_valid = indices[i][indices[i] >= 0]
        if row_valid.numel() > 0:
            unique = row_valid.unique()
            if unique.numel() != row_valid.numel():
                dups = row_valid.numel() - unique.numel()
                raise ValueError(
                    f"Row {i} has {dups} duplicate index(es)"
                )


def check_sparsity(
    dense: Tensor,
    target_sparsity: float,
    atol: float = 0.01,
) -> bool:
    """Check that a dense SDR has approximately the target sparsity.

    Sparsity is defined as the fraction of active (True / nonzero) bits.

    Args:
        dense: (B, N) bool or float tensor.
        target_sparsity: Expected fraction of active bits (e.g. 0.02).
        atol: Absolute tolerance for the sparsity check.

    Returns:
        True if the mean sparsity across the batch is within atol
        of target_sparsity.
    """
    if dense.dtype == torch.bool:
        actual = dense.float().mean(dim=1)  # (B,)
    else:
        actual = (dense != 0).float().mean(dim=1)  # (B,)

    mean_sparsity = actual.mean().item()
    return abs(mean_sparsity - target_sparsity) <= atol


def sdr_info(indices: Tensor, N: int) -> dict:
    """Return diagnostic information about an SDR batch.

    Useful for debugging and logging.

    Args:
        indices: (B, K) int64.
        N: Total number of columns.

    Returns:
        Dictionary with keys:
            batch_size, K, N, valid_counts (per-row),
            mean_sparsity, min_index, max_index.
    """
    B, K = indices.shape
    valid = indices >= 0
    valid_counts = valid.sum(dim=1)  # (B,)
    valid_vals = indices[valid]

    return {
        "batch_size": B,
        "K": K,
        "N": N,
        "valid_counts": valid_counts.tolist(),
        "mean_sparsity": (valid_counts.float().mean().item() / N) if N > 0 else 0.0,
        "min_index": int(valid_vals.min().item()) if valid_vals.numel() > 0 else None,
        "max_index": int(valid_vals.max().item()) if valid_vals.numel() > 0 else None,
    }


