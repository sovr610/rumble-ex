# Golden ratio constant (64-bit) for multiplicative hash mixing.
# phi = (1 + sqrt(5)) / 2;  _GOLDEN = floor(2^64 / phi)
_GOLDEN: int = 0x9E3779B97F4A7C15


def _avalanche_mix(x: Tensor) -> Tensor:
    """Apply bit-mixing (avalanche) to an int64 tensor.

    Ensures that small input differences produce large hash differences.

    Args:
        x: (...,) int64 tensor.

    Returns:
        (...,) int64 tensor with improved bit distribution.
    """
    # Standard integer avalanche: xor-shift cascade
    x = x ^ (x >> 32)
    x = x * 0x85EBCA6B  # kept within int64 via Python's arbitrary-precision
    x = x ^ (x >> 16)
    return x


def sdr_hash(indices: Tensor) -> Tensor:
    """Order-independent hash of index-form SDR.

    Sorts indices for determinism, applies multiplicative hashing with
    the golden-ratio constant, then XOR-combines per-index hashes.

    The K-loop is acceptable because K is typically 40-400.

    Args:
        indices: (B, K) int64 active indices.  -1 entries are excluded.

    Returns:
        (B,) int64 hash values.
    """
    B, K = indices.shape
    device = indices.device

    if K == 0:
        return torch.zeros(B, dtype=torch.long, device=device)

    # Replace -1 with a value > any valid index so they sort to the end
    safe = indices.clone()
    padding_mask = (indices < 0)  # (B, K)
    safe[padding_mask] = torch.iinfo(torch.long).max

    sorted_idx = safe.sort(dim=-1).values  # (B, K)

    h = torch.zeros(B, dtype=torch.long, device=device)
    for k in range(K):
        col = sorted_idx[:, k]
        # Skip padding positions
        is_valid = ~padding_mask.gather(1, indices.new_full((B, 1), k)).squeeze(1)
        # In sorted order, padding is at the end; but we use the original
        # mask gathered through sort for safety.
        is_pad = (col == torch.iinfo(torch.long).max)

        mixed = col * _GOLDEN
        mixed = _avalanche_mix(mixed)
        # Zero out padding contributions
        mixed = mixed * (~is_pad).long()
        h = h ^ mixed

    return h


def sdr_hash_multi(
    indices: Tensor,
    num_hashes: int,
    seeds: Optional[Tensor] = None,
) -> Tensor:
    """Multiple independent hashes of an index-form SDR.

    Useful for Locality-Sensitive Hashing (LSH) and bloom-filter style
    membership testing.

    Args:
        indices: (B, K) int64 active indices.
        num_hashes: Number of independent hash functions.
        seeds: (num_hashes,) int64 seeds.  If None, seeds are generated
            deterministically from the default sequence.

    Returns:
        (B, num_hashes) int64 hash values.
    """
    B, K = indices.shape
    device = indices.device

    if seeds is None:
        # Deterministic seed sequence based on golden ratio offsets
        seeds = torch.arange(num_hashes, dtype=torch.long, device=device) * _GOLDEN

    assert seeds.shape == (num_hashes,), (
        f"seeds must have shape ({num_hashes},), got {seeds.shape}"
    )

    hashes = torch.zeros(B, num_hashes, dtype=torch.long, device=device)

    # Pre-sort and mask once
    safe = indices.clone()
    padding_mask = (indices < 0)
    safe[padding_mask] = torch.iinfo(torch.long).max
    sorted_idx = safe.sort(dim=-1).values  # (B, K)
    is_pad = (sorted_idx == torch.iinfo(torch.long).max)  # (B, K)

    for h_idx in range(num_hashes):
        seed = seeds[h_idx]
        h = torch.zeros(B, dtype=torch.long, device=device)
        for k in range(K):
            col = sorted_idx[:, k]
            mixed = (col ^ seed) * _GOLDEN
            mixed = _avalanche_mix(mixed)
            mixed = mixed * (~is_pad[:, k]).long()
            h = h ^ mixed
        hashes[:, h_idx] = h

    return hashes


