@dataclass
class SDRConfig:
    """Configuration for SDR dimensions and hashing.

    Attributes:
        num_columns: Total number of columns/bits (N).  Default 2048
            matches the standard HTM spatial pooler output width.
        num_active: Active columns per SDR (K).  Default 41 is ~2%
            of 2048, the standard HTM sparsity target.
        hash_seed: Base seed for deterministic hash functions.
    """
    num_columns: int = 2048
    num_active: int = 41
    hash_seed: int = 42

    def __post_init__(self) -> None:
        if self.num_active > self.num_columns:
            raise ValueError(
                f"num_active ({self.num_active}) must be <= "
                f"num_columns ({self.num_columns})"
            )
        if self.num_active < 0:
            raise ValueError(f"num_active must be >= 0, got {self.num_active}")
        if self.num_columns < 1:
            raise ValueError(f"num_columns must be >= 1, got {self.num_columns}")

    @property
    def sparsity(self) -> float:
        """Fraction of active bits: K / N."""
        return self.num_active / self.num_columns


