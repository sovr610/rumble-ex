def indices_to_dense(indices: Tensor, N: int) -> Tensor:
    """Convert index-form SDR to dense boolean vector.

    Args:
        indices: (B, K) int64 tensor of active bit positions.
                 Values of -1 are treated as padding and ignored.
        N: Total number of columns (output width).

    Returns:
        (B, N) bool tensor with True at active positions.
    """
    B, K = indices.shape
    dense = torch.zeros(B, N, dtype=torch.bool, device=indices.device)
    # Mask out -1 padding
    valid = indices >= 0  # (B, K)
    # Clamp to valid range for scatter (padding slots get clamped to 0 then masked)
    safe_idx = indices.clamp(min=0)  # (B, K)
    # Use scatter_ to set active bits
    dense.scatter_(1, safe_idx, valid)
    return dense


def dense_to_indices(dense: Tensor, K: int) -> Tensor:
    """Convert dense SDR to index form by selecting top-K active positions.

    For boolean inputs, active positions are extracted via nonzero and
    padded/truncated to exactly K per row.  For float inputs, torch.topk
    selects the K largest values.

    Args:
        dense: (B, N) bool or float tensor.
        K: Number of active indices to extract per row.

    Returns:
        (B, K) int64 tensor.  Rows with fewer than K active bits are
        right-padded with -1.
    """
    B, N = dense.shape
    device = dense.device

    if dense.dtype == torch.bool:
        # Count active bits per row
        counts = dense.sum(dim=1)  # (B,)
        max_count = int(counts.max().item()) if B > 0 else 0

        if max_count == 0:
            return torch.full((B, K), -1, dtype=torch.long, device=device)

        # Convert to float for topk (handles ties deterministically)
        # Add small row-unique noise so topk breaks ties consistently
        float_dense = dense.float()
        # If K > number of True entries in some rows, topk still works --
        # the extra positions will be arbitrary zeros; we mask them below.
        actual_k = min(K, N)
        _, top_idx = torch.topk(float_dense, actual_k, dim=1, sorted=True)  # (B, actual_k)

        # Mask positions that were not actually active
        gathered = torch.gather(dense.long(), 1, top_idx)  # (B, actual_k)
        top_idx = top_idx.long()
        top_idx[gathered == 0] = -1

        # Pad or truncate to exactly K
        if actual_k < K:
            pad = torch.full(
                (B, K - actual_k), -1, dtype=torch.long, device=device
            )
            top_idx = torch.cat([top_idx, pad], dim=1)

        return top_idx
    else:
        # Float path: straightforward topk
        actual_k = min(K, N)
        _, top_idx = torch.topk(dense.float(), actual_k, dim=1, sorted=True)
        top_idx = top_idx.long()
        if actual_k < K:
            pad = torch.full(
                (B, K - actual_k), -1, dtype=torch.long, device=device
            )
            top_idx = torch.cat([top_idx, pad], dim=1)
        return top_idx


def indices_to_sparse_coo(indices: Tensor, N: int) -> Tensor:
    """Convert index-form SDR to a sparse COO tensor.

    Args:
        indices: (B, K) int64 active-bit indices.  -1 entries are ignored.
        N: Number of columns.

    Returns:
        Sparse COO tensor of shape (B, N) with values 1.0 at active
        positions (dtype float32).
    """
    B, K = indices.shape
    device = indices.device

    valid = indices >= 0  # (B, K) bool
    # Build COO index pairs (row, col)
    batch_idx = torch.arange(B, device=device).unsqueeze(1).expand(B, K)  # (B, K)
    row = batch_idx[valid]  # (nnz,)
    col = indices[valid]     # (nnz,)

    coo_indices = torch.stack([row, col], dim=0)  # (2, nnz)
    values = torch.ones(coo_indices.shape[1], dtype=torch.float32, device=device)

    sparse = torch.sparse_coo_tensor(coo_indices, values, size=(B, N))
    return sparse.coalesce()


