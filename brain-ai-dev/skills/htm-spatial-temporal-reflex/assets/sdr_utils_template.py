def soft_topk_mask(logits: Tensor, K: int, temperature: float = 1.0) -> Tensor:
    """Differentiable approximation to top-K selection via Gumbel-softmax.

    Produces a soft (B, N) mask where approximately K entries are close to 1.
    Useful for training SDR generators end-to-end.

    Args:
        logits: (B, N) float32 raw scores.
        K: Desired number of active positions.
        temperature: Softmax temperature.  Lower = sharper.

    Returns:
        (B, N) float32 tensor in approximately {0, 1}, sum ~= K per row.
    """
    B, N = logits.shape

    # Straight-through trick: hard top-K in forward, soft gradient in backward
    _, top_idx = torch.topk(logits, K, dim=1)  # (B, K)
    hard_mask = torch.zeros_like(logits)
    hard_mask.scatter_(1, top_idx, 1.0)

    # Soft mask for gradient
    soft_mask = torch.softmax(logits / temperature, dim=1) * K

    # Straight-through estimator: forward uses hard, backward uses soft
    return hard_mask + (soft_mask - soft_mask.detach())


def differentiable_overlap(
    a_logits: Tensor,
    b_logits: Tensor,
    K: int,
    temperature: float = 1.0,
) -> Tensor:
    """Differentiable SDR overlap for loss computation.

    Uses soft_topk_mask to produce differentiable masks, then computes
    overlap as the dot product of the soft masks.

    Args:
        a_logits: (B, N) float32.
        b_logits: (B, N) float32.
        K: Active bit count.
        temperature: Softmax temperature.

    Returns:
        (B,) float32 -- approximate overlap count.
    """
    mask_a = soft_topk_mask(a_logits, K, temperature)
    mask_b = soft_topk_mask(b_logits, K, temperature)
    return (mask_a * mask_b).sum(dim=1)


