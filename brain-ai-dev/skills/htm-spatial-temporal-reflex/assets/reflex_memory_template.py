class ReflexMemory(nn.Module):
    """Reflex Memory — Fast O(1) pattern prediction cache with LSH lookup.

    Caches frequent SDR->prediction mappings in a two-tier storage system
    (observations and promoted) for O(1) retrieval. Promoted entries bypass
    expensive Temporal Memory computation for known patterns.

    This is the upgraded implementation replacing the original ReflexMemory
    in brain_ai/temporal/htm.py. Key improvements over v1:

    - Explicit observation vs promoted tables with separate LSH indices
    - Confidence tracking per entry (prediction stability over time)
    - Automatic promotion when hit_count and confidence thresholds are met
    - Automatic demotion when post-promotion accuracy drops
    - Baseline snapshot at promotion time for correctness verification
    - Context hashing (winner_cells) for sequence disambiguation
    - Full state_dict/load_state_dict for checkpointing
    - LRU eviction with configurable capacity limits
    - Comprehensive statistics tracking

    Args:
        config: ReflexConfig with all tunable parameters.
    """

    def __init__(self, config: Optional[ReflexConfig] = None) -> None:
        super().__init__()
        self.config = config or ReflexConfig()

        # ---------------------------------------------------------------
        # Entry tables: key_hash (int) -> ReflexEntry
        # Using dicts keyed by a combined hash for O(1) amortized lookup.
        # ---------------------------------------------------------------
        self.observations: Dict[int, ReflexEntry] = {}
        self.promoted: Dict[int, ReflexEntry] = {}

        # ---------------------------------------------------------------
        # LSH indices: separate for observations and promoted so that
        # fast-path lookup only searches the promoted table.
        # ---------------------------------------------------------------
        self.obs_lsh = LSHIndex(
            num_columns=self.config.num_columns,
            num_tables=self.config.num_tables,
            bits_per_hash=self.config.bits_per_hash,
            max_per_bucket=self.config.max_per_bucket,
        )
        self.promo_lsh = LSHIndex(
            num_columns=self.config.num_columns,
            num_tables=self.config.num_tables,
            bits_per_hash=self.config.bits_per_hash,
            max_per_bucket=self.config.max_per_bucket,
        )

        # ---------------------------------------------------------------
        # Global step counter (registered as buffer for device tracking)
        # ---------------------------------------------------------------
        self.register_buffer("_step", torch.tensor(0, dtype=torch.long))

        # ---------------------------------------------------------------
        # Statistics (simple counters, not atomic -- single-threaded training)
        # ---------------------------------------------------------------
        self._hits: int = 0
        self._misses: int = 0
        self._promotions: int = 0
        self._demotions: int = 0
        self._evictions: int = 0

    # -----------------------------------------------------------------
    # Properties
    # -----------------------------------------------------------------

    @property
    def device(self) -> torch.device:
        """Return the device of the module (tracked via _step buffer)."""
        return self._step.device

    @property
    def step(self) -> int:
        """Current global step counter."""
        return self._step.item()

    # -----------------------------------------------------------------
    # Combined hash helper
    # -----------------------------------------------------------------

    @staticmethod
    def _combined_hash(sdr_indices: Tensor, context_hash: int) -> int:
        """Compute a combined hash from SDR indices and context hash.

        The SDR is hashed with an order-independent function, then combined
        with the context hash using a rotation-XOR to break symmetry.

        Args:
            sdr_indices: (K,) int tensor of active column indices.
            context_hash: 64-bit hash of the TM winner_cells state.

        Returns:
            64-bit combined hash as a Python int.
        """
        h1 = _sdr_hash(sdr_indices)
        if isinstance(h1, Tensor):
            h1 = h1.item()
        h1 = int(h1)
        h2 = int(context_hash)
        # Combine with rotation to avoid symmetry
        combined = h1 ^ (((h2 << 17) | ((h2 >> 47) & ((1 << 17) - 1))) & _MAX_HASH_CODE)
        return combined

    # -----------------------------------------------------------------
    # Lookup (fast path)
    # -----------------------------------------------------------------

    def lookup(
        self,
        sdr_indices: Tensor,
        context_hash: int = 0,
    ) -> Optional[Tuple[Tensor, float]]:
        """Try to find a promoted match for the given SDR.

        This is the fast path. Only searches the promoted table.

        Process:
            1. Compute LSH hash of sdr_indices
            2. Query promoted LSH index for candidates
            3. For each candidate: exact Jaccard verification
            4. If best match >= similarity_threshold and context matches: HIT
            5. Else: MISS

        Args:
            sdr_indices: (K,) int tensor of active column indices (sorted).
            context_hash: 64-bit context hash (0 if context unavailable).

        Returns:
            (pred_indices, confidence) if a promoted match is found, None
            otherwise. pred_indices is a (K_pred,) int tensor of predicted
            next active columns.
        """
        if not self.config.enabled or not self.promoted:
            self._misses += 1
            return None

        # Compute LSH hash codes for the query
        codes = self.promo_lsh.compute_hash_sparse(sdr_indices.to(self.device))
        candidates = self.promo_lsh.query(codes, self.config.max_candidates)

        if not candidates:
            self._misses += 1
            return None

        # Exact Jaccard verification of each candidate
        best_hash: Optional[int] = None
        best_jaccard: float = 0.0

        promoted_hashes = list(self.promoted.keys())

        for cand_idx in candidates:
            # The candidate index is the position in insertion order.
            # We stored the entry hash as the key. We need a way to map
            # cand_idx back to the hash. We maintain entry indices that
            # correspond to the order in promoted_hashes.
            if cand_idx < 0 or cand_idx >= len(promoted_hashes):
                continue
            entry_hash = promoted_hashes[cand_idx]
            entry = self.promoted[entry_hash]

            # Context check: if both have non-zero context, they must match
            if context_hash != 0 and entry.context_hash != 0:
                if context_hash != entry.context_hash:
                    continue

            # Jaccard similarity between query and stored key
            jaccard = _sdr_jaccard(sdr_indices, entry.key_indices.to(sdr_indices.device))

            if jaccard > best_jaccard:
                best_jaccard = jaccard
                best_hash = entry_hash

        if best_hash is not None and best_jaccard >= self.config.similarity_threshold:
            entry = self.promoted[best_hash]
            # Update access statistics
            entry.hit_count += 1.0
            entry.last_seen_step = self.step
            self._hits += 1
            return (entry.pred_indices.clone(), entry.confidence)

        self._misses += 1
        return None

    # -----------------------------------------------------------------
    # Observe (slow path recording)
    # -----------------------------------------------------------------

    def observe(
        self,
        sdr_indices: Tensor,
        pred_indices: Tensor,
        context_hash: int = 0,
    ) -> None:
        """Record an observation from the TM slow path.

        Called after the full TM computation produces a prediction for the
        given SDR. Tracks the pattern in the observation table and checks
        whether it should be promoted.

        Process:
            1. Hash the sdr_indices combined with context
            2. Check if observation exists (by hash + Jaccard)
            3. If exists: increment hit_count, update confidence
            4. If new: create observation entry
            5. Check promotion criteria -> promote if ready
            6. Handle LRU eviction if table full

        Args:
            sdr_indices: (K,) int tensor of active column indices (sorted).
            pred_indices: (K_pred,) int tensor of TM-predicted next active
                columns (sorted).
            context_hash: 64-bit context hash (0 if context unavailable).
        """
        if not self.config.enabled:
            return

        # Advance step counter
        self._step += 1

        # Periodic decay
        if self.step % self.config.decay_interval == 0 and self.step > 0:
            self.decay_access_counts()

        # Ensure tensors are on the right device
        sdr_indices = sdr_indices.to(self.device).long()
        pred_indices = pred_indices.to(self.device).long()

        # Sort indices for canonical ordering
        sdr_indices = sdr_indices.sort()[0]
        pred_indices = pred_indices.sort()[0]

        combined = self._combined_hash(sdr_indices, context_hash)

        # Check if this pattern is already in the observation table
        existing_hash = self._find_existing_observation(sdr_indices, context_hash)

        if existing_hash is not None:
            entry = self.observations[existing_hash]
            entry.hit_count += 1.0
            entry.last_seen_step = self.step
            self._update_confidence(entry, pred_indices)
            # Check if ready for promotion
            self._check_promotion(existing_hash, entry)
        else:
            # Also check if it is already promoted (update demotion tracking)
            promoted_hash = self._find_existing_promoted(sdr_indices, context_hash)
            if promoted_hash is not None:
                entry = self.promoted[promoted_hash]
                entry.hit_count += 1.0
                entry.last_seen_step = self.step
                # Track post-promotion accuracy for demotion
                self._check_demotion(promoted_hash, entry, pred_indices)
                return

            # Create new observation entry
            self._create_observation(combined, sdr_indices, pred_indices, context_hash)

    def _find_existing_observation(
        self,
        sdr_indices: Tensor,
        context_hash: int,
    ) -> Optional[int]:
        """Find an existing observation entry matching the given SDR.

        Uses LSH for candidate retrieval, then exact Jaccard verification.

        Args:
            sdr_indices: (K,) int tensor.
            context_hash: 64-bit context hash.

        Returns:
            The entry hash key if found, None otherwise.
        """
        if not self.observations:
            return None

        codes = self.obs_lsh.compute_hash_sparse(sdr_indices.to(self.device))
        candidates = self.obs_lsh.query(codes, self.config.max_candidates)

        obs_hashes = list(self.observations.keys())
        for cand_idx in candidates:
            if cand_idx < 0 or cand_idx >= len(obs_hashes):
                continue
            entry_hash = obs_hashes[cand_idx]
            entry = self.observations[entry_hash]

            # Context check
            if context_hash != 0 and entry.context_hash != 0:
                if context_hash != entry.context_hash:
                    continue

            jaccard = _sdr_jaccard(sdr_indices, entry.key_indices.to(sdr_indices.device))
            if jaccard >= self.config.similarity_threshold:
                return entry_hash

        return None

    def _find_existing_promoted(
        self,
        sdr_indices: Tensor,
        context_hash: int,
    ) -> Optional[int]:
        """Find an existing promoted entry matching the given SDR.

        Similar to _find_existing_observation but searches the promoted table.

        Args:
            sdr_indices: (K,) int tensor.
            context_hash: 64-bit context hash.

        Returns:
            The entry hash key if found, None otherwise.
        """
        if not self.promoted:
            return None

        codes = self.promo_lsh.compute_hash_sparse(sdr_indices.to(self.device))
        candidates = self.promo_lsh.query(codes, self.config.max_candidates)

        promo_hashes = list(self.promoted.keys())
        for cand_idx in candidates:
            if cand_idx < 0 or cand_idx >= len(promo_hashes):
                continue
            entry_hash = promo_hashes[cand_idx]
            entry = self.promoted[entry_hash]

            if context_hash != 0 and entry.context_hash != 0:
                if context_hash != entry.context_hash:
                    continue

            jaccard = _sdr_jaccard(sdr_indices, entry.key_indices.to(sdr_indices.device))
            if jaccard >= self.config.similarity_threshold:
                return entry_hash

        return None

    def _create_observation(
        self,
        entry_hash: int,
        sdr_indices: Tensor,
        pred_indices: Tensor,
        context_hash: int,
    ) -> None:
        """Create a new observation entry.

        Handles LRU eviction if the observation table is at capacity.

        Args:
            entry_hash: Combined hash for this pattern.
            sdr_indices: (K,) int tensor (sorted).
            pred_indices: (K_pred,) int tensor (sorted).
            context_hash: 64-bit context hash.
        """
        # Evict if at capacity
        if len(self.observations) >= self.config.max_observations:
            self._evict_lru(self.observations, self.obs_lsh, self.config.max_observations)

        entry = ReflexEntry(
            key_indices=sdr_indices.clone(),
            context_hash=context_hash,
            pred_indices=pred_indices.clone(),
            hit_count=1.0,
            last_seen_step=self.step,
            confidence=0.0,
            promoted=False,
            baseline_snapshot=None,
            prediction_history=deque(maxlen=self.config.demotion_window),
        )
        entry.prediction_history.append(pred_indices.clone())

        self.observations[entry_hash] = entry

        # Insert into observation LSH index
        # The LSH entry index is the position in the dict iteration order.
        # We use the current length - 1 as the index.
        idx = list(self.observations.keys()).index(entry_hash)
        codes = self.obs_lsh.compute_hash_sparse(sdr_indices)
        self.obs_lsh.insert(idx, codes)

    # -----------------------------------------------------------------
    # Confidence tracking
    # -----------------------------------------------------------------

    def _update_confidence(self, entry: ReflexEntry, tm_prediction: Tensor) -> None:
        """Update the confidence score for an observation entry.

        Confidence is computed as the fraction of recent observations where
        the TM's prediction agrees with the entry's stored prediction.
        Agreement is measured via Jaccard similarity with a threshold.

        Args:
            entry: The observation entry to update.
            tm_prediction: (K_pred,) int tensor of TM's current prediction.
        """
        # Add current prediction to history
        entry.prediction_history.append(tm_prediction.clone())

        # Update stored prediction using exponential moving average logic:
        # Compare against current stored prediction
        agreement = _sdr_jaccard(entry.pred_indices, tm_prediction)

        # Adaptive smoothing: lower alpha when more observations exist
        alpha = 2.0 / (entry.hit_count + 1.0)
        alpha = max(alpha, 0.05)  # floor to prevent freezing
        entry.confidence = (1.0 - alpha) * entry.confidence + alpha * agreement

        # If the new prediction is significantly better, update the stored one
        # based on majority voting across the history window.
        if len(entry.prediction_history) >= 3:
            entry.pred_indices = self._compute_majority_prediction(entry)

    def _compute_majority_prediction(self, entry: ReflexEntry) -> Tensor:
        """Compute the most common prediction from the entry's history.

        Uses index frequency voting: for each column index seen in the
        history, count how many predictions include it. Return the top-K
        most frequent indices as the consensus prediction.

        Args:
            entry: Entry with a non-empty prediction_history.

        Returns:
            (K_pred,) int tensor of majority-voted prediction indices.
        """
        # Count frequency of each column index across the history
        index_counts: Dict[int, int] = {}
        for pred in entry.prediction_history:
            for idx in pred.tolist():
                index_counts[idx] = index_counts.get(idx, 0) + 1

        # Take the K most frequent indices (K = median prediction length)
        pred_lengths = [len(p) for p in entry.prediction_history]
        target_k = sorted(pred_lengths)[len(pred_lengths) // 2]

        sorted_indices = sorted(index_counts.keys(), key=lambda i: -index_counts[i])
        top_indices = sorted(sorted_indices[:target_k])

        if not top_indices:
            return entry.pred_indices.clone()

        return torch.tensor(top_indices, dtype=torch.long, device=entry.pred_indices.device)

    @staticmethod
    def _compute_confidence(prediction_history: Deque[Tensor]) -> float:
        """Compute confidence as the fraction of observations matching the
        most common prediction.

        This is a static utility for external callers who want to evaluate
        confidence from a prediction history without an entry context.

        Args:
            prediction_history: Deque of (K_pred,) int tensors.

        Returns:
            Confidence score in [0, 1].
        """
        if len(prediction_history) < 2:
            return 0.0

        # Find the most common prediction (by tuple representation)
        pred_tuples = [tuple(sorted(p.tolist())) for p in prediction_history]
        from collections import Counter
        counts = Counter(pred_tuples)
        most_common_count = counts.most_common(1)[0][1]
        return most_common_count / len(prediction_history)

    # -----------------------------------------------------------------
    # Promotion / demotion
    # -----------------------------------------------------------------

    def _check_promotion(self, entry_hash: int, entry: ReflexEntry) -> None:
        """Check if an observation entry should be promoted to the fast path.

        Promotion criteria (ALL must be met):
            - entry is not already promoted
            - hit_count >= promotion_threshold
            - confidence >= min_confidence

        On promotion:
            - Snapshot baseline prediction
            - Move entry from observations to promoted table
            - Update LSH indices

        Args:
            entry_hash: Hash key of the entry in the observations dict.
            entry: The observation entry to evaluate.
        """
        if entry.promoted:
            return
        if entry.hit_count < self.config.promotion_threshold:
            return
        if entry.confidence < self.config.min_confidence:
            return

        # Evict from promoted if at capacity
        if len(self.promoted) >= self.config.max_promoted:
            self._evict_lru(self.promoted, self.promo_lsh, self.config.max_promoted)

        # Snapshot baseline prediction
        entry.baseline_snapshot = entry.pred_indices.clone()
        entry.promoted = True
        entry.post_promotion_correct = 0
        entry.post_promotion_total = 0

        # Remove from observation table and LSH
        obs_keys = list(self.observations.keys())
        if entry_hash in self.observations:
            obs_idx = obs_keys.index(entry_hash)
            codes = self.obs_lsh.compute_hash_sparse(entry.key_indices)
            self.obs_lsh.remove(obs_idx, codes)
            del self.observations[entry_hash]
            # Rebuild observation LSH indices after removal (indices shifted)
            self._rebuild_lsh(self.observations, self.obs_lsh)

        # Insert into promoted table and LSH
        self.promoted[entry_hash] = entry
        promo_idx = list(self.promoted.keys()).index(entry_hash)
        codes = self.promo_lsh.compute_hash_sparse(entry.key_indices)
        self.promo_lsh.insert(promo_idx, codes)

        self._promotions += 1
        logger.debug(
            "Promoted entry %#x: hit_count=%.1f confidence=%.3f",
            entry_hash & 0xFFFFFFFF, entry.hit_count, entry.confidence,
        )

    def _check_demotion(
        self,
        entry_hash: int,
        entry: ReflexEntry,
        actual_pred: Tensor,
    ) -> None:
        """Check if a promoted entry should be demoted.

        Tracks post-promotion accuracy over a rolling window. If accuracy
        drops below demotion_threshold, the entry is demoted back to the
        observation table.

        Args:
            entry_hash: Hash key of the entry in the promoted dict.
            entry: The promoted entry to evaluate.
            actual_pred: (K_pred,) int tensor of the TM's actual prediction
                for this pattern (ground truth).
        """
        if not entry.promoted:
            return

        # Compute accuracy of cached prediction vs actual TM prediction
        jaccard = _sdr_jaccard(entry.pred_indices, actual_pred)
        correct = jaccard >= self.config.similarity_threshold

        entry.post_promotion_total += 1
        if correct:
            entry.post_promotion_correct += 1

        # Only evaluate after enough samples in the window
        if entry.post_promotion_total < self.config.demotion_window:
            return

        accuracy = entry.post_promotion_correct / max(entry.post_promotion_total, 1)

        if accuracy < self.config.demotion_threshold:
            self._demote_entry(entry_hash, entry)

    def _demote_entry(self, entry_hash: int, entry: ReflexEntry) -> None:
        """Demote a promoted entry back to the observation table.

        Resets the entry's promotion state and moves it from the promoted
        table back to observations for re-evaluation.

        Args:
            entry_hash: Hash key of the entry in the promoted dict.
            entry: The promoted entry to demote.
        """
        entry.promoted = False
        entry.hit_count = 1.0  # Reset so it must re-earn promotion
        entry.confidence = 0.0
        entry.baseline_snapshot = None
        entry.post_promotion_correct = 0
        entry.post_promotion_total = 0
        entry.prediction_history.clear()

        # Remove from promoted table and LSH
        promo_keys = list(self.promoted.keys())
        if entry_hash in self.promoted:
            promo_idx = promo_keys.index(entry_hash)
            codes = self.promo_lsh.compute_hash_sparse(entry.key_indices)
            self.promo_lsh.remove(promo_idx, codes)
            del self.promoted[entry_hash]
            self._rebuild_lsh(self.promoted, self.promo_lsh)

        # Insert back into observation table
        if len(self.observations) >= self.config.max_observations:
            self._evict_lru(self.observations, self.obs_lsh, self.config.max_observations)

        self.observations[entry_hash] = entry
        obs_idx = list(self.observations.keys()).index(entry_hash)
        codes = self.obs_lsh.compute_hash_sparse(entry.key_indices)
        self.obs_lsh.insert(obs_idx, codes)

        self._demotions += 1
        logger.debug(
            "Demoted entry %#x back to observations",
            entry_hash & 0xFFFFFFFF,
        )

    # -----------------------------------------------------------------
    # LRU eviction
    # -----------------------------------------------------------------

    def _evict_lru(
        self,
        table: Dict[int, ReflexEntry],
        lsh_index: LSHIndex,
        max_size: int,
    ) -> None:
        """Evict the least-recently-used entry from a table.

        Finds the entry with the smallest last_seen_step and removes it.
        Tie-breaks by lowest hit_count.

        Args:
            table: The entry table (observations or promoted dict).
            lsh_index: The corresponding LSH index.
            max_size: Maximum allowed size (for logging).
        """
        if not table:
            return

        # Find the LRU entry
        lru_hash = min(
            table.keys(),
            key=lambda h: (table[h].last_seen_step, table[h].hit_count),
        )
        lru_entry = table[lru_hash]

        # Remove from LSH
        table_keys = list(table.keys())
        lru_idx = table_keys.index(lru_hash)
        codes = lsh_index.compute_hash_sparse(lru_entry.key_indices)
        lsh_index.remove(lru_idx, codes)

        # Remove from table
        del table[lru_hash]

        # Rebuild LSH after index shift
        self._rebuild_lsh(table, lsh_index)

        self._evictions += 1

    def _rebuild_lsh(
        self,
        table: Dict[int, ReflexEntry],
        lsh_index: LSHIndex,
    ) -> None:
        """Rebuild an LSH index from scratch for the given table.

        Called after insertion/removal that shifts entry indices. This is
        O(n) but only happens during promotion/demotion/eviction, not on
        the hot lookup path.

        Args:
            table: Entry table to rebuild from.
            lsh_index: LSH index to clear and repopulate.
        """
        lsh_index.clear()
        for idx, (_, entry) in enumerate(table.items()):
            codes = lsh_index.compute_hash_sparse(entry.key_indices)
            lsh_index.insert(idx, codes)

    # -----------------------------------------------------------------
    # Decay
    # -----------------------------------------------------------------

    def decay_access_counts(self) -> None:
        """Apply multiplicative decay to all hit_counts.

        Multiply every entry's hit_count by decay_rate. This prevents old
        patterns from persisting indefinitely. Promoted entries whose
        decayed hit_count drops below promotion_threshold are demoted.
        """
        rate = self.config.decay_rate

        # Decay observations
        for entry in self.observations.values():
            entry.hit_count *= rate

        # Decay promoted and check for demotion
        demote_hashes: List[int] = []
        for h, entry in self.promoted.items():
            entry.hit_count *= rate
            if entry.hit_count < self.config.promotion_threshold:
                demote_hashes.append(h)

        for h in demote_hashes:
            if h in self.promoted:
                self._demote_entry(h, self.promoted[h])

    # -----------------------------------------------------------------
    # Statistics
    # -----------------------------------------------------------------

    def get_statistics(self) -> Dict[str, float]:
        """Return a dictionary of Reflex Memory performance metrics.

        Returns:
            Dictionary with keys: hits, misses, hit_rate, promoted_count,
            observation_count, memory_utilization, promotions, demotions,
            evictions, mean_confidence.
        """
        total = self._hits + self._misses
        hit_rate = self._hits / max(total, 1)

        # Mean confidence of promoted entries
        if self.promoted:
            mean_conf = sum(e.confidence for e in self.promoted.values()) / len(self.promoted)
        else:
            mean_conf = 0.0

        total_capacity = self.config.max_observations + self.config.max_promoted
        total_used = len(self.observations) + len(self.promoted)
        utilization = total_used / max(total_capacity, 1)

        return {
            "hits": self._hits,
            "misses": self._misses,
            "hit_rate": hit_rate,
            "promoted_count": len(self.promoted),
            "observation_count": len(self.observations),
            "memory_utilization": utilization,
            "promotions": self._promotions,
            "demotions": self._demotions,
            "evictions": self._evictions,
            "mean_confidence": mean_conf,
        }

    def reset_statistics(self) -> None:
        """Reset hit/miss and event counters to zero."""
        self._hits = 0
        self._misses = 0
        self._promotions = 0
        self._demotions = 0
        self._evictions = 0

    def log_statistics(self) -> None:
        """Log current statistics at INFO level."""
        stats = self.get_statistics()
        logger.info(
            "Reflex: hit_rate=%.3f promoted=%d observations=%d "
            "evictions=%d demotions=%d mean_confidence=%.3f",
            stats["hit_rate"],
            stats["promoted_count"],
            stats["observation_count"],
            stats["evictions"],
            stats["demotions"],
            stats["mean_confidence"],
        )

    # -----------------------------------------------------------------
    # Baseline verification
    # -----------------------------------------------------------------

    def verify_against_baseline(
        self,
        sdr_indices: Tensor,
        tm_prediction: Tensor,
    ) -> bool:
        """Verify that a promoted entry's cached prediction matches the TM.

        For testing and periodic verification: look up the promoted entry
        for the given SDR and compare its cached prediction against the
        TM's current output.

        Args:
            sdr_indices: (K,) int tensor of active column indices.
            tm_prediction: (K_pred,) int tensor of the TM's current prediction.

        Returns:
            True if the promoted prediction matches (Jaccard >= threshold),
            False otherwise or if no promoted entry found.
        """
        result = self.lookup(sdr_indices)
        if result is None:
            return False

        pred, _ = result
        jaccard = _sdr_jaccard(pred, tm_prediction)
        return jaccard >= self.config.similarity_threshold

    # -----------------------------------------------------------------
    # State dict (full serialization)
    # -----------------------------------------------------------------

    def state_dict(self, destination=None, prefix="", keep_vars=False) -> Dict[str, Any]:
        """Serialize the complete Reflex Memory state.

        Includes all entry tables, LSH indices, projections, statistics,
        and configuration. Merges with nn.Module's standard state_dict
        (which captures registered buffers like _step).

        Returns:
            Dictionary suitable for torch.save().
        """
        base = super().state_dict(destination=destination, prefix=prefix, keep_vars=keep_vars)
        base[prefix + "_reflex_custom"] = {
            "observations": self._serialize_entries(self.observations),
            "promoted": self._serialize_entries(self.promoted),
            "obs_lsh": self.obs_lsh.state_dict(),
            "promo_lsh": self.promo_lsh.state_dict(),
            "statistics": {
                "hits": self._hits,
                "misses": self._misses,
                "promotions": self._promotions,
                "demotions": self._demotions,
                "evictions": self._evictions,
            },
            "config": asdict(self.config),
        }
        return base

    def load_state_dict(self, state_dict: Dict[str, Any], strict: bool = True) -> None:
        """Restore the complete Reflex Memory state from a serialized dict.

        Args:
            state_dict: Dictionary produced by state_dict().
            strict: If True (default), require all keys to match.
        """
        # Extract custom reflex state before passing to super
        custom_key = "_reflex_custom"
        # Find the custom key (may have a prefix)
        custom_data = None
        remaining = {}
        for k, v in state_dict.items():
            if k.endswith(custom_key):
                custom_data = v
            else:
                remaining[k] = v

        # Load nn.Module buffers (_step)
        if remaining:
            super().load_state_dict(remaining, strict=False)

        if custom_data is None:
            return

        # Restore config
        if "config" in custom_data:
            for key, value in custom_data["config"].items():
                if hasattr(self.config, key):
                    setattr(self.config, key, value)

        # Restore entries
        self.observations = self._deserialize_entries(custom_data.get("observations", []))
        self.promoted = self._deserialize_entries(custom_data.get("promoted", []))

        # Restore LSH indices
        if "obs_lsh" in custom_data:
            self.obs_lsh.load_state_dict(custom_data["obs_lsh"])
            self.obs_lsh.to(self.device)
        if "promo_lsh" in custom_data:
            self.promo_lsh.load_state_dict(custom_data["promo_lsh"])
            self.promo_lsh.to(self.device)

        # Restore statistics
        stats = custom_data.get("statistics", {})
        self._hits = stats.get("hits", 0)
        self._misses = stats.get("misses", 0)
        self._promotions = stats.get("promotions", 0)
        self._demotions = stats.get("demotions", 0)
        self._evictions = stats.get("evictions", 0)

    def _serialize_entries(
        self,
        entries: Dict[int, ReflexEntry],
    ) -> List[Dict[str, Any]]:
        """Serialize an entry table to a list of dicts.

        Args:
            entries: Dict mapping hash keys to ReflexEntry instances.

        Returns:
            List of serializable dictionaries.
        """
        result = []
        for h, e in entries.items():
            result.append({
                "key_hash": h,
                "key_indices": e.key_indices.cpu(),
                "context_hash": e.context_hash,
                "pred_indices": e.pred_indices.cpu(),
                "hit_count": e.hit_count,
                "last_seen_step": e.last_seen_step,
                "confidence": e.confidence,
                "promoted": e.promoted,
                "baseline_snapshot": (
                    e.baseline_snapshot.cpu() if e.baseline_snapshot is not None else None
                ),
                "post_promotion_correct": e.post_promotion_correct,
                "post_promotion_total": e.post_promotion_total,
                "prediction_history": [p.cpu() for p in e.prediction_history],
            })
        return result

    def _deserialize_entries(
        self,
        data: List[Dict[str, Any]],
    ) -> Dict[int, ReflexEntry]:
        """Deserialize a list of dicts back into an entry table.

        Args:
            data: List of dictionaries (from _serialize_entries).

        Returns:
            Dict mapping hash keys to ReflexEntry instances.
        """
        entries: Dict[int, ReflexEntry] = {}
        for d in data:
            history = deque(maxlen=self.config.demotion_window)
            for p in d.get("prediction_history", []):
                history.append(p.to(self.device))

            entry = ReflexEntry(
                key_indices=d["key_indices"].to(self.device),
                context_hash=d["context_hash"],
                pred_indices=d["pred_indices"].to(self.device),
                hit_count=d["hit_count"],
                last_seen_step=d["last_seen_step"],
                confidence=d["confidence"],
                promoted=d["promoted"],
                baseline_snapshot=(
                    d["baseline_snapshot"].to(self.device)
                    if d["baseline_snapshot"] is not None
                    else None
                ),
                prediction_history=history,
                post_promotion_correct=d.get("post_promotion_correct", 0),
                post_promotion_total=d.get("post_promotion_total", 0),
            )
            entries[d["key_hash"]] = entry
        return entries

    # -----------------------------------------------------------------
    # Device handling
    # -----------------------------------------------------------------

    def to(self, *args, **kwargs) -> "ReflexMemory":
        """Override to also move LSH indices and entry tensors to new device."""
        result = super().to(*args, **kwargs)
        device = result._step.device

        result.obs_lsh.to(device)
        result.promo_lsh.to(device)

        for entry in result.observations.values():
            entry.key_indices = entry.key_indices.to(device)
            entry.pred_indices = entry.pred_indices.to(device)
            if entry.baseline_snapshot is not None:
                entry.baseline_snapshot = entry.baseline_snapshot.to(device)

        for entry in result.promoted.values():
            entry.key_indices = entry.key_indices.to(device)
            entry.pred_indices = entry.pred_indices.to(device)
            if entry.baseline_snapshot is not None:
                entry.baseline_snapshot = entry.baseline_snapshot.to(device)

        return result


