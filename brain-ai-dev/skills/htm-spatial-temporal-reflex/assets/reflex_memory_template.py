class LSHIndex:
    """Locality-Sensitive Hashing index for fast approximate SDR lookup.

    Uses random hyperplane projections to generate binary hash codes.
    Each SDR is hashed into ``num_tables`` independent hash tables.
    Queries return the union of candidate entry indices across all tables.
    Multiple tables reduce the false negative rate at the cost of
    increased memory and slightly higher insert/query time.

    The projection matrices are fixed at construction time and persisted
    through state_dict/load_state_dict for checkpoint reproducibility.

    Args:
        num_columns: SDR dimensionality (N).
        num_tables: Number of independent hash tables.
        bits_per_hash: Number of projection bits per table. Each table has
            up to 2^bits_per_hash buckets.
        max_per_bucket: Maximum entries allowed in any single bucket.
            When exceeded, the oldest entry (by insertion order) in that
            bucket is evicted.
        device: Torch device for projection matrices.
    """

    def __init__(
        self,
        num_columns: int,
        num_tables: int,
        bits_per_hash: int,
        max_per_bucket: int,
        device: Optional[torch.device] = None,
    ) -> None:
        self.num_columns = num_columns
        self.num_tables = num_tables
        self.bits_per_hash = bits_per_hash
        self.max_per_bucket = max_per_bucket
        self.device = device or torch.device("cpu")

        # Random projection matrices: (num_tables, num_columns, bits_per_hash)
        # Each table has an independent random hyperplane family.
        self.projections: Tensor = torch.randn(
            num_tables, num_columns, bits_per_hash, device=self.device
        )

        # Hash tables: table_idx -> {bucket_key (int) -> [entry_indices]}
        self.tables: List[Dict[int, List[int]]] = [
            {} for _ in range(num_tables)
        ]

        # Pre-computed powers of 2 for bit packing
        self._powers: Tensor = (
            2 ** torch.arange(bits_per_hash, device=self.device, dtype=torch.long)
        )

    # -----------------------------------------------------------------
    # Hash computation
    # -----------------------------------------------------------------

    def _to_dense(self, sdr_indices: Tensor) -> Tensor:
        """Convert sparse SDR indices to a dense binary vector.

        Args:
            sdr_indices: (K,) int tensor of active column indices.

        Returns:
            (1, num_columns) float tensor with 1.0 at active positions.
        """
        dense = torch.zeros(1, self.num_columns, device=self.device, dtype=torch.float32)
        if sdr_indices.numel() > 0:
            dense[0, sdr_indices.long()] = 1.0
        return dense

    def compute_hash(self, sdr_dense: Tensor) -> Tensor:
        """Compute LSH hash codes for a dense SDR representation.

        Args:
            sdr_dense: (B, N) float tensor (dense binary SDR).

        Returns:
            (B, num_tables) int64 tensor of packed hash codes per table.
        """
        # Project: (B, N) @ (num_tables, N, bits)^T -> need reshaping
        # Reshape projections to (N, num_tables * bits)
        B = sdr_dense.shape[0]
        proj_flat = self.projections.permute(1, 0, 2).reshape(
            self.num_columns, self.num_tables * self.bits_per_hash
        )
        # (B, num_tables * bits)
        projected = sdr_dense.float() @ proj_flat
        # Reshape to (B, num_tables, bits)
        projected = projected.view(B, self.num_tables, self.bits_per_hash)
        # Binarize
        binary = (projected > 0).long()
        # Pack bits into single int per table
        # powers shape: (bits,) -> broadcast to (1, 1, bits)
        codes = (binary * self._powers.unsqueeze(0).unsqueeze(0)).sum(dim=-1)
        return codes  # (B, num_tables)

    def compute_hash_sparse(self, sdr_indices: Tensor) -> Tensor:
        """Compute LSH hash codes from sparse SDR indices.

        Convenience wrapper that converts sparse indices to dense, then hashes.

        Args:
            sdr_indices: (K,) int tensor of active column indices.

        Returns:
            (1, num_tables) int64 tensor of packed hash codes.
        """
        dense = self._to_dense(sdr_indices)
        return self.compute_hash(dense)

    # -----------------------------------------------------------------
    # Insert / query / remove
    # -----------------------------------------------------------------

    def insert(self, entry_idx: int, hash_codes: Tensor) -> None:
        """Insert an entry index into all hash tables.

        Args:
            entry_idx: Integer index identifying the entry.
            hash_codes: (1, num_tables) or (num_tables,) int64 hash codes.
        """
        codes = hash_codes.squeeze(0) if hash_codes.dim() == 2 else hash_codes
        for t in range(self.num_tables):
            bucket_key = codes[t].item()
            bucket = self.tables[t].setdefault(bucket_key, [])
            if entry_idx not in bucket:
                if len(bucket) >= self.max_per_bucket:
                    # Evict first (oldest by insertion order) entry in bucket
                    bucket.pop(0)
                bucket.append(entry_idx)

    def query(self, hash_codes: Tensor, max_candidates: int) -> List[int]:
        """Retrieve candidate entry indices matching the given hash codes.

        Takes the union of candidates across all tables, then ranks by the
        number of tables each candidate appeared in (multi-probe). Returns
        at most ``max_candidates`` entries.

        Args:
            hash_codes: (1, num_tables) or (num_tables,) int64 hash codes.
            max_candidates: Maximum number of candidate indices to return.

        Returns:
            List of entry indices, sorted by descending table-match count.
        """
        codes = hash_codes.squeeze(0) if hash_codes.dim() == 2 else hash_codes
        candidate_counts: Dict[int, int] = {}

        for t in range(self.num_tables):
            bucket_key = codes[t].item()
            bucket = self.tables[t].get(bucket_key, [])
            for idx in bucket:
                candidate_counts[idx] = candidate_counts.get(idx, 0) + 1

        # Sort by number of matching tables (descending), then by index (stable)
        sorted_candidates = sorted(
            candidate_counts.keys(),
            key=lambda i: (-candidate_counts[i], i),
        )
        return sorted_candidates[:max_candidates]

    def remove(self, entry_idx: int, hash_codes: Tensor) -> None:
        """Remove an entry from all hash tables.

        Args:
            entry_idx: Integer index of the entry to remove.
            hash_codes: (1, num_tables) or (num_tables,) int64 hash codes.
        """
        codes = hash_codes.squeeze(0) if hash_codes.dim() == 2 else hash_codes
        for t in range(self.num_tables):
            bucket_key = codes[t].item()
            bucket = self.tables[t].get(bucket_key, [])
            if entry_idx in bucket:
                bucket.remove(entry_idx)
                # Clean up empty buckets to save memory
                if not bucket:
                    del self.tables[t][bucket_key]

    def remove_all_references(self, entry_idx: int) -> None:
        """Remove an entry from ALL buckets in all tables (brute-force).

        Use when the entry's hash codes are unavailable (e.g., during
        deserialization rebuild). This is O(total_buckets) but is only
        called during maintenance, not on the hot path.

        Args:
            entry_idx: Integer index of the entry to remove.
        """
        for t in range(self.num_tables):
            for bucket_key in list(self.tables[t].keys()):
                bucket = self.tables[t][bucket_key]
                if entry_idx in bucket:
                    bucket.remove(entry_idx)
                    if not bucket:
                        del self.tables[t][bucket_key]

    def clear(self) -> None:
        """Remove all entries from all tables."""
        self.tables = [{} for _ in range(self.num_tables)]

    # -----------------------------------------------------------------
    # State dict support
    # -----------------------------------------------------------------

    def state_dict(self) -> dict:
        """Serialize the LSH index to a dictionary.

        Returns:
            Dictionary containing projections tensor and all hash tables.
        """
        return {
            "projections": self.projections.cpu().clone(),
            "tables": [
                {k: list(v) for k, v in table.items()}
                for table in self.tables
            ],
            "num_columns": self.num_columns,
            "num_tables": self.num_tables,
            "bits_per_hash": self.bits_per_hash,
            "max_per_bucket": self.max_per_bucket,
        }

    def load_state_dict(self, state: dict) -> None:
        """Restore the LSH index from a serialized dictionary.

        Args:
            state: Dictionary produced by ``state_dict()``.
        """
        self.projections = state["projections"].to(self.device)
        self.num_columns = state["num_columns"]
        self.num_tables = state["num_tables"]
        self.bits_per_hash = state["bits_per_hash"]
        self.max_per_bucket = state["max_per_bucket"]
        self.tables = [
            {k: list(v) for k, v in table.items()}
            for table in state["tables"]
        ]
        # Recompute powers
        self._powers = (
            2 ** torch.arange(self.bits_per_hash, device=self.device, dtype=torch.long)
        )

    def to(self, device: torch.device) -> "LSHIndex":
        """Move projection matrices to a new device.

        Args:
            device: Target torch device.

        Returns:
            Self (for chaining).
        """
        self.device = device
        self.projections = self.projections.to(device)
        self._powers = self._powers.to(device)
        return self


