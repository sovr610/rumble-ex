def _sdr_hash_fallback(indices: Tensor) -> Tensor:
    """Order-independent hash of SDR indices.

    Args:
        indices: (B, K) or (K,) int tensor of active column indices.

    Returns:
        (B,) or scalar int64 tensor of hash values.
    """
    if indices.dim() == 1:
        indices = indices.unsqueeze(0)
    B, K = indices.shape
    h = torch.zeros(B, dtype=torch.long, device=indices.device)
    for k in range(K):
        mixed = indices[:, k].long() * _GOLDEN
        mixed = (mixed >> 32) ^ mixed  # avalanche mixing
        h ^= mixed
    return h.squeeze(0) if B == 1 and indices.dim() == 2 else h


def _sdr_overlap_fallback(a: Tensor, b: Tensor) -> int:
    """Count overlapping active bits between two index tensors.

    Args:
        a: (K_a,) int tensor of active indices.
        b: (K_b,) int tensor of active indices.

    Returns:
        Number of shared indices.
    """
    set_a = set(a.tolist())
    set_b = set(b.tolist())
    return len(set_a & set_b)


def _sdr_jaccard_fallback(a: Tensor, b: Tensor) -> float:
    """Jaccard similarity between two SDR index tensors.

    Args:
        a: (K_a,) int tensor of sorted active indices.
        b: (K_b,) int tensor of sorted active indices.

    Returns:
        Jaccard coefficient in [0, 1].
    """
    set_a = set(a.tolist())
    set_b = set(b.tolist())
    intersection = len(set_a & set_b)
    union = len(set_a | set_b)
    return intersection / max(union, 1)


