    def _similar_sdr(base: Tensor, n: int = 2048, flip: int = 2) -> Tensor:
        """Create an SDR similar to base by flipping a few indices."""
        indices = base.tolist()
        all_cols = set(range(n))
        active = set(indices)
        inactive = list(all_cols - active)
