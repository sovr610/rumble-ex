# 5. AnomalyLikelihood
# ---------------------------------------------------------------------------

class AnomalyLikelihood:
    """Rolling Gaussian anomaly likelihood computation.

    Transforms raw anomaly scores (which are noisy and not comparable across
    different patterns) into a calibrated probability using a sliding-window
    Gaussian model of recent anomaly values.

    Usage::

        tracker = AnomalyLikelihood(window_size=1000)
        for raw_anomaly in stream:
            likelihood = tracker.compute(raw_anomaly)
            if likelihood > 0.9999:
                print("very unusual!")
    """

    def __init__(self, window_size: int = 1000, eps: float = 1e-6) -> None:
        self.window: deque = deque(maxlen=window_size)
        self.eps = eps

    def compute(self, anomaly: float) -> float:
        """Transform raw anomaly in [0, 1] to likelihood in [0, 1].

        Uses a Gaussian tail probability: for a z-score *z*,
        likelihood = 1 - 0.5 * (1 + erf(-z / sqrt(2))).

        Until enough samples accumulate (< 10), returns the raw anomaly.
        """
        self.window.append(anomaly)
        if len(self.window) < 10:
            return anomaly
        mean = statistics.mean(self.window)
        std = max(statistics.stdev(self.window), self.eps)
        z = (anomaly - mean) / std
        # Gaussian tail probability (upper tail)
        return 1.0 - 0.5 * (1.0 + math.erf(-z / math.sqrt(2)))

    def reset(self) -> None:
        """Clear the history window."""
        self.window.clear()


