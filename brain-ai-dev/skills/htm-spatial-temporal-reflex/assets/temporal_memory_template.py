def segment_reduce_loop(
    values: Tensor,
    seg_start: Tensor,
    seg_len: Tensor,
    num_segments: int,
) -> Tensor:
    """Sum *values* within each segment's synapse range (CSR reduction).

    This is the reference (loop-based) implementation.  Prefer
    :func:`segment_reduce` for production use.

    Args:
        values:       (M,) float -- per-synapse values to sum.
        seg_start:    (S,) int32 -- start index into *values* for each segment.
        seg_len:      (S,) int16 -- number of synapses for each segment.
        num_segments: int -- number of live segments (may be < S capacity).

    Returns:
        (num_segments,) float -- sum of values within each segment.
    """
    result = torch.zeros(num_segments, device=values.device, dtype=values.dtype)
    for s in range(num_segments):
        start = seg_start[s].item()
        length = seg_len[s].item()
        if length > 0:
            result[s] = values[start : start + length].sum()
    return result


def segment_reduce(
    values: Tensor,
    seg_start: Tensor,
    seg_len: Tensor,
    num_segments: int,
) -> Tensor:
    """Vectorized CSR reduction using ``repeat_interleave`` + ``scatter_add_``.

    Equivalent to ``result[s] = values[seg_start[s] : seg_start[s]+seg_len[s]].sum()``
    for each segment *s*, but fully vectorized.

    Args:
        values:       (M,) float -- per-synapse values.
        seg_start:    (S_cap,) int32 -- CSR row pointers (only first *num_segments* used).
        seg_len:      (S_cap,) int16 -- lengths per segment.
        num_segments: int -- number of live segments.

    Returns:
        (num_segments,) float -- per-segment sums.
    """
    if num_segments == 0:
        return torch.zeros(0, device=values.device, dtype=values.dtype)

    lens = seg_len[:num_segments].long()
    total_syn = lens.sum().item()
    if total_syn == 0:
        return torch.zeros(num_segments, device=values.device, dtype=values.dtype)

    # Build flat indices into *values* for all segments at once
    starts = seg_start[:num_segments].long()

    # Offsets within each segment: [0..len0-1, 0..len1-1, ...]
    offsets = torch.arange(total_syn, device=values.device)
    # Subtract cumulative lengths to get per-segment offset
    cumlen = torch.zeros(num_segments + 1, device=values.device, dtype=torch.long)
    cumlen[1:] = lens.cumsum(0)
    # Segment index for each synapse
    seg_ids = torch.repeat_interleave(
        torch.arange(num_segments, device=values.device), lens
    )
    # Global index = seg_start[s] + local_offset
    local_offset = offsets - cumlen[seg_ids]
    global_idx = starts[seg_ids] + local_offset

    # Gather values and scatter-add by segment id
    gathered = values[global_idx]
    result = torch.zeros(num_segments, device=values.device, dtype=values.dtype)
    result.scatter_add_(0, seg_ids, gathered.float())
    return result


