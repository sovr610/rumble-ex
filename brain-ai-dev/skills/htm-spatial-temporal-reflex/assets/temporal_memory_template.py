    D = torch.tensor([30, 31, 32, 33, 34], dtype=torch.int64)
    X = torch.tensor([40, 41, 42, 43, 44], dtype=torch.int64)
    Y = torch.tensor([50, 51, 52, 53, 54], dtype=torch.int64)

    # Train both sequences
    for _ in range(30):
        # ABCD
        tm.reset(device=device)
        for s in [A, B, C, D]:
            tm.step(s, learn=True)
        # XBCY
        tm.reset(device=device)
        for s in [X, B, C, Y]:
            tm.step(s, learn=True)

