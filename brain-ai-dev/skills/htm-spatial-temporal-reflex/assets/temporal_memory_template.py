class SparseSegmentStore:
    """CSR-style flat array storage for TM segments and synapses.

    Memory layout
    -------------
    Segments (capacity ``max_total_segments``)::

        seg_cell   (S,)  int32  -- which cell owns this segment
        seg_start  (S,)  int32  -- start offset into synapse arrays
        seg_len    (S,)  int16  -- number of live synapses in this segment
        seg_alive  (S,)  bool   -- whether the segment slot is occupied

    Synapses (capacity ``max_total_synapses``)::

        syn_src_cell (M,) int32   -- presynaptic cell id
        syn_perm     (M,) float32 -- permanence value in [0, 1]

    Per-cell index::

        cell_seg_start (N_cells,) int32  -- first segment index for this cell
        cell_seg_count (N_cells,) int16  -- number of segments for this cell

    The per-cell index is maintained lazily and rebuilt on demand via
    :meth:`_rebuild_cell_index`.

    Free-list management
    --------------------
    Freed segment slots are pushed to ``seg_free_list`` (LIFO).
    Freed synapse ranges are pushed to ``syn_free_ranges`` (coalesced on compaction).
    When fragmentation exceeds ``compaction_threshold``, :meth:`compact` defragments
    both arrays in O(num_live_synapses).
    """

    def __init__(self, config: TMConfig, device: Optional[torch.device] = None) -> None:
        self.config = config
        self.device = device or torch.device("cpu")
        S = config.max_total_segments
        M = config.max_total_synapses
        N = config.total_cells

        # --- Segment arrays ---
        self.seg_cell = torch.zeros(S, dtype=torch.int32, device=self.device)
        self.seg_start = torch.zeros(S, dtype=torch.int32, device=self.device)
        self.seg_len = torch.zeros(S, dtype=torch.int16, device=self.device)
        self.seg_alive = torch.zeros(S, dtype=torch.bool, device=self.device)

        # --- Synapse arrays ---
        self.syn_src_cell = torch.zeros(M, dtype=torch.int32, device=self.device)
        self.syn_perm = torch.zeros(M, dtype=torch.float32, device=self.device)

        # --- Per-cell index ---
        self.cell_seg_start = torch.zeros(N, dtype=torch.int32, device=self.device)
        self.cell_seg_count = torch.zeros(N, dtype=torch.int16, device=self.device)
        self._cell_index_dirty = True

        # --- Live counts ---
        self.num_segments: int = 0
        self.num_synapses: int = 0

        # --- Free lists ---
        self.seg_free_list: List[int] = []
        self.syn_free_ranges: List[Tuple[int, int]] = []  # (start, length)

        # --- Synapse write cursor (append position) ---
        self._syn_cursor: int = 0

        # --- Fragmentation tracking ---
        self._freed_synapse_count: int = 0

    # ----- helpers -----

    def _mark_cell_index_dirty(self) -> None:
        self._cell_index_dirty = True

    def _rebuild_cell_index(self) -> None:
        """Rebuild per-cell segment index from segment arrays."""
        if not self._cell_index_dirty:
            return
        N = self.config.total_cells
        self.cell_seg_count.zero_()

        alive_mask = self.seg_alive[: self._seg_capacity()]
        alive_indices = torch.where(alive_mask)[0]

        if alive_indices.numel() == 0:
            self.cell_seg_start.zero_()
            self._cell_index_dirty = False
            return

        cells = self.seg_cell[alive_indices]

        # Count segments per cell
        count = torch.zeros(N, dtype=torch.int16, device=self.device)
        for idx in alive_indices:
            c = self.seg_cell[idx].item()
            count[c] += 1
        self.cell_seg_count = count

        # Compute starts (prefix sum)
        starts = torch.zeros(N, dtype=torch.int32, device=self.device)
        starts[1:] = count[:-1].cumsum(0).to(torch.int32)
        self.cell_seg_start = starts

        self._cell_index_dirty = False

    def _seg_capacity(self) -> int:
        """Effective segment capacity (may be less than max during growth)."""
        return max(self.num_segments + len(self.seg_free_list), self.num_segments)

    def _alloc_segment_slot(self) -> int:
        """Return an available segment slot index, or -1 if full."""
        if self.seg_free_list:
            return self.seg_free_list.pop()
        # Append at end
        idx = 0
        # Find next available slot by scanning alive flags
        # Fast path: use a running max-index tracker
        all_alive = self.seg_alive[: self.config.max_total_segments]
        # Find first non-alive slot
        non_alive = torch.where(~all_alive)[0]
        if non_alive.numel() == 0:
            return -1  # full
        return non_alive[0].item()

    def _alloc_synapse_range(self, count: int) -> int:
        """Allocate a contiguous range of *count* synapse slots.

        Returns the start index, or -1 if no space.
        First tries the free-range list, then appends at cursor.
        """
        # Try free ranges (first-fit)
        for i, (start, length) in enumerate(self.syn_free_ranges):
            if length >= count:
                # Use this range
                if length == count:
                    self.syn_free_ranges.pop(i)
                else:
                    self.syn_free_ranges[i] = (start + count, length - count)
                self._freed_synapse_count -= count
                return start

        # Append at cursor
        if self._syn_cursor + count > self.config.max_total_synapses:
            return -1  # full
        start = self._syn_cursor
        self._syn_cursor += count
        return start

    # ----- public API -----

    def add_segment(
        self,
        cell_id: int,
        src_cells: Tensor,
        initial_perm: float,
    ) -> int:
        """Create a new segment on *cell_id* with synapses to *src_cells*.

        Args:
            cell_id:      Cell that owns this segment.
            src_cells:    (K,) int32 -- presynaptic cell ids.
            initial_perm: Initial permanence for all new synapses.

        Returns:
            Segment index (>= 0) on success, -1 if capacity exceeded.
        """
        # Check per-cell limit
        self._rebuild_cell_index()
        if self.cell_seg_count[cell_id].item() >= self.config.max_segments_per_cell:
            return -1

        seg_idx = self._alloc_segment_slot()
        if seg_idx < 0:
            return -1

        num_syn = min(src_cells.numel(), self.config.max_synapses_per_segment)
        if num_syn == 0:
            # Empty segment -- still valid, can grow later
            self.seg_cell[seg_idx] = cell_id
            self.seg_start[seg_idx] = 0
            self.seg_len[seg_idx] = 0
            self.seg_alive[seg_idx] = True
            self.num_segments += 1
            self._mark_cell_index_dirty()
            return seg_idx

        syn_start = self._alloc_synapse_range(num_syn)
        if syn_start < 0:
            return -1

        src = src_cells[:num_syn].to(dtype=torch.int32, device=self.device)
        self.syn_src_cell[syn_start : syn_start + num_syn] = src
        self.syn_perm[syn_start : syn_start + num_syn] = initial_perm

        self.seg_cell[seg_idx] = cell_id
        self.seg_start[seg_idx] = syn_start
        self.seg_len[seg_idx] = num_syn
        self.seg_alive[seg_idx] = True

        self.num_segments += 1
        self.num_synapses += num_syn
        self._mark_cell_index_dirty()
        return seg_idx

    def remove_segment(self, seg_idx: int) -> None:
        """Remove segment at *seg_idx*, freeing its synapse range."""
        if not self.seg_alive[seg_idx]:
            return
        length = int(self.seg_len[seg_idx].item())
        start = int(self.seg_start[seg_idx].item())

        if length > 0:
            self.syn_free_ranges.append((start, length))
            self._freed_synapse_count += length
            self.num_synapses -= length

        self.seg_alive[seg_idx] = False
        self.seg_len[seg_idx] = 0
        self.seg_free_list.append(seg_idx)
        self.num_segments -= 1
        self._mark_cell_index_dirty()

    def add_synapses(
        self,
        seg_idx: int,
        src_cells: Tensor,
        initial_perm: float,
    ) -> int:
        """Add synapses to an existing segment.

        If the segment's current contiguous range cannot grow (because the
        immediately-following slots are occupied), the segment is relocated
        to a new contiguous block.

        Args:
            seg_idx:      Segment to grow.
            src_cells:    (K,) int32 -- new presynaptic cell ids.
            initial_perm: Initial permanence for the new synapses.

        Returns:
            Number of synapses actually added.
        """
        if not self.seg_alive[seg_idx]:
            return 0

        old_start = int(self.seg_start[seg_idx].item())
        old_len = int(self.seg_len[seg_idx].item())
        space_left = self.config.max_synapses_per_segment - old_len
        num_add = min(src_cells.numel(), space_left)
        if num_add <= 0:
            return 0

        new_total = old_len + num_add

        # Try in-place extension: check if slots right after current range
        # are free (heuristic: if they are past the cursor, they are free)
        can_extend = (old_start + old_len == self._syn_cursor) or (old_len == 0)

        if can_extend and old_start + new_total <= self.config.max_total_synapses:
            # Extend in place
            ext_start = old_start + old_len
            src = src_cells[:num_add].to(dtype=torch.int32, device=self.device)
            self.syn_src_cell[ext_start : ext_start + num_add] = src
            self.syn_perm[ext_start : ext_start + num_add] = initial_perm
            self.seg_len[seg_idx] = new_total
            if old_start + new_total > self._syn_cursor:
                self._syn_cursor = old_start + new_total
            self.num_synapses += num_add
            return num_add

        # Relocate: allocate new range, copy old + append new
        new_start = self._alloc_synapse_range(new_total)
        if new_start < 0:
            return 0

        # Copy existing synapses
        if old_len > 0:
            self.syn_src_cell[new_start : new_start + old_len] = \
                self.syn_src_cell[old_start : old_start + old_len].clone()
            self.syn_perm[new_start : new_start + old_len] = \
                self.syn_perm[old_start : old_start + old_len].clone()
            # Free old range
            self.syn_free_ranges.append((old_start, old_len))
            self._freed_synapse_count += old_len

        # Append new
        src = src_cells[:num_add].to(dtype=torch.int32, device=self.device)
        self.syn_src_cell[new_start + old_len : new_start + new_total] = src
        self.syn_perm[new_start + old_len : new_start + new_total] = initial_perm

        self.seg_start[seg_idx] = new_start
        self.seg_len[seg_idx] = new_total
        self.num_synapses += num_add
        return num_add

    def remove_synapses(self, seg_idx: int, mask: Tensor) -> None:
        """Remove synapses where *mask* is True.

        The surviving synapses are compacted within the segment's range.

        Args:
            seg_idx: Segment to modify.
            mask:    (seg_len,) bool -- True for synapses to remove.
        """
        if not self.seg_alive[seg_idx]:
            return
        start = int(self.seg_start[seg_idx].item())
        length = int(self.seg_len[seg_idx].item())
        if length == 0:
            return

        keep = ~mask[:length]
        num_keep = keep.sum().item()
        num_removed = length - num_keep

        if num_removed == 0:
            return

        if num_keep == 0:
            # All synapses removed -- remove the whole segment
            self.remove_segment(seg_idx)
            return

        # Compact: move surviving synapses to front of range
        src_cells_kept = self.syn_src_cell[start : start + length][keep].clone()
        perm_kept = self.syn_perm[start : start + length][keep].clone()

        self.syn_src_cell[start : start + num_keep] = src_cells_kept
        self.syn_perm[start : start + num_keep] = perm_kept

        self.seg_len[seg_idx] = num_keep
        # The trailing slots [start+num_keep : start+length] are now garbage.
        # We track them as freed for fragmentation stats.
        freed_start = start + num_keep
        freed_len = num_removed
        self.syn_free_ranges.append((freed_start, freed_len))
        self._freed_synapse_count += freed_len
        self.num_synapses -= num_removed

    def get_segment_match_counts(
        self, active_cells_mask: Tensor
    ) -> Tensor:
        """Count connected active synapses per segment (vectorized).

        Args:
            active_cells_mask: (N_cells,) bool or float -- 1/True for active cells.

        Returns:
            (num_segments_alive,) int -- per-segment active-synapse counts.
            Also returns alive_indices: (num_segments_alive,) int for mapping.
        """
        alive_indices = torch.where(self.seg_alive[: self.config.max_total_segments])[0]
        num_alive = alive_indices.numel()
        if num_alive == 0:
            return torch.zeros(0, dtype=torch.int32, device=self.device), alive_indices

        starts = self.seg_start[alive_indices].long()
        lens = self.seg_len[alive_indices].long()
        total_syn = lens.sum().item()

        if total_syn == 0:
            return torch.zeros(num_alive, dtype=torch.int32, device=self.device), alive_indices

        # Build flat synapse index
        cumlen = torch.zeros(num_alive + 1, dtype=torch.long, device=self.device)
        cumlen[1:] = lens.cumsum(0)
        seg_ids = torch.repeat_interleave(
            torch.arange(num_alive, device=self.device, dtype=torch.long), lens
        )
        offsets = torch.arange(total_syn, device=self.device, dtype=torch.long)
        local_off = offsets - cumlen[seg_ids]
        global_idx = starts[seg_ids] + local_off

        # Lookup: is presynaptic cell active AND synapse connected?
        pre_cells = self.syn_src_cell[global_idx].long()
        perms = self.syn_perm[global_idx]

        is_active = active_cells_mask[pre_cells].float()
        is_connected = (perms >= self.config.connected_threshold).float()
        active_connected = is_active * is_connected

        # Scatter-add by segment
        counts = torch.zeros(num_alive, dtype=torch.float32, device=self.device)
        counts.scatter_add_(0, seg_ids, active_connected)
        return counts.to(torch.int32), alive_indices

    def get_matching_segment_counts(
        self, active_cells_mask: Tensor
    ) -> Tensor:
        """Like get_segment_match_counts but counts ALL synapses whose
        presynaptic cell is active (regardless of permanence >= connected).

        Used for the weaker "matching" check (min_threshold).

        Args:
            active_cells_mask: (N_cells,) bool or float.

        Returns:
            (num_segments_alive,) int, alive_indices
        """
        alive_indices = torch.where(self.seg_alive[: self.config.max_total_segments])[0]
        num_alive = alive_indices.numel()
        if num_alive == 0:
            return torch.zeros(0, dtype=torch.int32, device=self.device), alive_indices

        starts = self.seg_start[alive_indices].long()
        lens = self.seg_len[alive_indices].long()
        total_syn = lens.sum().item()
        if total_syn == 0:
            return torch.zeros(num_alive, dtype=torch.int32, device=self.device), alive_indices

        cumlen = torch.zeros(num_alive + 1, dtype=torch.long, device=self.device)
        cumlen[1:] = lens.cumsum(0)
        seg_ids = torch.repeat_interleave(
            torch.arange(num_alive, device=self.device, dtype=torch.long), lens
        )
        offsets = torch.arange(total_syn, device=self.device, dtype=torch.long)
        local_off = offsets - cumlen[seg_ids]
        global_idx = starts[seg_ids] + local_off

        pre_cells = self.syn_src_cell[global_idx].long()
        is_active = active_cells_mask[pre_cells].float()

        counts = torch.zeros(num_alive, dtype=torch.float32, device=self.device)
        counts.scatter_add_(0, seg_ids, is_active)
        return counts.to(torch.int32), alive_indices

    def get_best_matching_segment(
        self, cell_id: int, active_cells_mask: Tensor
    ) -> int:
        """Return the best matching segment for *cell_id*, or -1.

        "Best matching" = segment with the most active synapses (connected or
        not, using min_threshold semantics) among this cell's segments.

        Args:
            cell_id:          Cell to search.
            active_cells_mask: (N_cells,) bool/float.

        Returns:
            Segment index (into global seg_* arrays) or -1.
        """
        segs = self.get_segments_for_cell(cell_id)
        if not segs:
            return -1

        best_idx = -1
        best_count = -1

        for seg_idx in segs:
            start = int(self.seg_start[seg_idx].item())
            length = int(self.seg_len[seg_idx].item())
            if length == 0:
                continue
            pre_cells = self.syn_src_cell[start : start + length].long()
            # Count active presynaptic cells (all synapses, not just connected)
            count = active_cells_mask[pre_cells].sum().item()
            if count > best_count:
                best_count = count
                best_idx = seg_idx

        if best_count >= self.config.min_threshold:
            return best_idx
        return -1

    def get_segments_for_cell(self, cell_id: int) -> List[int]:
        """Return list of alive segment indices belonging to *cell_id*."""
        result: List[int] = []
        # Scan alive segments (linear, but bounded by num_segments)
        alive = torch.where(self.seg_alive[: self.config.max_total_segments])[0]
        for idx in alive:
            if self.seg_cell[idx].item() == cell_id:
                result.append(idx.item())
        return result

    def reinforce_segment(
        self,
        seg_idx: int,
        active_pre_mask: Tensor,
        perm_inc: float,
        perm_dec: float,
    ) -> None:
        """Reinforce a segment: inc permanence for active pre-cells, dec for inactive.

        Args:
            seg_idx:         Segment to reinforce.
            active_pre_mask: (N_cells,) bool/float -- presynaptic activity.
            perm_inc:        Permanence increment for active synapses.
            perm_dec:        Permanence decrement for inactive synapses.
        """
        if not self.seg_alive[seg_idx]:
            return
        start = int(self.seg_start[seg_idx].item())
        length = int(self.seg_len[seg_idx].item())
        if length == 0:
            return

        pre_cells = self.syn_src_cell[start : start + length].long()
        is_active = active_pre_mask[pre_cells].float()

        # Increment active, decrement inactive
        delta = is_active * perm_inc - (1.0 - is_active) * perm_dec
        self.syn_perm[start : start + length] = (
            self.syn_perm[start : start + length] + delta
        ).clamp(0.0, 1.0)

    def punish_segment(self, seg_idx: int, predicted_dec: float) -> None:
        """Punish a segment that made a false prediction.

        Decrements permanence of all connected synapses whose presynaptic
        cells were active (the signal that caused the false prediction).

        In simpler implementations, we just decrement all synapses.

        Args:
            seg_idx:       Segment to punish.
            predicted_dec: Permanence decrement amount.
        """
        if not self.seg_alive[seg_idx]:
            return
        start = int(self.seg_start[seg_idx].item())
        length = int(self.seg_len[seg_idx].item())
        if length == 0:
            return

        self.syn_perm[start : start + length] = (
            self.syn_perm[start : start + length] - predicted_dec
        ).clamp(0.0, 1.0)

    def prune_dead_synapses(self, threshold: float) -> int:
        """Remove synapses with permanence below *threshold* from all segments.

        Args:
            threshold: Permanence below which synapses are pruned.

        Returns:
            Total number of synapses pruned.
        """
        total_pruned = 0
        alive_indices = torch.where(self.seg_alive[: self.config.max_total_segments])[0]
        segments_to_remove: List[int] = []

        for seg_idx_t in alive_indices:
            seg_idx = seg_idx_t.item()
            start = int(self.seg_start[seg_idx].item())
            length = int(self.seg_len[seg_idx].item())
            if length == 0:
                continue

            perms = self.syn_perm[start : start + length]
            dead_mask = perms < threshold

            num_dead = dead_mask.sum().item()
            if num_dead == 0:
                continue

            if num_dead == length:
                # All synapses dead -- mark for removal
                segments_to_remove.append(seg_idx)
                total_pruned += length
                continue

            # Remove dead synapses in-place
            self.remove_synapses(seg_idx, dead_mask)
            total_pruned += num_dead

        for seg_idx in segments_to_remove:
            self.remove_segment(seg_idx)

        return total_pruned

    def compact(self) -> None:
        """Defragment synapse arrays by repacking all live segments contiguously.

        After compaction, ``_freed_synapse_count`` is 0 and ``syn_free_ranges``
        is empty.  This is O(num_live_synapses).
        """
        alive_indices = torch.where(self.seg_alive[: self.config.max_total_segments])[0]
        if alive_indices.numel() == 0:
            self._syn_cursor = 0
            self.syn_free_ranges.clear()
            self._freed_synapse_count = 0
            return

        cursor = 0
        for seg_idx_t in alive_indices:
            seg_idx = seg_idx_t.item()
            start = int(self.seg_start[seg_idx].item())
            length = int(self.seg_len[seg_idx].item())
            if length == 0:
                self.seg_start[seg_idx] = cursor
                continue

            if cursor != start:
                # Move synapse data
                self.syn_src_cell[cursor : cursor + length] = \
                    self.syn_src_cell[start : start + length].clone()
                self.syn_perm[cursor : cursor + length] = \
                    self.syn_perm[start : start + length].clone()
                self.seg_start[seg_idx] = cursor

            cursor += length

        self._syn_cursor = cursor
        self.syn_free_ranges.clear()
        self._freed_synapse_count = 0
        self._mark_cell_index_dirty()

    @property
    def fragmentation(self) -> float:
        """Fraction of allocated synapse space that is wasted (freed but not reclaimed)."""
        if self._syn_cursor == 0:
            return 0.0
        return self._freed_synapse_count / max(self._syn_cursor, 1)

    def get_stats(self) -> Dict[str, object]:
        """Return diagnostic statistics."""
        return {
            "num_segments": self.num_segments,
            "num_synapses": self.num_synapses,
            "avg_synapses_per_segment": (
                self.num_synapses / max(self.num_segments, 1)
            ),
            "fragmentation": self.fragmentation,
            "syn_cursor": self._syn_cursor,
            "seg_free_list_len": len(self.seg_free_list),
            "syn_free_ranges_len": len(self.syn_free_ranges),
            "memory_bytes_segments": (
                self.seg_cell.element_size() * self.seg_cell.numel()
                + self.seg_start.element_size() * self.seg_start.numel()
                + self.seg_len.element_size() * self.seg_len.numel()
                + self.seg_alive.element_size() * self.seg_alive.numel()
            ),
            "memory_bytes_synapses": (
                self.syn_src_cell.element_size() * self.syn_src_cell.numel()
                + self.syn_perm.element_size() * self.syn_perm.numel()
            ),
        }

    def state_dict(self) -> Dict[str, object]:
        """Serialize to a dictionary (for checkpointing)."""
        return {
            "seg_cell": self.seg_cell.cpu().clone(),
            "seg_start": self.seg_start.cpu().clone(),
            "seg_len": self.seg_len.cpu().clone(),
            "seg_alive": self.seg_alive.cpu().clone(),
            "syn_src_cell": self.syn_src_cell.cpu().clone(),
            "syn_perm": self.syn_perm.cpu().clone(),
            "cell_seg_start": self.cell_seg_start.cpu().clone(),
            "cell_seg_count": self.cell_seg_count.cpu().clone(),
            "num_segments": self.num_segments,
            "num_synapses": self.num_synapses,
            "seg_free_list": list(self.seg_free_list),
            "syn_free_ranges": list(self.syn_free_ranges),
            "syn_cursor": self._syn_cursor,
            "freed_synapse_count": self._freed_synapse_count,
        }

    def load_state_dict(self, state: Dict[str, object]) -> None:
        """Restore from a dictionary produced by :meth:`state_dict`."""
        self.seg_cell = state["seg_cell"].to(self.device)
        self.seg_start = state["seg_start"].to(self.device)
        self.seg_len = state["seg_len"].to(self.device)
        self.seg_alive = state["seg_alive"].to(self.device)
        self.syn_src_cell = state["syn_src_cell"].to(self.device)
        self.syn_perm = state["syn_perm"].to(self.device)
        self.cell_seg_start = state["cell_seg_start"].to(self.device)
        self.cell_seg_count = state["cell_seg_count"].to(self.device)
        self.num_segments = state["num_segments"]
        self.num_synapses = state["num_synapses"]
        self.seg_free_list = list(state["seg_free_list"])
        self.syn_free_ranges = list(state["syn_free_ranges"])
        self._syn_cursor = state["syn_cursor"]
        self._freed_synapse_count = state["freed_synapse_count"]
        self._cell_index_dirty = True

    def to(self, device: torch.device) -> "SparseSegmentStore":
        """Move all tensors to *device*."""
        self.device = device
        self.seg_cell = self.seg_cell.to(device)
        self.seg_start = self.seg_start.to(device)
        self.seg_len = self.seg_len.to(device)
        self.seg_alive = self.seg_alive.to(device)
        self.syn_src_cell = self.syn_src_cell.to(device)
        self.syn_perm = self.syn_perm.to(device)
        self.cell_seg_start = self.cell_seg_start.to(device)
        self.cell_seg_count = self.cell_seg_count.to(device)
        return self


