    last_epoch_anomalies = []

    for epoch in range(30):
        tm.reset(device=device)
        epoch_anom = []
        for step_cols in seq_cols:
            out = tm.step(step_cols, learn=True)
            epoch_anom.append(out.anomaly_score.item())
        if epoch == 0:
            first_epoch_anomalies = epoch_anom[1:]  # skip first (always anomalous)
        if epoch == 29:
            last_epoch_anomalies = epoch_anom[1:]

