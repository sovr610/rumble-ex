@dataclass
class TMConfig:
    """Configuration for the CSR-backed Temporal Memory.

    All counts use HTM-standard defaults (Numenta white-paper values).
    Capacity fields (max_total_*) should be sized for your deployment target;
    the defaults are generous for a single-column-count = 2048 setting.
    """

    # --- Column / cell geometry ---
    column_count: int = 2048
    cells_per_column: int = 32
    num_active_columns: int = 41  # K -- active columns per SDR

    # --- Segment activation ---
    activation_threshold: int = 13   # min active synapses for segment to fire
    min_threshold: int = 10          # weaker match threshold for learning
    max_new_synapses: int = 20       # synapses sampled when creating segment
    max_synapses_per_segment: int = 255
    max_segments_per_cell: int = 128

    # --- Permanence ---
    initial_permanence: float = 0.21
    connected_threshold: float = 0.5   # synapse "connected" above this
    perm_inc: float = 0.1
    perm_dec: float = 0.1
    predicted_dec: float = 0.05        # punishment for false predictions
    prune_threshold: float = 0.01      # remove synapses below this

    # --- Capacity ---
    max_total_segments: int = 100_000
    max_total_synapses: int = 2_000_000

    # --- Compaction ---
    compaction_threshold: float = 0.3  # compact when fragmentation > 30%

    # --- Misc ---
    seed: int = 42

    def __post_init__(self) -> None:
        """Validate configuration invariants."""
        if self.column_count <= 0:
            raise ValueError(f"column_count must be > 0, got {self.column_count}")
        if self.cells_per_column <= 0:
            raise ValueError(f"cells_per_column must be > 0, got {self.cells_per_column}")
        if self.num_active_columns <= 0:
            raise ValueError(f"num_active_columns must be > 0, got {self.num_active_columns}")
        if self.num_active_columns > self.column_count:
            raise ValueError(
                f"num_active_columns ({self.num_active_columns}) "
                f"> column_count ({self.column_count})"
            )
        if self.activation_threshold <= 0:
            raise ValueError(
                f"activation_threshold must be > 0, got {self.activation_threshold}"
            )
        if self.min_threshold <= 0:
            raise ValueError(f"min_threshold must be > 0, got {self.min_threshold}")
        if self.min_threshold > self.activation_threshold:
            raise ValueError(
                f"min_threshold ({self.min_threshold}) must be "
                f"<= activation_threshold ({self.activation_threshold})"
            )
        if not (0.0 < self.connected_threshold < 1.0):
            raise ValueError(
                f"connected_threshold must be in (0, 1), got {self.connected_threshold}"
            )
        if self.initial_permanence < 0.0 or self.initial_permanence > 1.0:
            raise ValueError(
                f"initial_permanence must be in [0, 1], got {self.initial_permanence}"
            )
        if self.max_total_segments <= 0:
            raise ValueError(
                f"max_total_segments must be > 0, got {self.max_total_segments}"
            )
        if self.max_total_synapses <= 0:
            raise ValueError(
                f"max_total_synapses must be > 0, got {self.max_total_synapses}"
            )
        if not (0.0 < self.compaction_threshold <= 1.0):
            raise ValueError(
                f"compaction_threshold must be in (0, 1], got {self.compaction_threshold}"
            )

    @property
    def total_cells(self) -> int:
        """Total number of cells across all columns."""
        return self.column_count * self.cells_per_column


