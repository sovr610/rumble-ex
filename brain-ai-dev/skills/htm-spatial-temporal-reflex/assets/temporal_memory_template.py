class TemporalMemory(nn.Module):
    """HTM Temporal Memory with CSR-style segment storage.

    Learns sequence transitions between Sparse Distributed Representations
    via cells-in-columns and dendritic segments.  All learning is Hebbian
    (local, no backprop, no optimizer).

    Typical usage::

        cfg = TMConfig(column_count=2048, cells_per_column=32)
        tm = TemporalMemory(cfg)
        tm.reset(batch_size=1, device=torch.device("cpu"))

        for sdr in sdr_stream:
            out = tm.step(sdr, learn=True)
            print(out.anomaly_score, out.pred_sdr)

    Args:
        config: :class:`TMConfig` with all hyperparameters.
    """

    def __init__(self, config: TMConfig) -> None:
        super().__init__()
        self.config = config
        self.N_cells = config.total_cells

        # Segment store (plain class, not nn.Module)
        self.store = SparseSegmentStore(config)

        # Per-step state (registered as buffers for device tracking)
        self.register_buffer("_active_cells", torch.zeros(0, dtype=torch.int32))
        self.register_buffer("_winner_cells", torch.zeros(0, dtype=torch.int32))
        self.register_buffer("_predictive_cells", torch.zeros(0, dtype=torch.int32))
        self.register_buffer("_prev_active_cells", torch.zeros(0, dtype=torch.int32))
        self.register_buffer("_prev_winner_cells", torch.zeros(0, dtype=torch.int32))
        self.register_buffer("_step_count", torch.tensor(0, dtype=torch.long))

        # Active/predictive cells as dense mask (for vectorized matching)
        self.register_buffer(
            "_active_mask", torch.zeros(self.N_cells, dtype=torch.float32)
        )
        self.register_buffer(
            "_prev_active_mask", torch.zeros(self.N_cells, dtype=torch.float32)
        )

        # Anomaly likelihood tracker
        self._anomaly_tracker = AnomalyLikelihood()

        # RNG for segment creation
        self._rng = torch.Generator()
        self._rng.manual_seed(config.seed)

    # ----- addressing helpers -----

    def _cell_to_column(self, cell_id: int) -> int:
        """Map cell_id -> column_id."""
        return cell_id // self.config.cells_per_column

    def _column_to_cells(self, column_id: int) -> Tuple[int, int]:
        """Map column_id -> (start_cell, end_cell) half-open range."""
        start = column_id * self.config.cells_per_column
        return start, start + self.config.cells_per_column

    def _column_to_cells_tensor(self, column_id: int) -> Tensor:
        """Return (cells_per_column,) int tensor of cell ids for a column."""
        start = column_id * self.config.cells_per_column
        return torch.arange(
            start,
            start + self.config.cells_per_column,
            dtype=torch.int32,
            device=self._active_mask.device,
        )

    # ----- reset -----

    def reset(
        self, batch_size: int = 1, device: Optional[torch.device] = None
    ) -> None:
        """Reset per-step state.  Segments/synapses are **not** cleared.

        Call this at the start of a new sequence.  The segment store persists
        across resets so that learned sequences are retained.

        Args:
            batch_size: Ignored in current single-batch implementation (kept
                        for API compatibility).
            device:     Move store tensors to this device if given.
        """
        if device is not None:
            self.store.to(device)
            # Move buffers
            self._active_mask = self._active_mask.to(device)
            self._prev_active_mask = self._prev_active_mask.to(device)

        dev = self._active_mask.device
        self._active_cells = torch.zeros(0, dtype=torch.int32, device=dev)
        self._winner_cells = torch.zeros(0, dtype=torch.int32, device=dev)
        self._predictive_cells = torch.zeros(0, dtype=torch.int32, device=dev)
        self._prev_active_cells = torch.zeros(0, dtype=torch.int32, device=dev)
        self._prev_winner_cells = torch.zeros(0, dtype=torch.int32, device=dev)
        self._active_mask.zero_()
        self._prev_active_mask.zero_()

    # ----- core compute phases -----

    @torch.no_grad()
    def _compute_active_cells(
        self, active_columns: Tensor
    ) -> Tuple[Tensor, Tensor, int]:
        """Compute active_cells and winner_cells from active columns.

        For **predicted** columns (any cell in the column is in
        ``_predictive_cells``): activate only predicted cells.

        For **unpredicted** (bursting) columns: activate ALL cells in
        the column; pick a winner based on best matching segment (or
        least-used cell if no segments match).

        Args:
            active_columns: (K,) int -- indices of active columns.

        Returns:
            active_cells:  (A,) int32 -- all cells that fire this step.
            winner_cells:  (W,) int32 -- one winner per active column.
            burst_count:   int -- number of columns that bursted.
        """
        device = active_columns.device
        predictive_set = set(self._predictive_cells.tolist())
        prev_active_mask = self._prev_active_mask

        active_list: List[int] = []
        winner_list: List[int] = []
        burst_count = 0

        for col in active_columns.tolist():
            col = int(col)
            start, end = self._column_to_cells(col)
            col_cells = list(range(start, end))

            # Which cells in this column are predicted?
            predicted_in_col = [c for c in col_cells if c in predictive_set]

            if predicted_in_col:
                # Predicted column: activate only predicted cells
                active_list.extend(predicted_in_col)
                winner_list.extend(predicted_in_col)
            else:
                # Bursting: activate all cells
                burst_count += 1
                active_list.extend(col_cells)

                # Pick winner: cell with best matching segment
                best_cell = col_cells[0]
                best_match = -1
                for c in col_cells:
                    seg_idx = self.store.get_best_matching_segment(c, prev_active_mask)
                    if seg_idx >= 0:
                        s = int(self.store.seg_start[seg_idx].item())
                        l = int(self.store.seg_len[seg_idx].item())
                        if l > 0:
                            pre = self.store.syn_src_cell[s : s + l].long()
                            match = prev_active_mask[pre].sum().item()
                            if match > best_match:
                                best_match = match
                                best_cell = c
                winner_list.append(best_cell)

        active_cells = torch.tensor(active_list, dtype=torch.int32, device=device)
        winner_cells = torch.tensor(winner_list, dtype=torch.int32, device=device)
        return active_cells, winner_cells, burst_count

    @torch.no_grad()
    def _compute_predictive_cells(self, active_cells: Tensor) -> Tensor:
        """Find cells with segments that match current activity.

        A cell is predictive if it has at least one segment with
        ``>= activation_threshold`` connected active synapses.

        Uses vectorized segment matching from :class:`SparseSegmentStore`.

        Args:
            active_cells: (A,) int32 -- currently active cells.

        Returns:
            predictive_cells: (P,) int32 -- cells predicted for next step.
        """
        device = active_cells.device
        # Build dense active mask
        active_mask = torch.zeros(self.N_cells, dtype=torch.float32, device=device)
        if active_cells.numel() > 0:
            active_mask[active_cells.long()] = 1.0

        counts, alive_indices = self.store.get_segment_match_counts(active_mask)
        if counts.numel() == 0:
            return torch.zeros(0, dtype=torch.int32, device=device)

        # Segments meeting activation threshold
        meeting = counts >= self.config.activation_threshold
        if not meeting.any():
            return torch.zeros(0, dtype=torch.int32, device=device)

        seg_indices = alive_indices[meeting]
        pred_cell_ids = self.store.seg_cell[seg_indices].to(torch.int32)
        # Unique cell ids
        pred_cell_ids = torch.unique(pred_cell_ids)
        return pred_cell_ids

    @torch.no_grad()
    def _learn(
        self,
        active_columns: Tensor,
        burst_columns: Tensor,
        prev_active_cells: Tensor,
        prev_winner_cells: Tensor,
    ) -> None:
        """Apply Hebbian learning rules.

        Three learning phases:

        1. **Correctly predicted columns**: For each winner cell in a
           correctly-predicted column, reinforce the segment that caused
           the prediction (strengthen active-pre synapses, weaken inactive).
           Grow new synapses to previously-active cells if needed.

        2. **Bursting columns**: For each winner cell in a bursting column,
           find the best matching segment or create a new one.  Connect
           synapses to previous winner cells.

        3. **False predictions**: For cells that were predicted but whose
           column was NOT active, punish the segments that caused the
           false prediction.

        Args:
            active_columns:    (K,) int -- active column indices.
            burst_columns:     (B_count,) int -- columns that bursted.
            prev_active_cells: (A_prev,) int32 -- active cells from prev step.
            prev_winner_cells: (W_prev,) int32 -- winner cells from prev step.
        """
        if prev_active_cells.numel() == 0 and prev_winner_cells.numel() == 0:
            return

        device = active_columns.device
        prev_active_mask = torch.zeros(
            self.N_cells, dtype=torch.float32, device=device
        )
        if prev_active_cells.numel() > 0:
            prev_active_mask[prev_active_cells.long()] = 1.0

        active_col_set = set(active_columns.tolist())
        burst_col_set = set(burst_columns.tolist())
        predicted_col_set = active_col_set - burst_col_set  # correctly predicted

        # ---- Phase 1: reinforce correctly predicted columns ----
        for col in predicted_col_set:
            col = int(col)
            start, end = self._column_to_cells(col)
            for cell_id in range(start, end):
                # Only reinforce winner cells (cells that were predicted)
                if cell_id not in set(self._winner_cells.tolist()):
                    continue
                segs = self.store.get_segments_for_cell(cell_id)
                if not segs:
                    continue
                # Find the segment that caused prediction (best active match)
                best_seg = -1
                best_count = -1
                for seg_idx in segs:
                    s = int(self.store.seg_start[seg_idx].item())
                    l = int(self.store.seg_len[seg_idx].item())
                    if l == 0:
                        continue
                    pre = self.store.syn_src_cell[s : s + l].long()
                    perms = self.store.syn_perm[s : s + l]
                    connected = perms >= self.config.connected_threshold
                    count = (
                        prev_active_mask[pre] * connected.float()
                    ).sum().item()
                    if count > best_count:
                        best_count = count
                        best_seg = seg_idx
                if best_seg >= 0:
                    self.store.reinforce_segment(
                        best_seg, prev_active_mask,
                        self.config.perm_inc, self.config.perm_dec,
                    )
                    # Grow new synapses to previously active cells not yet synapsed
                    self._grow_synapses(best_seg, prev_winner_cells)

        # ---- Phase 2: learn on bursting columns ----
        for col in burst_col_set:
            col = int(col)
            start, end = self._column_to_cells(col)
            # Find the winner cell for this column
            winner_cells_set = set(self._winner_cells.tolist())
            for cell_id in range(start, end):
                if cell_id not in winner_cells_set:
                    continue
                # Try to find a matching segment
                best_seg = self.store.get_best_matching_segment(
                    cell_id, prev_active_mask
                )
                if best_seg >= 0:
                    # Reinforce existing segment
                    self.store.reinforce_segment(
                        best_seg, prev_active_mask,
                        self.config.perm_inc, self.config.perm_dec,
                    )
                    self._grow_synapses(best_seg, prev_winner_cells)
                else:
                    # Create new segment
                    self._create_segment(cell_id, prev_winner_cells)

        # ---- Phase 3: punish false predictions ----
        for cell_id in self._predictive_cells.tolist():
            cell_id = int(cell_id)
            col = self._cell_to_column(cell_id)
            if col in active_col_set:
                continue  # correctly predicted, already handled
            # This cell predicted but its column was not active
            segs = self.store.get_segments_for_cell(cell_id)
            for seg_idx in segs:
                self.store.punish_segment(seg_idx, self.config.predicted_dec)

        # ---- Periodic maintenance ----
        step = self._step_count.item()
        if step > 0 and step % 100 == 0:
            self.store.prune_dead_synapses(self.config.prune_threshold)
        if self.store.fragmentation > self.config.compaction_threshold:
            self.store.compact()

    @torch.no_grad()
    def _grow_synapses(self, seg_idx: int, candidate_cells: Tensor) -> None:
        """Grow new synapses on *seg_idx* to cells in *candidate_cells*
        that are not already synapsed.

        Samples up to ``max_new_synapses`` from the candidates.
        """
        if candidate_cells.numel() == 0:
            return

        start = int(self.store.seg_start[seg_idx].item())
        length = int(self.store.seg_len[seg_idx].item())

        # Current presynaptic cells
        if length > 0:
            existing = set(self.store.syn_src_cell[start : start + length].tolist())
        else:
            existing = set()

        # Filter candidates
        candidates = [
            c for c in candidate_cells.tolist() if int(c) not in existing
        ]
        if not candidates:
            return

        space = self.config.max_synapses_per_segment - length
        num_to_add = min(len(candidates), self.config.max_new_synapses, space)
        if num_to_add <= 0:
            return

        # Random sample
        perm = torch.randperm(len(candidates), generator=self._rng)[:num_to_add]
        selected = torch.tensor(
            [candidates[i] for i in perm.tolist()],
            dtype=torch.int32,
            device=self.store.device,
        )
        self.store.add_synapses(seg_idx, selected, self.config.initial_permanence)

    @torch.no_grad()
    def _create_segment(self, cell_id: int, candidate_cells: Tensor) -> int:
        """Create a new segment on *cell_id* connected to a sample of
        *candidate_cells*.

        Returns:
            Segment index, or -1 if capacity exceeded.
        """
        if candidate_cells.numel() == 0:
            return -1

        num_syn = min(candidate_cells.numel(), self.config.max_new_synapses)
        perm = torch.randperm(candidate_cells.numel(), generator=self._rng)[:num_syn]
        src_cells = candidate_cells[perm].to(torch.int32)

        seg_idx = self.store.add_segment(
            cell_id, src_cells, self.config.initial_permanence
        )
        return seg_idx

    # ----- anomaly -----

    @torch.no_grad()
    def _compute_anomaly(
        self, active_columns: Tensor, predicted_columns: Tensor
    ) -> Tensor:
        """Compute raw anomaly score.

        anomaly = 1 - |predicted intersection active| / |active|

        Args:
            active_columns:    (K,) int -- active column indices.
            predicted_columns: (K_pred,) int -- predicted column indices.

        Returns:
            (1,) float in [0, 1].
        """
        if active_columns.numel() == 0:
            return torch.tensor([1.0], device=active_columns.device)
        if predicted_columns.numel() == 0:
            return torch.tensor([1.0], device=active_columns.device)

        active_set = set(active_columns.tolist())
        pred_set = set(predicted_columns.tolist())
        overlap = len(active_set & pred_set)
        anomaly = 1.0 - overlap / len(active_set)
        return torch.tensor(
            [max(0.0, min(1.0, anomaly))], device=active_columns.device
        )

    def _predictive_cells_to_columns(self, predictive_cells: Tensor) -> Tensor:
        """Convert predictive cell ids to unique predicted column ids.

        Args:
            predictive_cells: (P,) int32.

        Returns:
            (K_pred,) int64 -- unique predicted column indices.
        """
        if predictive_cells.numel() == 0:
            return torch.zeros(0, dtype=torch.int64, device=predictive_cells.device)
        cols = (predictive_cells.long() // self.config.cells_per_column)
        return torch.unique(cols)

    # ----- main step -----

    @torch.no_grad()
    def step(self, active_columns: Tensor, learn: bool = True) -> SequenceOutput:
        """Process one timestep of the temporal memory.

        This is the main entry point.  Call once per SDR from the Spatial
        Pooler.

        Args:
            active_columns: (K,) int -- indices of active columns from SP.
                            For batch processing, call step() in a loop
                            (HTM is inherently online / sequential).
            learn:          Whether to apply Hebbian learning rules.

        Returns:
            :class:`SequenceOutput` with sdr, pred_sdr, anomaly_score, aux.
        """
        device = active_columns.device
        self._step_count += 1

        # Ensure active_columns is 1D int
        active_columns = active_columns.to(dtype=torch.int64, device=device).flatten()
        K = active_columns.numel()

        # Save previous state
        self._prev_active_cells = self._active_cells.clone()
        self._prev_winner_cells = self._winner_cells.clone()
        self._prev_active_mask = self._active_mask.clone()

        # 1. Compute active/winner cells from active columns + predictions
        active_cells, winner_cells, burst_count = self._compute_active_cells(
            active_columns
        )

        # 2. Compute anomaly BEFORE updating predictions (use current predictions)
        predicted_columns = self._predictive_cells_to_columns(self._predictive_cells)
        anomaly_raw = self._compute_anomaly(active_columns, predicted_columns)

        # 3. Determine burst columns for learning
        burst_columns_list: List[int] = []
        pred_col_set = set(predicted_columns.tolist())
        for col in active_columns.tolist():
            if int(col) not in pred_col_set:
                burst_columns_list.append(int(col))
        burst_columns = torch.tensor(
            burst_columns_list, dtype=torch.int64, device=device
        )

        # 4. Learn from activation patterns
        if learn:
            self._learn(
                active_columns, burst_columns,
                self._prev_active_cells, self._prev_winner_cells,
            )

        # 5. Update active mask
        self._active_mask.zero_()
        if active_cells.numel() > 0:
            self._active_mask[active_cells.long()] = 1.0

        # 6. Compute new predictive cells for next step
        new_predictive = self._compute_predictive_cells(active_cells)

        # 7. Store state
        self._active_cells = active_cells
        self._winner_cells = winner_cells
        self._predictive_cells = new_predictive

        # 8. Build output
        pred_columns = self._predictive_cells_to_columns(new_predictive)
        anomaly_score = anomaly_raw.squeeze()

        # Pad sdr and pred_sdr to consistent shape (K, K_pred)
        sdr = active_columns.unsqueeze(0)  # (1, K)
        if pred_columns.numel() > 0:
            pred_sdr = pred_columns.unsqueeze(0)  # (1, K_pred)
        else:
            pred_sdr = torch.zeros(1, 0, dtype=torch.int64, device=device)

        anomaly_score = anomaly_score.unsqueeze(0)  # (1,)

        return SequenceOutput(
            sdr=sdr,
            pred_sdr=pred_sdr,
            anomaly_score=anomaly_score,
            aux={
                "burst_count": burst_count,
                "overlap": int(K) - burst_count,
                "active_cells_count": active_cells.numel(),
                "winner_cells_count": winner_cells.numel(),
                "predictive_cells_count": new_predictive.numel(),
                "segment_stats": self.store.get_stats(),
                "anomaly_likelihood": self._anomaly_tracker.compute(
                    anomaly_score.item()
                ),
            },
        )

    @torch.no_grad()
    def predict(
        self, active_columns_seq: List[Tensor], learn: bool = True
    ) -> List[SequenceOutput]:
        """Process a sequence of SDRs, returning SequenceOutput per step.

        Convenience wrapper around :meth:`step` for multi-step sequences.

        Args:
            active_columns_seq: List of (K,) int tensors, one per timestep.
            learn: Whether to learn.

        Returns:
            List of SequenceOutput, one per timestep.
        """
        outputs: List[SequenceOutput] = []
        for ac in active_columns_seq:
            out = self.step(ac, learn=learn)
            outputs.append(out)
        return outputs

    def get_memory_stats(self) -> Dict[str, object]:
        """Return combined memory statistics.

        Returns:
            Dictionary with: num_segments, num_synapses,
            avg_synapses_per_segment, fragmentation, memory_bytes,
            step_count, predictive_cells_count.
        """
        stats = self.store.get_stats()
        seg_bytes = stats["memory_bytes_segments"]
        syn_bytes = stats["memory_bytes_synapses"]
        mask_bytes = self._active_mask.element_size() * self._active_mask.numel() * 2
        stats["memory_bytes"] = seg_bytes + syn_bytes + mask_bytes
        stats["step_count"] = self._step_count.item()
        stats["predictive_cells_count"] = self._predictive_cells.numel()
        return stats

    def extra_repr(self) -> str:
        return (
            f"columns={self.config.column_count}, "
            f"cells_per_col={self.config.cells_per_column}, "
            f"total_cells={self.N_cells}, "
            f"segments={self.store.num_segments}, "
            f"synapses={self.store.num_synapses}"
        )


