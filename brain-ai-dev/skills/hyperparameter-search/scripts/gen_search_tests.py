def generate_test_file(filename: str = "test_hyperparameter_search.py") -> str:
    """Generate the complete test file as a string."""
    sections = []
    sections.append(HEADER.format(filename=filename))
    sections.extend(_search_engine_tests())
    sections.extend(_search_space_tests())
    sections.extend(_lr_finder_tests())
    sections.extend(_trial_manager_tests())
    sections.extend(_early_stopping_tests())
    sections.extend(_config_tests())
    return "\n".join(sections)


def count_tests(content: str) -> int:
    """Count test functions in generated content."""
    return content.count("\n    def test_")


def main():
    parser = argparse.ArgumentParser(description="Generate pytest test cases for HPO")
    parser.add_argument("-o", "--output", type=str, default=None,
                        help="Output file path (default: stdout)")
    parser.add_argument("--count", action="store_true",
                        help="Just print the test count")
    args = parser.parse_args()

    content = generate_test_file(
        filename=os.path.basename(args.output) if args.output else "test_hyperparameter_search.py"
    )
    n = count_tests(content)

    if args.count:
        print(f"Generated {n} test cases")
        return

    if args.output:
        Path(args.output).parent.mkdir(parents=True, exist_ok=True)
        with open(args.output, "w") as f:
            f.write(content)
        print(f"Wrote {n} test cases to {args.output}")
    else:
        print(content)
        print(f"\n# --- Generated {n} test cases ---", file=sys.stderr)


if __name__ == "__main__":
    main()
