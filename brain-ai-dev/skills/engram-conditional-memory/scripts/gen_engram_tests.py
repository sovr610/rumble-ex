# ---------------------------------------------------------------------------
# Verification
# ---------------------------------------------------------------------------

def _verify(code: str) -> bool:
    """Check generated code with ast.parse to ensure syntax validity.

    Returns True on success, prints diagnostic and returns False on failure.
    """
    try:
        ast.parse(code, filename="<generated test_engram.py>")
        return True
    except SyntaxError as exc:
        lines = code.splitlines()
        lineno = exc.lineno or 0
        start = max(0, lineno - 5)
        end = min(len(lines), lineno + 5)
        context = "\n".join(
            (">>> " if i + 1 == lineno else "    ")
            + f"{i + 1:4d} | {lines[i]}"
            for i in range(start, end)
        )
        print(
            f"ERROR: Generated code has a syntax error at line {lineno}:\n"
            f"  {exc.msg}\n\n{context}\n",
            file=sys.stderr,
        )
        return False


# ---------------------------------------------------------------------------
# Test counting
# ---------------------------------------------------------------------------

def _count_tests(code: str) -> tuple:
    """Count test classes and test methods in the generated code.

    Returns (num_classes, num_tests).
    """
    tree = ast.parse(code)
    num_classes = 0
    num_tests = 0

    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name.startswith("Test"):
            num_classes += 1
            for item in node.body:
                if isinstance(item, ast.FunctionDef) and item.name.startswith("test_"):
                    num_tests += 1

    return num_classes, num_tests


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Generate comprehensive Engram Conditional Memory test suite. "
            "Output goes to stdout by default."
        ),
    )
    parser.add_argument(
        "--output", "-o",
        type=str,
        default=None,
        help="Write to this file instead of stdout.",
    )
    args = parser.parse_args()

    code = _assemble()

    if not _verify(code):
        return 1

    num_classes, num_tests = _count_tests(code)

    if args.output:
        with open(args.output, "w", encoding="utf-8") as fh:
            fh.write(code)
        print(
            f"Wrote {len(code):,} bytes to {args.output}",
            file=sys.stderr,
        )
    else:
        sys.stdout.write(code)

    print(
        f"\nSummary:\n"
        f"  Test classes: {num_classes}\n"
        f"  Total tests:  {num_tests}\n"
        f"  File size:    {len(code):,} bytes ({len(code.splitlines()):,} lines)\n",
        file=sys.stderr,
    )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
