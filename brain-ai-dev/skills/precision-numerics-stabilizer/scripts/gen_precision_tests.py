    def test_loss_spike_detection(self):
        """P5-T2: is_spike returns True for 4x jump with spike_pct=200."""
        detector = LossSpikeDetector(window=30, spike_pct=200.0, min_samples=5)
        for _ in range(20):
            detector.is_spike(1.0)
        assert detector.is_spike(4.0) is True  # 4.0 > 3.0 * 1.0

    def test_spike_threshold_boundary(self):
        """P5-T3: Exactly at threshold does not trigger spike (strictly greater)."""
        detector = LossSpikeDetector(window=30, spike_pct=200.0, min_samples=5)
        for _ in range(20):
            detector.is_spike(1.0)
        # Exactly 3.0 with spike_pct=200 -> threshold = 1.0 * 3.0 = 3.0
        # 3.0 is NOT strictly > 3.0
        assert detector.is_spike(3.0) is False

