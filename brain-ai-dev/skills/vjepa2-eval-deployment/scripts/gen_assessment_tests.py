def count_tests(content: str) -> int:
    return content.count("    def test_")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Generate 100+ pytest tests for V-JEPA 2 assessment"
    )
    p.add_argument(
        "--output", "-o", type=str, default=None,
        help="Output directory for test files (default: print to stdout)."
    )
    p.add_argument(
        "--run", action="store_true",
        help="Run the generated tests with pytest after writing them."
    )
    p.add_argument(
        "--verbose", "-v", action="store_true",
        help="Verbose pytest output."
    )
    return p.parse_args()


def main() -> int:
    args = parse_args()

    total_tests = sum(count_tests(c) for c in TEST_FILES.values())
    print(f"V-JEPA 2 Assessment Test Generator")
    print(f"Test files: {len(TEST_FILES)}")
    print(f"Total test methods: {total_tests}")

    if args.output is None:
        # Print to stdout
        for filename, content in TEST_FILES.items():
            n = count_tests(content)
            print(f"\n{'=' * 70}")
            print(f"# {filename}  ({n} tests)")
            print("=" * 70)
            print(content)
        return 0

    # Write to output directory
    output_dir = Path(args.output)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Write conftest.py
    conftest_path = output_dir / "conftest.py"
    conftest_path.write_text(CONFTEST)
    print(f"  Written: {conftest_path}")

    for filename, content in TEST_FILES.items():
        path = output_dir / filename
        path.write_text(content)
        n = count_tests(content)
        print(f"  Written: {path}  ({n} tests)")

    print(f"\nTotal: {total_tests} test methods across {len(TEST_FILES)} files.")
    print(f"Run with: python -m pytest {output_dir}/ -v")

    if args.run:
        cmd = [sys.executable, "-m", "pytest", str(output_dir)]
        if args.verbose:
            cmd.append("-v")
        print(f"\nRunning: {' '.join(cmd)}")
        result = subprocess.run(cmd)
        return result.returncode

    return 0


if __name__ == "__main__":
    sys.exit(main())
