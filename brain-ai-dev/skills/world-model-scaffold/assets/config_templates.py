def generate_hardware_config(
    device: str = "cuda",
    dtype: str = "float32",
    distributed_strategy: str = "none",
    num_gpus: int = 1,
    compile_enabled: bool = False,
) -> str:
    """Generate YAML content for hardware.yaml.

    Parameters
    ----------
    device : str
        Compute device: cpu, cuda, cuda:0, etc.
    dtype : str
        Default tensor dtype: float32, float16, bfloat16.
    distributed_strategy : str
        Distributed training: none, ddp, fsdp, deepspeed.
    num_gpus : int
        Number of GPUs for distributed training.
    compile_enabled : bool
        Whether to enable torch.compile.

    Returns
    -------
    str
        Valid YAML string.
    """
    return f"""# Hardware and device configuration
# Generated by world-model-scaffold

device: {device}

precision:
  dtype: {dtype}
  amp: false
  amp_dtype: float16

distributed:
  strategy: {distributed_strategy}
  num_gpus: {num_gpus}
  backend: nccl
  find_unused_parameters: false

compile:
  enabled: {str(compile_enabled).lower()}
  mode: default
  fullgraph: false
  dynamic: false

memory:
  gradient_checkpointing: false
  pin_memory: true
  empty_cache_every: 0

performance:
  cudnn_benchmark: true
  tf32: true
  deterministic: false
"""


# ---------------------------------------------------------------------------
# Writer
# ---------------------------------------------------------------------------


def write_configs(
    output_dir: str,
    encoder_type: str = "vit",
    encoder_embed_dim: int = 512,
    dynamics_type: str = "rssm",
    decoder_type: str = "conv",
    data_root: str = "/data/world_model_dataset",
    device: str = "cuda",
) -> None:
    """Write all four config YAML files to output_dir.

    Creates the output directory if it does not exist.

    Parameters
    ----------
    output_dir : str
        Directory in which to write model.yaml, training.yaml,
        dataset.yaml, and hardware.yaml.
    encoder_type : str
        Encoder registry key for model.yaml.
    encoder_embed_dim : int
        Shared embedding dimension for model.yaml.
    dynamics_type : str
        Dynamics registry key for model.yaml.
    decoder_type : str
        Decoder registry key for model.yaml.
    data_root : str
        Dataset root path for dataset.yaml.
    device : str
        Compute device for hardware.yaml.
    """
    Path(output_dir).mkdir(parents=True, exist_ok=True)

    files = {
        "model.yaml": generate_model_config(
            encoder_type=encoder_type,
            encoder_embed_dim=encoder_embed_dim,
            dynamics_type=dynamics_type,
            decoder_type=decoder_type,
        ),
        "training.yaml": generate_training_config(),
        "dataset.yaml": generate_dataset_config(data_root=data_root),
        "hardware.yaml": generate_hardware_config(device=device),
    }

    for filename, content in files.items():
        path = os.path.join(output_dir, filename)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)

    print(f"Wrote {len(files)} config files to: {output_dir}")


# ---------------------------------------------------------------------------
# Self-test block
# ---------------------------------------------------------------------------


if __name__ == "__main__":
    import sys
    import tempfile

    try:
        import yaml  # type: ignore[import]
    except ImportError:
        print("pyyaml not installed; skipping YAML parse checks.")
        yaml = None  # type: ignore[assignment]

    errors: list[str] = []

    def fail(msg: str) -> None:
        errors.append(f"FAIL: {msg}")

    def ok(msg: str) -> None:
        print(f"  PASS: {msg}")

    # -----------------------------------------------------------------------
    # Test each generator
    # -----------------------------------------------------------------------
    REQUIRED_MODEL_KEYS = ["encoder", "dynamics", "decoder"]
    REQUIRED_TRAINING_KEYS = ["optimizer", "training", "loss"]
    REQUIRED_DATASET_KEYS = ["data", "splits", "sequence"]
    REQUIRED_HARDWARE_KEYS = ["device", "precision", "distributed", "compile"]

    generators = [
        ("model.yaml", generate_model_config, REQUIRED_MODEL_KEYS),
        ("training.yaml", generate_training_config, REQUIRED_TRAINING_KEYS),
        ("dataset.yaml", generate_dataset_config, REQUIRED_DATASET_KEYS),
        ("hardware.yaml", generate_hardware_config, REQUIRED_HARDWARE_KEYS),
    ]

    print("=== Config generation tests ===")
    for name, gen_fn, required_keys in generators:
        print(f"\n  --- {name} ---")
        try:
            content = gen_fn()
            assert isinstance(content, str), "Generator must return str"
            assert len(content) > 0, "Generator must return non-empty string"
            ok(f"{name}: non-empty string produced ({len(content)} chars)")
        except Exception as exc:
            fail(f"{name}: generation failed: {exc}")
            continue

        if yaml is not None:
            try:
                parsed = yaml.safe_load(content)
                assert isinstance(parsed, dict), "Parsed YAML must be a dict"
                ok(f"{name}: parses as valid YAML dict")
            except Exception as exc:
                fail(f"{name}: YAML parse failed: {exc}")
                continue

            for key in required_keys:
                if key not in parsed:
                    fail(f"{name}: missing required key '{key}'")
                else:
                    ok(f"{name}: required key '{key}' present")

    # -----------------------------------------------------------------------
    # Test dimensional consistency in model config
    # -----------------------------------------------------------------------
    print("\n=== Dimensional consistency test ===")
    if yaml is not None:
        try:
            content = generate_model_config(encoder_embed_dim=256)
            parsed = yaml.safe_load(content)
            enc_dim = parsed["encoder"]["params"]["embed_dim"]
            dyn_dim = parsed["dynamics"]["params"]["state_dim"]
            dec_dim = parsed["decoder"]["params"]["input_dim"]
            if enc_dim == dyn_dim == dec_dim:
                ok(f"All dims consistent: {enc_dim}")
            else:
                fail(
                    f"Dimension inconsistency: enc={enc_dim}, dyn={dyn_dim}, dec={dec_dim}"
                )
        except Exception as exc:
            fail(f"Dimensional consistency check failed: {exc}")

    # -----------------------------------------------------------------------
    # Test write_configs writes files
    # -----------------------------------------------------------------------
    print("\n=== write_configs file write test ===")
    with tempfile.TemporaryDirectory() as tmpdir:
        try:
            write_configs(tmpdir)
            for fname in ["model.yaml", "training.yaml", "dataset.yaml", "hardware.yaml"]:
                path = os.path.join(tmpdir, fname)
                assert os.path.isfile(path), f"Missing: {path}"
                assert os.path.getsize(path) > 0, f"Empty: {path}"
                ok(f"File written and non-empty: {fname}")
        except Exception as exc:
            fail(f"write_configs failed: {exc}")

    # -----------------------------------------------------------------------
    # Test numeric values in training config
    # -----------------------------------------------------------------------
    print("\n=== Numeric value validation ===")
    if yaml is not None:
        try:
            parsed = yaml.safe_load(generate_training_config(lr=1e-3, batch_size=64))
            assert parsed["optimizer"]["lr"] == 1e-3, "lr mismatch"
            assert parsed["training"]["batch_size"] == 64, "batch_size mismatch"
            assert parsed["training"]["epochs"] == 100, "epochs mismatch"
            ok("Numeric values correctly embedded in YAML")
        except Exception as exc:
            fail(f"Numeric value validation failed: {exc}")

    # -----------------------------------------------------------------------
    # Summary
    # -----------------------------------------------------------------------
    print("\n=== Summary ===")
    if errors:
        for e in errors:
            print(f"  {e}")
        print(f"\n{len(errors)} test(s) FAILED.")
        sys.exit(1)
    else:
        print("All config template tests PASSED.")
        sys.exit(0)
