def generate_dataset_config(
    data_root: str = "/data/world_model_dataset",
    data_format: str = "hdf5",
    sequence_length: int = 16,
    image_size: int = 64,
    num_workers: int = 4,
) -> str:
    """Generate YAML content for dataset.yaml.

    Parameters
    ----------
    data_root : str
        Root directory or environment variable substitution token.
    data_format : str
        Dataset file format: hdf5, zarr, folder.
    sequence_length : int
        Number of frames per training sequence.
    image_size : int
        Square image resolution.
    num_workers : int
        DataLoader worker count.

    Returns
    -------
    str
        Valid YAML string.
    """
    return f"""# Dataset configuration
# Generated by world-model-scaffold
# Use ${{DATA_ROOT}} syntax to substitute environment variables.

data:
  root: {data_root}
  format: {data_format}

splits:
  train: train/
  val: val/
  test: test/

sequence:
  length: {sequence_length}
  frame_skip: 1
  image_size: [{image_size}, {image_size}]
  channels: 3

preprocessing:
  normalize: true
  mean: [0.485, 0.456, 0.406]
  std: [0.229, 0.224, 0.225]
  random_crop: false
  horizontal_flip: false
  color_jitter:
    enabled: false
    brightness: 0.4
    contrast: 0.4
    saturation: 0.4

loader:
  num_workers: {num_workers}
  pin_memory: true
  prefetch_factor: 2
  persistent_workers: true
"""


# ---------------------------------------------------------------------------
