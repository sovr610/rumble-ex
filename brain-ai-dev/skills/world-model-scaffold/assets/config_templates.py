"""
config_templates.py
===================
Generators for the four YAML configuration files in the world model scaffold.

Each function returns a valid YAML string.  The ``write_configs`` function
writes all four files to a given output directory.

Usage (self-test):
    python config_templates.py
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Optional


# ---------------------------------------------------------------------------
# Model config
# ---------------------------------------------------------------------------


def generate_model_config(
    encoder_type: str = "vit",
    encoder_embed_dim: int = 512,
    dynamics_type: str = "rssm",
    decoder_type: str = "conv",
    include_memory: bool = False,
    include_planner: bool = False,
) -> str:
    """Generate YAML content for model.yaml.

    Parameters
    ----------
    encoder_type : str
        Registry key for the encoder implementation.
    encoder_embed_dim : int
        Embedding dimension; must match dynamics state_dim.
    dynamics_type : str
        Registry key for the dynamics implementation.
    decoder_type : str
        Registry key for the decoder implementation.
    include_memory : bool
        Whether to enable the memory section.
    include_planner : bool
        Whether to enable the planner section.

    Returns
    -------
    str
        Valid YAML string.
    """
    memory_block = f"""
memory:
  enabled: {str(include_memory).lower()}
  type: episodic
  params:
    capacity: 1000
    key_dim: {encoder_embed_dim}
    value_dim: {encoder_embed_dim}
"""

    planner_block = f"""
planner:
  enabled: {str(include_planner).lower()}
  type: cem
  params:
    num_samples: 1000
    num_elites: 100
    num_iterations: 5
    action_dim: 6
    horizon: 12
"""

    yaml_str = f"""# Model architecture configuration
# Generated by world-model-scaffold

encoder:
  type: {encoder_type}
  params:
    embed_dim: {encoder_embed_dim}
    image_size: 64
    patch_size: 8
    num_heads: 8
    depth: 6
    dropout: 0.1

dynamics:
  type: {dynamics_type}
  params:
    state_dim: {encoder_embed_dim}
    action_dim: 6
    hidden_dim: 256
    num_layers: 2
    cell_type: gru

decoder:
  type: {decoder_type}
  params:
    input_dim: {encoder_embed_dim}
    output_shape: [3, 64, 64]
    hidden_channels: [256, 128, 64]
{memory_block if include_memory else "memory:\\n  enabled: false\\n"}
{planner_block if include_planner else "planner:\\n  enabled: false\\n"}
"""
    return yaml_str


# ---------------------------------------------------------------------------
# Training config
# ---------------------------------------------------------------------------


def generate_training_config(
    lr: float = 3e-4,
    batch_size: int = 32,
    epochs: int = 100,
    optimizer_type: str = "adamw",
    scheduler_type: str = "cosine",
) -> str:
    """Generate YAML content for training.yaml.

    Parameters
    ----------
    lr : float
        Base learning rate.
    batch_size : int
        Training batch size.
    epochs : int
        Total training epochs.
    optimizer_type : str
        Optimizer identifier: adam, adamw, sgd, rmsprop.
    scheduler_type : str
        LR scheduler: cosine, linear, constant, one_cycle.

    Returns
    -------
    str
        Valid YAML string.
    """
    return f"""# Training hyperparameters
# Generated by world-model-scaffold

optimizer:
  type: {optimizer_type}
  lr: {lr}
  weight_decay: 1.0e-5
  betas: [0.9, 0.999]
  eps: 1.0e-8

scheduler:
  type: {scheduler_type}
  warmup_steps: 1000
  total_steps: 100000
  min_lr: 1.0e-6

loss:
  recon_weight: 1.0
  kl_weight: 0.1
  reward_weight: 1.0
  cont_weight: 0.1

training:
  epochs: {epochs}
  batch_size: {batch_size}
  grad_clip: 100.0
  log_every: 100
  validate_every: 1000
  save_every: 5000
  seed: 42

checkpoint:
  save_dir: checkpoints/
  keep_last: 5
  resume_from: null
"""


