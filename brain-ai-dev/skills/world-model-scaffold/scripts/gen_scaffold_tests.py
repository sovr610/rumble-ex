def generate_test_file(
    output_path: str,
    scaffold_dir: str = "",
) -> None:
    """Write the generated test file to output_path.

    Parameters
    ----------
    output_path : str
        Destination .py file path.
    scaffold_dir : str
        If provided, adds a conftest hint comment.  Not embedded in tests
        (tests use the fixture mechanism instead).
    """
    output_path = os.path.abspath(output_path)
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    with open(output_path, "w", encoding="utf-8") as fh:
        if scaffold_dir:
            fh.write(
                f"# scaffold_dir hint (override with --scaffold_dir): {scaffold_dir}\n"
            )
        fh.write(HEADER)

    file_size = os.path.getsize(output_path)
    print(f"Generated test file: {output_path} ({file_size} bytes)")

    # Count test functions
    with open(output_path, encoding="utf-8") as fh:
        content = fh.read()
    test_count = content.count("\ndef test_")
    print(f"Total test functions: {test_count}")


