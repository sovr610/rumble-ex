def main():
    parser = argparse.ArgumentParser(
        description="Generate 100+ pytest test cases for distributed-scaling skill."
    )
    parser.add_argument(
        "--output", "-o", type=str, default=None,
        help="Output file path. If not set, prints to stdout.",
    )
    parser.add_argument(
        "--run", action="store_true",
        help="Generate to a temp file and run with pytest.",
    )
    parser.add_argument(
        "--count-only", action="store_true",
        help="Only print the test count, do not output the file.",
    )
    args = parser.parse_args()

    content = generate_test_file()
    test_count = count_tests(content)

    if args.count_only:
        print(f"Generated test count: {test_count}")
        return 0

    if args.run:
        import tempfile
        with tempfile.NamedTemporaryFile(
            mode="w", suffix=".py", prefix="test_distributed_gen_",
            delete=False,
        ) as f:
            f.write(content)
            tmp_path = f.name

        print(f"Generated {test_count} test cases -> {tmp_path}")
        import subprocess
        result = subprocess.run(
            [sys.executable, "-m", "pytest", tmp_path, "-v", "--tb=short"],
        )
        os.unlink(tmp_path)
        return result.returncode

    if args.output:
        os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
        with open(args.output, "w") as f:
            f.write(content)
        print(f"Generated {test_count} test cases -> {args.output}", file=sys.stderr)
    else:
        print(content)
        print(f"\n# Generated {test_count} test cases", file=sys.stderr)

    return 0


if __name__ == "__main__":
    sys.exit(main())
