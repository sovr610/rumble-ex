def gen_gradient_accumulation_tests() -> str:
    """Generate GradientAccumulator test cases."""
    return textwrap.dedent('''\
    # ===================================================================
    # GradientAccumulator Tests
    # ===================================================================

    class TestGradientAccumulatorConstruction:
        @pytest.mark.parametrize("accum_steps", [1, 2, 4, 8, 16, 32])
        def test_construction(self, accum_steps):
            acc = GradientAccumulator(accumulation_steps=accum_steps)
            assert acc.accumulation_steps == accum_steps

        def test_invalid_zero(self):
            with pytest.raises(ValueError):
                GradientAccumulator(accumulation_steps=0)

        def test_invalid_negative(self):
            with pytest.raises(ValueError):
                GradientAccumulator(accumulation_steps=-1)

    class TestEffectiveBatchSize:
        @pytest.mark.parametrize("micro,accum,world,expected", [
            (32, 1, 1, 32),
            (16, 4, 4, 256),
            (8, 8, 8, 512),
            (4, 16, 8, 512),
            (4, 8, 32, 1024),
            (2, 32, 8, 512),
            (1, 1, 1, 1),
        ])
        def test_batch_sizes(self, micro, accum, world, expected):
            acc = GradientAccumulator(accumulation_steps=accum)
            assert acc.effective_batch_size(micro, world) == expected

    class TestLRScaling:
        @pytest.mark.parametrize("eff_batch,ref_batch,mode,expected_ratio", [
            (256, 256, "linear", 1.0),
            (512, 256, "linear", 2.0),
            (1024, 256, "linear", 4.0),
            (256, 256, "sqrt", 1.0),
            (1024, 256, "sqrt", 2.0),
        ])
        def test_scaling_ratios(self, eff_batch, ref_batch, mode, expected_ratio):
            lr = compute_scaled_lr(1.0, eff_batch, ref_batch, mode=mode)
            assert abs(lr - expected_ratio) < 1e-6

        def test_invalid_mode(self):
            with pytest.raises(ValueError):
                compute_scaled_lr(1.0, 512, 256, mode="cubic")

    class TestCosineSchedule:
        @pytest.mark.parametrize("step,expected_range", [
            (0, (0.0, 0.01)),
            (50, (0.4, 0.6)),
            (100, (0.99, 1.01)),
            (550, (0.1, 1.0)),
            (1000, (0.09, 0.11)),
        ])
        def test_schedule_values(self, step, expected_range):
            lr = get_cosine_lr(step, warmup_steps=100, total_steps=1000,
                              peak_lr=1.0, min_lr=0.1)
            assert expected_range[0] <= lr <= expected_range[1], \\
                f"step={step}: lr={lr} not in {expected_range}"

    class TestAccumulationStep:
        @pytest.mark.parametrize("accum_steps", [1, 2, 4, 8])
        def test_step_pattern(self, small_model, accum_steps):
            acc = GradientAccumulator(accumulation_steps=accum_steps)
            opt = torch.optim.SGD(small_model.parameters(), lr=0.01)
            step_results = []
            for i in range(accum_steps * 2):
                x = torch.randn(4, 16)
                out = small_model(x)
                loss = out.sum()
                did_step = acc.step(loss, opt, small_model)
                step_results.append(did_step)
            # Optimizer should step exactly twice
            assert sum(step_results) == 2
            assert acc.optimizer_steps == 2

    class TestAccumulationEquivalence:
        @pytest.mark.parametrize("accum_steps", [2, 4, 8])
        def test_gradient_equivalence(self, accum_steps):
            M = 8
            torch.manual_seed(42)
            model_a = nn.Sequential(nn.Linear(16, 32), nn.ReLU(), nn.Linear(32, 4))
            model_b = copy.deepcopy(model_a)
            data = torch.randn(accum_steps * M, 16)
            target = torch.randn(accum_steps * M, 4)

            out_a = model_a(data)
            loss_a = nn.functional.mse_loss(out_a, target)
            loss_a.backward()

            acc = GradientAccumulator(accumulation_steps=accum_steps)
            for k in range(accum_steps):
                s, e = k * M, (k + 1) * M
                out_b = model_b(data[s:e])
                loss_b = nn.functional.mse_loss(out_b, target[s:e])
                acc.backward_only(loss_b)

            for (na, pa), (nb, pb) in zip(
                model_a.named_parameters(), model_b.named_parameters()
            ):
                torch.testing.assert_close(pa.grad, pb.grad, atol=1e-5, rtol=1e-5)

    class TestScaleLoss:
        @pytest.mark.parametrize("accum_steps,loss_val,expected", [
            (1, 3.0, 3.0),
            (2, 4.0, 2.0),
            (4, 8.0, 2.0),
            (8, 16.0, 2.0),
        ])
        def test_scale(self, accum_steps, loss_val, expected):
            acc = GradientAccumulator(accumulation_steps=accum_steps)
            scaled = acc.scale_loss(torch.tensor(loss_val))
            assert abs(scaled.item() - expected) < 1e-6

    ''')


