def main() -> int:
    """Entry point for the test generator CLI."""
    parser = argparse.ArgumentParser(
        description="Generate comprehensive pytest tests for dual-process reasoning.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=textwrap.dedent("""\
            Examples:
              python gen_reasoning_tests.py
              python gen_reasoning_tests.py --output /tmp/test_dp.py --verbose
              python gen_reasoning_tests.py --dry-run
        """),
    )
    parser.add_argument(
        "--output", "-o",
        default=_DEFAULT_OUTPUT,
        help=f"Output path for the generated test file (default: {_DEFAULT_OUTPUT})",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Validate and report without writing the file.",
    )
    parser.add_argument(
        "--verbose", "-v",
        action="store_true",
        help="Print the generated source to stdout.",
    )
    args = parser.parse_args()

    # Build content
    content = build_test_file()
    content = _add_header(content)

    # Validate syntax
    if not validate_syntax(content):
        print("[FAIL] Generated code has syntax errors.", file=sys.stderr)
        return 1

    num_classes, num_methods = count_tests(content)
    num_cases = count_parametrize_expansions(content)
    num_lines = content.count("\n") + 1

    print(f"Generated {num_classes} test classes with {num_methods} test methods "
          f"({num_cases} test cases including parametrize expansions), "
          f"{num_lines} lines, syntax valid.")

    if args.verbose:
        print("\n" + "=" * 78)
        print(content)
        print("=" * 78)

    if args.dry_run:
        print("[DRY RUN] File not written.")
        return 0

    # Resolve output path
    output_path = Path(args.output)
    if not output_path.is_absolute():
        # Resolve relative to the skill root (dual-process-reasoning/)
        skill_root = Path(__file__).resolve().parent.parent
        output_path = skill_root / output_path

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")
    print(f"Wrote {output_path}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
