def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate pytest test suite for the video dataloader pipeline."
    )
    parser.add_argument(
        "-o", "--output-dir",
        default=None,
        help="Output directory for the generated test file (default: print to stdout)",
    )
    parser.add_argument(
        "--run",
        action="store_true",
        help="Write the test file and immediately run it with pytest",
    )
    parser.add_argument(
        "--output-file",
        default="test_video_pipeline.py",
        help="Filename for the generated test file (default: test_video_pipeline.py)",
    )
    args = parser.parse_args()

    if args.output_dir is None and not args.run:
        # Print to stdout
        print(TEST_FILE_CONTENT)
        return 0

    output_dir = args.output_dir or tempfile.mkdtemp(prefix="video_tests_")
    os.makedirs(output_dir, exist_ok=True)
    output_path = os.path.join(output_dir, args.output_file)

    with open(output_path, "w") as f:
        f.write(TEST_FILE_CONTENT)

    print(f"Generated test file: {output_path}")
    print(f"Run with: pytest {output_path} -v")

    # Count test functions
    test_count = TEST_FILE_CONTENT.count("    def test_")
    parametrize_count = TEST_FILE_CONTENT.count("@pytest.mark.parametrize")
    print(f"Test functions: {test_count}")
    print(f"Parametrize decorators: {parametrize_count}")

    if args.run:
        print(f"\nRunning: pytest {output_path} -v")
        result = subprocess.run(
            [sys.executable, "-m", "pytest", output_path, "-v", "--tb=short"],
            capture_output=False,
        )
        return result.returncode

    return 0


if __name__ == "__main__":
    sys.exit(main())
