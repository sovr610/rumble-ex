class TestFrameSampling:

    @pytest.mark.parametrize("total_frames,num_frames,stride", [
        (64,  16, 4),
        (100, 8,  2),
        (200, 32, 4),
        (16,  16, 1),
        (1000, 4, 8),
    ])
    def test_indices_count(self, total_frames, num_frames, stride):
        indices = compute_frame_indices(total_frames, num_frames, stride)
        assert len(indices) == num_frames

    @pytest.mark.parametrize("total_frames,num_frames,stride", [
        (64,  16, 4),
        (5,   16, 4),   # short video
        (1,   8,  2),   # single frame
        (100, 10, 1),
    ])
    def test_indices_clamped_to_valid_range(self, total_frames, num_frames, stride):
        indices = compute_frame_indices(total_frames, num_frames, stride)
        assert all(0 <= i < total_frames for i in indices), (
            f"Index out of range: {indices} for total_frames={total_frames}"
        )

    @pytest.mark.parametrize("total_frames,num_frames,stride", [
        (64, 16, 4),
        (100, 8, 2),
    ])
    def test_indices_non_decreasing(self, total_frames, num_frames, stride):
        for _ in range(10):
            indices = compute_frame_indices(total_frames, num_frames, stride)
            assert indices == sorted(indices), f"Indices not sorted: {indices}"

    def test_short_video_does_not_raise(self):
        # Video has fewer frames than span
        indices = compute_frame_indices(total_frames=3, num_frames=16, stride=4)
        assert len(indices) == 16
        assert all(0 <= i < 3 for i in indices)

    def test_single_frame_video_all_zero(self):
        indices = compute_frame_indices(total_frames=1, num_frames=8, stride=2)
        assert all(i == 0 for i in indices)

    def test_random_start_varies(self):
        unique_starts = set()
        for _ in range(100):
            indices = compute_frame_indices(total_frames=500, num_frames=8, stride=4)
            unique_starts.add(indices[0])
        assert len(unique_starts) > 5, (
            f"Expected varied starts, got only {len(unique_starts)} unique"
        )

    @pytest.mark.parametrize("total,num,stride", [
        (64, 16, 4),
        (100, 8, 2),
        (5, 16, 4),
        (1, 8, 2),
        (200, 4, 8),
    ])
    def test_clamping_guarantees(self, total, num, stride):
        for _ in range(20):
            indices = compute_frame_indices(total, num, stride)
            assert max(indices) < total
            assert min(indices) >= 0

    def test_stride_1_sequential(self):
        for _ in range(10):
            indices = compute_frame_indices(total_frames=100, num_frames=10, stride=1)
            assert len(indices) == 10
            # With stride=1, consecutive indices differ by exactly 1
            diffs = [indices[i+1] - indices[i] for i in range(len(indices)-1)]
            assert all(d == 1 for d in diffs)


