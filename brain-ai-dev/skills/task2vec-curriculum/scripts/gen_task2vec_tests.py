def _default_output() -> str:
    """Resolve the default output path relative to the project root."""
    # Try to find the project root (contains brain_ai/ or scripts/)
    here = Path(__file__).resolve().parent  # scripts/
    skill_root = here.parent               # task2vec-curriculum/
    # Go up to the repo root
    repo_root = skill_root.parent.parent   # human-brain/
    target = repo_root / "tests" / "test_task2vec.py"
    return str(target)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate tests/test_task2vec.py for the Task2Vec skill.",
    )
    parser.add_argument(
        "--output", "-o",
        default=_default_output(),
        help="Path to write the generated test file "
             "(default: tests/test_task2vec.py relative to repo root).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the generated file to stdout instead of writing to disk.",
    )
    parser.add_argument(
        "--verbose", "-v",
        action="store_true",
        help="Print extra diagnostics about what the generator is doing.",
    )
    parser.add_argument(
        "--run",
        action="store_true",
        help="Generate the test file and immediately run it with pytest.",
    )
    args = parser.parse_args()

    content = build_test_file()

    # Count test methods
    test_count = content.count("\n    def test_")
    class_count = content.count("\nclass Test")

    if args.verbose:
        print(f"[gen_task2vec_tests] Generated {test_count} test methods "
              f"across {class_count} test classes.")
        print(f"[gen_task2vec_tests] Total lines: {content.count(chr(10)) + 1}")

    if args.dry_run:
        print(content)
        print(f"\n# --- DRY RUN --- {test_count} tests, {class_count} classes ---")
        return

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")
    print(f"[gen_task2vec_tests] Wrote {output_path} "
          f"({test_count} tests, {class_count} classes)")

    if args.run:
        print(f"[gen_task2vec_tests] Running pytest on {output_path} ...")
        result = subprocess.run(
            [sys.executable, "-m", "pytest", str(output_path), "-v", "--tb=short"],
            cwd=str(output_path.parent.parent),
        )
        sys.exit(result.returncode)


if __name__ == "__main__":
    main()
