def _build_helpers() -> str:
    return _dedent("""\
        # ===========================================================================
        # Assertion helpers
        # ===========================================================================

        def assert_l2_normalized(vec: np.ndarray, tol: float = 1e-5) -> None:
            \"\"\"Assert that *vec* has unit L2 norm.\"\"\"
            norm = float(np.linalg.norm(vec))
            assert abs(norm - 1.0) < tol, (
                f"L2 norm {norm:.8f} not within {tol} of 1.0"
            )


        def cosine_sim(a: np.ndarray, b: np.ndarray) -> float:
            \"\"\"Cosine similarity between two flat vectors.\"\"\"
            na = np.linalg.norm(a)
            nb = np.linalg.norm(b)
            if na < 1e-12 or nb < 1e-12:
                return 0.0
            return float(np.dot(a, b) / (na * nb))


        def make_random_embedding(dim: int, rng: np.random.RandomState) -> np.ndarray:
            \"\"\"Return a random L2-normalised vector of length *dim*.\"\"\"
            v = rng.randn(dim).astype(np.float32)
            v /= np.linalg.norm(v) + 1e-12
            return v


        def make_planted_clusters(
            n_tasks: int,
            n_clusters: int,
            dim: int,
            separation: float = 3.0,
            seed: int = 42,
        ) -> Tuple[np.ndarray, np.ndarray, List[str]]:
            \"\"\"Create *n_tasks* L2-normalised embeddings from *n_clusters* planted
            Gaussian clusters.

            Returns:
                embeddings:  (n_tasks, dim) float32
                labels:      (n_tasks,) int
                task_ids:    list of deterministic id strings
            \"\"\"
            rng = np.random.RandomState(seed)
            tasks_per_cluster = n_tasks // n_clusters
            remainder = n_tasks - tasks_per_cluster * n_clusters

            centers = rng.randn(n_clusters, dim).astype(np.float32) * separation

            embeddings_list: List[np.ndarray] = []
            labels_list: List[int] = []

            for c in range(n_clusters):
                count = tasks_per_cluster + (1 if c < remainder else 0)
                noise = rng.randn(count, dim).astype(np.float32) * 0.3
                cluster_points = centers[c] + noise
                embeddings_list.append(cluster_points)
                labels_list.extend([c] * count)

            embeddings = np.concatenate(embeddings_list, axis=0)
            # L2 normalise rows
            norms = np.linalg.norm(embeddings, axis=1, keepdims=True)
            embeddings = embeddings / np.maximum(norms, 1e-12)

            labels = np.array(labels_list, dtype=np.int64)
            task_ids = [f"task_{i:04d}" for i in range(n_tasks)]

            return embeddings, labels, task_ids

        """)


