                idx_0 = rng0.choice(len(task_ids), size=len(task_ids),
                                     replace=True, p=weights_0)
                order_0 = [task_ids[i] for i in idx_0]

                # Epoch 50: p_hard ~ 0.5 -> mixed
                rng50 = np.random.RandomState(50)
                weights_50 = np.array([
                    0.5 if diff[t] > median_d else 0.5
                    for t in task_ids
                ])
                weights_50 /= weights_50.sum() + 1e-12
                idx_50 = rng50.choice(len(task_ids), size=len(task_ids),
                                       replace=True, p=weights_50)
                order_50 = [task_ids[i] for i in idx_50]

