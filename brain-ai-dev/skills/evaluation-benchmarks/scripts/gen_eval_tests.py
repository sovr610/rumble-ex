def generate_test_code() -> str:
    parts = [HEADER]
    for name, body in TESTS:
        body_dedented = textwrap.dedent(body)
        parts.append(f"def {name}():\n{textwrap.indent(body_dedented, '    ')}\n")
    # Count footer
    parts.append(f"\n# Total tests generated: {len(TESTS)}\n")
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate 100+ pytest test cases for assessment infrastructure."
    )
    parser.add_argument("--output", type=str, default=None,
                        help="Output path: directory (writes test_*.py files) or single .py file.")
    parser.add_argument("--count", action="store_true",
                        help="Print test count and exit.")
    args = parser.parse_args()

    if args.count:
        print(f"Total tests: {len(TESTS)}")
        return

    code = generate_test_code()

    if args.output is None:
        print(code)
    elif args.output.endswith(".py"):
        os.makedirs(os.path.dirname(args.output) or ".", exist_ok=True)
        with open(args.output, "w") as fh:
            fh.write(code)
        print(f"Wrote {len(TESTS)} tests to {args.output}")
    elif os.path.isdir(args.output) or not os.path.exists(args.output):
        os.makedirs(args.output, exist_ok=True)
        path = os.path.join(args.output, "test_generated_benchmarks.py")
        with open(path, "w") as fh:
            fh.write(code)
        print(f"Wrote {len(TESTS)} tests to {path}")
    else:
        print(f"Unknown output format: {args.output}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
