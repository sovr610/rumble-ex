class SimpleMetricsSuite:
    """Minimal inline metrics suite for generated tests."""
    def __init__(self, num_classes=10):
        self.num_classes = num_classes
        self.reset()

    def reset(self):
        self._cm = torch.zeros(self.num_classes, self.num_classes, dtype=torch.int64)
        self._total = 0

    def update(self, preds, targets):
        if preds.numel() == 0:
            return
        targets = targets.long()
        if preds.dim() > 1:
            preds = preds.argmax(dim=-1)
        else:
            preds = preds.long()
        for t, p in zip(targets, preds):
            ti, pi = t.item(), p.item()
            if 0 <= ti < self.num_classes and 0 <= pi < self.num_classes:
                self._cm[ti, pi] += 1
        self._total += targets.shape[0]

    def compute(self):
        if self._total == 0:
            return {"accuracy": 0.0, "f1_macro": 0.0}
        tp = self._cm.diag()
        fp = self._cm.sum(dim=0) - tp
        fn = self._cm.sum(dim=1) - tp
        acc = float(tp.sum()) / float(self._total)
        prec = torch.zeros_like(tp, dtype=torch.float)
        rec = torch.zeros_like(tp, dtype=torch.float)
        m = (tp + fp) > 0
        prec[m] = tp[m].float() / (tp + fp)[m].float()
        m2 = (tp + fn) > 0
        rec[m2] = tp[m2].float() / (tp + fn)[m2].float()
        f1 = torch.zeros_like(prec)
        m3 = (prec + rec) > 0
        f1[m3] = 2 * prec[m3] * rec[m3] / (prec + rec)[m3]
        return {"accuracy": acc, "f1_macro": float(f1.mean())}

